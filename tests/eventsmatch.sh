#!/bin/sh
# Счётчики отвалов интерфейсов: обработчик hotplug против того, кто эти счётчики читает.
#
# ЧЕМ СТЕНД СТОИТ. Не словами кода, а следствием: запускается НАСТОЯЩИЙ обработчик
# files/etc/hotplug.d/iface/96-splify2 с теми же переменными, какие ему даёт netifd
# (ACTION/INTERFACE), и проверяется получившийся файл счётчиков. Ни одна проверка ниже не
# заглядывает внутрь скрипта.
#
# И ГЛАВНОЕ — ФОРМАТ ФАЙЛА ПРОВЕРЯЕТ ЕГО НАСТОЯЩИЙ ЧИТАТЕЛЬ. Числа сверяются не разбором в
# стенде, а вызовом tm_event из files/usr/lib/splify2/telemetry.sh: писатель и читатель здесь
# в разных файлах и разных пакетах мыслей, и разойтись они могут молча — счётчики в панели
# просто остались бы нулями, а нуль неотличим от «у человека ничего не отваливалось».
#
# ГОНКА. Обработчики hotplug netifd запускает параллельно, и одновременный ifdown это не
# редкость, а норма (WAN уходит вместе со своим wan6). Поэтому здесь есть проверка на двадцать
# одновременных запусков: она мерит ровно то, ради чего в обработчике заведён тальник вместо
# «прочитал, прибавил, записал».
#
# Запуск: sh tests/eventsmatch.sh
set -u
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT" || exit 2

H=files/etc/hotplug.d/iface/96-splify2
TM=files/usr/lib/splify2/telemetry.sh

pass=0 fail=0
check() {
    if [ "$2" = "$3" ]; then
        pass=$((pass + 1))
    else
        fail=$((fail + 1))
        printf 'FAIL %s\n  ожидалось: %s\n  получено:  %s\n' "$1" "$2" "$3"
    fi
}

T="$(mktemp -d /tmp/eventsmatch.XXXXXX)"
trap 'rm -rf "$T"' EXIT INT TERM
EV="$T/events"
FW="$T/firewall"
# Команда отправки, которую зовёт обработчик при падении WAN. По умолчанию её нет: почти
# всюду ниже проверяются счётчики, а не отправка, и лишний запуск там только мешал бы.
EV_TELEMETRY_CMD="$T/нет-такой-команды"

# Настройка фаервола — та самая, по которой OpenWrt отличает внешний интерфейс от внутреннего.
# Аплинк здесь назван человеком (`internet`), а не `wan`: иначе проверка не отличала бы разбор
# зоны от совпадения по имени.
cat > "$FW" <<'EOF'
config zone
	option name 'lan'
	list network 'lan'
	list network 'guest'

config zone
	option name 'wan'
	list network 'internet'
	list network 'wan6'
	option masq '1'
EOF

# Запуск обработчика ровно так, как его зовёт netifd: переменными окружения.
run() {  # ДЕЙСТВИЕ ИНТЕРФЕЙС
    ACTION="$1" INTERFACE="$2" DEVICE="eth0" TM_EVENTS="$EV" FW_CONF="$FW" \
        TELEMETRY_SH="$ROOT/$TM" TELEMETRY_CMD="$EV_TELEMETRY_CMD" \
        sh "$H" </dev/null >/dev/null 2>&1
}
# Чтение счётчика НАСТОЯЩИМ читателем — функцией сборщика телеметрии.
ev() {  # ИМЯ -> число
    TM_EVENTS="$EV" sh -c ". $TM; tm_event $1" 2>/dev/null
}
reset() { rm -f "$EV" "$EV".* 2>/dev/null; }

# ---- ifup не стоит ничего ---------------------------------------------------------------
# Скрипт выполняется на КАЖДОМ событии интерфейса, а на загрузке это пачка ifup. Проверяется
# следствием: после ifup нет ни файла счётчиков, ни тальников — то есть обработчик ушёл до
# первой работы с диском.
reset
run ifup wan
run ifup lan
run ifup internet
check "после ifup файла счётчиков нет вовсе" "no" \
      "$([ -e "$EV" ] && echo yes || echo no)"
check "и ни одного тальника тоже" "0" \
      "$(ls "$EV".* 2>/dev/null | grep -c . || true)"
check "и читатель видит ноль" "0" "$(ev iface_down)"

# ---- uci и ubus на горячем пути не зовутся ------------------------------------------------
# Тоже следствием: в PATH подкладываются `uci` и `ubus`, которые оставляют след. Обработчик
# бежит на каждом событии сети, а разбор всей конфигурации uci ради одного ответа — самая
# дорогая вещь, которую он мог бы себе позволить.
mkdir -p "$T/bin"
for c in uci ubus; do
    printf '#!/bin/sh\ntouch "%s/called-%s"\nexit 1\n' "$T" "$c" > "$T/bin/$c"
    chmod +x "$T/bin/$c"
done
reset
PATH="$T/bin:$PATH" run ifup wan
PATH="$T/bin:$PATH" run ifdown internet
check "ни uci, ни ubus не позваны ни разу" "0" \
      "$(ls "$T"/called-* 2>/dev/null | grep -c . || true)"

# ---- ifdown по WAN поднимает ОБА счётчика -------------------------------------------------
reset
run ifdown wan
check "wan: счётчик отвалов WAN — единица" "1" "$(ev wan_down)"
check "wan: счётчик отвалов интерфейсов — единица" "1" "$(ev iface_down)"

# ---- ifdown по НЕ-WAN поднимает только один -----------------------------------------------
reset
run ifdown lan
check "lan: отвал WAN не засчитан" "0" "$(ev wan_down)"
check "lan: отвал интерфейса засчитан" "1" "$(ev iface_down)"

# ---- что считается WAN --------------------------------------------------------------------
reset; run ifdown wan6
check "wan6 — это тоже WAN" "1" "$(ev wan_down)"
reset; run ifdown wan_4g
check "wan_4g (второй аплинк) — это WAN" "1" "$(ev wan_down)"
# Переименованный человеком аплинк узнаётся по зоне фаервола `wan`, а не по имени.
reset; run ifdown internet
check "переименованный аплинк узнан по зоне фаервола" "1" "$(ev wan_down)"
check "и как отвал интерфейса он тоже засчитан" "1" "$(ev iface_down)"
reset; run ifdown guest
check "гостевая сеть из зоны lan — не WAN" "0" "$(ev wan_down)"
check "но отвалом интерфейса она осталась" "1" "$(ev iface_down)"
# Без файла фаервола (он бывает не создан) обработчик обязан не падать и считать общий счётчик.
reset
ACTION=ifdown INTERFACE=internet TM_EVENTS="$EV" FW_CONF="$T/нет-такого" \
    TELEMETRY_SH="$ROOT/$TM" TELEMETRY_CMD="$T/нет-такой-команды" \
    sh "$H" </dev/null >/dev/null 2>&1
check "без настройки фаервола обработчик не падает" "0" "$?"
check "и общий счётчик всё равно поднят" "1" "$(ev iface_down)"

# ---- КУМУЛЯТИВНОСТЬ -----------------------------------------------------------------------
# Счётчики копятся с загрузки, а не показывают последнее событие: пропущенная отправка
# телеметрии не должна терять ни одного отвала.
reset
run ifdown wan; run ifdown wan; run ifdown wan
check "три отвала WAN — это три" "3" "$(ev wan_down)"
check "и три отвала интерфейса" "3" "$(ev iface_down)"
run ifdown lan; run ifdown lan
check "два отвала не-WAN счётчик WAN не тронули" "3" "$(ev wan_down)"
check "а общий счётчик стал пятью" "5" "$(ev iface_down)"

# ---- формат файла: его читает сборщик, а не стенд ------------------------------------------
# Строки ровно той формы, какую разбирает tm_event (`имя=число`), и ни одной лишней: файл
# отдаётся в панель как есть, и мусор в нём стал бы полем неизвестного вида.
check "в файле ровно две строки" "2" "$(grep -c . "$EV" 2>/dev/null)"
check "и обе — «имя=число»" "2" "$(grep -c '^[a-z_]*=[0-9]*$' "$EV" 2>/dev/null)"

# ---- ГОНКА --------------------------------------------------------------------------------
# Двадцать обработчиков одновременно: двенадцать по WAN, восемь по lan. Именно так их и
# запускает netifd — параллельно, без всякой очереди. Наивное «прочитал, прибавил, записал»
# теряет здесь события молча, и потерю никто не заметит: счётчик просто окажется поменьше.
reset
n=0
while [ "$n" -lt 12 ]; do run ifdown wan & n=$((n + 1)); done
while [ "$n" -lt 20 ]; do run ifdown lan & n=$((n + 1)); done
wait
check "20 одновременных ifdown — 20 отвалов интерфейсов" "20" "$(ev iface_down)"
check "из них 12 по WAN" "12" "$(ev wan_down)"
check "и файл после гонки остался в две строки" "2" "$(grep -c . "$EV" 2>/dev/null)"

# ---- ГОНКА, РАСТЯНУТАЯ ВО ВРЕМЕНИ --------------------------------------------------------
# Двадцать запусков выше — проверка вероятностная: окно, в котором отставший обработчик
# затирает файл СВОИМ УСТАРЕВШИМ числом, узкое, и на быстрой машине его можно не поймать ни
# разу. А ловить надо именно его: там теряются события у человека, чей WAN отваливается
# пачкой, и теряются молча — счётчик просто оказывается поменьше.
#
# Поэтому окно раскрывается насильно: первому обработчику подсовывается медленный `mv`
# (подмена файла растянута на две секунды), и пока он в ней сидит, отрабатывает второй,
# обычный. Первый подменяет файл ПОСЛЕ второго — и обязан заметить, что его число устарело,
# и переписать заново. Если не заметит, в файле останется единица вместо двойки.
mkdir -p "$T/slow"
cat > "$T/slow/mv" <<EOF
#!/bin/sh
if [ ! -f "$T/slow/hit" ]; then : > "$T/slow/hit"; sleep 2; fi
for _m in /bin/mv /usr/bin/mv; do [ -x "\$_m" ] && exec "\$_m" "\$@"; done
exit 1
EOF
chmod +x "$T/slow/mv"
reset
PATH="$T/slow:$PATH" run ifdown wan &
sleep 1
run ifdown wan
wait
check "отставший обработчик не затёр файл своим устаревшим числом" "2" "$(ev iface_down)"
check "и по WAN тоже двойка" "2" "$(ev wan_down)"

# ---- счётчики падений соседствуют с отвалами и не затираются ------------------------------
#
# Писателей у видимого файла двое: отвалы считает этот обработчик, падения — команда отправки.
# Пока сборка файла была написана в обработчике отдельной копией, он собирал его ТОЛЬКО из
# своих тальников, то есть каждый ifdown стирал счётчик падений. Заметить это можно было бы
# лишь по нулям в панели, а ноль неотличим от «ничего не падало».
reset
mkdir -p "$EV.c"
printf 'xxx' > "$EV.c/steer"     # три падения движка, записанных не нами
run ifdown wan
check "падения движка пережили пересборку файла" "3" "$(ev crash_steer)"
check "и отвал WAN посчитан в том же файле" "1" "$(ev wan_down)"
run ifdown lan
check "и второй отвал их тоже не стёр" "3" "$(ev crash_steer)"

# ---- падение WAN уезжает НЕМЕДЛЕННО -------------------------------------------------------
#
# Откуда вообще берётся внеплановая отправка: из мест, которые о падении УЖЕ узнают. Сторожевой
# демон ради этого не заводится — постоянный процесс на роутере здесь не платят ни за что.
# Проверяется по следствию: подставная команда записывает свои аргументы.
cat > "$T/telemetry-cmd" <<EOF
#!/bin/sh
printf '%s\n' "\$*" >> "$T/now-calls"
EOF
chmod +x "$T/telemetry-cmd"
reset; rm -f "$T/now-calls"
EV_TELEMETRY_CMD="$T/telemetry-cmd" run ifdown wan
# Отправка уходит отдельным процессом в фоне (netifd не должен ждать разговора с панелью),
# поэтому запись её аргументов может отстать от обработчика на несколько миллисекунд.
_w=0
while [ "$_w" -lt 40 ] && [ ! -s "$T/now-calls" ]; do _w=$((_w + 1)); sleep 0.05 2>/dev/null || sleep 1; done
check "отвал WAN позвал внеплановую отправку" "1" \
      "$(grep -c -- '--now wan_flap' "$T/now-calls" 2>/dev/null || echo 0)"
check "и сказал, что упало" "1" \
      "$(grep -c -- '--what wan' "$T/now-calls" 2>/dev/null || echo 0)"
# А НЕ-WAN отвал — не повод: гостевая сеть или отдельный VLAN опускаются штатно, и внеплановая
# отправка на каждый такой случай была бы тем самым потопом, только со стороны обработчика.
reset; rm -f "$T/now-calls"
EV_TELEMETRY_CMD="$T/telemetry-cmd" run ifdown lan
sleep 0.2 2>/dev/null || true
check "отвал не-WAN внеплановой отправки не зовёт" "0" \
      "$(grep -c . "$T/now-calls" 2>/dev/null || echo 0)"
check "но в счётчик он попал" "1" "$(ev iface_down)"

printf '\n%d проверок пройдено' "$pass"
if [ "$fail" -gt 0 ]; then printf ', %d ПРОВАЛЕНО\n' "$fail"; exit 1; fi
printf '\nвсе проверки прошли\n'
