/** Строки интерфейса — по-русски, прямо в разметке.
 *
 *  Здесь жил словарь на двести английских msgid из splify первой версии и переводчик находок
 *  splify-doctor (`tCheck`/`tFix`). Ни одно из этого не работало: интерфейс с самого начала
 *  зовёт `t()` с русской строкой, и словарь с английскими ключами не находил ни одну из них
 *  (I-047), а находки doctor splify2 не порождает вовсе — их печатает движок, уже по-русски
 *  (I-048). Полкилобайта переводов на каждое открытие страницы ради функции тождества.
 *
 *  `t()` оставлена как точка, через которую однажды пройдёт второй язык, если он понадобится:
 *  вызовы уже стоят у новых строк, и убирать их, чтобы потом расставлять заново, незачем. Пока
 *  языка один — это тождество, и оно обязано быть таким явно, а не через словарь, в котором
 *  ключей нет. */
export function t(msgid: string): string {
    return msgid
}
