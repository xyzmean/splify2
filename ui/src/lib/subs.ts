import { cacheGet, cacheSet } from '@/lib/cache'
import type { SubQuota } from '@/lib/rpc'

/** ПЕРЕЧЕНЬ ПОДПИСОК ПРОШЛОГО ОТКРЫТИЯ.
 *
 *  Зачем он запоминается. Числа каждой подписки помнит её собственный блок (ключ
 *  `card:<имя>`), но НАРИСОВАТЬ этот блок страница не может, пока не узнает, что подписка
 *  вообще есть: перечень приезжает отдельным вызовом (`sub_list`), а он уходит после
 *  загрузки LuCI, загрузчика и бандла. Всё это время на месте подписок пусто, и блоки
 *  появляются рывком — тем сильнее, чем их больше: у двух подписок на экране разом
 *  вырастают два блока и разъезжают всё, что под ними.
 *
 *  Поэтому здесь запоминается ровно то, чем подписки НАЗЫВАЮТСЯ: имя, заголовок, вид
 *  источника и путь к файлу узлов. Этого хватает, чтобы нарисовать блоки сразу — со своими
 *  запомненными числами внутри, — а свежий перечень заменяет их, когда приедет.
 *
 *  ЧИСЕЛ ЗДЕСЬ НЕТ НАМЕРЕННО. Остаток лежит в памяти своего блока, и вторая копия тех же
 *  чисел разошлась бы с первой на первом же обновлении: блок спрашивает панель при каждом
 *  открытии, а перечень — только когда его перечитают.
 *
 *  Устарев, этот перечень не врёт ничем, кроме лишнего блока у подписки, удалённой из
 *  другого окна: он проживёт до ответа роутера и исчезнет. Ровно та же цена, что у
 *  запомненного остатка. */

const KEY = 'subs'

export interface SubRow {
    name: string
    title?: string
    url?: string
    kind?: 'url' | 'links' | 'none'
    path: string
    present: boolean
    bytes?: number
    mtime?: number
    used?: number
    quota?: SubQuota
}

/** Перечень с прошлого открытия. `null` — не запомнено ничего: первое открытие, чужой
 *  браузер, приватное окно. */
export function subsRemembered(): SubRow[] | null {
    const rows = cacheGet<SubRow[]>(KEY)
    /* Проверка не педантизм: в памяти лежит то, что записала ПРЕЖНЯЯ версия страницы, и
     * форма записи могла с тех пор смениться. Строка без имени и пути в блоке подписки
     * означала бы пустой заголовок и блок, к которому не привязан ни один выход. */
    if (!Array.isArray(rows)) return null
    const ok = rows.filter((s) => s && typeof s.name === 'string' && typeof s.path === 'string')
    return ok.length ? ok : null
}

/** Запомнить перечень. Числа снимаются: у них своё место. */
export function subsRemember(rows: SubRow[] | undefined): void {
    cacheSet(
        KEY,
        (rows || []).map(({ name, title, url, kind, path, present, bytes, mtime, used }) => ({
            name, title, url, kind, path, present, bytes, mtime, used,
        })),
    )
}
