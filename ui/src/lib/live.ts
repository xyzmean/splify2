/** Живые данные экрана — ОДИН опрос на всё.
 *
 *  Раньше их читала только страница состояния. Теперь они нужны и закреплённой колонке, и
 *  вкладке логов, а два независимых опроса значили бы два разных мгновения на одном экране:
 *  колонка говорит «работает», таблица рядом показывает нули, и оба правы. Здесь снимок один,
 *  и его видят все.
 *
 *  Скорость считается из разницы двух снимков — именно её человек и высматривает, глядя на
 *  счётчики: «сколько всего» отвечает на другой вопрос. Поэтому и снимок обязан быть один:
 *  разница по значениям, снятым в разные моменты, делится на неверное время и показывает
 *  скорость, которой не было. */

export interface DiagCheck {
    id: string
    /** `note` — совет, а не находка: верен всегда и в счётчики движка не идёт. Без него советы
     *  считались предупреждениями, и «работает, но есть о чём знать» горело постоянно — то есть
     *  тревога стояла на исправном роутере и учила не смотреть на неё вовсе. */
    verdict: 'ok' | 'note' | 'warn' | 'fail'
    what: string
    why: string
}

export interface Diag {
    checks: DiagCheck[]
    warn: number
    fail: number
}

export interface Build {
    present: boolean
    vless: boolean
    arch?: string
    version?: string
    /** Поднимется ли движок после перезагрузки. Именно это снимает «Остановить всё», и
     *  именно поэтому подпись тумблера читает состояние, а не помнит своё: между двумя
     *  открытиями страницы движок могли остановить из консоли. */
    enabled?: boolean
    /** Работает ли хоть один экземпляр прямо сейчас. */
    running?: boolean
}

export interface Live {
    status: Status | null
    /** Время работы движка в секундах и сколько устройств сейчас ходит в сеть. */
    net: { uptime: number; active_clients: number } | null
    /** Что установлено: версия, вариант, архитектура. Спрашивается ОДИН раз, а не по кругу:
     *  ответ добывается запуском движка, и делать это каждые пять секунд на роутере с 64 МБ
     *  значит платить процессом за неменяющееся число. Перечитывается по refresh() — то есть
     *  после установки, когда оно и меняется. */
    build: Build | null
    /** Что можно поставить: архитектура пакетов и релизы от новых к старым. Спрашивается
     *  так же редко, как build, и по той же причине — запрос уходит наружу. */
    releases: Releases | null
    /** Версии самого интерфейса. Спрашивается там же и так же редко, как releases. */
    selfUpdate: SelfUpdateInfo | null
    /** Ошибка движка. Отдельно от `status === null`, потому что «ещё не пришло» и «не
     *  отвечает» требуют разного: первое — подождать, второе — показать причину. */
    error: string | null
    /** Показанное — ПРОШЛОЕ: снимок с прошлого открытия страницы, пока не пришёл первый
     *  ответ роутера. Врать этим нельзя, поэтому признак вынесен наружу: интерфейс обязан
     *  показать, что числа ещё не сегодняшние, а не выдавать их за живые.
     *
     *  Теперь у «прошлого» два источника, и оба помечаются этим признаком: снимок из памяти
     *  браузера (до первого ответа роутера) и запомненный ответ САМОГО ДВИЖКА — тот, что
     *  приходит на первом, быстром круге. Разные они только тем, где лежали; для человека
     *  оба значат одно — «числа ещё не сегодняшние, свежие уже едут». */
    stale: boolean
    diag: Diag | null
    /** Движок старее проверок состояния. Не ошибка страницы, а отдельное сообщение: иначе
     *  выглядело бы как поломка интерфейса на исправном роутере. */
    diagOld: boolean
    devs: Record<string, { rx: string; tx: string }> | null
    /** Скорость прямо сейчас, готовыми строками. Пусто до второго опроса и когда трафика
     *  нет: нуль там был бы неправдой — мы его не измеряли. */
    speed: {
        ch: Record<string, { up: string | null; down: string | null }>
        dev: Record<string, { rx: string | null; tx: string | null }>
    }
    /** Перечитать сейчас, не дожидаясь следующего круга. Нужно после «Применить»: без этого
     *  человек видит прежние числа и не понимает, подействовало ли. */
    refresh: () => void
}

/** Байты человеческим размером. Точность до десятой доли: «223,4 МБ» отвечает на вопрос,
 *  а «234085837» требует считать разряды глазами. */
export function human(n: number) {
    if (!isFinite(n) || n <= 0) return '0 Б'
    const u = ['Б', 'КБ', 'МБ', 'ГБ', 'ТБ']
    let i = 0
    let v = n
    while (v >= 1024 && i < u.length - 1) { v /= 1024; i++ }
    return `${i === 0 ? v : v.toFixed(1).replace('.', ',')} ${u[i]}`
}

/** Скорость из разницы двух опросов. Отрицательная разница значит, что счётчики начались
 *  заново (перезагрузка) — такую не показываем вовсе. */
export function rate(bytes: number, ms: number) {
    if (!(ms > 0) || !(bytes > 0)) return null
    const bits = (bytes * 8 * 1000) / ms
    if (bits >= 1e6) return `${(bits / 1e6).toFixed(1).replace('.', ',')} Мбит/с`
    if (bits >= 1e3) return `${Math.round(bits / 1e3)} кбит/с`
    return `${Math.round(bits)} бит/с`
}

const PERIOD_MS = 5000
/** Как долго верить запомненным версиям выпусков. Шесть часов — как у памяти бэкенда. */
const VERSIONS_TTL_MS = 6 * 3600 * 1000

/** Снимок прошлого открытия. Держится в памяти браузера ради одного: страница открывается
 *  внутри LuCI, и до первого ответа ubus проходят секунды — сначала грузится сама LuCI, потом
 *  наш загрузчик, потом бандл, и только потом уходят вызовы. Замерено на роутере: вердикт
 *  появлялся через 3,2 с даже после того, как из первого пакета убрали походы в интернет.
 *
 *  Врать снимком нельзя: «Работает», нарисованное по вчерашним данным, — это не задержка, а
 *  неправда. Поэтому вместе со снимком отдаётся признак `stale`, и интерфейс показывает
 *  прошлое как прошлое, пока не приедет настоящее. */
type Snapshot = { status: Status | null; diag: Diag | null; build: Build | null }

export function useLive(): Live {
    const saved = useRef<Snapshot | null>(cacheGet<Snapshot>('live'))
    const [stale, setStale] = useState(!!saved.current)
    const [status, setStatus] = useState<Status | null>(saved.current?.status ?? null)
    const [error, setError] = useState<string | null>(null)
    const [diag, setDiag] = useState<Diag | null>(saved.current?.diag ?? null)
    /* Снимок для следующего открытия страницы кладётся каждым кругом, а проверки приходят не
     * каждым: без этой ссылки круг без проверок стирал бы из снимка вердикт, который у нас
     * есть, и страница открывалась бы без него — то самое «Загрузка…» вместо состояния,
     * ради снятия которого снимок и заведён. */
    const diagNow = useRef<Diag | null>(saved.current?.diag ?? null)
    useEffect(() => { diagNow.current = diag }, [diag])
    const [diagOld, setDiagOld] = useState(false)
    const [devs, setDevs] = useState<Record<string, { rx: string; tx: string }> | null>(null)
    const [speed, setSpeed] = useState<Live['speed']>({ ch: {}, dev: {} })
    const [build, setBuild] = useState<Build | null>(saved.current?.build ?? null)
    /* Версии — из памяти браузера: за ними роутер ходит на GitHub (или по обходным путям),
     * и полторы секунды на каждый из двух вопросов при каждом открытии окна — ради чисел,
     * которые меняются раз в неделю. Запомненное рисуется сразу; свежее спрашивается, когда
     * запомненному больше шести часов. */
    const versionsSaved = useRef(cacheGet<{ at: number; releases: Releases | null; selfUpdate: SelfUpdateInfo | null }>('versions'))
    const [releases, setReleases] = useState<Releases | null>(versionsSaved.current?.releases ?? null)
    const [selfUpdate, setSelfUpdate] = useState<SelfUpdateInfo | null>(versionsSaved.current?.selfUpdate ?? null)
    const [net, setNet] = useState<{ uptime: number; active_clients: number } | null>(null)
    const prev = useRef<{
        t: number
        ch: Record<string, { up: number; down: number }>
        dev: Record<string, { rx: number; tx: number }>
    } | null>(null)
    /** Счётчик «перечитай сейчас». Меняется — эффект перезапускается. */
    const [nonce, setNonce] = useState(0)
    /** Память движка спрашивалась ли уже. Ссылкой, а не переменной внутри эффекта: эффект
     *  перезапускается на каждый refresh() — после «Применить», после установки пакета, — и
     *  переменная внутри него означала бы «память на первом круге ПОСЛЕ КАЖДОГО обновления».
     *  А там свежие числа и есть то, зачем человек нажал кнопку: ускорять открытие окна
     *  нужно один раз, при открытии. */
    const askedFast = useRef(false)

    useEffect(() => {
        let stop = false
        /* Перекрывающиеся опросы. Круг на медленном роутере может не уложиться в пять
         * секунд, и тогда два load() гонялись бы за prev.current: скорость считалась бы
         * из разницы снимков, снятых с неверным интервалом (I-013). Опоздавший круг не
         * ставится в очередь — следующий тик всё равно принесёт свежее. */
        let inflight = false
        /* Проверки движка спрашиваются НЕ каждый круг.
         *
         * Замер на стенде (mipsel 24kc, 880 МГц): круг без проверок стоит роутеру 240 мс,
         * с проверками — 432 мс, то есть они почти удваивают самую частую работу во всём
         * интерфейсе. А меняются они реже всего: приговор перестаёт быть верным, когда
         * что-то применили или туннель упал. Первое интерфейс знает сам — после apply он
         * зовёт refresh(), а тот перезапускает эффект и первым же кругом спрашивает
         * проверки. Второе видно и без них: поле `up` выхода приходит каждый круг и
         * рисуется сразу.
         *
         * Поэтому проверки идут первым кругом, после каждого refresh(), при возвращении на
         * вкладку — и раз в двадцать секунд просто так. */
        const DIAG_EVERY = 4
        let round = 0
        /* Объект ubus старее интерфейса: пакет обновили, rpcd не перезапустили. Тогда
         * метода `live` нет, и круг идёт прежними пятью вызовами. Проверяется один раз за
         * жизнь эффекта: отказ метода — это не «сеть моргнула», он не пройдёт и в
         * следующий раз. */
        let legacy = false
        /* Первый круг — БЫСТРЫЙ: просим движок отдать запомненное состояние, чтобы экран
         * нарисовался без ожидания, и тут же идём вторым кругом за свежим.
         *
         * Зачем это здесь, а не решением бэкенда. Полный `steer status` стоит 91 мс на
         * стенде, и он же нужен первым при открытии окна — то есть складывается со всем
         * остальным, что страница спрашивает в тот же миг (LuCI выполняет вызовы одного
         * такта подряд одним запросом). Замерено на роутере: до первого состояния проходило
         * 3,2 с. Движок теперь помнит свой последний ответ и умеет отдать его немедленно;
         * решать, когда память годится вместо измерения, обязан тот, кто спрашивает, —
         * метод, который решал бы это сам, было бы нечем попросить сказать правду.
         *
         * Ровно один круг, а не «пока не устареет»: дальше страница и так опрашивает роутер
         * каждые пять секунд, и память там была бы не ускорением, а враньём. */
        let wantFast = !askedFast.current
        askedFast.current = true
        /* Был ли последний ответ памятью. Не в состоянии React, а здесь: значение нужно
         * внутри того же круга, между разбором ответа и finish(), а состояние до следующего
         * рендера не обновится. */
        let cachedNow = false

        /* Беда приезжает УСПЕШНЫМ промисом. Бэкенд по контракту (docs/rpcd-api.md)
         * отвечает на любую ошибку объектом {ok:false, error} и кодом возврата нуль,
         * поэтому промис резолвится, и проверка одного лишь status === 'rejected'
         * такую беду не замечает вовсе.
         *
         * Цена была ровно обратной задуманному: движок не отвечает (спека битая,
         * файла списка нет, движок откатили) → status отдаёт {ok:false,...} →
         * setError(null) и объект ошибки в состоянии → рельс печатает «Работает»
         * зелёной точкой, а заголовок диагностики — «Всё в порядке». Ветка «Проверка
         * состояния недоступна», написанная ровно под этот случай, была недостижима.
         * В самом бэкенде про это сказано прямо: «честная ошибка, а не пустой объект,
         * который интерфейс покажет как „всё в порядке“». */
        const failure = (v: unknown): string | null => {
            if (!v || typeof v !== 'object') return null
            const o = v as { ok?: unknown; error?: unknown }
            if (o.ok === false || o.ok === 0)
                return typeof o.error === 'string' && o.error ? o.error : 'бэкенд вернул ошибку'
            return null
        }
        const asText = (e: unknown): string => String(e instanceof Error ? e.message : e)

        /** Один круг прежними вызовами — для объекта, который не знает `live`.
         *
         *  Памяти движка здесь нет и не будет: объект, не знающий `live`, тем более не знает
         *  про `--fast`, а второй путь с той же политикой разошёлся бы с первым. Старый
         *  роутер получает то, что получал всегда. */
        const loadLegacy = async (withDiag: boolean) => {
            /* allSettled, а не all: отказ одного источника не должен уносить остальные.
             * Проверок состояния нет у старого движка, и это не повод гасить экран. */
            const [s, d, g, ni] = await Promise.allSettled([
                rpc.status(), rpc.devStats(),
                withDiag ? rpc.diag() : Promise.resolve(null), rpc.netInfo(),
            ])
            if (stop) return
            if (s.status === 'fulfilled' && !failure(s.value)) { setStatus(s.value); setError(null) }
            else setError(s.status === 'fulfilled' ? failure(s.value)! : asText(s.reason))
            const devices = d.status === 'fulfilled' && !failure(d.value) ? d.value.devices || {} : null
            if (withDiag) {
                if (g.status === 'fulfilled' && g.value && !failure(g.value)) {
                    setDiag(g.value); setDiagOld(false)
                } else setDiagOld(true)
            }
            const netv = ni.status === 'fulfilled' && !failure(ni.value) ? ni.value : null
            finish(s.status === 'fulfilled' && !failure(s.value) ? s.value : null, devices, netv, null)
        }

        const finish = (
            st: Status | null,
            devices: Record<string, { rx: string; tx: string }> | null,
            netv: { uptime: number; active_clients: number } | null,
            dg: Diag | null,
        ) => {
            /* Первый ответ роутера — конец «прошлого»: дальше на экране живое.
             *
             * Кроме одного случая: движок отдал ЗАПОМНЕННОЕ (быстрый круг). Тогда прошлое
             * никуда не делось — оно лишь приехало с роутера, а не из памяти браузера, — и
             * снимать признак здесь значило бы объявить память измерением ровно в тот
             * момент, когда мы её и попросили. */
            setStale(cachedNow)
            if (devices) setDevs(devices)
            if (netv) setNet(netv)

            /* Снимок для следующего открытия. Только то, что не вредит, устарев и будучи
             * помеченным: состояние выходов, счёт проверок и версия движка. Скорости сюда не
             * едут — они считаются из разницы двух опросов, и «прошлая скорость» это число
             * ни о чём. */
            if (st) cacheSet('live', { status: st, diag: dg ?? diagNow.current, build: null })

            /* СКОРОСТЬ ИЗ ЗАПОМНЕННОГО ОТВЕТА НЕ СЧИТАЕТСЯ ВОВСЕ, и точка отсчёта им не
             * ставится.
             *
             * Счётчики каналов в таком ответе — те, что движок видел, когда собирал снимок:
             * до пяти минут назад. Взяв их точкой отсчёта, следующий круг поделил бы разницу
             * за пять минут на свои двести миллисекунд и показал бы скорость в сотню раз
             * больше настоящей — ровно та ошибка, ради снятия которой опрос и сведён к
             * одному снимку (I-013), только теперь с неверным ЧИСЛИТЕЛЕМ вместо
             * знаменателя.
             *
             * Терять при этом нечего: точку отсчёта поставит свежий круг, который выпускается
             * сразу за этим, и первая скорость появится там же, где появлялась всегда — на
             * следующем опросе. */
            if (cachedNow) { prev.current = null; return }

            const now = Date.now()
            const ch: Record<string, { up: number; down: number }> = {}
            if (st)
                for (const c of st.channels || [])
                    ch[c.name] = { up: c.bytes ?? 0, down: c.down_bytes ?? 0 }
            const dev: Record<string, { rx: number; tx: number }> = {}
            if (devices)
                for (const [n, v] of Object.entries(devices))
                    dev[n] = { rx: Number(v.rx), tx: Number(v.tx) }
            const p = prev.current
            if (p) {
                const ms = now - p.t
                const chs: Live['speed']['ch'] = {}
                for (const [n, v] of Object.entries(ch))
                    chs[n] = {
                        up: p.ch[n] ? rate(v.up - p.ch[n].up, ms) : null,
                        down: p.ch[n] ? rate(v.down - p.ch[n].down, ms) : null,
                    }
                const devs2: Live['speed']['dev'] = {}
                for (const [n, v] of Object.entries(dev))
                    devs2[n] = {
                        rx: p.dev[n] ? rate(v.rx - p.dev[n].rx, ms) : null,
                        tx: p.dev[n] ? rate(v.tx - p.dev[n].tx, ms) : null,
                    }
                setSpeed({ ch: chs, dev: devs2 })
            }
            prev.current = { t: now, ch, dev }
        }

        const load = async (force?: 'diag') => {
            if (inflight) return
            inflight = true
            /* Быстрый круг ОДИН и первый. Признак снимается сразу, до запроса: иначе отказ
             * или гонка оставили бы страницу просить память по кругу. */
            const fast = wantFast
            wantFast = false
            /* НА БЫСТРОМ КРУГЕ ПРОВЕРОК НЕ ПРОСИМ, и это половина смысла быстрого круга.
             *
             * Память движка отдаётся мгновенно, а `steer diag` считается заново — 201 мс на
             * стенде, вдвое дороже самого состояния. Спросив их вместе, мы бы вернули то
             * ожидание, ради снятия которого память и заведена. Приговор при этом на экране
             * есть: он лежит в снимке из памяти браузера с прошлого открытия и помечен как
             * прошлое — тем же признаком `stale`, что и сама память движка.
             *
             * Свежие проверки приезжают догоняющим кругом, который выпускается сразу за этим. */
            const withDiag = !fast && (force === 'diag' || round % DIAG_EVERY === 0)
            /* Спрошенные ПО ПРОСЬБЕ проверки перезапускают отсчёт двадцати секунд, а не
             * сбивают его фазу. Иначе догоняющий круг (и любой refresh, и возврат на вкладку)
             * оставлял бы следующий плановый опрос проверок там, где он и стоял, — то есть
             * через считанные секунды после только что полученного приговора. */
            round = withDiag ? 1 : round + 1
            try {
                /* Тело круга — отдельной функцией, а не ветками с `return` прямо здесь: из
                 * этого места надо ВСЕГДА дойти до догоняющего круга ниже, а ранний `return`
                 * пропускал бы его. На этом уже попался старый объект: он уходит в прежние
                 * вызовы первым же `return`, и проверки не приезжали к нему вовсе. */
                await (async () => {
                    if (legacy) { await loadLegacy(withDiag); return }
                    const r = await rpc.live(withDiag, fast).catch((e) => asText(e))
                    if (stop) return
                    if (typeof r === 'string') {
                        /* Метода нет — это не отказ роутера, а старый объект. Переходим на
                         * прежние вызовы молча: человеку показывать нечего, всё работает. */
                        legacy = true
                        await loadLegacy(withDiag)
                        return
                    }
                    const bad = failure(r)
                    if (bad) { setError(bad); setStale(false); return }
                    setStatus(r.status)
                    setError(null)
                    /* Ответ движка ЗАПОМНЕННЫЙ — значит показанное всё ещё прошлое, и свежий
                     * круг уже выпущен ниже. Экран говорит «Обновление…» до его ответа. */
                    cachedNow = r.status?.cached === true
                    if (withDiag) {
                        if (r.diag) { setDiag(r.diag); setDiagOld(false) }
                        else if (r.diag_old) setDiagOld(true)
                    }
                    finish(r.status, r.devices || null, r.net || null, r.diag ?? null)
                })()
            } finally {
                inflight = false
            }
            /* Догоняющий круг — СРАЗУ за быстрым, а не через пять секунд, и он идёт ВСЕГДА,
             * когда быстрый был.
             *
             * Причин две, и вторая не зависит от первой. Память движка — это прошлое, и
             * оставить её на экране до следующего тика значило бы показывать прошлое пять
             * секунд там, где до сих пор показывалось «Загрузка…». А проверок движка быстрый
             * круг не просил вовсе, и без догоняющего они приехали бы только на двадцатой
             * секунде — то есть движок постарее ключа (он отвечает живым состоянием, без
             * `cached`) остался бы на исправном роутере без приговора на четыре круга.
             *
             * Вызов вне finally: inflight к этому моменту уже снят, иначе второй круг
             * отбросил бы сам себя. */
            if (fast && !stop) void load('diag')
        }
        void load()
        /* Опрос ЗАМИРАЕТ, пока вкладка скрыта, и догоняет одним кругом при возврате.
         *
         * Круг стоит роутеру пяти запусков shell-скрипта плюс двух запусков движка, и на
         * 880 МГц это порядка секунды процессора на каждые пять секунд. Пока паузы не было,
         * забытая в фоне вкладка на телефоне стучалась в роутер двенадцать раз в минуту
         * вечно — то есть постоянная нагрузка от страницы, которую никто не смотрит. Это
         * самая дорогая работа во всём интерфейсе именно потому, что она не прекращается.
         *
         * Догоняющий круг обязателен: без него вернувшийся человек видит снимок той
         * давности, когда он ушёл, а счётчики скорости считаются из разницы двух снимков и
         * дали бы среднее за всё время отсутствия. prev сбрасывается по той же причине —
         * интервал между снимками не пять секунд, и скорость из него бессмысленна. */
        const tick = () => { if (!document.hidden) void load() }
        const id = setInterval(tick, PERIOD_MS)
        const onVisible = () => {
            if (document.hidden) return
            prev.current = null
            void load('diag')
        }
        document.addEventListener('visibilitychange', onVisible)
        return () => {
            stop = true
            clearInterval(id)
            document.removeEventListener('visibilitychange', onVisible)
        }
    }, [nonce])

    /* Отдельным эффектом: этот ответ добывается запуском движка, и в общем круге он стоил бы
     * процесса каждые пять секунд. */
    /* И НЕ В ПЕРВОМ ПАКЕТЕ. uhttpd исполняет вызовы одного пакета подряд, поэтому всё, что
     * выпущено в один такт с `live`, стоит между человеком и первым вердиктом. Полсекунды
     * задержки уводят этот вызов в следующий пакет: экран рисуется по `live` и снимку из
     * памяти (сборка движка там уже есть), а свежий ответ дописывается следом. */
    useEffect(() => {
        let stop = false
        const t = setTimeout(() => {
            rpc.engine()
                .then((b) => { if (!stop) setBuild(b) })
                .catch(() => { if (!stop) setBuild(null) })
        }, 500)
        return () => { stop = true; clearTimeout(t) }
    }, [nonce])

    /* Список релизов — тоже раз на круг обновления, а не в пятисекундном опросе: запрос
     * уходит на GitHub с двадцатисекундным таймаутом, и держать его в общем цикле значило
     * бы ходить в интернет двенадцать раз в минуту с роутера.
     *
     * Здесь, а не в карточке движка, потому что ответ нужен ДВУМ местам сразу: карточке —
     * чтобы заполнить список версий, левой колонке — чтобы подпись кнопки перестала обещать
     * обновление, которого нет (I-038). Пока запрос жил в карточке, колонка о нём не знала. */
    /* И ОТДЕЛЬНЫМ ЗАХОДОМ В ОЧЕРЕДЬ, а не вместе с состоянием. LuCI складывает вызовы,
     * выпущенные в одном такте, в ОДИН запрос к ubus и выполняет их подряд, поэтому самый
     * медленный задерживает все. Эти два идут на api.github.com через интернет — замерено на
     * роутере: пакет из одиннадцати вызовов занимал 5,7 с, из них состояние движка было
     * готово за четверть секунды, а обзор всё это время писал «Загрузка…». `setTimeout`
     * уводит поход на GitHub в следующий пакет: страница рисуется по состоянию, а версии
     * дописываются, когда приедут.
     *
     * Задержка именно секундная, а не нулевая: одного такта не хватает — очередь LuCI
     * складывает в пакет всё, что выпущено, пока предыдущий запрос ещё в пути, и вызов из
     * setTimeout(0) успевал попасть в тот же пакет. Проверено на роутере пакет за пакетом. */
    useEffect(() => {
        let stop = false
        /* refresh() (nonce) — после установки, когда версии и меняются: тогда спрашиваем всегда. */
        const fresh = versionsSaved.current && Date.now() - versionsSaved.current.at < VERSIONS_TTL_MS
        if (fresh && nonce === 0) return
        const t = setTimeout(() => {
            Promise.allSettled([rpc.steerVersions(), rpc.splify2Versions()]).then(([r, u]) => {
                if (stop) return
                const rel = r.status === 'fulfilled' ? r.value : null
                const up = u.status === 'fulfilled' ? u.value : null
                setReleases(rel)
                setSelfUpdate(up)
                if (rel || up) {
                    versionsSaved.current = { at: Date.now(), releases: rel, selfUpdate: up }
                    cacheSet('versions', versionsSaved.current)
                }
            })
        }, 1200)
        return () => { stop = true; clearTimeout(t) }
    }, [nonce])

    return {
        status, error, diag, diagOld, devs, speed, build, net, releases, selfUpdate, stale,
        refresh: () => setNonce((n) => n + 1),
    }
}
