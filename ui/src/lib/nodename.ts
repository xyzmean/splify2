/** Имя узла подписки: то, что пишет продавец, — и то, что из него можно взять.
 *
 *  Отдельным файлом, потому что читают его два места: строка выхода на главной и выбор
 *  локации в составе выхода. Две копии разбора разошлись бы на первом же продавце, который
 *  ставит флаг не в начало.
 *
 *  ЭМОДЗИ-ФЛАГ — ЭТО ПАРА БУКВ. 🇳🇱 = N+L региональными индикаторами, поэтому код страны из
 *  него вычитается, а не угадывается. Рисуем мы его потом сами картинкой: шрифта с флагами
 *  в Windows нет, и там, где мы ждали флаг, человек видит две мелкие буквы. */

/** Код страны из имени узла: «🇳🇱 Мобильный #6» → NL. */
export function ccFromName(s?: string | null): string | undefined {
    if (!s) return undefined
    const m = s.match(/[\u{1F1E6}-\u{1F1FF}]{2}/u)
    if (!m) return undefined
    const cc = [...m[0]].map((ch) => String.fromCharCode(ch.codePointAt(0)! - 0x1f1e6 + 65)).join('')
    return /^[A-Z]{2}$/.test(cc) ? cc : undefined
}

/** Имя узла без эмодзи: флага, звёзд и прочих значков продавца. Они либо повторяют то, что
 *  мы рисуем сами, либо не относятся к делу, а место в строке занимают. */
export function plainName(s?: string | null): string {
    if (!s) return ''
    return s
        .replace(/[\u{1F1E6}-\u{1F1FF}]/gu, '')
        .replace(/[\u{1F300}-\u{1FAFF}\u{2190}-\u{2BFF}\u{FE00}-\u{FE0F}\u{200D}]/gu, '')
        .replace(/\s{2,}/g, ' ')
        .replace(/^[\s·|,\-—]+|[\s·|,\-—]+$/g, '')
        .trim()
}
