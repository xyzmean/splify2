import { type SubQuota } from '@/lib/rpc'

/** Остаток трафика подписки: что из него можно посчитать, а что нельзя.
 *
 *  Панель называет четыре числа — отдано, принято, объём периода и его конец. Всё остальное
 *  на карточке «Подписка» считается ЗДЕСЬ, в одном месте: половина этих величин выводится
 *  друг из друга, и разложи их по компонентам — они разойдутся на первом же изменении.
 *
 *  Чего здесь принципиально нет: догадок о длине периода. Панель начала периода не сообщает,
 *  а «обычно тридцать дней» на подписке на девяносто завысило бы темп втрое — и обзор обещал
 *  бы, что трафик кончится, когда он не кончится. Темп берётся из ДВУХ наблюдений (`since` и
 *  `at` от бэкенда), а пока они слишком близко — не берётся вовсе. */

/** Сколько должно пройти между двумя наблюдениями, чтобы темп что-то значил.
 *
 *  Шесть часов, потому что расход неровный: вечер за один час может дать больше, чем сутки
 *  до него, и предсказание «хватит на два дня» из часового окна пугало бы человека каждый
 *  вечер. До этого срока строки про темп на карточке просто нет — это честнее числа, которое
 *  через час станет другим втрое. */
export const MIN_SPAN_MS = 6 * 3600 * 1000

const DAY_MS = 86400 * 1000

/** Байты приезжают строками (в int32 объём подписки не влезает), и пустая строка значит
 *  «панель этого не назвала» — не нуль. Разница видна на подписке без ограничения по
 *  объёму: там `total` пуст, и нуль вместо него нарисовал бы «осталось 0». */
function num(v: string | undefined): number | null {
    if (v === undefined || v === '') return null
    const n = Number(v)
    return Number.isFinite(n) && n >= 0 ? n : null
}

/** Объём периода словами панели: пусто ИЛИ НОЛЬ — ограничения нет.
 *
 *  Ноль здесь не «нисколько не выдано»: `total=0` — принятое у панелей (Marzban, Remnawave,
 *  3x-ui и родня) обозначение безлимитного тарифа, и мобильные клиенты читают его так же.
 *  Замерено на живой подписке (sub.skytunnel.pw): панель отдаёт `upload=0; download=0;
 *  total=0; expire=…`, и обзор рисовал по этому «0 Б из 0 Б осталось» с пустой полосой — то
 *  есть показывал исчерпанную подписку там, где ограничения нет вовсе. */
function totalNum(v: string | undefined): number | null {
    const n = num(v)
    return n === 0 ? null : n
}

export interface QuotaView {
    /** Израсходовано за период по счёту ПАНЕЛИ: отдано плюс принято. */
    used: number
    /** Объём периода; null — подписка без ограничения по объёму. */
    total: number | null
    /** Остаток; null, когда объём не назван. Ниже нуля не опускается: панель, отдавшая
     *  расход больше объёма, описывает исчерпанную подписку, а не долг. */
    left: number | null
    /** Доля израсходованного, 0..1; null без объёма. */
    part: number | null
    /** Unix-время конца периода в миллисекундах; null — срок не назван. */
    expire: number | null
    /** Сколько суток до сброса; null без срока. Округление ВНИЗ: «остался день» точнее,
     *  чем «два», когда до сброса двадцать пять часов. */
    daysLeft: number | null
    /** Измеренный расход в сутки; null, пока наблюдений мало (см. MIN_SPAN_MS). */
    perDay: number | null
    /** На сколько суток хватит остатка при измеренном темпе; null, если нечего делить или
     *  не на что. */
    forecastDays: number | null
    /** Кончится раньше сброса. Только когда известны оба срока — иначе это не утверждение,
     *  а предположение, и красить им карточку нельзя. */
    tight: boolean
    /** Остатка хватит дольше, чем длится период: при нынешнем темпе трафик не кончится.
     *
     *  Нужен потому, что «хватит при таком темпе» на медленном расходе даёт числа, которые
     *  никто не читает: остаток в 200 ГБ при десяти мегабайтах в сутки — это двадцать тысяч
     *  суток, и строка «на 20 000 дней» сообщает не срок, а то, что срока нет. Там, где
     *  сравнивать не с чем (панель не назвала конец периода), считаем таким запас больше
     *  года: за год подписка сменится, и число суток теряет смысл раньше, чем кончится
     *  трафик. */
    outlasts: boolean
    /** Когда спрашивали панель, словами. Пусто, если время не названо. */
    age: string
}

/** Дата сброса словами: «12 сентября». Год не показываем — срок подписки в пределах месяцев,
 *  и год в строке лишний ровно до того случая, когда он не лишний; тогда его видно по дате. */
export function resetText(expireMs: number): string {
    return new Date(expireMs).toLocaleDateString('ru-RU', { day: 'numeric', month: 'long' })
}

/** «12 мин назад», «3 ч назад», «2 д назад». Секунды не показываем: числа обновляются
 *  запросом к панели, и «14 с назад» обещает точность, которой у них нет. */
export function agoText(ms: number): string {
    if (!(ms > 0)) return 'только что'
    const min = Math.floor(ms / 60000)
    if (min < 1) return 'только что'
    if (min < 60) return `${min} мин назад`
    const h = Math.floor(min / 60)
    if (h < 24) return `${h} ч назад`
    return `${Math.floor(h / 24)} д назад`
}

/** Сутки словами, с русским счётом. Числительное здесь неизбежно: строка «до конца периода»
 *  читается как ответ на вопрос, а не как счётчик, и двоеточие с числом («суток: 15») в этом
 *  месте выглядело бы протоколом. Везде, где счётчик всё-таки счётчик, в интерфейсе стоит
 *  «подпись: число» — и склонений там нет по построению. */
export function daysText(n: number): string {
    const t = Math.abs(n) % 100
    const o = t % 10
    if (t > 10 && t < 20) return `${n} дней`
    if (o === 1) return `${n} день`
    if (o >= 2 && o <= 4) return `${n} дня`
    return `${n} дней`
}

export function readQuota(q: SubQuota, now: number = Date.now()): QuotaView {
    const up = num(q.up) ?? 0
    const down = num(q.down) ?? 0
    const used = up + down
    const total = totalNum(q.total)
    const left = total === null ? null : Math.max(0, total - used)
    const part = total && total > 0 ? Math.min(1, used / total) : null

    const expire = q.expire > 0 ? q.expire * 1000 : null
    const daysLeft = expire === null ? null : Math.max(0, Math.floor((expire - now) / DAY_MS))

    /* Темп — по двум наблюдениям бэкенда, и только по ним. `since_used` — расход в момент
     * первого наблюдения периода; разница делится на прошедшее время. Отрицательная разница
     * означает, что панель обнулила счётчик между наблюдениями, а бэкенд этого ещё не увидел:
     * тогда темпа нет, а не «минус столько-то в сутки». */
    const sinceMs = q.since > 0 ? q.since * 1000 : 0
    const atMs = q.at > 0 ? q.at * 1000 : 0
    const span = sinceMs && atMs ? atMs - sinceMs : 0
    const grew = used - (num(q.since_used) ?? 0)
    const perDay = span >= MIN_SPAN_MS && grew > 0 ? (grew * DAY_MS) / span : null

    const forecastDays =
        perDay && perDay > 0 && left !== null ? Math.floor(left / perDay) : null
    const tight = forecastDays !== null && daysLeft !== null && forecastDays < daysLeft
    const outlasts =
        forecastDays !== null &&
        (daysLeft !== null ? forecastDays >= daysLeft : forecastDays > 365)

    return {
        used, total, left, part, expire, daysLeft, perDay, forecastDays, tight, outlasts,
        age: atMs ? agoText(now - atMs) : '',
    }
}

/** Пора ли спросить панель заново.
 *
 *  Четверть часа: числа панели меняются не быстрее, чем человек качает трафик, а запрос
 *  уходит с роутера в интернет с таймаутом двадцать секунд. Открытие обзора чаще раза в
 *  четверть часа — обычное дело, и ходить наружу на каждое из них незачем. */
export const STALE_MS = 15 * 60 * 1000

export function isStale(q: SubQuota | undefined, now: number = Date.now()): boolean {
    if (!q || !q.at) return true
    return now - q.at * 1000 > STALE_MS
}
