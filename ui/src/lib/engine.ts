import type { Build } from '@/lib/live'
import { type Status } from '@/lib/model'

/** Что можно предложить сделать с движком — в одном месте на весь интерфейс.
 *
 *  Место одно потому, что мест было два и они расходились. Левая колонка выбирала подпись
 *  по одному признаку («установлен ли движок вообще») и на свежей версии звала обновляться;
 *  карточка ниже ту же операцию называла «Переустановить». Человек читал первую подпись как
 *  состояние — «вышла новая версия», — шёл по ней и находил другое слово (I-038).
 *
 *  Сравнивать есть с чем: rpcd отдаёт установленную версию (engine) и релизы от новых к
 *  старым (steer_versions). Не хватало не данных, а того, чтобы кто-то их сопоставил. */

export interface Releases {
    /** Архитектура ПАКЕТОВ. Приходит и тогда, когда движка нет, — единственный ответ,
     *  который сообщает её в этом состоянии. */
    arch: string
    /** От новых к старым. Только цифры и точки: этим значением собирается имя файла пакета,
     *  и число составляющих не важно — «26.9» такая же законная версия, как «1.2.0». */
    versions: string[]
    /** Название выпуска по его версии: «26.9» → «26.9 Andromeda». Может не прийти вовсе,
     *  если бэкенд старее интерфейса. */
    names?: Record<string, string>
    /** Почему список такой, какой есть. Приходит только на запасном пути: перечень релизов
     *  не отдали (закрытый api.github.com или выбранный лимит, splify2#15), и версия взята
     *  из VERSION главной ветки — одна и без названия выпуска. Молчать здесь нельзя: одна
     *  строка в списке иначе читается как «релиз всего один». */
    note?: string
}

/** Числа версии. Хвост, который числом не является, отбрасывается: версия приезжает и с
 *  кодовым именем выпуска («26.9 Andromeda»), и с суффиксом сборки, а сравнивать надо числа.
 *
 *  Отсутствующая составляющая — нуль, поэтому «26.9» и «26.9.0» равны, а число составляющих
 *  сравнению не мешает: требовать три части значило бы объявить собственный выпуск непонятным. */
function parts(v: string): number[] {
    const m = /^\d+(?:\.\d+)*/.exec(v.trim())
    return m ? m[0].split('.').map((n) => parseInt(n, 10)) : []
}

/** Сравнение версий по числам, а не по строкам: «0.9.10» строкой меньше «0.9.9», а «26.9»
 *  строкой меньше «9.9». Возвращает <0, 0, >0 — как принято у компараторов. */
export function cmpVersion(a: string, b: string): number {
    const pa = parts(a)
    const pb = parts(b)
    for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
        const d = (pa[i] || 0) - (pb[i] || 0)
        if (d) return d
    }
    return 0
}

/** Как выпуск называется. Версия — то, чем ставится пакет; название — то, как о выпуске
 *  говорят и как он подписан на странице релизов («26.9 Andromeda»).
 *
 *  Названия может не быть: бэкенд старее интерфейса, у релиза нет заголовка, GitHub не
 *  ответил. Тогда версия называет себя сама — это хуже, чем название, но лучше пустой
 *  строки, по которой нечего выбрать. */
export function releaseName(version: string, names?: Record<string, string>): string {
    const n = names?.[version]
    return n && n.trim() ? n : version
}

/** Что стоит и что можно поставить — про сам интерфейс.
 *
 *  Живёт здесь, рядом с версиями движка, а не в компоненте: lib не должен зависеть от
 *  components даже типом, иначе граница между слоями держится только на привычке. */
export interface SelfUpdateInfo {
    /** Что стоит сейчас. Пусто, если пакет поставлен руками мимо apk. */
    current: string
    /** Релизы от новых к старым, только цифры и точки — см. Releases.versions. */
    versions: string[]
    /** Название выпуска по его версии — см. Releases.names. */
    names?: Record<string, string>
    /** Почему список такой, какой есть — см. Releases.note. */
    note?: string
}

export interface EngineAction {
    /** Подпись кнопки. */
    label: string
    /** Самая свежая доступная версия — null, если список ещё не пришёл или пуст. */
    latest: string | null
    /** Установленное старее самого свежего. */
    outdated: boolean
}

export function engineAction(build: Build | null, releases: Releases | null): EngineAction {
    const latest = releases?.versions?.length ? releases.versions[0] : null

    if (!build?.present) return { label: 'Установить', latest, outdated: false }

    // Список ещё не пришёл (или интернета на роутере нет) — значит про «свежее» мы не знаем
    // ничего. Молчание здесь честнее догадки: обещать обновление, которого никто не
    // проверял, и есть та самая находка.
    if (!latest || !build.version) return { label: 'Переустановить', latest, outdated: false }

    const outdated = cmpVersion(build.version, latest) < 0
    /* Подпись называет выпуск так, как он подписан на странице релизов: человек читал
     * «Обновить до 26.9», а искал «Andromeda» — и не находил, потому что искал не число. */
    return {
        label: outdated ? `Обновить до ${releaseName(latest, releases?.names)}` : 'Переустановить',
        latest,
        outdated,
    }
}

/** Умеет ли установленный движок список локаций и смешанный пул (контракт steer T-015).
 *
 *  Спрашивается у СОСТОЯНИЯ, а не у версии, и это не стилистика: номер версии движку
 *  проставляет релизный workflow, а не коммит, поэтому сборка из main через два коммита
 *  после релиза называет то же число, что и релиз.
 *
 *  Два ответа, потому что движков в поле два поколения; подробности — у веток ниже. */
export function poolsSupported(status: Status | null): boolean {
    if (!status) return false
    /* Прямой ответ движка, начиная со steer 1.3.0: перечень умений печатается верхним уровнем
     * и виден там, где выхода подписки нет вовсе, — а смешанный пул нужнее всего именно там
     * (xsteer плюс wireguard), и именно там движок постарше молча уводит канал в blackhole. */
    if (Array.isArray(status.features)) return status.features.includes('pool')
    /* Движок до 1.3.0: перечня нет, и спросить можно только косвенно — поле `nodes` у выхода
     * kind=vless печатается всегда, в том числе пустым, а движок постарше не печатает его
     * вовсе. Ни одного такого выхода нет — ответить нечем, и тогда ответ «не умеет»: цена
     * ошибки несимметрична. Сказав «умеет» зря, мы дадим человеку собрать пул, который молча
     * повезёт трафик не туда; сказав «не умеет» зря, мы всего лишь не покажем выбор. */
    const outs = Object.values(status.outputs || {})
    return outs.some((o) => o.kind === 'vless' && Array.isArray(o.nodes))
}
