/** Страна по коду ISO 3166-1 alpha-2, как её называет внешняя сторона (`loc=` в ответе
 *  cdn-cgi/trace).
 *
 *  ЗАЧЕМ СВОЙ СПИСОК, А НЕ Intl.DisplayNames. Он есть в браузере и знает все страны, но на
 *  роутере интерфейс открывают и из приложений с урезанным движком, а падать из-за подписи
 *  под адресом нельзя. Поэтому список свой, короткий — те страны, где стоят узлы, — а всё
 *  остальное показывается кодом: «NL» лучше пустоты и лучше выдумки.
 *
 *  Флаг НЕ хранится: он вычисляется из тех же двух букв (региональные индикаторы идут подряд
 *  от 0x1F1E6), и держать его строкой значило бы завести второе место, где страна может
 *  разойтись сама с собой. */

const NAMES: Record<string, string> = {
    AM: 'Армения', AT: 'Австрия', AZ: 'Азербайджан', BE: 'Бельгия', BG: 'Болгария',
    BR: 'Бразилия', CA: 'Канада', CH: 'Швейцария', CY: 'Кипр', CZ: 'Чехия',
    DE: 'Германия', DK: 'Дания', EE: 'Эстония', ES: 'Испания', FI: 'Финляндия',
    FR: 'Франция', GB: 'Великобритания', GE: 'Грузия', HK: 'Гонконг', HU: 'Венгрия',
    IE: 'Ирландия', IL: 'Израиль', IN: 'Индия', IT: 'Италия', JP: 'Япония',
    KZ: 'Казахстан', LT: 'Литва', LU: 'Люксембург', LV: 'Латвия', MD: 'Молдавия',
    NL: 'Нидерланды', NO: 'Норвегия', PL: 'Польша', PT: 'Португалия', RO: 'Румыния',
    RS: 'Сербия', RU: 'Россия', SE: 'Швеция', SG: 'Сингапур', SK: 'Словакия',
    TR: 'Турция', UA: 'Украина', US: 'США', AE: 'ОАЭ', AU: 'Австралия',
}

/** Флаг из кода: две заглавные буквы → две региональные буквы-индикатора. */
export function flag(cc: string): string {
    const c = (cc || '').trim().toUpperCase()
    if (!/^[A-Z]{2}$/.test(c)) return ''
    return String.fromCodePoint(...[...c].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65))
}

/** Название страны для человека. Неизвестный код возвращается как есть. */
export function country(cc: string): string {
    const c = (cc || '').trim().toUpperCase()
    if (!/^[A-Z]{2}$/.test(c)) return ''
    return NAMES[c] || c
}

/** Строка локации целиком: «🇩🇪 Германия». Без кода — пусто, и вызывающий сам решает,
 *  показывать ли что-то взамен. */
export function place(cc?: string): string {
    const f = flag(cc || '')
    const n = country(cc || '')
    return n ? (f ? `${f} ${n}` : n) : ''
}
