import { describe, expect, it } from 'vitest'
import { toPunycodeList } from '@/lib/validate'

// Свой список доменов, записанный буквами своего алфавита.
//
// ЗАЧЕМ СТЕНД. Отказ здесь молчаливый с обеих сторон: `sanitize_list` выбрасывает строку с
// кириллицей и сообщает только число отброшенных, а если бы её пропустили — резолвер движка
// сравнивает байты имени из запроса DNS, куда браузер кладёт уже `xn--…`, и домен не совпал бы
// никогда. То есть и «список не принялся», и «список принялся и не работает» выглядят
// одинаково: правило стоит, трафик идёт мимо.
describe('свои списки: домены переводятся в punycode до отправки', () => {
    it('кириллический домен уезжает как xn--', () => {
        expect(toPunycodeList('россия.рф')).toBe('xn--h1alffa9f.xn--p1ai')
    })

    it('обычный домен не трогается вовсе — ни регистр, ни пробелы', () => {
        const src = '  Example.COM  \nyoutube.com'
        expect(toPunycodeList(src)).toBe(src)
    })

    it('звёздочка поддомена переживает перевод: это наша разметка, а не часть имени', () => {
        expect(toPunycodeList('*.рф')).toBe('*.xn--p1ai')
    })

    it('комментарий и отступ остаются на месте', () => {
        expect(toPunycodeList('  почта.рф  # моя почта')).toBe('  xn--80a1acny.xn--p1ai  # моя почта')
    })

    it('строка-комментарий целиком не трогается, даже кириллическая', () => {
        expect(toPunycodeList('# мои домены')).toBe('# мои домены')
    })

    it('пустые строки и переводы строк сохраняются как есть', () => {
        expect(toPunycodeList('a.ru\n\nрф.рф\n')).toBe('a.ru\n\nxn--p1ai.xn--p1ai\n')
    })

    it('то, что не разбирается как имя, возвращается дословно — судить будет роутер', () => {
        expect(toPunycodeList('не домен вовсе')).toBe('не домен вовсе')
    })
})
