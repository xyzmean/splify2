# Разобрать тег: в AD_TAG — по какому качаем, в AD_TAG_WARN — что с настройкой не так.
#
# РАЗБОР И ПЕЧАТЬ РАЗВЕДЕНЫ, и это не вкус: печать (ad_tag) зовут в подстановке `$( )`, то
# есть в подоболочке, откуда предупреждение наружу не выйдет. Настройка, отбитая молча, —
# это ровно та беда, от которой предупреждение и заведено. Поэтому вызывающий сначала зовёт
# ad_tag_resolve в СВОЕЙ оболочке и говорит человеку, если есть что сказать.
#
# Проверяется СИМВОЛЬНО, потому что значение из uci уезжает в URL: тег с косой чертой или
# «..» строил бы ссылку не туда, куда написано в AD_BASE. И отдельно отбивается `latest` —
# см. довод у AD_TAG_DEFAULT.
ad_tag_resolve() {
    AD_TAG_WARN=""
    AD_TAG="$AD_TAG_DEFAULT"
    _ad_t="$(uci -q get splify2.main.allow_domains_tag 2>/dev/null)"
    case "$_ad_t" in
        '') ;;
        latest|LATEST)
            AD_TAG_WARN="tag=latest фиксацией версии не является — берём зашитый $AD_TAG_DEFAULT" ;;
        *[!A-Za-z0-9_.-]*)
            AD_TAG_WARN="tag «$_ad_t» на тег релиза не похож — берём зашитый $AD_TAG_DEFAULT" ;;
        *) AD_TAG="$_ad_t" ;;
    esac
}

# Тег, по которому качаем. Разбирается при первом спросе — в том числе внутри подстановки,
# где память о разборе наружу не выйдет: считать его заново дешевле, чем требовать от
# вызывающего порядок вызовов.
ad_tag() {
    [ -n "$AD_TAG" ] || ad_tag_resolve
    printf '%s' "$AD_TAG"
}

# Виды списков сервиса через пробел. Пусто — такого сервиса у издателя нет.
ad_kinds() {  # СЕРВИС
