# Второй издатель списков — itdoginfo/allow-domains. Описание источника и минимум кода,
# который его читает.
#
# ЗАЧЕМ ВТОРОЙ ИСТОЧНИК. Тем же издателем пользуется podkop, то есть его состав категорий
# людям этой аудитории уже знаком, и вопрос «а почему у вас телеграм не тот, что у соседа»
# снимается сам. Наш манифест (ru-bypass-ipsets) при этом остаётся на месте: это не замена,
# а второй издатель рядом.
#
# ПОЧЕМУ .srs, А НЕ ПЛОСКИЕ .lst. Плоские списки у этого издателя лежат ТОЛЬКО в дереве
# ветки main, а в релизе текстовых файлов нет ни одного: там 25 наборов `.srs` (sing-box) и
# 36 `.mrs` (mihomo). Ветка — это плавающее состояние, и пиннить её пришлось бы по SHA
# коммита, то есть по значению, которого человеку негде взять. Релиз же имеет ТЕГ. А читать
# `.srs` движок теперь умеет сам (`steer srs-read`), так что двоичность формата перестала
# быть ценой.
#
# ПОЧЕМУ ФАЙЛОМ, А НЕ ТАБЛИЦЕЙ В СКРИПТЕ — тот же довод, что у doh-providers.conf: состав
# сервисов у издателя меняется чаще, чем код вокруг него, и добавление сервиса не должно
# быть правкой программы. Отличие от doh-providers.conf одно: здесь рядом с таблицей лежат
# и функции, которые её читают. Иначе их пришлось бы держать в ДВУХ местах — в объекте rpcd
# (кнопка «Загрузить») и в ночном обновлении, — а расхождение этих двух половин проект уже
# проходил: каталог в интерфейсе открывался, а ночью списки тихо не приезжали. Тег и его
# употребление обязаны лежать в одном файле.
#
# Подключается строкой `. /usr/share/splify2/allow-domains.sh` из обеих половин. Пути и
# значения переопределяемы окружением — иначе стенд не проверить, не трогая рабочую систему.

# Короткое имя источника. Оно же — подкаталог в каталоге списков и приставка к id списка в
# list_fetch («itdog:telegram»). Одно имя на все три роли: разные означали бы, что путь на
# диске и запрос из интерфейса связаны только договорённостью в чужой голове.
AD_ID=${AD_ID:-itdog}
AD_REPO=${AD_REPO:-itdoginfo/allow-domains}

# ФИКСАЦИЯ ВЕРСИИ. Тег релиза, а не `latest`, и это главное решение в этом файле.
#
# `latest/download/<файл>` у издателя работает, но означает, что состав списков у человека
# меняется САМ СОБОЙ — раз в неделю, ночью, без его участия. Роутер, который вчера пускал
# сайт в туннель, а сегодня нет, при плавающей ссылке необъясним: сравнивать не с чем, и
# сказать «у меня была вот эта версия» человек не может. Тег даёт воспроизводимость: два
# роутера с одним тегом маршрутизируют одинаково, а откат — это возврат прежнего тега.
#
# Тег ЗАШИТ В ПАКЕТ (значение ниже), а не подбирается на роутере. Значит поднять версию
# списков может только новая сборка splify2 — то есть человек, который её выпустил и
# проверил, — либо сам владелец роутера явным `uci set splify2.main.allow_domains_tag=…`.
# Ночное обновление тег НЕ ДВИГАЕТ никогда: ровно это и есть «состав меняется сам собой».
#
# Разрешать `latest` через uci мы не станем (см. ad_tag): это единственное значение,
# которое молча отменяет всё сказанное выше, и набрать его человек попробует первым.
AD_TAG_DEFAULT=${AD_TAG_DEFAULT:-2026-08-31_16-18}

# Ссылка строится по тегу. Не `latest`, не `refs/heads/main` — см. выше.
AD_BASE=${AD_BASE:-https://github.com/itdoginfo/allow-domains/releases/download}

