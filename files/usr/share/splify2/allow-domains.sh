}

# Название для человека. Пусто — сервиса нет.
ad_title() {  # СЕРВИС
    printf '%s\n' "$AD_SERVICES" | awk -F'|' -v s="$1" '$1 == s { print $3; exit }'
}

# Путь списка ОТНОСИТЕЛЬНО каталога списков.
#
# Раскладка та же, что у нашего манифеста и у своих списков: доменные — в подкаталоге
# domains/, адресные — рядом. Вид списка обязан читаться из пути: `telegram.lst` доменный и
# `telegram.lst` адресный неразличимы, а интерфейсу надо положить их в РАЗНЫЕ поля правила.
# На схлопывании двух списков в один проект уже обжигался (I-011).
#
# Свой подкаталог ($AD_ID) — чтобы имена двух издателей не сталкивались: `news.lst` есть и
# там, и там, и это разные списки.
ad_rel() {  # СЕРВИС ВИД
    case "$2" in
        domains) printf '%s/domains/%s.lst' "$AD_ID" "$1" ;;
        *)       printf '%s/%s.lst' "$AD_ID" "$1" ;;
    esac
}

# Обратное преобразование: «СЕРВИС ВИД» из относительного пути, или код 1, если путь не наш.
# По ней ночное обновление понимает, у какого файла из спеки хозяин — этот издатель.
ad_service_of() {  # ОТН_ПУТЬ
    case "$1" in
        "$AD_ID"/domains/*.lst) _ad_s="${1#"$AD_ID"/domains/}"; _ad_k=domains ;;
        "$AD_ID"/*.lst)         _ad_s="${1#"$AD_ID"/}";         _ad_k=prefixes ;;
        *) return 1 ;;
    esac
    _ad_s="${_ad_s%.lst}"
    # Имя из спеки — чужой ввод: спека приезжает и архивом настроек. Тот же символьный
    # рубеж, что у имён своих списков.
    case "$_ad_s" in ''|*[!A-Za-z0-9_-]*) return 1 ;; esac
    printf '%s %s' "$_ad_s" "$_ad_k"
}

ad_url() {  # СЕРВИС
    printf '%s/%s/%s.srs' "$AD_BASE" "$(ad_tag)" "$1"
}

# Тег, которым набит лежащий на диске список. Пусто — отметки нет.
ad_stamp_get() {  # СЕРВИС ВИД
    [ -s "$AD_STAMP" ] || return 1
    awk -v s="$1" -v k="$2" '$1 == s && $2 == k { print $3; exit }' "$AD_STAMP"
}

# Записать отметку. Пишем ТОЛЬКО при изменении: файл лежит во флеш-разделе, и переписывать
# «то же самое» — износ ради ничего.
ad_stamp_put() {  # СЕРВИС ВИД ТЕГ
    [ "$(ad_stamp_get "$1" "$2")" = "$3" ] && return 0
    mkdir -p "$(dirname "$AD_STAMP")" 2>/dev/null || return 1
    { [ -f "$AD_STAMP" ] && awk -v s="$1" -v k="$2" '!($1 == s && $2 == k)' "$AD_STAMP"
      printf '%s %s %s\n' "$1" "$2" "$3"
    } > "$AD_STAMP.tmp" && mv "$AD_STAMP.tmp" "$AD_STAMP"
}

# Разложить набор на два наших списка ЧУЖИМИ РУКАМИ — командой движка, а не своим разбором.
#
# Формат двоичный (сжатый поток с деревом правил), и второй его разбор в оболочке был бы
# ровно тем расхождением, которое проект ловит стендами: движок читает набор при сборке
# правил, и «наш разбор понял иначе» означало бы список, которого движок не примет.
#
# Домены и подсети — в РАЗНЫЕ файлы: у нас это два разных вида списка (см. ad_rel).
#
# Коды возврата ПЕРЕДАЮТСЯ КАК ЕСТЬ, потому что они значат разное и человеку надо сказать
# разное: 2 — «набор понят, но списком не выразим» (такой список нам пока не подходит,
# и с прежним файлом всё в порядке), 1 — «это не набор sing-box или он испорчен» (то есть
# скачалось битое, и виноват путь до издателя, а не сам список).
# ТРЕТЬИМ ПОТОКОМ — СУЖЕНИЕ (`--meta-out`): `proto=udp` и `ports=50000-65535,19000-20000`,
# если набор сужен по протоколу или портам. Без этого потока движок отвергает такой набор
# кодом 2 — и правильно: отдать подсети Cloudflare без «только udp» значит увести в туннель
# весь TCP к 104.16.0.0/12. Сужение принадлежит КАНАЛУ, а не списку (steer, srs.c), поэтому
# оно кладётся рядом со списком подсетей файлом `.meta`, а в канал его переносит интерфейс
# (второй канал-спутник с `proto`/`ports`, см. ui/src/lib/model.ts, expandNarrow).
ad_split() {  # ФАЙЛ.SRS ФАЙЛ_ДОМЕНОВ ФАЙЛ_ПОДСЕТЕЙ ФАЙЛ_СУЖЕНИЯ
    AD_NOTE=""
    _ad_err="$1.err"
    "${STEER:-/usr/sbin/steer}" srs-read "$1" --out "$2" --prefixes-out "$3" --meta-out "$4" 2>"$_ad_err"
    _ad_rc=$?
    # Причина — первой строкой, без приставок «steer: » и «srs: »: строка уедет человеку в
    # интерфейс и в журнал, где ни имя команды, ни имя её подсистемы ничего не объясняют, а
    # место в сообщении занимают («такой список нам пока не подходит — srs: набор понят…»).
    AD_NOTE="$(head -1 "$_ad_err" 2>/dev/null | sed -e 's/^steer: //' -e 's/^srs: //')"
    rm -f "$_ad_err"
    return "$_ad_rc"
}

# Добыть сервис: скачать набор и разложить его. Пути к готовому кладёт в AD_DOM и AD_PFX.
#
# Коды: 0 — готово; 1 — не скачалось; 2 — набор понят, но списком не выразим; 3 — скачалось
# не то (не набор sing-box или испорчен). Три и два РАЗНЫЕ, и это требование: первое значит
# «такой список нам пока не подходит», второе — «скачалось битое». Слить их в один код
# значило бы обвинять сеть в том, чего она не делала.
ad_get() {  # СЕРВИС
    AD_DOM="$AD_TMP/$1.dom"
    AD_PFX="$AD_TMP/$1.pfx"
    AD_META="$AD_TMP/$1.meta"
    AD_NOTE=""
    # Один набор даёт ОБА вида списка, а зовут эту функцию по видам по очереди (ночное
    # обновление ходит сначала по адресным файлам спеки, потом по доменным). Без памяти
    # внутри прогона тот же файл качался бы дважды.
    [ -f "$AD_DOM" ] && [ -f "$AD_PFX" ] && return 0
    # Скачивание — общее с обеими половинами (fetch.sh): прямой адрес, обходные пути
    # GitHub, туннель роутера. Своя лестница здесь означала бы, что у аудитории, у которой
    # GitHub закрыт, второй издатель не работает вовсе.
    command -v download >/dev/null 2>&1 || return 1
    mkdir -p "$AD_TMP" 2>/dev/null || return 1
    _ad_srs="$AD_TMP/$1.srs"
    download "$(ad_url "$1")" "$_ad_srs" || { rm -f "$_ad_srs"; return 1; }
    # Разбор в «.new», а подмена — после успеха: половина разбора на месте готового списка
    # выглядела бы для памяти прогона как «уже приезжало».
    ad_split "$_ad_srs" "$AD_DOM.new" "$AD_PFX.new" "$AD_META.new"
    _ad_rc=$?
    rm -f "$_ad_srs"
    if [ "$_ad_rc" != 0 ]; then
        rm -f "$AD_DOM.new" "$AD_PFX.new" "$AD_META.new"
        [ "$_ad_rc" = 2 ] && return 2
        return 3
    fi
    mv "$AD_DOM.new" "$AD_DOM" && mv "$AD_PFX.new" "$AD_PFX" && mv "$AD_META.new" "$AD_META"
}

# То же, что ad_get, но ссылка задана снаружи, а не выведена из тега издателя.
#
# ЗАЧЕМ. Каталог списков (lists.json) научился называть наборы сам: у записи есть `url` и
# `format: "srs"`. Тогда «откуда качать» знает КАТАЛОГ, а не таблица в пакете, — и это
# главное, ради чего каталог заводился: добавить сервис можно правкой каталога, а не новой
# сборкой splify2. Разбор набора при этом тот же самый, и второй его экземпляр здесь
# означал бы, что коды отказов и их объяснения надо помнить в двух местах.
#
# Коды возврата и смысл AD_DOM/AD_PFX/AD_META — как у ad_get.
ad_get_url() {  # ССЫЛКА ИМЯ_ДЛЯ_ФАЙЛОВ
    AD_DOM="$AD_TMP/$2.dom"
    AD_PFX="$AD_TMP/$2.pfx"
    AD_META="$AD_TMP/$2.meta"
    AD_NOTE=""
    [ -f "$AD_DOM" ] && [ -f "$AD_PFX" ] && return 0
    command -v download >/dev/null 2>&1 || return 1
    mkdir -p "$AD_TMP" 2>/dev/null || return 1
    _agu_srs="$AD_TMP/$2.srs"
    download "$1" "$_agu_srs" || { rm -f "$_agu_srs"; return 1; }
    ad_split "$_agu_srs" "$AD_DOM.new" "$AD_PFX.new" "$AD_META.new"
    _agu_rc=$?
    rm -f "$_agu_srs"
    if [ "$_agu_rc" != 0 ]; then
        rm -f "$AD_DOM.new" "$AD_PFX.new" "$AD_META.new"
        [ "$_agu_rc" = 2 ] && return 2
        return 3
    fi
    mv "$AD_DOM.new" "$AD_DOM" && mv "$AD_PFX.new" "$AD_PFX" && mv "$AD_META.new" "$AD_META"
}

# Положить (или убрать) сужение рядом с УСТАНОВЛЕННЫМ списком подсетей: `<список без .lst>.meta`.
# Зовётся везде, где список подсетей встаёт на диск, — иначе один путь установки знал бы про
# сужение, а два других нет, и тот же набор то сужался бы, то нет. Пустое сужение — файла нет:
# его отсутствие и означает «канал без ограничений».
ad_meta_install() {  # ПУТЬ_СПИСКА_ПОДСЕТЕЙ
    _ami_dst="${1%.lst}.meta"
    if [ -s "${AD_META:-}" ]; then
        cp "$AD_META" "$_ami_dst.new.$$" && mv "$_ami_dst.new.$$" "$_ami_dst" || { rm -f "$_ami_dst.new.$$"; return 1; }
    else
        rm -f "$_ami_dst"
    fi
    return 0
}

# Сужение установленного списка подсетей — в JSON-объект `narrow` текущего объекта jshn.
# Ничего не добавляет, если файла нет: отсутствие ключа и есть «сужения нет».
ad_meta_json() {  # ПУТЬ_СПИСКА_ПОДСЕТЕЙ
    _amj="${1%.lst}.meta"
    [ -s "$_amj" ] || return 1
    _amj_proto="$(sed -n 's/^proto=//p' "$_amj" | head -1)"
    _amj_ports="$(sed -n 's/^ports=//p' "$_amj" | head -1)"
    [ -n "$_amj_proto$_amj_ports" ] || return 1
    json_add_object narrow
    [ -n "$_amj_proto" ] && json_add_string proto "$_amj_proto"
    json_add_array ports
    _amj_ifs="$IFS"; IFS=','
    for _amj_p in $_amj_ports; do [ -n "$_amj_p" ] && json_add_string "" "$_amj_p"; done
    IFS="$_amj_ifs"
    json_close_array
    json_close_object
    return 0
}

# Что вышло из набора для запрошенного вида. Печатает путь; код 1 — этого вида в наборе нет.
ad_out_of() {  # ВИД
    case "$1" in
        domains) [ -s "$AD_DOM" ] || return 1; printf '%s' "$AD_DOM" ;;
        *)       [ -s "$AD_PFX" ] || return 1; printf '%s' "$AD_PFX" ;;
    esac
}

# Как назвать вид человеку. Сообщения об отказе иначе говорили бы «нет prefixes».
ad_kind_ru() {  # ВИД
    [ "$1" = domains ] && printf 'доменов' || printf 'подсетей'
}

# ВСЯ ТАБЛИЦА РАЗОМ — по строке «сервис|виды через пробел|название».
#
# Нужна тому, кто показывает КАТАЛОГ, а не спрашивает про один сервис. Через ad_kinds и
# ad_title тот же перебор стоил бы двух awk на сервис, то есть полусотни запусков процессов
# на один ответ; на 880 МГц это секунда за открытие вкладки — ровно та цена, которую
# local_lists однажды уже платил и с которой его переписывали.
#
# И главное: разбор ТОТ ЖЕ, что у ad_kinds/ad_title, и живёт он здесь, рядом с таблицей.
# Второй разбор в объекте rpcd разошёлся бы с этим на первом же добавленном сервисе — а
# расходиться ему есть где: разделитель видов у нас запятая, а наружу они уходят списком.
#
# NF >= 3 отбрасывает пустые строки по краям значения: они есть всегда, потому что таблица
# записана многострочной кавычкой.
ad_each() {
    printf '%s\n' "$AD_SERVICES" |
        awk -F'|' 'NF >= 3 { gsub(/,/, " ", $2); print $1 "|" $2 "|" $3 }'
}

# Снять отметку. Зовётся при УДАЛЕНИИ списка: отметка говорит «лежащий файл набит этим
# тегом», и пережившая свой файл она — заявление о том, чего нет. Пока её никто не удалял,
# ложь была тихой (единственный читатель, ночное обновление, сверяет отметку вместе с
# наличием файла), но тихой она остаётся ровно до появления второго читателя — например
# каталога, который показывает версию скачанного.
#
# Файл переписывается, только если строка в нём была: флеш-раздел, и запись «того же
# самого» — износ ради ничего (тот же довод, что у ad_stamp_put).
ad_stamp_del() {  # СЕРВИС ВИД
    [ -s "$AD_STAMP" ] || return 0
    ad_stamp_get "$1" "$2" >/dev/null || return 0
    awk -v s="$1" -v k="$2" '!($1 == s && $2 == k)' "$AD_STAMP" > "$AD_STAMP.tmp" &&
        mv "$AD_STAMP.tmp" "$AD_STAMP"
}
