# Методы, которым разбор большого файла дороже их собственной работы.
#
# ЗАЧЕМ ЭТОТ ФАЙЛ ОТДЕЛЬНЫЙ, А НЕ ВЕТКИ В rpcd/splify2. Замерено на стенде (mipsel 24kc,
# 880 МГц, OpenWrt 25.12): busybox ash разбирает скрипт ЛЕНИВО, команду за командой, и
# `exec` в первой строке 250-килобайтного файла стоит 8 мс против 128 мс, если дойти до
# конца. У самого объекта splify2 разбор — 84 мс на вызов, ещё 24 мс уходит на преамбулу;
# итого 126 мс постоянной платы за КАЖДЫЙ вызов, при том что `steer status` считается 91 мс,
# а чтение счётчиков устройств — 30 мс. То есть больше половины работы роутера на опрос
# уходило не на ответ, а на повторный разбор одного и того же файла.
#
# Поэтому rpcd/splify2 в первых строках уводит сюда самые частые и самые дешёвые методы:
# маленький файл разбирается за единицы миллисекунд, а большой не разбирается вовсе. Здесь
# лежат круг опроса (зовётся раз в пять секунд, пока открыта страница) и чтение спеки (два
# вызова на каждое открытие, работы в них — прочитать файл).
#
# Что сюда НЕ надо переносить: всё, чья собственная работа дороже сотни миллисекунд, — там
# плата за разбор уже не заметна, а файл стал бы вторым складом методов.
#
# ЗАЧЕМ ОДИН МЕТОД ВМЕСТО ПЯТИ. Страница опрашивала status, dev_stats, engine_state, diag и
# net_info по кругу раз в пять секунд — пять запусков скрипта, 1220 мс на стенде. LuCI
# складывает вызовы одного такта в ОДИН запрос к ubus и выполняет их подряд, поэтому это ещё
# и ожидание на экране: числа обновлялись через 1,2-1,5 с после начала круга. Здесь один
# запуск: 15 мс платы вместо 630.
#
# Помощники живут здесь, а зовут их отсюда И из старых методов dev_stats/net_info — чтобы
# счёт остался в одном месте. Вторая реализация тех же чисел разошлась бы с первой молча.

. "${JSHN_SH:-/usr/share/libubox/jshn.sh}"

STEER="${STEER:-/usr/sbin/steer}"
SPEC="${SPEC:-/etc/steer/spec.json}"

# Содержимое документа, собранного jshn, — без внешних скобок.
#
# Нужно потому, что в одном ответе встречаются две вещи сразу: готовый JSON движка, который
# надо отдать ДОСЛОВНО (свой разбор означал бы вторую модель состояния в shell), и наши
# собственные поля, которым нужно экранирование jshn. Собрать всё одним jshn нельзя — он не
# умеет вставлять чужой готовый документ; печатать всё самим нельзя — имена устройств
# приходят от ядра. Отсюда шов: части собираются как обычно, а склеиваются печатью.
fast_inner() {
    _i="$1"
    _i="${_i#\{}"
    _i="${_i%\}}"
    printf '%s' "$_i"
}

# Счётчики САМИХ устройств, а не правил.
#
# Понадобилось потому, что счётчик канала в nft отвечает не на тот вопрос, который человек
# задаёт. Он стоит на правиле, ставящем метку, а метка ставится на пути «из локальной сети
# наружу»: обратный поток приходит с туннельного устройства и под `ip saddr <локальная сеть>`
# не подпадает. На живом роутере это выглядело как 4,3 МБ при скачанных 223 МБ — то есть
# 61 байт на пакет, одни подтверждения.
#
# rx у туннельного устройства — это то, что движок ОТДАЛ клиентам, то есть скачанное; tx —
# то, что он у них забрал. Для wireguard и amneziawg смысл тот же, считает ядро.
#
# Счётчики читаются ВСТРОЕННЫМ read, а не cat: это самый частый счёт из всех. Было четыре
# подстановки команды на устройство, то есть четыре fork+exec; на типовой коробке устройств
# десять-четырнадцать — сорок с лишним процессов на вызов. Замер в busybox sh на шести
# устройствах: 27,8 мс через cat против 1,8 мс через read, в пятнадцать раз.
fast_devices() {
    json_init
    json_add_object devices
    for _d in "${SYSNET_STATS:-/sys/class/net}"/*/statistics; do
        _n="${_d%/statistics}"; _n="${_n##*/}"
        [ "$_n" = lo ] && continue
        [ -d "$_d" ] || continue
        _rxb=0; _txb=0; _rxp=0; _txp=0
        read -r _rxb < "$_d/rx_bytes" 2>/dev/null || _rxb=0
        read -r _txb < "$_d/tx_bytes" 2>/dev/null || _txb=0
        read -r _rxp < "$_d/rx_packets" 2>/dev/null || _rxp=0
        read -r _txp < "$_d/tx_packets" 2>/dev/null || _txp=0
        json_add_object "$_n"
        json_add_string rx "$_rxb"
        json_add_string tx "$_txb"
        json_add_string rx_packets "$_rxp"
        json_add_string tx_packets "$_txp"
        json_close_object
    done
    json_close_object
    json_dump
}

# Что человек хочет знать о работе туннеля прямо сейчас.
#
# ВНЕШНЕГО IP здесь нет, и это не забывчивость. Чтобы узнать адрес, которым нас видят
# снаружи, запрос обязан уйти ЧЕРЕЗ туннель. А правило маршрутизации у steer выбирает
# таблицу по МЕТКЕ пакета, не по адресу источника: привязка запроса к адресу туннельного
# устройства маршрут не переключает, пакет уходит обычным путём и показывает адрес
# провайдера — то есть отвечает на другой вопрос, причём убедительно. Нужен SO_BINDTODEVICE,
# которого нет ни у uclient-fetch, ни у busybox wget.
#
# Поэтому поля нет вовсе, а не «есть, но пустое»: пустое поле человек читает как «не смогли
# узнать», хотя причина в том, что мы не умеем спросить.
fast_net() {
    # Время работы движка. procd отдаёт pid, а начало жизни процесса лежит в /proc: 22-е
    # поле stat — тики с загрузки системы. Спрашиваем именно так, а не «когда применили»:
    # применение туннель не перезапускает, и человек спрашивает про процесс.
    _up=0
    _pid="$(pgrep -f "$STEER vless" 2>/dev/null | head -1)"
    [ -z "$_pid" ] && _pid="$(pgrep -f 'steer vless' 2>/dev/null | head -1)"
    if [ -n "$_pid" ] && [ -r "/proc/$_pid/stat" ]; then
        _start="$(awk '{print $22}' "/proc/$_pid/stat" 2>/dev/null)"
        _btime="$(awk '{print $1}' /proc/uptime 2>/dev/null | cut -d. -f1)"
        _hz=100                      # CONFIG_HZ на всех целях OpenWrt, где мы собираемся
        [ -n "$_start" ] && [ -n "$_btime" ] && _up=$((_btime - _start / _hz))
        [ "$_up" -lt 0 ] && _up=0
    fi

    # Сколько устройств сейчас ходит В СЕТЬ — а не «через туннель», и это важная разница.
    #
    # Привязать соединение к выходу нечем: движок ставит метку ПАКЕТУ, а метку соединения
    # пишет с версии 1.2.x, но в conntrack по ней ещё надо уметь спросить. Считать здесь
    # «клиентов туннеля» значило бы выдать за них всех, кто вообще что-то открыл, — число
    # выглядело бы осмысленным и было бы неверным.
    _active=0
    _lan="$(uci -q get network.lan.ipaddr | cut -d. -f1-3)"
    if [ -r /proc/net/nf_conntrack ] && [ -n "$_lan" ]; then
        _active="$(awk -v pfx="src=$_lan." '
            index($0, pfx) { if (match($0, /src=[0-9.]+/)) seen[substr($0, RSTART+4, RLENGTH-4)] = 1 }
            END { n = 0; for (k in seen) n++; print n }' /proc/net/nf_conntrack 2>/dev/null)"
    fi
    [ -n "$_active" ] || _active=0
    printf '"uptime":%d,"active_clients":%d' "$_up" "$_active"
}

# Весь круг одним ответом.
#
# `diag` — по просьбе, а не всегда. Замер на стенде: `steer diag` стоит 201 мс против 91 мс
# у `steer status`, то есть проверки — самая дорогая часть круга, а меняются они реже всего:
# приговор перестаёт быть верным, когда что-то применили или туннель упал. Первое интерфейс
# знает сам (после apply он перечитывает круг немедленно), второе видно и без проверок — по
# полю `up` выхода в том же ответе. Поэтому решает СПРАШИВАЮЩИЙ: страница просит проверки на
# первом круге, после применения и раз в двадцать секунд.
#
# Журнала движка здесь нет намеренно. Его читает один-единственный экран — «Диагностика», — и
# `logread -l 300 | grep steer` стоит 76 мс на каждом круге. Экран, которому он нужен,
# спрашивает engine_state сам, пока открыт.
fast_live() {
    _input=''
    read -r _input 2>/dev/null
    _want_diag=0
    case "$_input" in
        *'"diag"'*) json_load "$_input" 2>/dev/null && {
                json_get_var _d diag
                case "$_d" in 1|true) _want_diag=1 ;; esac
            } ;;
    esac

    # Движок печатает JSON сам. Если он не отвечает — честная ошибка, а не пустой объект,
    # который интерфейс покажет как «всё в порядке».
    _st="$("$STEER" status --spec "$SPEC" 2>/dev/null)"
    case "$_st" in
        '{'*) ;;
        *) printf '{"ok":false,"error":"движок не ответил"}\n'; return 0 ;;
    esac

    _dev="$(fast_devices)"
    _netp="$(fast_net)"

    _diagp=''
    if [ "$_want_diag" = 1 ]; then
        # Ненулевой код возврата — НЕ повод для ошибки: движок возвращает 1, когда нашёл
        # поломку, и это ровно тот ответ, который надо показать. Судим по виду вывода.
        _dg="$("$STEER" diag --spec "$SPEC" 2>/dev/null)"
        case "$_dg" in
            '{'*) _diagp=",\"diag\":$_dg" ;;
            # Движок старее проверок. Отдельным полем, а не молчанием: интерфейс обязан
            # отличить «проверок не умеет» от «проверки не нашли ничего».
            *) _diagp=',"diag_old":true' ;;
        esac
    fi

    printf '{"status":%s,%s,"net":{%s}%s}\n' \
        "$_st" "$(fast_inner "$_dev")" "$_netp" "$_diagp"
}

# Спека, как она лежит на диске.
#
# Работы здесь — прочитать файл, а звалось это дважды на каждое открытие страницы (сама спека
# и снимок применённого): 246 мс из которых 250 — плата за разбор объекта. Отсюда и переезд.
fast_spec_get() {
    [ -s "$SPEC" ] && cat "$SPEC" || printf '{"schema":1,"outputs":{},"channels":[]}\n'
}

# Снимок спеки в момент последнего apply. Чего не применяли — то и применено: до первого
# apply честнее всего считать применённым сохранённое, иначе свежепоставленный пакет
# показывал бы неприменённые изменения, которых человек не делал.
fast_applied_get() {
    if [ -s "${APPLIED:-/etc/steer/spec.applied.json}" ]; then cat "${APPLIED:-/etc/steer/spec.applied.json}"
    elif [ -s "$SPEC" ]; then cat "$SPEC"
    else printf '{"schema":1,"outputs":{},"channels":[]}\n'
    fi
}
