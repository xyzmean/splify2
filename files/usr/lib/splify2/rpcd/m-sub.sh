#!/bin/sh
# Часть объекта rpcd splify2 — подключается диспетчером /usr/libexec/rpcd/splify2 по имени
# метода. ЗАЧЕМ ФАЙЛОВ НЕСКОЛЬКО. busybox ash разбирает файл целиком, и объект в 4500 строк
# стоил 110 мс разбора на КАЖДЫЙ вызов — при том, что сам ответ считается за 30-90 мс.
# Диспетчер разбирает только себя, общие помощники (common.sh) и группу вызванного метода.
# Переменные и швы для стендов объявлены в диспетчере и здесь доступны как есть.


# Этой группе нужно скачивание (fetch.sh): подключается здесь, а не каждым вызовом объекта.
need_fetch


# Где в uci лежит ссылка подписки. У первой — там же, где лежала всегда: перенос ключа
# означал бы, что после обновления пакета роутер забыл свою подписку.
sub_uci_key() {  # NAME FIELD(url|kind|title)
    if [ "$1" = main ]; then
        case "$2" in
            url)  printf 'splify2.main.sub_url' ;;
            kind) printf 'splify2.main.sub_kind' ;;
            *)    printf 'splify2.main.sub_title' ;;
        esac
    else
        printf 'splify2.sub_%s.%s' "$1" "$2"
    fi
}

sub_get() {  # NAME FIELD
    uci -q get "$(sub_uci_key "$1" "$2")"
}

sub_put() {  # NAME FIELD VALUE
    uci_file || return 1
    if [ "$1" = main ]; then
        uci -q get splify2.main >/dev/null 2>&1 || uci -q set splify2.main=splify2
    else
        uci -q get "splify2.sub_$1" >/dev/null 2>&1 || uci -q set "splify2.sub_$1=subscription"
    fi
    if [ -n "$3" ]; then uci -q set "$(sub_uci_key "$1" "$2")=$3"
    else uci -q delete "$(sub_uci_key "$1" "$2")" 2>/dev/null
    fi
}

# Вид источника: url — подписка, которую есть чем обновить, links — вставленные руками
# ссылки, none — источника нет.
sub_kind_of() {  # NAME
    _k="$(sub_get "$1" kind)"
    [ -n "$_k" ] || { [ -n "$(sub_get "$1" url)" ] && _k=url || _k=none; }
    printf '%s' "$_k"
}

# Занята ли подписка выходом. Удалять файл, на который ссылается выход, нельзя молча: движок
# читает его при подъёме, и правило осталось бы вести в туннель без единого узла.
sub_used_by() {  # PATH -> ЧИСЛО
    # Одно число и всегда. Прежняя запись (`grep -c ... || echo 0`) печатала ДВА нуля:
    # grep без совпадений и печатает 0, и выходит с ненулевым кодом, то есть срабатывала и
    # ветка `||`. Дальше это уезжало в json_add_int и роняло весь ответ — метод отдавал
    # пустоту, а интерфейс показывал «подписок нет».
    _u=0
    if [ -s "$SPEC" ]; then
        _u="$(jsonfilter -i "$SPEC" -e '@.outputs[*].sub_file' 2>/dev/null |
              grep -Fx -c -- "$1" 2>/dev/null)"
    fi
    case "${_u:-}" in ''|*[!0-9]*) _u=0 ;; esac
    printf '%s' "$_u"
}

hwid() {
    if [ -z "$HWID_CACHED" ]; then
        HWID_CACHED="$("$STEER" sub-hwid 2>/dev/null | jsonfilter -e '@.hwid' 2>/dev/null)"
        # Пустой ответ законен: «не из чего считать» — ни одного физического порта с
        # постоянным MAC. Признак «уже спрашивали» ставится отдельно, чтобы пустой ответ не
        # приводил к повторному запуску движка при каждом обращении.
        HWID_CACHED="${HWID_CACHED:--}"
    fi
    [ "$HWID_CACHED" = "-" ] && return 1
    printf '%s\n' "$HWID_CACHED"
}

# Остаток трафика в ответ. Ничего не запрашивает — только читает запомненное.
sub_userinfo_emit() {
    [ -s "$SUB_INFO" ] || return 1
    _up=""; _dn=""; _tot=""; _exp=""; _at=""; _at0=""; _used0=""
    while IFS='=' read -r _k _v; do
        case "$_k" in
            upload)   _up="$_v" ;;
            download) _dn="$_v" ;;
            total)    _tot="$_v" ;;
            expire)   _exp="$_v" ;;
            at)       _at="$_v" ;;
            at0)      _at0="$_v" ;;
            used0)    _used0="$_v" ;;
        esac
    done < "$SUB_INFO"
    json_add_object quota
    # Байты — СТРОКАМИ. 200 ГБ это 2·10^11, а json_add_int у jshn 32-битный: подписка на
    # 200 ГБ приехала бы обрезанным числом, и обзор показал бы остаток, которого нет. Тот же
    # довод, по которому строками отдаются счётчики dev_stats.
    json_add_string up "${_up:-}"
    json_add_string down "${_dn:-}"
    json_add_string total "${_tot:-}"
    # Срок и время опроса — unix-время, в int32 оно влезает до 2038 года.
    json_add_int expire "${_exp:-0}"
    json_add_int at "${_at:-0}"
    # Первое наблюдение периода: по нему и по нынешнему считается измеренный темп расхода.
    # Отдаётся вместе с числами, а не вычисляется здесь: делить и предсказывать — работа
    # интерфейса, а второе место, где то же число считается иначе, разойдётся с первым.
    json_add_int since "${_at0:-0}"
    json_add_string since_used "${_used0:-0}"
    json_close_object
    return 0
}

sub_fetch() {  # URL
    SUB_ANSWER="$("$STEER" sub-fetch "$1" --out "$SUB" --info "$SUB_INFO" 2>/dev/null)"
    case "$SUB_ANSWER" in '{'*) ;; *) return 1 ;; esac
    [ "$(sub_answer ok)" = "true" ]
}

# Поле ответа движка. Пустая строка, если поля нет: у отказа нет ни названия, ни остатка, и
# отличать «поля нет» от «поле пустое» вызывающему здесь не нужно.
sub_answer() {  # ПОЛЕ
    [ -n "$SUB_ANSWER" ] || return 1
    printf '%s' "$SUB_ANSWER" | jsonfilter -e "@.$1" 2>/dev/null
}

# Спросить у панели ОДИН остаток трафика, не подменяя подписку. Тоже вызовом движка: та же
# проба заголовков, та же арифметика периода, тот же файл.
sub_quota_ask() {  # URL
    "$STEER" sub-quota "$1" --info "$SUB_INFO" >/dev/null 2>&1 || return 1
    # Числа теперь лежат в файле — сказать остаётся только, нашлось ли в нём что-нибудь.
    [ -s "$SUB_INFO" ]
}

case "$2" in

    sub_set)
        # Две формы одного и того же: ссылка на подписку и сами ссылки vless://.
        #
        # Движок различия не знает вовсе — он читает файл, где по строке на узел, и сам
        # разбирает base64, если это base64 (см. sub.c). Подписка это ровно такой файл,
        # который кто-то другой держит на сервере. Значит «вставить одну vless://» — не
        # новая возможность движка, а отсутствовавшая строчка ЗДЕСЬ: прежний код отвечал
        # «ссылка должна начинаться с http://», то есть человек с одним сервером от
        # знакомого не мог сделать вообще ничего.
        #
        # Ссылок может быть несколько — по одной на строку или через пробел. Пишем как
        # есть: разбирать их здесь значило бы держать вторую реализацию разбора vless://
        # в shell, а у движка она уже есть и она же будет применена.
        read -r input
        json_load "$input" 2>/dev/null || fail "неразбираемый запрос"
        json_get_var url url
        json_get_var sub_name name
        json_get_var sub_title title
        [ -n "$url" ] || fail "не указана ссылка"
        sub_use "$sub_name"
        mkdir -p "$(dirname "$SUB")"
        case "$url" in
            https://*|http://*)
                # Одним вызовом движка: скачать, разобрать заголовки, посчитать пригодные
                # узлы и, если их нет ни одного, перезапросить у панели другой формат. Здесь
                # остаётся взять из ответа то, что нужно учёту.
                sub_fetch "$url" || fail "подписка не скачалась${SUB_ANSWER:+: $(sub_answer error)}"
                dev_warn="$(sub_answer warn)"
                # Ссылка из ответа, а не та, что просили: движок мог перезапросить подписку с
                # суффиксом /json, и обновлять в следующий раз надо по ТОЙ ссылке. Прежде это
                # решение дублировалось здесь строкой `url="${url%/}/json"` — то есть
                # оболочка повторяла правило, которое применил не она.
                _u="$(sub_answer url)"
                [ -n "$_u" ] && url="$_u"
                kind=url
                ;;
            vless://*)
                # Пробелы между ссылками превращаем в переводы строк: из однострочного
                # поля ввода многострочная вставка приезжает склеенной пробелами.
                printf '%s\n' "$url" | tr ' \t' '\n\n' | grep '^vless://' > "$SUB.tmp" \
                    || fail "в тексте нет ссылок vless://"
                [ -s "$SUB.tmp" ] || { rm -f "$SUB.tmp"; fail "в тексте нет ссылок vless://"; }
                mv "$SUB.tmp" "$SUB"
                kind=links
                ;;
            *) fail "нужна ссылка на подписку (http:// или https://) либо ссылка vless://" ;;
        esac
        # Новая подписка — новые узлы, значит клиента надо перечитать. Иначе туннель
        # продолжает работать по узлу, которого в подписке может уже не быть.
        #
        # Словом, а не пустым файлом: пустой затирал накопленное «instances» (подписку
        # задают как раз при заведении выхода, до применения), и новый туннель оставался
        # без экземпляра. Повод здесь именно params — набор выходов подписка не меняет.
        dirty_mark "$VLESS_DIRTY" params
        # Ссылка сохраняется, чтобы её можно было обновить одной кнопкой и показать
        # человеку, откуда взялись узлы. В uci, а не в спеке: спека — вход движка, и
        # URL ему не нужен ни для чего.
        #
        # Файл конфигурации создаётся здесь: пакет его не кладёт, а `uci set` в
        # несуществующий файл молча ничего не делает — ссылка «сохранялась» и пропадала,
        # причём sub_set отвечал ok. Тихая потеря настройки хуже отказа.
        #
        # Для vless:// сохраняется ВИД, а не текст: показывать человеку обратно ссылку с
        # его же ключом незачем, а обновлять её нечем — обновляют подписку, не ссылку.
        uci_file || fail "не удалось создать $UCI_SPLIFY2 — кончилось место?"
        [ "$kind" = url ] && sub_put "$SUB_NAME" url "$url" || sub_put "$SUB_NAME" url ""
        sub_put "$SUB_NAME" kind "$kind"
        # Название: что дал человек, иначе то, что назвала панель. Своё имя переписывать
        # ответом панели нельзя — человек его для того и вписал.
        [ -n "$sub_title" ] || sub_title="$(sub_answer title)"
        [ -n "$sub_title" ] && sub_put "$SUB_NAME" title "$sub_title"
        uci -q commit splify2
        json_init
        json_add_boolean ok 1
        json_add_string kind "$kind"
        json_add_string name "$SUB_NAME"
        json_add_string title "${sub_title:-}"
        json_add_string path "$SUB"
        json_add_int bytes "$(wc -c 2>/dev/null < "$SUB" || echo 0)"
        # Сколько узлов движок счёл ПРИГОДНЫМИ. Считал он их тем же кодом, которым читает
        # подписку при подъёме туннеля, — значит это то самое число, по которому туннель и
        # поднимется. Прежде оболочка добывала его отдельным запуском движка и регулярным
        # выражением по его JSON, поэтому в ответ оно не попадало вовсе.
        [ -n "$(sub_answer usable)" ] && json_add_int usable "$(sub_answer usable)"
        # Сказанное панелью про устройство — в ответе, а не в журнале: человек нажал кнопку
        # и должен узнать там же, что скачалась заглушка, а не гадать позже по туннелю,
        # который «настроен и не работает».
        [ -n "${dev_warn:-}" ] && json_add_string warn "$dev_warn"
        json_add_string hwid "$(hwid)"
        # Остаток трафика — в ответе на ту же кнопку, которая ходила к панели. Иначе обзор
        # показывал бы прежние числа до следующего опроса, а человек только что нажал
        # «Обновить» именно затем, чтобы увидеть свежие.
        sub_userinfo_emit
        json_dump
        ;;

    sub_info)
        # `|| input=''` ЗДЕСЬ БЫЛО ОШИБКОЙ. ubus отдаёт JSON без завершающего перевода
        # строки, и `read` в этом случае возвращает ненулевой код, УЖЕ ЗАПОЛНИВ переменную.
        # Ветка `||` затирала прочитанное: имя подписки не доезжало, метод отвечал по
        # первой, и на экране у второй подписки стояли чужие числа. Остальные методы
        # читают вход простым `read -r input` — по той же причине.
        input=''
        read -r input 2>/dev/null || true
        sub_use "$(jsonfilter -s "${input:-{\}}" -e '@.name' 2>/dev/null)"
        json_init
        json_add_string url "$(sub_get "$SUB_NAME" url)"
        json_add_string name "$SUB_NAME"
        # Вид источника: url — подписка, которую можно обновить; links — вставленные
        # руками ссылки, обновлять которые нечем. Интерфейсу это нужно, чтобы не
        # предлагать «Обновить» там, где обновление ничего не значит.
        json_add_string kind "$(sub_kind_of "$SUB_NAME")"
        json_add_string path "$SUB"
        # Идентификатор устройства отдаётся ВСЕГДА, а не только после скачивания: человек
        # заводит роутер в панели заранее, и найти там свою коробку он может только по этой
        # строке. Пустая строка значит «не из чего считать» — ни одного физического порта с
        # постоянным MAC; тогда заголовок не уходит вовсе, и об этом говорит sub_set.
        json_add_string hwid "$(hwid)"
        if [ -s "$SUB" ]; then
            json_add_boolean present 1
            json_add_int bytes "$(wc -c 2>/dev/null < "$SUB" || echo 0)"
            json_add_int mtime "$(date -r "$SUB" +%s 2>/dev/null || echo 0)"
        else
            json_add_boolean present 0
        fi
        # Остаток трафика — тот, что запомнен с последнего обращения к панели. Сюда он
        # приходит БЕЗ запроса наружу: sub_info спрашивают по кругу вместе с остальным
        # состоянием, и ходить с роутера к панели каждые пять секунд нельзя. Обновляет
        # его отдельный метод sub_quota, который зовут по нажатию и по устареванию.
        #
        # Поля `quota` нет вовсе — значит панель остатка не сообщала: ни разу, либо в
        # последний раз промолчала. Интерфейс к этому готов и говорит об этом прямо.
        sub_userinfo_emit
        json_dump
        ;;

    sub_quota)
        # Спросить у панели остаток трафика. Отдельный метод, а не поле sub_info, и это
        # разделение по цене: sub_info спрашивают в общем опросе каждые пять секунд, а
        # здесь уходит запрос в интернет с таймаутом в двадцать секунд.
        #
        # Подписку метод НЕ подменяет — ни файл, ни узлы, ни выбранный узел. Поэтому его
        # можно звать при открытии обзора, ничем не рискуя: единственное следствие —
        # переписанный файл остатка.
        # `|| input=''` ЗДЕСЬ БЫЛО ОШИБКОЙ. ubus отдаёт JSON без завершающего перевода
        # строки, и `read` в этом случае возвращает ненулевой код, УЖЕ ЗАПОЛНИВ переменную.
        # Ветка `||` затирала прочитанное: имя подписки не доезжало, метод отвечал по
        # первой, и на экране у второй подписки стояли чужие числа. Остальные методы
        # читают вход простым `read -r input` — по той же причине.
        input=''
        read -r input 2>/dev/null || true
        sub_use "$(jsonfilter -s "${input:-{\}}" -e '@.name' 2>/dev/null)"
        url="$(sub_get "$SUB_NAME" url)"
        kind="$(sub_kind_of "$SUB_NAME")"
        json_init
        json_add_boolean ok 1
        json_add_string kind "$kind"
        json_add_string name "$SUB_NAME"
        if [ "$kind" != url ] || [ -z "$url" ]; then
            # Спрашивать некого: узлы вставлены ссылками vless:// (или их нет вовсе), а
            # ссылка не панель — заголовков у неё не бывает. Отказом это не считаем:
            # человек ничего не сделал не так.
            json_add_boolean asked 0
            json_add_string why "узлы заданы ссылками vless:// — остаток брать негде: его сообщает панель подписки, а не ссылка"
        elif sub_quota_ask "$url"; then
            json_add_boolean asked 1
        else
            json_add_boolean asked 1
            # Две разные причины одним полем намеренно: интерфейс в обоих случаях говорит
            # одно и то же («панель не сообщает остаток»), а различить их можно в журнале.
            json_add_string why "панель не сообщила остаток трафика"
        fi
        sub_userinfo_emit
        json_dump
        ;;

    sub_list)
        # Все подписки роутера одним ответом. Именно списком, а не по одной: экран VLESS
        # показывает их вместе, и десять вызовов ради десяти строк — это десять запусков
        # shell на роутере с 64 МБ.
        #
        # Остаток здесь приходит ЗАПОМНЕННЫЙ, как и в sub_info: наружу за ним ходит
        # отдельный sub_quota, который зовут по нажатию.
        json_init
        json_add_array subs
        for n in $(sub_names); do
            sub_use "$n"
            json_add_object ""
            json_add_string name "$SUB_NAME"
            json_add_string title "$(sub_get "$SUB_NAME" title)"
            json_add_string url "$(sub_get "$SUB_NAME" url)"
            json_add_string kind "$(sub_kind_of "$SUB_NAME")"
            json_add_string path "$SUB"
            if [ -s "$SUB" ]; then
                json_add_boolean present 1
                json_add_int bytes "$(wc -c 2>/dev/null < "$SUB" || echo 0)"
                json_add_int mtime "$(date -r "$SUB" +%s 2>/dev/null || echo 0)"
            else
                json_add_boolean present 0
            fi
            # Сколько выходов на неё ссылается: по этому числу интерфейс говорит, чем
            # занята подписка, и отказывается удалять занятую.
            json_add_int used "$(sub_used_by "$SUB")"
            sub_userinfo_emit
            json_close_object
        done
        json_close_array
        json_add_string hwid "$(hwid)"
        json_dump
        ;;

    sub_del)
        # Удалить подписку целиком: файл узлов, запомненный остаток и ключи uci.
        #
        # ЗАНЯТУЮ НЕ УДАЛЯЕМ. Выход читает файл узлов при подъёме, и снос файла под живым
        # выходом — это правило, которое ведёт в туннель без единого узла: маршрутизация
        # выглядит настроенной, а трафик не идёт никуда. Поэтому отказ со словами, чем она
        # занята, а не молчаливое удаление.
        read -r input
        json_load "$input" 2>/dev/null || fail "неразбираемый запрос"
        json_get_var sub_name name
        [ -n "$sub_name" ] || fail "не указано имя подписки"
        sub_use "$sub_name"
        used="$(sub_used_by "$SUB")"
        [ "${used:-0}" = 0 ] || fail "подписка занята выходами: $used"
        rm -f "$SUB" "$SUB_INFO"
        if [ "$SUB_NAME" = main ]; then
            uci -q delete splify2.main.sub_url 2>/dev/null
            uci -q delete splify2.main.sub_kind 2>/dev/null
            uci -q delete splify2.main.sub_title 2>/dev/null
        else
            uci -q delete "splify2.sub_$SUB_NAME" 2>/dev/null
        fi
        uci -q commit splify2
        # Узлы сменились для всех, кто их читал, — клиента надо перечитать.
