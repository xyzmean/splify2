# Телеметрия: согласие и предпросмотр пакета. Контракт — docs/TELEMETRY.md.
#
# ЗДЕСЬ НЕТ ОТПРАВКИ, и это не забывчивость. Отправка живёт в отдельной команде, которую
# зовёт расписание: у вызова ubus свой срок жизни, а запрос наружу может висеть двадцать
# секунд. Объект отвечает на два вопроса — «согласен ли человек» и «что именно уедет».
#
# ПРЕДПРОСМОТР ОТДАЁТ ТЕ ЖЕ БАЙТЫ, ЧТО УЕДУТ. Не «примерный состав» и не перечень полей:
# сборщик один (telemetry.sh), метод зовёт его же, команда отправки зовёт его же. Это не
# вежливость, а второй стенд, работающий на живом роутере, — там, где утечка появляется от
# настройки, которой нет ни в одной песочнице: имя выхода с почтой внутри, панель с токеном
# в поддомене, вписанный руками резолвер.

case "$2" in

    telemetry_state)
        need_telemetry
        json_init
        _tl_c="$(tm_consent)"
        # ТРИ СОСТОЯНИЯ, а не два. «Не спрашивали» даёт интерфейсу право предложить один раз;
        # «отказался» не даёт никогда. Одним булевым полем их не различить, и тогда человек,
        # однажды сказавший «нет», получал бы предложение при каждом открытии.
        json_add_string consent "$_tl_c"
        json_add_boolean on "$([ "$_tl_c" = on ] && echo 1 || echo 0)"
        # Идентификатор показывается ТОЛЬКО если он уже посчитан: считать его ради ответа на
        # опрос страницы нельзя — это 600 000 проходов PBKDF2, секунды на слабом роутере.
        json_add_string id "$(uci -q get splify2.main.telemetry_id 2>/dev/null || true)"
        json_add_int last_at "$(tm_int "$(uci -q get splify2.main.telemetry_at 2>/dev/null || echo 0)")"
        json_add_string last_error "$(uci -q get splify2.main.telemetry_error 2>/dev/null || true)"
        json_dump
        ;;

    telemetry_set)
        need_telemetry
        read -r input 2>/dev/null
        [ -n "$input" ] || input='{}'
        json_load "$input" 2>/dev/null
        json_get_var on on 2>/dev/null
        case "${on:-}" in
            1|0|true|false) ;;
            *) fail "on: 1 — согласие, 0 — отказ" ;;
        esac
        uci_file
        case "$on" in
            1|true) uci -q set splify2.main.telemetry=1 ;;
            *)      uci -q set splify2.main.telemetry=0 ;;
        esac
        uci -q commit splify2
        # Отказ УБИРАЕТ идентификатор. Он выведен из MAC и посчитан один раз; оставить его
        # лежать после «нет» значило бы хранить готовый ключ к человеку, который сказал не
        # хранить. Согласие вернёт то же самое значение — счёт детерминирован.
        case "$on" in
            1|true) ;;
            *) uci -q delete splify2.main.telemetry_id 2>/dev/null
               uci -q delete splify2.main.telemetry_at 2>/dev/null
               uci -q delete splify2.main.telemetry_error 2>/dev/null
               uci -q commit splify2 ;;
        esac
        json_init; json_add_boolean ok 1; json_add_string consent "$(tm_consent)"; json_dump
        ;;

    telemetry_preview)
        need_telemetry
        # РАБОТАЕТ И ПРИ ВЫКЛЮЧЕННОЙ ТЕЛЕМЕТРИИ — иначе посмотреть, что уедет, можно было бы
        # только ПОСЛЕ согласия, то есть после того, как оно уже уехало.
        #
        # Пакет отдаётся ДОСЛОВНО тем, что напечатал сборщик: пересобрать его здесь через
        # jshn значило бы завести второй экземпляр той же сборки — ровно то, чего экран
        # «вот что уедет» и должен избежать. Тот же приём, что с `status` движка.
        if ! tm_build 2>/dev/null; then
            # Идентификатор считает движок, и на роутере без движка его нет вовсе. Отказ
            # громкий: пустой пакет человек прочёл бы как «ничего не уезжает».
            fail "пакет не собрался: идентификатор считает движок, а его нет или он не ответил"
        fi
        ;;

    *) fail "неизвестный метод" ;;
esac
