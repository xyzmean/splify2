#!/bin/sh
# Часть объекта rpcd splify2 — подключается диспетчером /usr/libexec/rpcd/splify2 по имени
# метода. ЗАЧЕМ ФАЙЛОВ НЕСКОЛЬКО. busybox ash разбирает файл целиком, и объект в 4500 строк
# стоил 110 мс разбора на КАЖДЫЙ вызов — при том, что сам ответ считается за 30-90 мс.
# Диспетчер разбирает только себя, общие помощники (common.sh) и группу вызванного метода.
# Переменные и швы для стендов объявлены в диспетчере и здесь доступны как есть.


# Помощники, нужные больше чем одной группе методов (и блоку list).


# Имя подписки в виде, годном и для имени файла, и для имени секции uci: латиница, цифры и
# подчёркивание. Дефис уходит тоже — uci имён с ним не принимает.
sub_slug() {
    printf '%s' "${1:-}" | tr -c 'A-Za-z0-9_' '_' | cut -c1-24 | sed 's/_*$//'
}

# Переставить SUB и SUB_INFO на нужную подписку. После вызова ВСЕ помощники (sub_fetch,
# sub_quota_ask, sub_userinfo_emit) работают с ней и ни о чём не знают — в этом и смысл:
# «какая подписка выбрана» решается в одном месте, а движку пути называются явно.
sub_use() {
    SUB_NAME="$(sub_slug "${1:-main}")"
    [ -n "$SUB_NAME" ] || SUB_NAME=main
    if [ "$SUB_NAME" = main ]; then
        SUB="${SUB_MAIN:-/etc/steer/sub.txt}"
    else
        SUB="$SUBS_DIR/$SUB_NAME.txt"
    fi
    SUB_INFO="${SUB%.txt}.userinfo"
}

# Все подписки роутера: первая и заведённые после неё. Перечень собирается из uci, а файлы
# лишь дополняют его — подписка, чей файл скачан, но ключ потерян, всё равно должна быть
# видна, иначе её нельзя ни обновить, ни удалить.
sub_names() {
    { [ -s "${SUB_MAIN:-/etc/steer/sub.txt}" ] || [ -n "$(uci -q get splify2.main.sub_url)" ] && echo main
      uci -q show splify2 2>/dev/null | sed -n "s/^splify2\.sub_\([A-Za-z0-9_]*\)=subscription$/\1/p"
      [ -d "$SUBS_DIR" ] && for _f in "$SUBS_DIR"/*.txt; do
          [ -e "$_f" ] || continue
          _b="${_f##*/}"; printf '%s\n' "${_b%.txt}"
      done
    } 2>/dev/null | awk 'NF && !seen[$0]++'
}

# Найти файл списка в манифесте по id И ВИДУ.
#
# Вид обязателен, и это не перестраховка: `categories` и `domain_lists` — разные
# пространства имён, и один id законно есть в обоих. У издателя так с `hodca` и `news`:
# адресный `hodca.lst` (5444 подсети) и доменный `domains/hodca.lst` (250 имён).
#
# Прежняя версия искала сначала в доменных, поэтому на запрос АДРЕСНОЙ категории скачивала
# доменный файл. Дальше канал читал домены как подсети, nft отвергал набор целиком — и
# вставала вся маршрутизация. Симптом «включил Хостинги и CDN, всё умерло» — отсюда.
manifest_file() {  # ID ВИД
    case "$2" in
        domains)  jsonfilter -i "$MANIFEST" -e "@.domain_lists[@.id='$1'].file" 2>/dev/null ;;
        prefixes) jsonfilter -i "$MANIFEST" -e "@.categories[@.id='$1'].file" 2>/dev/null ;;
        *)
            # Вид не указан — старый вызов. Тогда порядок обратный прежнему: адресные
            # первыми, потому что доменные лежат в своём подкаталоге и путь у них
            # различим, а вот адресная категория при промахе давала именно ту поломку.
            f="$(jsonfilter -i "$MANIFEST" -e "@.categories[@.id='$1'].file" 2>/dev/null)"
            [ -n "$f" ] || f="$(jsonfilter -i "$MANIFEST" -e "@.domain_lists[@.id='$1'].file" 2>/dev/null)"
            printf '%s' "$f"
            ;;
    esac
}

# Локальный путь списка: ПОВТОРЯЕТ путь у издателя, а не берёт от него имя файла.
#
# `basename` схлопывал `hodca.lst` и `domains/hodca.lst` в один локальный файл, и они
# затирали друг друга. То же правило продублировано в интерфейсе (pathFor) — разойдясь,
# они дадут «список скачан, а канал его не находит».
#
# ПУТЬ ПРИХОДИТ ИЗ ИНТЕРНЕТА, и проверяется он здесь, в единственном месте, где
# собирается. Поле `file` берётся из манифеста издателя (адрес которого вдобавок
# переопределяется через uci), а срезание ведущих слэшей от `..` не спасает: `file` вида
# `../../../etc/crontabs/root` давал запись файла ОТ ROOT куда угодно, содержимым с того
# же издателя, — крон, rc.local, сам этот скрипт. Тем же путём list_remove удалял любой
# файл: проверка «занят каналом» сравнивала уже подменённый путь.
#
# Для СВОИХ списков эта мысль додумана давно (см. list_put: «без этого ../../etc/passwd
# было бы законным именем»), а для чужих — нет, хотя чужой источник доверия заслуживает
# меньше. Правило одно на оба случая: имя может состоять только из безопасных символов,
# и ни одна его часть не может быть «..».
# Возвращает НЕНУЛЕВОЙ код на негодном пути, а не зовёт fail сама, и это важно: её
# вызывают в подстановке `$( )`, то есть в подоболочке, где exit из fail завершил бы
# только подоболочку. Ответ об ошибке ушёл бы в переменную вместо клиента, а скрипт
# спокойно продолжил бы работу с этой строкой как с путём. Поэтому решение принимает
# вызывающий: `dest="$(local_path "$f")" || fail ...`.
local_path() {  # ПУТЬ_У_ИЗДАТЕЛЯ
    rel="$(echo "$1" | sed 's|^/*||')"
    case "$rel" in
        ''|.|..|*/../*|*/..|../*|*//*) return 1 ;;
        *[!A-Za-z0-9_./-]*)            return 1 ;;
    esac
    printf '%s/%s' "$LISTS" "$rel"
}

# Доскачать списки, на которые ссылается спека, но которых нет на диске. Печатает
# предупреждения об НЕскачанном (по строке на файл), код возврата всегда 0: недоступность
# сервера издателя не должна отменять сохранение или применение целиком.
#
# ЗАЧЕМ ОБЩЕЙ ФУНКЦИЕЙ, а не в одной ветке. Движок умирает на отсутствующем файле, и делает
# это ДВАЖДЫ: при `apply --dry-run` в spec_set (проверка до записи) и при настоящем apply.
# Пока доскачивание стояло только в apply, выбор нового сервиса не сохранялся ВООБЩЕ:
# автосохранение вызывало spec_set, тот гонял dry-run, движок не находил файл и отвечал
# «/etc/steer/lists/cloudflare.lst: cannot read a channel's list», правка откатывалась, и
# человек видел ошибку там, где ничего не применял. Момент, когда файл обязан существовать, —
# любая проверка спеки движком, поэтому вызывать надо перед каждой.
fetch_missing_lists() {  # ПУТЬ_К_СПЕКЕ
    _spec="$1"
    [ -s "$MANIFEST" ] || return 0
    _base="$(jsonfilter -i "$MANIFEST" -e '@.base_url')"
    [ -n "$_base" ] || return 0
    for _f in $(jsonfilter -i "$_spec" \
        -e '@.channels[*].match.prefixes_files[*]' \
        -e '@.channels[*].match.domains_files[*]' 2>/dev/null | sort -u); do
        [ -s "$_f" ] && continue
        _rel="${_f#"$LISTS"/}"
        [ "$_rel" = "$_f" ] && continue     # файл вне каталога списков — не наш
        _dest="$(local_path "$_rel")" || continue
        mkdir -p "$(dirname "$_dest")"
        if download "$_base/$_rel" "$_dest"; then
            [ -n "$FETCH_NOTE" ] && echo "список $_rel: $FETCH_NOTE"
        else
            echo "список $_rel не скачался — канал, который на него ссылается, не поднимется${FETCH_NOTE:+ ($FETCH_NOTE)}"
        fi
    done
    return 0
}

# Включён ли фикс. Умолчание — включён: он нужен именно тем, кто ещё ничего не настроил.
zm_fix_on() {
    case "$(uci -q get splify2.main.zm_fix 2>/dev/null)" in
        0|off|no|false) return 1 ;;
        *) return 0 ;;
    esac
}

# uid пользователя nobody. Читается из /etc/passwd, а не зашивается: 65534 — соглашение, а
# не стандарт, и на роутере с чужой прошивкой оно может быть другим. Под этим же именем мы
# сами записываем `option user` в настройку прокси (см. doh_write), так что связь не
# случайная.
doh_uid() {
    _du="$(awk -F: '$1 == "nobody" { print $3; exit }' /etc/passwd 2>/dev/null)"
    case "${_du:-}" in ''|*[!0-9]*) printf '65534' ;; *) printf '%s' "$_du" ;; esac
}

doh_tunnel_on() {
    case "$(uci -q get splify2.main.doh_via_tunnel 2>/dev/null)" in
        1|on|yes|true|always) return 0 ;;
        *) return 1 ;;
    esac
}

# Устройство первого ПОДНЯТОГО выхода с устройством. Печатает «имя устройство».
#
# Именно поднятого, в отличие от zm_mark: маршрут через мёртвое устройство ядро не примет, а
# имя выхода мы показываем человеку — и назвать мёртвый выход значило бы обещать то, чего нет.
doh_out() {
    _do_st="$("$STEER" status --spec "$SPEC" 2>/dev/null)"
    [ -n "$_do_st" ] || return 1
    for _do_o in $("$STEER" outputs --spec "$SPEC" 2>/dev/null); do
        [ "$_do_o" = direct ] && continue
        case "$_do_o" in *[!a-zA-Z0-9_-]*) continue ;; esac
        [ "$(printf '%s' "$_do_st" | jsonfilter -e "@.outputs.$_do_o.up" 2>/dev/null)" = true ] ||
            continue
        _do_d="$(printf '%s' "$_do_st" | jsonfilter -e "@.outputs.$_do_o.device" 2>/dev/null)"
        [ -n "$_do_d" ] || continue
        printf '%s %s' "$_do_o" "$_do_d"
        return 0
    done
    return 1
}

# Снять всё своё: правило (сколько бы копий ни накопилось — `ip rule add` дубликаты не
# проверяет) и таблицу. Прежние версии ставили ещё и таблицу nftables — снимаем и её, иначе
# после обновления пакета она осталась бы висеть и метила бы трафик в никуда.
doh_rules_down() {
    _dd_n=0
    while [ "$_dd_n" -lt 32 ] && ip rule del pref "$DOH_RULE_PREF" 2>/dev/null; do
        _dd_n=$((_dd_n + 1))
    done
    ip route flush table "$DOH_RT" 2>/dev/null
    nft delete table inet splify2_doh 2>/dev/null
    return 0
}

doh_rules_sync() {
    if ! doh_tunnel_on || ! doh_installed; then
        doh_rules_down
        return 0
    fi
    _dr_pair="$(doh_out)" || { doh_rules_down; return 0; }
    _dr_dev="${_dr_pair#* }"
    doh_rules_down
    ip route replace default dev "$_dr_dev" table "$DOH_RT" 2>/dev/null ||
        { doh_rules_down; return 0; }
    _dr_uid="$(doh_uid)"
    ip rule add uidrange "$_dr_uid-$_dr_uid" table "$DOH_RT" pref "$DOH_RULE_PREF" 2>/dev/null ||
        { doh_rules_down; return 0; }
    return 0
}

uci_file() {
    [ -f "$UCI_SPLIFY2" ] && return 0
    mkdir -p "$(dirname "$UCI_SPLIFY2")" 2>/dev/null
    touch "$UCI_SPLIFY2" 2>/dev/null
    [ -f "$UCI_SPLIFY2" ]
}

# Признак НАКАПЛИВАЕТСЯ: слово в файле, по строке на повод. Пишет его сохранение, читает
# применение, а сохранений между двумя применениями бывает много — автосохранение зовёт
# spec_set после каждой правки, кнопку «Применить» нажимают один раз. Пока признак
# перезаписывался, ранний повод терялся поздним: завели выход vless (instances), тут же
# выбрали ему узел (params) — и apply сигналил экземпляру, которого ещё нет, вместо того
# чтобы пересобрать набор. Туннель при этом не поднимался до перезапуска движка, а в
# интерфейсе выглядел настроенным; ровно с этой жалобой пришёл пользователь (splicicd#20).
dirty_mark() {  # ФАЙЛ_ПРИЗНАКА СЛОВО
    grep -qx "$2" "$1" 2>/dev/null || echo "$2" >> "$1"
}

zapret_names() {  # ФАЙЛ_СПЕКИ
    [ -s "$1" ] || return 0
    "$STEER" outputs --kind zapret --spec "$1" 2>/dev/null | tr '\n' ' '
}

# Есть ли выход kind=zapret, у которого обработчик не жив. Приговор берётся у ДВИЖКА
# (`status`, поле `up`), а не считается здесь: он выводит номер очереди из метки и ищет
# процесс по нему, и повторять этот вывод в shell значило бы завести второй источник правды.
zapret_needs_instances() {
    _zn="$(zapret_names "$SPEC")"
    [ -n "$_zn" ] || return 1
    _zn_st="$("$STEER" status --spec "$SPEC" 2>/dev/null)"
    for _zn_o in $_zn; do
        [ "$(printf '%s' "$_zn_st" | jsonfilter -e "@.outputs.$_zn_o.up" 2>/dev/null)" = true ] ||
            return 0
    done
    return 1
}

# Устройства выходов перечисленных видов. Имена спрашиваются у движка флагом --devices, а не
# берутся как имена выходов: устройство выводится из имени выхода, НО может быть задано в спеке
# явно, и тогда «имя выхода» — это молча неверный список ровно там, где по нему настраивают
# фаервол. kind=direct отсеивается сам: устройства у него нет, и --devices ничего не печатает.
fw_devices_of() {  # ВИДЫ_ЧЕРЕЗ_ЗАПЯТУЮ
    for k in $(printf '%s' "$1" | tr ',' ' '); do
        "$STEER" outputs --kind "$k" --devices --spec "$SPEC" 2>/dev/null
    done | grep . | sort -u
}

# Поставить скачанный пакет, не оставив роутер без того, что работало.
#
# Порядок здесь — не стиль, а разница между «установка не удалась» и «роутер больше не
# маршрутизирует». `apk del` запускает pre-deinstall снимаемого пакета, а тот
# останавливает и ОТКЛЮЧАЕТ сервис; stop_service движка сносит таблицу nft и вычищает
# ip rule. Пока удаление стояло первым, любой отказ apk add — не та архитектура,
# кончилось место, битый файл — оставлял роутер без движка, без правил и со снятым
# автозапуском, то есть перезагрузка уже не спасала. И всё это в ответ на «обновить»,
# то есть на действие, которое ничего ломать не собиралось (I-049).
#
# Поэтому сначала ставим. Обновление в пределах одного варианта — самый частый путь —
# при этом вообще не проходит через удаление: apk заменяет пакет на месте.
#
# --force-overwrite нужен потому, что расширенный и базовый пакеты движка владеют одним
# /usr/sbin/steer. Но конфликт ИМЁН пакетов (provides/conflicts) он не снимает — вот на
# нём удаление и остаётся законным, уже вторым шагом.
#
# Возвращает код apk; заполняет PKG_OUT (вывод apk) и PKG_REMOVED (снимался ли пакет).
# Поставить локальный файл тем менеджером, который есть. --force-overwrite понимают оба
# и нужен обоим (см. выше про общий /usr/sbin/steer); --allow-untrusted — только apk:
# у opkg проверки подписи для локального файла нет вовсе, и такого флага он не знает.
#
# У opkg есть беда, которой нет у apk: зависимости локального файла он ищет в СПИСКАХ
# ПАКЕТОВ, а на свежей прошивке их нет — списки не переживают перезагрузку. Тогда установка
# падает на «cannot find dependency ip-full for steer», хотя пакет скачан и лежит рядом.
# Списки обновляются и установка повторяется ровно один раз: если зависимости нет и после
# обновления, дело не в списках.
pkg_add_file() {  # ФАЙЛ
    if [ "$PM" = apk ]; then
        apk add --allow-untrusted --force-overwrite "$1" 2>&1
        return $?
    fi
    _pa_out="$(opkg install --force-overwrite "$1" 2>&1)"
    _pa_rc=$?
    if [ "$_pa_rc" != 0 ]; then
        case "$_pa_out" in
            *"cannot find dependency"*|*"unresolved"*|*"incompatible with the architectures"*)
                opkg update >/dev/null 2>&1
                _pa_out="$(opkg install --force-overwrite "$1" 2>&1)
списки пакетов были пусты — обновил их (opkg update) и повторил"
                _pa_rc=$?
                ;;
        esac
    fi
    printf '%s' "$_pa_out"
    return $_pa_rc
}

pkg_del() {  # ИМЯ
    if [ "$PM" = apk ]; then apk del "$1" >/dev/null 2>&1
    else opkg remove "$1" >/dev/null 2>&1
    fi
}

# Путь своего списка. Доменные лежат в подкаталоге, адресные — рядом, как у издателя.
custom_path() {  # ИМЯ ВИД
    case "$2" in
        domains) printf '%s/%s/domains/%s.lst' "$LISTS" "$CUSTOM" "$1" ;;
        *)       printf '%s/%s/%s.lst'         "$LISTS" "$CUSTOM" "$1" ;;
    esac
}

# ОТКУДА ВЗЯЛСЯ СВОЙ СПИСОК — рядом с ним, отдельным файлом.
#
# ЗАЧЕМ. Завести список можно тремя способами: набрать записи руками, выбрать файл, дать
# ссылку. Изменить его после этого было НЕЧЕМ: единственная кнопка рядом со списком —
# удалить и завести заново. А правка нужна ровно по тому же разделению, каким список
# завели: у файла меняют файл, у ссылки — ссылку, у набранного руками — сами записи. Не зная
# происхождения, интерфейс вынужден предлагать все три способа всем, и человек, положивший
# файл на 20 тысяч строк, получает предложение отредактировать его в текстовом поле.
#
# ПОЧЕМУ ФАЙЛОМ, А НЕ В uci. Список — это файл на диске, и его происхождение обязано
# лежать там же: список, положенный руками в /etc/steer/lists/custom, и его запись в uci
# разошлись бы при первом же `rm`. Плюс так происхождение переживает то же, что и сам
# список, и теряется вместе с ним, а не отдельно.
#
# ФОРМАТ — «ключ=значение» по строке, как у SUB_INFO: разбирается тем же `while read`, а
# вторая реализация разбора JSON в оболочке не нужна ни здесь, ни там.
#
# Расширение НЕ «.lst»: `local_lists` и сборка архива обходят каталог по `*.lst`, и файл
# происхождения, попавший в эту выборку, стал бы виден как ещё один список — с записями
# вида «source=file», которые санитайзер отбросит все до одной.
custom_meta_path() {  # ИМЯ ВИД
    printf '%s.src' "$(custom_path "$1" "$2")"
}

# Чужой текст на входе движка. Проверяется ЗДЕСЬ, а не в интерфейсе: интерфейс можно
# обойти, а последствие непроверенного списка молчаливое — спека применится, nft отвергнет
# набор, и канал останется пустым без единого слова о причине.
#
# Что делаем с почти-верным: одиночный адрес дополняем до /32 (человек пишет 1.2.3.4, имея
# в виду именно его), домены приводим к нижнему регистру и снимаем ведущее «*.» — то есть
# принимаем распространённые записи вместо того, чтобы отвергать их из принципа. Что
# отбросили — считаем и говорим числом: молчаливая потеря строк здесь была бы худшим из
# возможных поведений.
sanitize_list() {  # ВИД ВХОД ВЫХОД ФАЙЛ_СЧЁТЧИКОВ
    awk -v kind="$1" -v stat="$4" '
    # Октет 0..255 и длина префикса 0..32 — то, чего не выражает регулярное выражение.
    function ip_ok(a,   p, i) {
        split(a, p, ".")
        for (i = 1; i <= 4; i++) if (p[i] + 0 > 255 || p[i] == "" || length(p[i]) > 3) return 0
        return 1
    }
    function cidr_ok(a,   q) {
        split(a, q, "/")
        if (!ip_ok(q[1])) return 0
        return (q[2] + 0 <= 32 && q[2] != "" && length(q[2]) <= 2)
    }
    {
        line = $0
        sub(/\r$/, "", line)
        sub(/#.*/, "", line)
        gsub(/^[ \t]+|[ \t]+$/, "", line)
        if (line == "") next
        if (kind == "prefixes") {
            # Проверяются и ДИАПАЗОНЫ значений, а не только форма. Раньше «10.0.0.256» и
            # «192.168.0.0/40» проходили как верные, движок их тоже пропускает (он смотрит
            # только на цифры, точки и слэши), и отвергал их уже nft — целиком весь
            # ruleset одной транзакцией, сообщением про синтаксис nft. Человек при этом
            # видел «Список «x»: строк 12» и не знал, какая строка виновата.
            if (line ~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$/)         { if (ip_ok(line))       { print line "/32"; ok++; next } bad++; next }
            if (line ~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+\/[0-9]+$/) { if (cidr_ok(line))     { print line;       ok++; next } bad++; next }
            bad++; next
        }
        line = tolower(line)
        sub(/^\*\./, "", line)
        sub(/\.$/, "", line)
        if (line ~ /^[a-z0-9]([a-z0-9._-]*[a-z0-9])?$/ && line ~ /\./) { print line; ok++; next }
        bad++
    }
    END { printf "%d %d\n", ok+0, bad+0 > stat }
    ' "$2" > "$3"
}

# Строка, которая станет словом shell или частью имени: имена устройств, выходов и
# каналов. Проверяется потому, что импорт делает спеку МЕНЕЕ доверенным источником, а на
# том конце её строки попадают в командные строки: движок подставляет lan_device в
# popen("ip -4 -o addr show ...") без фильтрации (I-003), а этот самый скрипт подставляет
# имена выходов vless в `ubus call service signal {"instance":"vless_$o"}`, а имена их
# устройств — в настройку зоны фаервола (fw_sync). Пока спеку писал только root через
# spec_set, это была теоретическая
# слабость; принятый файл делает её входом.
backup_safe_word() {  # СТРОКА
    case "$1" in
        '') return 1 ;;
        *[!A-Za-z0-9_.:@-]*) return 1 ;;
    esac
    return 0
}

# Собрать архив в stdout.
backup_build() {
    printf 'splify2-backup %s\n' "$BACKUP_FORMAT"
    printf '# Настройки splify2: спека, подписка, свои списки, поля uci.\n'
    printf '# Восстанавливается тем же интерфейсом. Зеркал категорий издателя здесь нет:\n'
    printf '# роутер скачивает их сам, они одинаковы у всех и обновляются по расписанию.\n'
    printf '# ВНИМАНИЕ: внутри ссылки vless:// с ключами. Файл секретен, как пароль.\n'
    if [ -s "$SPEC" ]; then
        printf '[spec]\n'
        # awk 1, а не cat: файл без завершающего перевода строки склеил бы свою последнюю
        # строку с заголовком следующего раздела.
        awk 1 "$SPEC"
    fi
    if [ -s "$SUB" ]; then
        printf '[sub]\n'
        awk 1 "$SUB"
    fi
    for f in "$LISTS/$CUSTOM"/*.lst "$LISTS/$CUSTOM"/domains/*.lst; do
        [ -f "$f" ] || continue
        n="${f##*/}"; n="${n%.lst}"
        # Имя проверяется и на выходе: в каталог мог положить файл не интерфейс, а руки,
        # и тогда заголовок раздела получился бы таким, какой сам же разборщик отвергнет.
        case "$n" in ''|*[!A-Za-z0-9_-]*) continue ;; esac
        case "$f" in *"/$CUSTOM/domains/"*) printf '[list domains %s]\n' "$n" ;;
                     *) printf '[list prefixes %s]\n' "$n" ;; esac
        awk 1 "$f"
    done
    printf '[options]\n'
    for k in sub_url sub_kind wizard; do
        v="$(uci -q get "splify2.main.$k")"
        [ -n "$v" ] && printf '%s=%s\n' "$k" "$v"
    done
    return 0
}
