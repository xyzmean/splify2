#!/bin/sh
# Часть объекта rpcd splify2 — подключается диспетчером /usr/libexec/rpcd/splify2 по имени
# метода. ЗАЧЕМ ФАЙЛОВ НЕСКОЛЬКО. busybox ash разбирает файл целиком, и объект в 4500 строк
# стоил 110 мс разбора на КАЖДЫЙ вызов — при том, что сам ответ считается за 30-90 мс.
# Диспетчер разбирает только себя, общие помощники (common.sh) и группу вызванного метода.
# Переменные и швы для стендов объявлены в диспетчере и здесь доступны как есть.


# Этой группе нужно скачивание (fetch.sh): подключается здесь, а не каждым вызовом объекта.
need_fetch


# Метка и таблица выхода, через который уводить. Первый поднятый выход со своей меткой:
# другого выбора здесь нет и не нужно — фикс имеет смысл там, где напрямую не дойти.
zm_mark() {  # печатает МЕТКУ
    _zm_st="$("$STEER" status --spec "$SPEC" 2>/dev/null)"
    [ -n "$_zm_st" ] || return 1
    for _zm_o in $("$STEER" outputs --spec "$SPEC" 2>/dev/null); do
        [ "$_zm_o" = direct ] && continue
        case "$_zm_o" in *[!a-zA-Z0-9_-]*) continue ;; esac
        _zm_m="$(printf '%s' "$_zm_st" | jsonfilter -e "@.outputs.$_zm_o.mark" 2>/dev/null)"
        case "${_zm_m:-}" in 0x*) printf '%s' "$_zm_m"; return 0 ;; esac
    done
    return 1
}

# Убрать канал, который дописывала версия 1.2.3. Тогда фикс жил правилом в спеке — оно
# касалось клиентов и висело у человека в правилах; теперь его там быть не должно, и молча
# оставить его значило бы, что обновление не исправило ровно то, ради чего вышло.
zm_drop_channel() {
    jsonfilter -i "$SPEC" -e '@.channels[*].name' 2>/dev/null | grep -qx "$ZM_CHANNEL" || return 1
    # Ищем ровно ту форму, которую писала 1.2.3, — мы её и сочиняли. Три случая: канал в
    # середине, последним и единственным; иначе после удаления останется висячая запятая, и
    # спека перестанет быть JSON.
    _zd_re='{"name":"'"$ZM_CHANNEL"'","match":{"prefixes_files":\["[^"]*"\]},"out":"[^"]*"}'
    sed -e "s|$_zd_re,||" -e "s|,$_zd_re||" -e "s|$_zd_re||" "$SPEC" > "$SPEC.zm" 2>/dev/null
    if [ -s "$SPEC.zm" ] && "$STEER" apply --dry-run --spec "$SPEC.zm" >/dev/null 2>&1 &&
       ! jsonfilter -i "$SPEC.zm" -e '@.channels[*].name' 2>/dev/null | grep -qx "$ZM_CHANNEL"; then
        mv "$SPEC.zm" "$SPEC"
        return 0
    fi
    rm -f "$SPEC.zm"
    return 1
}

# Собрать (или снять) таблицу с адресами GitHub.
zm_rules_sync() {
    if ! zm_fix_on || [ ! -s "$ZM_LIST" ]; then
        nft delete table inet "$ZM_TABLE" 2>/dev/null
        return 0
    fi
    _zm_mark="$(zm_mark)" || { nft delete table inet "$ZM_TABLE" 2>/dev/null; return 0; }
    _zm_el="$(grep -oE '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+(/[0-9]+)?' "$ZM_LIST" | tr '\n' ',' | sed 's/,$//')"
    [ -n "$_zm_el" ] || { nft delete table inet "$ZM_TABLE" 2>/dev/null; return 0; }
    nft delete table inet "$ZM_TABLE" 2>/dev/null
    # `type route hook output` — метка ставится ДО решения о маршруте, иначе ядро не станет
    # его пересматривать и пакет уйдёт прежним путём. Маска — та же, что у движка: слово
    # метки общее, и затирать чужие биты нельзя.
    nft -f - <<NFT 2>/dev/null
table inet $ZM_TABLE {
    set gh {
        type ipv4_addr
        flags interval
        auto-merge
        elements = { $_zm_el }
    }
    chain out {
        type route hook output priority mangle + 1; policy accept;
        ip daddr @gh meta mark set mark and 0xf00fffff or $_zm_mark ct mark set mark counter
    }
}
NFT
}

dirty_has() {  # ФАЙЛ_ПРИЗНАКА СЛОВО
    grep -qx "$2" "$1" 2>/dev/null
}

# Отпечаток того, от чего зависит выбор узла. Меняется он — надо перезапустить клиента,
# не меняется — трогать туннель нельзя: перезапуск роняет все соединения через него, а
# заново выбранный «первый рабочий» может оказаться другим узлом. Правка списка домены
# не должна менять выходной адрес.
vless_fingerprint() {  # ФАЙЛ_СПЕКИ
    f="$1"
    [ -s "$f" ] || { echo none; return; }
    for o in $("$STEER" outputs --kind vless --spec "$f" 2>/dev/null); do
        printf '%s:%s:%s\n' "$o" \
            "$(jsonfilter -i "$f" -e "@.outputs.$o.sub_file" 2>/dev/null)" \
            "$(jsonfilter -i "$f" -e "@.outputs.$o.node" 2>/dev/null)"
    done | md5sum | awk '{print $1}'
}

# Обфускатор читает адрес сервера и локальный порт ОДИН РАЗ при старте — как клиент vless
# читает узел. Правка любого другого поля выхода (устройства, on_fail, списки каналов) его
# не касается, и трогать процесс из-за неё нельзя: перезапуск рвёт сессию, а с ней и
# рукопожатие WireGuard поверх неё.
obfs_fingerprint() {  # ФАЙЛ_СПЕКИ
    f="$1"
    [ -s "$f" ] || { echo none; return; }
    for o in $("$STEER" outputs --obfs --spec "$f" 2>/dev/null); do
        printf '%s:%s:%s\n' "$o" \
            "$(jsonfilter -i "$f" -e "@.outputs.$o.obfs.server" 2>/dev/null)" \
            "$(jsonfilter -i "$f" -e "@.outputs.$o.obfs.listen" 2>/dev/null)"
    done | md5sum | awk '{print $1}'
}

obfs_names() {  # ФАЙЛ_СПЕКИ
    [ -s "$1" ] || return 0
    "$STEER" outputs --obfs --spec "$1" 2>/dev/null | tr '\n' ' '
}

# То же для vless, и по той же причине, что у обфускации: смена узла лечится сигналом
# живому экземпляру, а появление НОВОГО выхода — нет, потому что экземпляра ещё нет.
vless_names() {  # ФАЙЛ_СПЕКИ
    [ -s "$1" ] || return 0
    "$STEER" outputs --kind vless --spec "$1" 2>/dev/null | tr '\n' ' '
}

fw_note() {  # СТРОКА
    mkdir -p "$(dirname "$FW_OWNED")" 2>/dev/null
    grep -qxF "$1" "$FW_OWNED" 2>/dev/null || printf '%s\n' "$1" >> "$FW_OWNED"
}

fw_noted() { grep -qxF "$1" "$FW_OWNED" 2>/dev/null; }

fw_unnote() {  # СТРОКА
    [ -f "$FW_OWNED" ] || return 0
    grep -vxF "$1" "$FW_OWNED" > "$FW_OWNED.tmp" 2>/dev/null
    mv "$FW_OWNED.tmp" "$FW_OWNED" 2>/dev/null || rm -f "$FW_OWNED.tmp"
}

zone_index() {  # ИМЯ_ЗОНЫ
    uci show firewall 2>/dev/null | sed -n "s/^firewall\.@zone\[\([0-9]*\)\]\.name='$1'$/\1/p" | head -1
}

# В какой зоне уже лежит это устройство. Пусто — ни в какой.
#
# Нужно потому, что устройство в ДВУХ зонах fw4 не прощает, а устройство выхода kind=interface
# человек мог назначить в зону сам — страница интерфейса в LuCI это предлагает. Молча добавив
# его во вторую, мы получили бы отказ перезагрузки правил и неработающий фаервол целиком.
fw_zone_of_device() {  # ИМЯ_УСТРОЙСТВА
    uci show firewall 2>/dev/null |
        sed -n "s/^firewall\.@zone\[\([0-9]*\)\]\.device=.*'\?$1'\?.*$/\1/p" | head -1
}

fw_zone_devices() {  # ИНДЕКС
    uci -q get "firewall.@zone[$1].device" 2>/dev/null | tr ' ' '\n' | grep . | sort -u
}

# Принять существующую зону за свою, если отличить её от нашей нельзя.
#
# Зона steer_vless заводилась и прежними версиями, когда расписок ещё не было. Без принятия она
# навсегда осталась бы «чужой» и перестала бы убираться вместе с последним туннельным выходом —
# ровно та накопительная беда, от которой и просили избавить.
#
# Условие строгое: в зоне нет НИ ОДНОГО устройства, которого мы не завели бы сами. Есть
# постороннее — значит зону правили руками, и она чужая: дополняем, но не чистим и не удаляем.
fw_adopt_if_ours() {  # ЗОНА ИНДЕКС СПИСОК_НУЖНЫХ
    fw_noted "zone $1" && return 0
    for d in $(fw_zone_devices "$2"); do
        printf '%s\n' "$3" | grep -qx "$d" || return 1
    done
    fw_note "zone $1"
    for d in $(fw_zone_devices "$2"); do fw_note "dev $1 $d"; done
    return 0
}

# Одна зона: создать, дополнить, убрать ушедшее, удалить саму зону, когда её устройств не
# осталось. Удаляет ТОЛЬКО записанное за нами. Печатает, что сделала; код 1 — изменения были.
fw_zone_sync() {  # ЗОНА ВИДЫ MASQ
    _z="$1"; _kinds="$2"; _masq="$3"
    want="$(fw_devices_of "$_kinds")"
    idx="$(zone_index "$_z")"
    changed=0
    msg=""
    skipped=""

    # Устройства, которым зона УЖЕ назначена человеком, отсеиваются здесь — до решения
    # создавать нашу. Иначе на роутере, где все туннели человек развёл по своим зонам,
    # оставалась бы пустая зона с пробросом в неё: мусор, который выглядит как недоделка.
    #
    # Отсев именно тут, а не при добавлении: там мы бы уже создали зону, а отменять
    # созданное — лишний путь, на котором легко оставить половину.
    if [ -n "$want" ]; then
        _keep=""
        for d in $want; do
            other="$(fw_zone_of_device "$d")"
            if [ -n "$other" ] && { [ -z "$idx" ] || [ "$other" != "$idx" ]; }; then
                skipped="$skipped $d"
                continue
            fi
            _keep="$_keep$d
"
        done
        want="$(printf '%s' "$_keep" | grep . | sort -u)"
    fi
    # Говорится СРАЗУ, а не в конце: после отсева зона может оказаться ненужной вовсе, и
    # тогда работа кончится раньше, а человек так и не узнает, почему его туннель в нашу
    # зону не попал. Молчание здесь читается как «сделали и не помогло».
    [ -n "$skipped" ] &&
        echo "устройства$skipped уже в своих зонах фаервола — оставлены как есть"

    if [ -z "$want" ]; then
        [ -n "$idx" ] || { fw_unnote "zone $_z"; return 0; }
        fw_adopt_if_ours "$_z" "$idx" "" || return 0
        # Сначала правила проброса на зону, потом сама зона: удалив зону первой, мы оставили бы
        # forwarding, ссылающийся в пустоту, и fw4 отказался бы перезагружаться.
        while :; do
            f="$(uci show firewall 2>/dev/null | sed -n "s/^firewall\.\(@forwarding\[[0-9]*\]\)\.dest='$_z'$/\1/p" | head -1)"
            [ -n "$f" ] || break
            uci -q delete "firewall.$f" || break
            changed=1
        done
        for d in $(fw_zone_devices "$idx"); do fw_unnote "dev $_z $d"; done
        uci -q delete "firewall.@zone[$idx]" && changed=1
        if [ "$changed" = 1 ]; then
            uci -q commit firewall
            fw_unnote "zone $_z"
            echo "зона $_z удалена — выходов с такими устройствами в спеке больше нет"
        fi
        return "$changed"
    fi

    if [ -z "$idx" ]; then
        uci -q add firewall zone >/dev/null
        uci -q set firewall.@zone[-1].name="$_z"
        # input REJECT: зона нужна для транзита, а не для доступа к самому роутеру со стороны
        # туннеля. forward ACCEPT — иначе смысла в ней нет.
        uci -q set firewall.@zone[-1].input='REJECT'
        uci -q set firewall.@zone[-1].output='ACCEPT'
        uci -q set firewall.@zone[-1].forward='ACCEPT'
        uci -q set firewall.@zone[-1].masq="$_masq"
        uci -q set firewall.@zone[-1].mtu_fix='1'
        idx="$(zone_index "$_z")"
        [ -n "$idx" ] || return 0
        fw_note "zone $_z"
        changed=1
        msg="зона $_z создана (NAT: $_masq)"
    else
        fw_adopt_if_ours "$_z" "$idx" "$want" || true
    fi

    have="$(fw_zone_devices "$idx")"
    added=""
    for d in $want; do
        printf '%s\n' "$have" | grep -qx "$d" && continue
        uci -q add_list "firewall.@zone[$idx].device"="$d"
        fw_note "dev $_z $d"
        added="$added $d"
        changed=1
    done

    # Убираем только записанное за нами: устройство, положенное в эту зону руками, спека не
    # описывает и описывать не должна — вынести его значило бы поломать чужую настройку молча.
    removed=""
    for d in $have; do
        printf '%s\n' "$want" | grep -qx "$d" && continue
        fw_noted "dev $_z $d" || continue
        uci -q del_list "firewall.@zone[$idx].device"="$d"
        fw_unnote "dev $_z $d"
        removed="$removed $d"
        changed=1
    done

    # Разрешение lan -> зона. Без него зона есть, а трафик всё равно не идёт: политика forward
    # у fw4 применяется к паре зон, а не к одной.
    uci show firewall 2>/dev/null | grep -q "\.dest='$_z'" || {
        uci -q add firewall forwarding >/dev/null
        uci -q set firewall.@forwarding[-1].src='lan'
        uci -q set firewall.@forwarding[-1].dest="$_z"
        changed=1
        msg="${msg:+$msg, }проброс lan -> $_z добавлен"
    }

    if [ "$changed" = 1 ]; then
        uci -q commit firewall
        [ -n "$added" ] && msg="${msg:+$msg, }добавлены устройства:$added"
        [ -n "$removed" ] && msg="${msg:+$msg, }убраны ушедшие устройства:$removed"
        fw_noted "zone $_z" || msg="$msg (зона $_z не наша — только дополняем, ничего не удаляем)"
        echo "$msg"
    fi
    return "$changed"
}

# Привести фаервол в соответствие со спекой. Перезагрузка правил ОДНА на все зоны: fw4 reload
# перестраивает набор целиком, и звать его на каждую зону значило бы дважды уронить транзит.
fw_sync() {
    any=0
    for z in $FW_ZONES; do
        _n="${z%%:*}"; _rest="${z#*:}"
        _k="${_rest%%:*}"; _m="${_rest##*:}"
        out="$(fw_zone_sync "$_n" "$_k" "$_m")" || any=1
        # По строке: fw_zone_sync печатает и «что сделали», и «что не тронули», а один
        # printf на многострочное значение оставил бы вторую строку без имени того, кто
        # говорит, — в общем выводе apply она читалась бы как сообщение движка.
        [ -n "$out" ] && printf '%s\n' "$out" | while IFS= read -r l; do
            [ -n "$l" ] && printf 'splify2: %s\n' "$l"
        done
    done
    if [ "$any" = 1 ]; then
        fw4 reload >/dev/null 2>&1 || /etc/init.d/firewall reload >/dev/null 2>&1
    fi
}

case "$2" in

    spec_set)
        read -r input
        json_load "$input" 2>/dev/null || fail "неразбираемый запрос"
        json_get_var spec spec
        [ -n "$spec" ] || fail "пустая спецификация"
        # Временный файл РЯДОМ с целевым, а не в /tmp, и это не мелочь. /tmp на OpenWrt —
        # tmpfs, а спека лежит на overlay; mv между разными файловыми системами busybox
        # делает копированием с удалением, а не rename(). Значит подмена НЕ атомарна:
        # обрыв на середине (кончился overlay — а он 6,9 МБ) оставлял на месте рабочей
        # спеки обрубок, и интерфейс при этом отвечал «Сохранено». Внутри одной ФС mv —
        # это rename, то есть либо старый файл, либо новый, третьего не бывает.
        # Ровно так уже сделано в download() выше, по той же причине.
        mkdir -p "$(dirname "$SPEC")"
        tmp="$SPEC.new.$$"
        printf '%s' "$spec" > "$tmp" || { rm -f "$tmp"; fail "не удалось записать спецификацию — кончилось место?"; }
        # Списки, на которые ссылается ПРИСЛАННАЯ спека, доскачиваем ДО проверки: движок
        # умирает на отсутствующем файле, и без этого выбор нового сервиса не сохранялся вовсе
        # (см. fetch_missing_lists). Предупреждения о нескачанном не отменяют сохранение —
        # спека с недоступным списком остаётся верной, просто её канал не поднимется.
        set_warn="$(fetch_missing_lists "$tmp")"
        # Компилятор — единственный судья: он же будет это применять. Проверка до
        # записи означает, что на диске не окажется спеки, которую движок отвергнет
        # при следующей загрузке.
        if ! err="$("$STEER" apply --dry-run --spec "$tmp" 2>&1 >/dev/null)"; then
            rm -f "$tmp"
            # Если список не скачался, ПРИЧИНА в этом, и её надо назвать первой. Сообщение
            # движка называет следствие — «cannot read a channel's list» — и отправляет
            # человека искать испорченный файл, которого никогда не было на диске. Проверено:
            # при недоступном списке ответ был ровно таким, без единого слова о загрузке.
            fail "${set_warn:+$set_warn; }${err:-движок отверг спецификацию}"
        fi
        # Сравниваем ДО подмены: после неё старого отпечатка уже не узнать.
        before="$(vless_fingerprint "$SPEC")"
        after="$(vless_fingerprint "$tmp")"
        # Обфускация: важно не только «изменилось», но и «изменился ли НАБОР выходов».
        # Смена адреса сервера лечится сигналом живому экземпляру, а появление нового
        # выхода с obfs — нет: экземпляра ещё не существует, и сигнал уходить некому.
        # Такой выход выглядел бы настроенным и молча не работал бы до перезагрузки.
        obfs_before="$(obfs_fingerprint "$SPEC")"
        obfs_after="$(obfs_fingerprint "$tmp")"
        obfs_before_n="$(obfs_names "$SPEC")"
        obfs_after_n="$(obfs_names "$tmp")"
        vless_before_n="$(vless_names "$SPEC")"
        vless_after_n="$(vless_names "$tmp")"
        zapret_before_n="$(zapret_names "$SPEC")"
        zapret_after_n="$(zapret_names "$tmp")"
        # Код возврата mv проверяется: без этого «Сохранено» печаталось независимо от
        # того, легла спека на диск или нет.
        mv "$tmp" "$SPEC" || { rm -f "$tmp"; fail "не удалось заменить спецификацию"; }
        # Признак пишется СЛОВОМ, как у обфускации, а не пустым файлом: экземпляру,
        # которого ещё нет, сигналить некому — см. развёрнутое объяснение в ветке apply.
        # Помета ДОБАВЛЯЕТСЯ к уже накопленным, а не заменяет их (см. dirty_mark).
        # Развилка внутри одного сохранения при этом остаётся прежней: смена НАБОРА не
        # сигналит живым туннелям, иначе добавление второго выхода перезапускало бы
        # первый — а это смена выходного адреса, которой никто не просил.
        if [ "$vless_before_n" != "$vless_after_n" ]; then
            dirty_mark "$VLESS_DIRTY" instances
        elif [ "$before" != "$after" ]; then
            dirty_mark "$VLESS_DIRTY" params
        fi
        if [ "$obfs_before" != "$obfs_after" ]; then
            if [ "$obfs_before_n" != "$obfs_after_n" ]; then
                dirty_mark "$OBFS_DIRTY" instances
            else
                dirty_mark "$OBFS_DIRTY" params
            fi
        fi
        # У выхода обхода повод один — появился он или исчез. Стратегию (единственное, что у
        # него ещё есть) правит не спека, а отдельный метод, и там свой способ применить её
        # живому обработчику. Поэтому здесь только `instances`.
        [ "$zapret_before_n" != "$zapret_after_n" ] && dirty_mark "$ZAPRET_DIRTY" instances
        # Предупреждение о нескачанном списке едет В ОТВЕТЕ, а не в журнал: сохранение
        # прошло, спека верна, но канал, ссылающийся на недоступный список, не поднимется —
        # и узнать об этом человек должен там же, где нажимал, а не догадываться позже по
        # неработающему каналу.
        json_init; json_add_boolean ok 1
        [ -n "$set_warn" ] && json_add_string warn "$set_warn"
        json_dump
        ;;

    apply)
        need_zapret; need_doh
        # Зона туннельных устройств приводится в порядок ДО apply: иначе первый же прогон
        # объявит, что устройство никому не известно, и будет прав. Синхронизация в обе
        # стороны — добавить появившееся и убрать ушедшее вместе с самой зоной, когда
        # туннельных выходов не осталось (см. fw_sync).
        zone_msg="$(fw_sync 2>&1)"
        # То же доскачивание, что и при сохранении: спеку могли положить на диск в обход
        # интерфейса (splify2 spec_set — не единственный способ), да и файл мог быть удалён
        # уборкой между сохранением и применением.
        fetch_warn="$(fetch_missing_lists "$SPEC")"

        # Фикс Zapret Manager версии 1.2.3 жил правилом в спеке — убираем его оттуда, если
        # он там остался: теперь фикс касается только самого роутера (см. zm_rules_sync).
        zm_drop_channel || true
        out="$("$STEER" apply --spec "$SPEC" 2>&1)"; rc=$?
        # Снимок — только на успехе: неудавшийся apply ничего не изменил в ядре, и счётчик
        # обязан продолжать это показывать.
        [ "$rc" -eq 0 ] && cp "$SPEC" "$APPLIED" 2>/dev/null
        # Свои таблицы собираются ПОСЛЕ движка: тот сносит и ставит свою заново, а наши
        # ссылаются на его метку — до его применения ссылаться было бы не на что. Обе рядом
        # потому, что делают одно и то же для двух разных поводов (фикс GitHub и DoH), и
        # забыть одну из них при правке apply — самый простой способ выкатить настройку,
        # которая включена в интерфейсе и не действует.
        zm_rules_sync
        doh_rules_sync
        # И третье, из той же семьи: force_dns у https-dns-proxy обязан согласиться с тем,
        # нужен ли движку свой резолвер. Ровно здесь, потому что ровно здесь доменные каналы
        # появляются и исчезают, а два перенаправления порта 53 в одной точке дают гонку, из
        # которой проигравший выходит молча (см. doh_force_sync).
        doh_force_sync
        [ -n "$fetch_warn" ] && out="$fetch_warn
$out"
        [ -n "$zone_msg" ] && out="$zone_msg
$out"

        # Клиент VLESS читает спеку и подписку ОДИН РАЗ при старте, поэтому смена узла или
        # подписки без перезапуска не значит ничего: в интерфейсе выбрано новое, в туннеле
        # работает старое, и понять это невозможно. Перезапускаем — но только когда
        # изменилось именно это, иначе правка любого списка роняла бы соединения через
        # туннель и меняла выходной адрес.
        if [ -f "$VLESS_DIRTY" ]; then
            # Два повода с разной ценой — ровно как у обфускации ниже, и раньше здесь был
            # только второй:
            #
            #   instances — набор выходов vless изменился (выход появился, исчез или его
            #               переименовали, а имя экземпляра это `vless_<выход>`).
            #               Экземпляра для нового выхода ещё НЕТ, и сигнал уходит в
            #               никуда. `start` на работающем сервисе заставляет procd
            #               сверить описанные экземпляры с запущенными и завести разницу.
            #   params    — сменился узел или подписка у существующего выхода: хватит
            #               сигнала живому экземпляру. `start` здесь бесполезен: описание
            #               экземпляра от номера узла не зависит, procd видит его
            #               неизменившимся и процесс не трогает — подписку никто не
            #               перечитает.
            #
            # Поводы НЕ исключают друг друга: между двумя применениями бывает и то и
            # другое, и тогда нужны оба действия. Порядок обязателен именно этот —
            # сигнал живым, потом сборка набора: наоборот только что созданный
            # экземпляр получал бы TERM через мгновение после запуска.
            #
            # Прежде спасал побочный эффект: reload_dnsd ниже при отсутствии экземпляра
            # dnsd делает start всего сервиса. То есть новый туннель поднимался, ТОЛЬКО
            # если в спеке нет доменных каналов, — а они есть в самой обычной
            # конфигурации этого продукта. С ними экземпляр dnsd существует, start не
            # случается, и туннель не появлялся до перезагрузки роутера, выглядя
            # настроенным. Для обфускации этот же сценарий давно назван недопустимым.
            #
            # Пустой файл — от версий, где sub_set помечал смену подписки без слова:
            # читается как params, ровно так он тогда и работал.
            [ -s "$VLESS_DIRTY" ] || dirty_mark "$VLESS_DIRTY" params
            if dirty_has "$VLESS_DIRTY" params; then
                for o in $("$STEER" outputs --kind vless --spec "$SPEC" 2>/dev/null); do
                    # Через ubus, а не procd_send_signal: тот живёт в
                    # /lib/functions/procd.sh, которого в rpcd-скрипте нет. Сигнал именно
                    # ЭТОМУ экземпляру — резолвер и сторож перезапускать незачем, а '*'
                    # однажды уже убивал туннель при каждом сохранении.
                    ubus call service signal \
                        "{\"name\":\"steer\",\"instance\":\"vless_$o\",\"signal\":15}" 2>/dev/null
                    out="$out
splify2: туннель $o перезапущен — сменился узел или подписка"
                done
            fi
            if dirty_has "$VLESS_DIRTY" instances; then
                "$INITD" start >/dev/null 2>&1
                out="$out
splify2: набор туннелей изменился — экземпляры пересобраны"
            fi
            rm -f "$VLESS_DIRTY"
        fi
        # Обфускаторы. Два разных случая с разной ценой:
        #
        #   params    — сменился адрес сервера или локальный порт: хватит сигнала живому
        #               экземпляру, procd поднимет его заново с новой спекой;
        #   instances — набор выходов с obfs изменился: экземпляра для нового выхода ещё
        #               не существует, и сигналить некому. `start` на работающем сервисе
        #               заставляет procd СВЕРИТЬ описанные экземпляры с запущенными и
        #               завести/снять разницу — без этого новый выход молча не работал бы
        #               до перезагрузки роутера, выглядя настроенным.
        if [ -f "$OBFS_DIRTY" ]; then
            # Тот же порядок и та же причина, что у vless выше: поводы складываются,
            # сигнал живым уходит раньше сборки набора.
            [ -s "$OBFS_DIRTY" ] || dirty_mark "$OBFS_DIRTY" params
            if dirty_has "$OBFS_DIRTY" params; then
                for o in $("$STEER" outputs --obfs --spec "$SPEC" 2>/dev/null); do
                    ubus call service signal \
                        "{\"name\":\"steer\",\"instance\":\"obfs_$o\",\"signal\":15}" 2>/dev/null
                    out="$out
splify2: обфускатор $o перезапущен — сменился сервер или порт"
                done
            fi
            if dirty_has "$OBFS_DIRTY" instances; then
                "$INITD" start >/dev/null 2>&1
                out="$out
splify2: набор обфускаторов изменился — экземпляры пересобраны"
            fi
            rm -f "$OBFS_DIRTY"
        fi
        # Обработчики обхода DPI. Повод один — набор выходов kind=zapret изменился, — и
        # лечится он тем же `start`: procd сверяет описанные экземпляры с запущенными и
        # заводит разницу, не трогая остальные. Проверено на роутере: новый zapret_youtube
        # поднялся, а PIDы клиентов vless не изменились. `restart` уронил бы туннели на
        # секунды ради выхода, который к ним не относится.
        #
        # Признак снимается ТОЛЬКО когда экземпляры на самом деле поднялись. Иначе первый же
        # неудачный подъём (пакета zapret ещё нет, файл стратегии пуст) стирал бы повод, и
        # выход остался бы без обработчика до перезагрузки роутера — выглядя настроенным.
        if [ -n "$(zapret_names "$SPEC")" ] && ! zp_installed; then
            # Выход обхода есть, а обхода нет. Пересобирать экземпляры незачем — поднимать
            # нечего, — но сказать надо: при on_fail=drop трафик такого канала ОСТАНОВЛЕН.
            rm -f "$ZAPRET_DIRTY"
            out="$out
splify2: есть выход обхода DPI, а пакет zapret не установлен — поставьте его во вкладке Zapret"
        elif [ -f "$ZAPRET_DIRTY" ] || zapret_needs_instances; then
            "$INITD" start >/dev/null 2>&1
            # Приговор выносится НЕ СРАЗУ: procd поднимает экземпляр не в тот же миг, и без
            # ожидания «не поднялся» печаталось бы на обработчике, который поднимется через
            # секунду, — то есть ложная тревога на исправной настройке. Ложная тревога дороже
            # отсутствующей: по ней настраивают лишнее и перестают верить сообщениям.
            #
            # Приговор выносится по СОСТОЯНИЮ, а не по счётчику кругов: пока условие стояло
            # `[ "$_ap_zw" -lt 4 ]` перед опросом, состояние после ЧЕТВЁРТОГО сна не
            # спрашивалось ни разу. Обработчик, поднявшийся на четвёртой секунде, объявлялся
            # не поднявшимся — то есть последний сон покупал ровно ту ложную тревогу, ради
            # избавления от которой всё ожидание и заведено.
            _ap_zw=0; _ap_zdown=0
            while zapret_needs_instances; do
                if [ "$_ap_zw" -ge 4 ]; then _ap_zdown=1; break; fi
                sleep 1
                _ap_zw=$((_ap_zw + 1))
            done
            if [ "$_ap_zdown" = 1 ]; then
                out="$out
splify2: обработчик обхода DPI не поднялся — выбрана ли стратегия во вкладке Zapret?"
            else
                rm -f "$ZAPRET_DIRTY"
                out="$out
splify2: набор выходов обхода DPI изменился — обработчики пересобраны"
            fi
        fi
        # Резолвер обязан перечитать спеку: список файлов у доменного канала он берёт
        # при старте, поэтому после apply он ещё матчит прежние домены. Без этого
        # выбранный в интерфейсе список молча не работает — правила новые, а резолвер
        # старый. Экземпляр перезапускается без снятия правил, маршрутизация не мигает.
        [ "$rc" -eq 0 ] && "$INITD" reload_dnsd >/dev/null 2>&1
        # Вывод движка отдаётся целиком, включая предупреждения: он знает то, чего
        # интерфейс знать не может — например, что у туннеля нет NAT и трафик в него
        # уедет без возврата.
        json_init
        json_add_boolean ok $([ $rc -eq 0 ] && echo 1 || echo 0)
        json_add_string output "$out"
        json_dump
        ;;

    *) fail "неизвестный метод" ;;
esac
