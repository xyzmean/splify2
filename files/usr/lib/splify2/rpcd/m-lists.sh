#!/bin/sh
# Часть объекта rpcd splify2 — подключается диспетчером /usr/libexec/rpcd/splify2 по имени
# метода. ЗАЧЕМ ФАЙЛОВ НЕСКОЛЬКО. busybox ash разбирает файл целиком, и объект в 4500 строк
# стоил 110 мс разбора на КАЖДЫЙ вызов — при том, что сам ответ считается за 30-90 мс.
# Диспетчер разбирает только себя, общие помощники (common.sh) и группу вызванного метода.
# Переменные и швы для стендов объявлены в диспетчере и здесь доступны как есть.


# Этой группе нужно скачивание (fetch.sh): подключается здесь, а не каждым вызовом объекта.
need_fetch

# Описание второго издателя списков (itdoginfo/allow-domains): где он живёт, каким тегом
# зафиксирован, что публикует и как его двоичные наборы становятся нашими списками.
#
# ПУТЬ здесь, а подключение — внутри list_fetch: файл нужен ровно одному вызову, а разбор
# подключённого файла busybox ash делает целиком и на каждый вызов объекта (см. шапку).
# Тот же файл подключает splify2-update-lists — второй экземпляр этих знаний означал бы, что
# кнопка «Загрузить» и ночное обновление берут списки разных версий.
AD_SH=${AD_SH:-/usr/share/splify2/allow-domains.sh}


manifest_url() {
    u="$(uci -q get splify2.main.manifest_url)"
    [ -n "$u" ] && printf '%s' "$u" || printf '%s' "$MANIFEST_URL_DEFAULT"
}

# Запомнить происхождение. Пустые значения пишутся тоже: «файл выбран, а имени его мы не
# знаем» — это не то же, что «происхождение неизвестно», и различать их надо.
custom_meta_put() {  # ИМЯ ВИД ИСТОЧНИК ССЫЛКА ИМЯ_ФАЙЛА
    _cm="$(custom_meta_path "$1" "$2")"
    mkdir -p "$(dirname "$_cm")"
    {
        printf 'source=%s\n' "$3"
        printf 'url=%s\n' "$4"
        printf 'file=%s\n' "$5"
        printf 'at=%s\n' "$(date +%s)"
    } > "$_cm.tmp" && mv "$_cm.tmp" "$_cm"
}

# Прочитать происхождение в CM_SOURCE / CM_URL / CM_FILE / CM_AT.
#
# Файла нет — CM_SOURCE остаётся пустым, и это законное состояние, а не поломка: так
# выглядят списки, заведённые до появления этого файла, положенные в каталог руками и
# вернувшиеся из архива настроек (архив происхождения не носит — см. backup_build).
# Интерфейс тогда предлагает все три способа, как предлагал всегда.
custom_meta_get() {  # ИМЯ ВИД
    CM_SOURCE=""; CM_URL=""; CM_FILE=""; CM_AT=""
    _cm="$(custom_meta_path "$1" "$2")"
    [ -s "$_cm" ] || return 1
    while IFS='=' read -r _k _v; do
        case "$_k" in
            source) CM_SOURCE="$_v" ;;
            url)    CM_URL="$_v" ;;
            file)   CM_FILE="$_v" ;;
            at)     CM_AT="$_v" ;;
        esac
    done < "$_cm"
    [ -n "$CM_SOURCE" ]
}

case "$2" in

    lists)
        # Манифест отдаётся как есть — превращать его в форму интерфейса здесь значило
        # бы держать разбор в shell, где он дороже и хуже проверяем.
        if [ ! -s "$MANIFEST" ]; then
            mkdir -p "$(dirname "$MANIFEST")"
            download "$(manifest_url)" "$MANIFEST" ||
                fail "манифест не скачался${FETCH_NOTE:+: $FETCH_NOTE}"
        fi
        cat "$MANIFEST"
        ;;

    list_fetch)
        read -r input
        json_load "$input" 2>/dev/null || fail "неразбираемый запрос"
        json_get_var id id
        [ -n "$id" ] || fail "не указан список"
        json_get_var kind kind

        # ВТОРОЙ ИЗДАТЕЛЬ — по приставке в id: «itdog:telegram».
        #
        # Приставкой, а не отдельным методом, и это решение про совместимость. Метод — это
        # запись в сигнатуре объекта (см. `list` в диспетчере) и запись в договорённости с
        # интерфейсом; второй метод «то же, но у другого издателя» означал бы, что каждое
        # место, которое умеет качать список, надо учить дважды. Пространство id при этом
        # разделено честно: у нашего манифеста id — это слово из категорий, двоеточия в нём
        # нет и быть не может.
        #
        # Описание источника подключается ЗДЕСЬ, а не в шапке файла: группа `lists` — это
        # ещё и local_lists, который зовётся на каждое открытие настроек, а busybox ash
        # разбирает подключённый файл целиком (см. шапку). Платить за разбор описания
        # источника должен тот вызов, которому оно нужно.
        case "$id" in
            *:*)
                [ -r "$AD_SH" ] || fail "описания источника $AD_SH нет — пакет собран не целиком"
                . "$AD_SH"
                # Приставку сверяет САМО описание: имя источника задано в нём, и второй его
                # экземпляр здесь означал бы, что переименование источника надо помнить в
                # двух файлах.
                [ "${id%%:*}" = "$AD_ID" ] || fail "неизвестный источник списков: ${id%%:*}"
                svc="${id#*:}"
                # Имя сервиса становится частью пути на диске, поэтому проверяется до всего
                # остального — тем же рубежом, что имена своих списков в list_put.
                case "$svc" in
                    ''|*[!A-Za-z0-9_-]*) fail "имя сервиса: латиница, цифры, дефис и подчёркивание" ;;
                esac
                case "$kind" in
                    domains|prefixes) ;;
                    *) fail "вид списка: domains (домены) или prefixes (подсети)" ;;
                esac
                # «Такого сервиса у издателя нет» и «скачать не вышло» — разные ответы:
                # первый значит, что спрашивать нечего, и повтор ничего не изменит.
                kinds="$(ad_kinds "$svc")"
                [ -n "$kinds" ] || fail "у издателя $AD_REPO нет списка $svc"
                case " $kinds " in
                    *" $kind "*) ;;
                    *) fail "издатель не публикует $(ad_kind_ru "$kind") сервиса $svc" ;;
                esac
                ad_tag_resolve
                AD_TMP="/tmp/splify2-srs.$$"
                ad_get "$svc"
                ad_rc=$?
                if [ "$ad_rc" != 0 ]; then
                    rm -rf "$AD_TMP"
                    # Три беды — три ответа. Код 2 значит «набор понят, но списком не
                    # выразим», то есть с загрузкой всё в порядке и повторять её незачем;
                    # код 1 значит «приехало не то», и вот его повторять как раз стоит.
                    case "$ad_rc" in
                        1) fail "набор $svc не скачался${FETCH_NOTE:+: $FETCH_NOTE}" ;;
                        2) fail "такой список нам пока не подходит: $AD_NOTE" ;;
                        *) fail "скачался испорченный набор $svc: $AD_NOTE" ;;
                    esac
                fi
                # КЛАДЁМ ОБА ВИДА, а не только запрошенный: набор один, и подсети из него
                # уже разобраны. Выбросить половину значило бы скачать тот же файл второй
                # раз, когда человек включит второй вид того же сервиса.
                ad_via="$FETCH_NOTE"
                for k in $kinds; do
                    src="$(ad_out_of "$k")" || continue
                    dest="$(local_path "$(ad_rel "$svc" "$k")")" ||
                        fail "недопустимый путь списка: $(ad_rel "$svc" "$k")"
                    mkdir -p "$(dirname "$dest")"
                    # Перенос рядом с целью, потом переименование — как в list_put: mv
                    # атомарен только внутри одной ФС, а разбор лежит в /tmp (tmpfs), тогда
                    # как списки на overlay. Между ФС busybox копирует, то есть обрыв
                    # оставил бы ровно тот обрубок, от которого mv и должен спасать.
                    mv "$src" "$dest.new.$$" && mv "$dest.new.$$" "$dest" || {
                        rm -f "$dest.new.$$"; rm -rf "$AD_TMP"
                        fail "список $svc не записался — кончилось место?"; }
                    # Чем набит файл. Тем же значением пользуется ночное обновление, чтобы
                    # не качать зафиксированный тег повторно.
                    ad_stamp_put "$svc" "$k" "$AD_TAG"
                done
                rm -rf "$AD_TMP"
                dest="$(local_path "$(ad_rel "$svc" "$kind")")" || fail "недопустимый путь списка"
                # Вида в наборе может не оказаться, хотя издатель его объявляет: истину
                # говорит движок, а таблица сервисов — только подсказка.
                [ -s "$dest" ] || fail "в наборе $svc нет $(ad_kind_ru "$kind")"
                json_init
                json_add_boolean ok 1
                json_add_int count "$(grep -c . "$dest")"
                json_add_string path "$dest"
                # Версия отдаётся вместе со списком: интерфейсу есть что показать рядом с
                # числом записей, а поддержке — что спросить.
                json_add_string tag "$AD_TAG"
                [ -n "$ad_via" ] && json_add_string via "$ad_via"
                json_dump
                exit 0
                ;;
        esac

        [ -s "$MANIFEST" ] || fail "манифест не загружен"
        base="$(jsonfilter -i "$MANIFEST" -e '@.base_url')"
        file="$(manifest_file "$id" "$kind")"
        [ -n "$file" ] || fail "списка $id нет в манифесте"
        [ -n "$base" ] || fail "в манифесте нет base_url"
        dest="$(local_path "$file")" || fail "издатель прислал недопустимый путь списка: $file"
        mkdir -p "$(dirname "$dest")"
        download "$base/$file" "$dest" || fail "список не скачался${FETCH_NOTE:+: $FETCH_NOTE}"
        json_init
        json_add_boolean ok 1
        json_add_int count "$(grep -c . "$dest")"
        json_add_string path "$dest"
        # Каким путём приехало. Пусто — прямым; иначе строка объясняет обход, и интерфейсу
        # есть что показать вместо молчаливой паузы в полминуты.
        [ -n "$FETCH_NOTE" ] && json_add_string via "$FETCH_NOTE"
        json_dump
        ;;

    lists_update)
        # Обновить всё, что используется, прямо сейчас — кнопка в каталоге.
        #
        # Зовётся ТОТ ЖЕ скрипт, что ходит по расписанию, а не своя укладка рядом. Он
        # один знает всё, что к обновлению прилагается: подгонку адресных списков под
        # память (`steer fit`), проверку скачанного до подмены, откат на прежние копии,
        # если движок отверг новое, и apply в конце. Вторая реализация разошлась бы с
        # первой на первом же изменении, а расходиться ей есть где.
        #
        # Скрипт умеет только syslog: его log() печатает в stdout лишь под терминалом, а
        # здесь терминала нет. Поэтому ему передаётся REPORT — файл, куда он дублирует те
        # же строки. Отправлять человека в журнал за ответом на нажатие кнопки нельзя.
        [ -x "$UPDATE_LISTS" ] || fail "обновлятор списков не найден"
        rep="/tmp/splify2-lists-update.$$"
        rm -f "$rep"
        : > "$rep"
        REPORT="$rep" "$UPDATE_LISTS" >/dev/null 2>&1
        lu_rc=$?
        lu_changed="$(grep -c ': обновлён' "$rep" 2>/dev/null)"
        lu_failed="$(grep -c 'оставлен прежний\|не скачался' "$rep" 2>/dev/null)"
        json_init
        # ok=0 только тогда, когда что-то не обновилось. Прогон без изменений — успех:
        # значит списки уже свежие.
        json_add_boolean ok "$([ "$lu_rc" = 0 ] && echo 1 || echo 0)"
        json_add_int updated "${lu_changed:-0}"
        json_add_int failed "${lu_failed:-0}"
        json_add_array lines
        while read -r lu_line; do
            [ -n "$lu_line" ] && json_add_string "" "$lu_line"
        done < "$rep"
        json_close_array
        json_dump
        rm -f "$rep"
        ;;

    list_put)
        # Свой список: текстом, по ссылке или файлом.
        #
        # Вопрос пришёл снаружи: маршрутизировать можно было только то, что опубликовал
        # издатель. Движок сопоставляет исключительно по файлам, а каталог рисуется из
        # манифеста, поэтому свой .lst, положенный в /etc/steer/lists руками, был виден
        # local_lists — и не предлагался ни одному правилу.
        #
        # Файл — тем же методом по частям (append), а не отдельным транспортом: ubus не
        # резиновый, а cgi-io означал бы второй путь загрузки со своими правами и своей
        # проверкой формата. Один вход — одна проверка.
        read -r input
        json_load "$input" 2>/dev/null || fail "неразбираемый запрос"
        json_get_var name name
        json_get_var kind kind
        json_get_var text text
        json_get_var url url
        json_get_var append append
        # ОТКУДА список. Спрашивается явно, а не выводится из того, что пришло: `text` без
        # ссылки означает и «набрал руками», и «выбрал файл» — файл интерфейс шлёт тем же
        # полем, порциями по тысяче строк (см. CustomLists). Различить их здесь нечем, а
        # различать надо: правят их разными способами.
        #
        # Поля нет вовсе (старый интерфейс) — считаем по тому, что пришло: ссылка значит
        # ссылку, текст значит «руками». Это ровно то, что и было раньше, только теперь
        # записано.
        json_get_var source source
        json_get_var filename filename
        # Имя — часть пути на диске, поэтому проверяется до всего остального. Без этого
        # «../../etc/passwd» было бы законным именем списка.
        case "$name" in
            ''|*[!A-Za-z0-9_-]*) fail "имя списка: латиница, цифры, дефис и подчёркивание" ;;
        esac
        case "$kind" in
            domains|prefixes) ;;
            *) fail "вид списка: domains (домены) или prefixes (подсети)" ;;
        esac
        raw="/tmp/splify2-put.$$"
        rm -f "$raw" "$raw.clean" "$raw.stat"
        if [ -n "$url" ]; then
            case "$url" in
                http://*|https://*) ;;
                *) fail "ссылка должна начинаться с http:// или https://" ;;
            esac
            download "$url" "$raw" || fail "не скачалось: $url${FETCH_NOTE:+ ($FETCH_NOTE)}"
        else
            [ -n "$text" ] || fail "пустой список"
            printf '%s\n' "$text" > "$raw"
        fi
        sz="$(wc -c 2>/dev/null < "$raw" || echo 0)"
        if [ "$sz" -gt "$LIST_MAX_BYTES" ]; then
            rm -f "$raw"
            fail "список больше $((LIST_MAX_BYTES / 1024)) КБ — столько на роутер не кладём"
        fi
        sanitize_list "$kind" "$raw" "$raw.clean" "$raw.stat"
        rm -f "$raw"
        read -r kept dropped < "$raw.stat"
        rm -f "$raw.stat"
        if [ "${kept:-0}" -eq 0 ]; then
            rm -f "$raw.clean"
            fail "не разобрано ни одной строки: для $kind ждём $([ "$kind" = prefixes ] && echo 'подсети вида 10.0.0.0/8' || echo 'имена вида example.org')"
        fi
        # Доменные — в подкаталог, адресные — рядом: ровно та же раскладка, что у
        # издателя. Вид списка обязан читаться из пути, иначе `mine.lst` доменный и
        # `mine.lst` адресный неразличимы, а интерфейсу надо положить их в РАЗНЫЕ поля
        # правила. На схлопывании двух списков в один проект уже обжигался (I-011).
        dest="$(custom_path "$name" "$kind")"
        mkdir -p "$(dirname "$dest")"
        # Предел считается по ИТОГОВОМУ файлу, а не по одной порции.
        #
        # Проверка выше смотрит только на то, что пришло этим вызовом, а интерфейс грузит
        # файл кусками по тысяче строк с append, и число кусков ничем не ограничено. То
        # есть предел, заведённый ради overlay в 6,9 МБ, обходился самым обычным способом
        # им пользоваться: выбрал файл на 40 МБ — сорок вызовов по мегабайту, ни один не
        # превысил предел, а флеш забит, и дальше не пишется ни спека, ни конфиг, ни
        # журнал, причём без единого слова о причине.
        if [ "$append" = 1 ] || [ "$append" = true ]; then
            have="$(wc -c 2>/dev/null < "$dest" || echo 0)"
            add="$(wc -c 2>/dev/null < "$raw.clean" || echo 0)"
            if [ "$((have + add))" -gt "$LIST_MAX_BYTES" ]; then
                rm -f "$raw.clean"
                fail "список «$name» дорос бы до $(( (have + add) / 1024 )) КБ, а предел $((LIST_MAX_BYTES / 1024)) КБ — столько на роутер не кладём"
            fi
        fi
        case "$append" in
            1|true) cat "$raw.clean" >> "$dest" || { rm -f "$raw.clean"; fail "не дописалось — кончилось место?"; } ;;
            # Замена через mv, а не через «> файл»: оборванная запись поверх рабочего
            # списка оставила бы канал маршрутизировать половину.
            #
            # Но сам mv атомарен только ВНУТРИ одной файловой системы, а $raw лежит в
            # /tmp (tmpfs), тогда как списки — на overlay. Между ФС busybox копирует, то
            # есть обрыв оставляет ровно тот обрубок, от которого mv и должен был спасти.
            # Поэтому сначала переносим рядом с целью, и только потом переименовываем.
            *)      mv "$raw.clean" "$dest.new.$$" &&
                    mv "$dest.new.$$" "$dest" ||
                    { rm -f "$raw.clean" "$dest.new.$$"; fail "не записалось — кончилось место?"; } ;;
        esac
        rm -f "$raw.clean"
        # Происхождение запоминается на ПЕРВОЙ порции, а не на каждой: порции — это один и
        # тот же файл, и запись при каждой означала бы `at` последнего куска вместо времени
        # выбора файла. Плюс лишняя запись на overlay за каждую тысячу строк.
        case "$append" in
            1|true) ;;
            *)
                case "$source" in
                    text|file|url) ;;
                    *) [ -n "$url" ] && source=url || source=text ;;
                esac
                # Имя файла — только для показа человеку («выбран blocked.txt»), поэтому от
                # него нужна ровно читаемость. Чистится тем же доводом, что заголовки HWID:
                # строка приходит из браузера и уедет в JSON и на экран.
                filename="$(printf '%s' "$filename" | tr -d '\r\n\t"\\/' | cut -c1-64)"
                custom_meta_put "$name" "$kind" "$source" \
                    "$([ "$source" = url ] && printf '%s' "$url")" "$filename"
                ;;
        esac
        json_init
        json_add_boolean ok 1
        json_add_string path "$dest"
        json_add_int count "$(grep -c . "$dest")"
        json_add_int dropped "${dropped:-0}"
        json_dump
        ;;

    list_remove)
        read -r input
        json_load "$input" 2>/dev/null || fail "неразбираемый запрос"
        json_get_var id id
        json_get_var kind kind
        json_get_var name name
        # Свой список ищется по имени, а не через манифест: в манифесте его нет и быть
        # не может, поэтому прежний код удалить его не мог вовсе.
        if [ -n "$name" ]; then
            case "$name" in
                *[!A-Za-z0-9_-]*) fail "имя списка: латиница, цифры, дефис и подчёркивание" ;;
            esac
            dest="$(custom_path "$name" "${kind:-}")"
            # Вид могли не указать — тогда ищем оба, но удаляем ровно один: имя внутри
            # своих списков уникально по виду, как и у издателя.
            if [ ! -f "$dest" ]; then
                dest="$(custom_path "$name" domains)"
                [ -f "$dest" ] || dest="$(custom_path "$name" prefixes)"
            fi
            [ -f "$dest" ] || fail "своего списка $name нет"
            if [ -s "$SPEC" ] && grep -q "$dest" "$SPEC"; then
                fail "список используется каналом — сначала снимите галочку"
            fi
            # Вместе со списком снимается и запись о его происхождении: оставленная, она
            # переехала бы на СЛЕДУЮЩИЙ список того же имени и рассказала бы про него
            # чужую правду — «выбран blocked.txt» на списке, набранном руками.
            rm -f "$dest" "$dest.src"
            json_init; json_add_boolean ok 1; json_dump
            exit 0
        fi
        [ -n "$id" ] || fail "не указан список"
        file="$(manifest_file "$id" "$kind")"
        [ -n "$file" ] || fail "списка $id нет в манифесте"
        dest="$(local_path "$file")" || fail "издатель прислал недопустимый путь списка: $file"
        # Канал, указывающий на файл, после удаления не скомпилируется: движок читает
        # список при сборке правил и падает на отсутствующем. Поэтому удаление
        # ОТКАЗЫВАЕТСЯ, пока список кем-то используется, вместо того чтобы оставить
        # спеку, которая перестанет применяться при следующей перезагрузке.
        #
        # Ищем ПОЛНЫЙ путь, а не имя файла: `hodca.lst` встречается и в адресном канале, и
        # внутри `domains/hodca.lst`, и поиск по имени запрещал бы удаление одного из-за
        # другого.
        if [ -s "$SPEC" ] && grep -q "$dest" "$SPEC"; then
            fail "список используется каналом — сначала снимите галочку"
        fi
        rm -f "$dest"
        json_init; json_add_boolean ok 1; json_dump
        ;;

    list_custom)
        # СВОИ списки с происхождением: что правится и чем.
        #
        # Отдельным методом, а не полем local_lists, и это разделение по цене: local_lists
        # считается одним awk по всему каталогу (46 файлов на роутере) и зовётся на каждое
        # открытие настроек, а происхождение нужно только своим спискам — их единицы — и
        # только там, где их правят. Складывать одно в другое значило бы читать по файлу
        # происхождения на каждый список издателя, которого у него нет и быть не может.
        #
        # Печатает jshn, а не awk: записей единицы, а в ответе есть строки от человека
        # (ссылка, имя файла), которым экранирование обязательно.
        json_init
        json_add_array lists
        for f in "$LISTS/$CUSTOM"/*.lst "$LISTS/$CUSTOM"/domains/*.lst; do
            [ -f "$f" ] || continue
            n="${f##*/}"; n="${n%.lst}"
            # Имя проверяется и здесь, на ВЫХОДЕ: в каталог мог положить файл не интерфейс,
            # а руки, и тогда имя уедет в JSON и обратно в list_put как путь. Тот же довод,
            # по которому имя проверяется в backup_build.
            case "$n" in ''|*[!A-Za-z0-9_-]*) continue ;; esac
            case "$f" in *"/$CUSTOM/domains/"*) k=domains ;; *) k=prefixes ;; esac
            custom_meta_get "$n" "$k" || true
            json_add_object ""
            json_add_string name "$n"
            json_add_string kind "$k"
            json_add_string path "$f"
            json_add_int count "$(grep -c . "$f" 2>/dev/null || echo 0)"
            json_add_int bytes "$(wc -c 2>/dev/null < "$f" || echo 0)"
            # Происхождение. Пустой `source` значит «неизвестно»: список завели до появления
            # этой записи, положили в каталог руками или вернули из архива настроек. Врать
            # тут нельзя — интерфейс тогда предлагает все три способа правки, как предлагал
            # всегда, а не один неверный.
            json_add_string source "${CM_SOURCE:-}"
            json_add_string url "${CM_URL:-}"
            json_add_string filename "${CM_FILE:-}"
            json_add_int at "${CM_AT:-0}"
            json_close_object
        done
        json_close_array
        json_dump
        ;;

    list_get)
        # Записи своего списка обратно, порциями.
        #
        # ЗАЧЕМ. Редактор списка, набранного руками, обязан показать то, что лежит на
        # роутере. Пустое поле вместо записей — это не «начни заново», а предложение
        # незаметно потерять то, что человек набирал: он допишет одну строку, нажмёт
        # «Сохранить», и остальные исчезнут.
        #
        # ПОРЦИЯМИ, по тому же доводу, что list_put и backup_get: ubus не резиновый, а свой
        # список разрешён до LIST_MAX_BYTES. Нарезка по БАЙТАМ, а не по строкам, и ровно на
        # границе: смещение приходит от вызывающего, и делить его на строки означало бы
        # второй счёт того же места.
        #
        # Читаются только СВОИ списки. Список издателя правке не подлежит: он приезжает по
        # расписанию, и всякая правка была бы стёрта следующим обновлением молча.
        read -r input
        json_load "$input" 2>/dev/null || fail "неразбираемый запрос"
        json_get_var name name
        json_get_var kind kind
        json_get_var offset offset
        case "$name" in
            ''|*[!A-Za-z0-9_-]*) fail "имя списка: латиница, цифры, дефис и подчёркивание" ;;
        esac
        case "$kind" in
            domains|prefixes) ;;
            *) fail "вид списка: domains (домены) или prefixes (подсети)" ;;
        esac
        case "${offset:-0}" in ''|*[!0-9]*) offset=0 ;; esac
        src="$(custom_path "$name" "$kind")"
        [ -f "$src" ] || fail "своего списка $name нет"
        total="$(wc -c 2>/dev/null < "$src" || echo 0)"
        # Нарезка ровно та же, что у архива настроек, вместе с заплаткой: подстановка команды
        # съедает ЗАВЕРШАЮЩИЕ переводы строки, а кусок обязан приехать байт в байт — иначе на
        # границе куска пропадает перевод строки и две записи списка склеиваются в одну.
        # Склеенная запись не отбрасывается санитайзером, а МОЛЧА теряет обе: «10.0.0.0/810.1.0.0/8»
        # это не подсеть, и обе исчезают из канала.
        text="$(tail -c "+$((offset + 1))" "$src" | head -c "$LIST_CHUNK"; printf X)"
        text="${text%X}"
        got="$(printf '%s' "$text" | wc -c)"
        next=$((offset + got))
        eof=0
        [ "$next" -ge "$total" ] && eof=1
        json_init
        json_add_boolean ok 1
        json_add_string name "$name"
        json_add_string kind "$kind"
        json_add_int total "$total"
        json_add_int offset "$offset"
        # Сколько СЧИТАНО, а не сколько просили: длина куска считается от него самого, иначе
        # смещение уезжало бы на каждой границе.
        json_add_int next "$next"
        json_add_boolean eof "$eof"
        json_add_string text "$text"
        json_dump
        ;;

    local_lists)
        # Что уже лежит на диске. Без этого интерфейс не может отличить скачанный
        # список от невыбранного: кнопка «Загрузить» висела и над готовым, а выбрать
        # можно было то, чего на роутере нет.
        #
        # ТРИ ПРОЦЕССА НА ВЕСЬ КАТАЛОГ, А НЕ ДВА НА КАЖДЫЙ ФАЙЛ. Было `grep -c .` и `date -r`
        # в подстановке на каждый файл: на роутере со всем каталогом это 46 файлов, то есть
        # 92 запуска процессов. Замер на стенде 10.8.1.87 (mipsel 24kc, 880 МГц): 1197 мс на
        # вызов — самый дорогой метод объекта, и платит его человек каждый раз, открывая
        # «Настройки» или каталог. Стало 390 мс: счёт строк одним grep по всем файлам, времена
        # одним ls, склейка и печать одним awk.
        #
        # `grep -c .`, а не `wc -l`: считаются НЕПУСТЫЕ строки, и это не придирка — свой
        # список человек правит руками, пустая строка в нём законна, а число на экране
        # обязано означать «столько записей». /dev/null в списке файлов — чтобы grep печатал
        # «путь:число» и на единственном файле тоже: без второго имени он печатает голое
        # число, и разобрать его было бы нечем.
        #
        # Время файла берётся из `ls -l --full-time` и переводится в секунды mktime(). Если
        # busybox собран без этого ключа, времена придут нулями, а счёт — нет: поле остаётся
        # в контракте (docs/rpcd-api.md), но его значение — лучшее из доступного, и это
        # честнее, чем 46 запусков `date` ради числа, которое на экране сейчас не показывает
        # никто.
        #
        # ПЕЧАТАЕТ awk, А НЕ jshn, и это единственное место в объекте, где так. Замер там же:
        # сборка тех же сорока шести записей через jshn — 187 мс, то есть половина нынешней
        # цены метода ушла бы на неё. Безопасно это ровно потому, что ключ здесь не
        # произвольная строка: имена списков чистит list_put, и awk ниже пропускает всё, что
        # не состоит из букв, цифр, точки, дефиса, подчёркивания и косой черты. Файл с
        # кавычкой в имени не наш, и промолчать о нём честнее, чем выдать поломанный JSON.
        _ll_files="$(find "$LISTS" -name '*.lst' -type f 2>/dev/null)"
        # Пути подставляются РАЗДЕЛЕНИЕМ СЛОВ, а не через xargs: конвейер с printf и xargs —
        # это ещё четыре запуска процессов, а на 880 МГц каждый стоит около двадцати
        # миллисекунд. Пробелов в наших именах не бывает (см. выше), а сорок шесть путей
        # далеко не упираются в предел длины командной строки.
        # И С ПАМЯТЬЮ: даже эти 390 мс платятся на каждое открытие каталога и правил, а файлы
        # меняются ночным обновлением. Память годна, пока ни один файл не новее её и число
        # файлов то же (удалённый файл новее не станет — его ловит счёт).
        _ll_c="${LOCAL_LISTS_CACHE:-/tmp/splify2-local_lists.json}"
        _ll_n="$(printf '%s\n' "$_ll_files" | grep -c .)"
        if [ -s "$_ll_c" ] && [ "$(cat "$_ll_c.n" 2>/dev/null)" = "$_ll_n" ] &&
           [ -z "$(find "$LISTS" -name '*.lst' -type f -newer "$_ll_c" 2>/dev/null | head -1)" ]; then
            cat "$_ll_c"
            exit 0
        fi
        # shellcheck disable=SC2086
        { grep -c . /dev/null $_ll_files 2>/dev/null
          ls -l --full-time $_ll_files 2>/dev/null
        } | awk -v pfx="$LISTS/" '
            # Строки grep — «путь:число», в них нет пробелов. Строки ls — девять полей:
            # права, ссылки, владелец, группа, размер, дата, время, зона, путь.
            NF == 1 { i = index($0, ":"); if (i) c[substr($0, 1, i - 1)] = substr($0, i + 1); next }
            NF >= 9 {
                split($6, d, "-"); split($7, t, ":")
                m[$NF] = mktime(d[1] " " d[2] " " d[3] " " t[1] " " t[2] " " int(t[3]))
                next
            }
            END {
                printf "{\"files\":{"
                n = 0
                for (p in c) {
                    if (p == "/dev/null") continue
                    r = p; sub("^" pfx, "", r)
                    if (r !~ /^[A-Za-z0-9._\/-]+$/) continue
                    printf "%s\"%s\":{\"count\":%d,\"mtime\":%d}", (n++ ? "," : ""), r, c[p], (p in m ? m[p] : 0)
                }
                printf "}}\n"
            }' | tee "$_ll_c.tmp"
        # Память — только целиком записанная: обрубок при нехватке места в /tmp хуже её отсутствия.
        [ -s "$_ll_c.tmp" ] && mv "$_ll_c.tmp" "$_ll_c" && printf '%s' "$_ll_n" > "$_ll_c.n"
        rm -f "$_ll_c.tmp"
        ;;

    fetch_mode|fetch_mode_set)
        # Качать списки и пакеты через туннель или нет. Два состояния, и других быть не
        # должно: переключатель значит то, что на нём написано, а не «мы сами решим, если не
        # вышло». Умолчание — нет.
        #
        # Имя выхода отдаётся вместе с состоянием: без поднятого выхода включать нечего, и
        # знать это надо до выбора, а не после. Считает его та же функция, что и само
        # скачивание, — иначе интерфейс обещал бы один выход, а файл ехал бы через другой.
        uci_file || fail "не удалось создать $UCI_SPLIFY2 — кончилось место?"
        uci -q get splify2.main >/dev/null 2>&1 || uci -q set splify2.main=splify2
        if [ "$2" = fetch_mode_set ]; then
            read -r input
            json_load "$input" 2>/dev/null || fail "неразбираемый запрос"
            json_get_var mode mode
            case "$mode" in
                always|off) ;;
                *) fail "режим бывает always или off" ;;
            esac
            uci -q set splify2.main.fetch_via_tunnel="$mode"
            uci -q commit splify2
            json_init; json_add_boolean ok 1; json_add_string mode "$mode"; json_dump
        else
            json_init
            fetch_tunnel_on && json_add_string mode always || json_add_string mode off
            json_add_string out "$(fetch_out | cut -d' ' -f1)"
            json_dump
        fi
        ;;

    zm_fix|zm_fix_set)
        # Фикс Zapret Manager: уводить ли адреса GitHub в туннель. Включён по умолчанию — он
        # нужен именно тем, кто ещё ничего не настроил и до GitHub не дошёл.
        uci_file || fail "не удалось создать $UCI_SPLIFY2 — кончилось место?"
        uci -q get splify2.main >/dev/null 2>&1 || uci -q set splify2.main=splify2
        if [ "$2" = zm_fix_set ]; then
            read -r input
            json_load "$input" 2>/dev/null || fail "неразбираемый запрос"
            json_get_var on on
            case "$on" in
                1|true) uci -q set splify2.main.zm_fix=1 ;;
                0|false) uci -q set splify2.main.zm_fix=0 ;;
                *) fail "нужно true или false" ;;
            esac
            uci -q commit splify2
            json_init; json_add_boolean ok 1
            zm_fix_on && json_add_boolean on 1 || json_add_boolean on 0
            json_dump
        else
            json_init
            zm_fix_on && json_add_boolean on 1 || json_add_boolean on 0
            # Имя канала — чтобы интерфейс мог показать, что именно появится в правилах.
            json_add_string channel "$ZM_CHANNEL"
            json_dump
        fi
        ;;

    *) fail "неизвестный метод" ;;
esac
