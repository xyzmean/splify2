#!/bin/sh
# Часть объекта rpcd splify2 — подключается диспетчером /usr/libexec/rpcd/splify2 по имени
# метода. ЗАЧЕМ ФАЙЛОВ НЕСКОЛЬКО. busybox ash разбирает файл целиком, и объект в 4500 строк
# стоил 110 мс разбора на КАЖДЫЙ вызов — при том, что сам ответ считается за 30-90 мс.
# Диспетчер разбирает только себя, общие помощники (common.sh) и группу вызванного метода.
# Переменные и швы для стендов объявлены в диспетчере и здесь доступны как есть.


# Сеть по адресу с префиксом: 192.168.1.1/24 -> 192.168.1.0/24.
#
# Нужна для ПОДСКАЗКИ рядом с именем устройства в перечне сетей клиентов: сама
# маршрутизация адресов не спрашивает, движок сверяет `iifname`. Показывается сеть, а не
# адрес роутера, потому что человек узнаёт устройство по сети, в которой живут его
# компьютеры, а не по единственному адресу шлюза в ней.
#
# Всё, что не разбирается (не IPv4, мусор вместо длины), возвращается как есть: подставить
# выдуманную сеть хуже, чем показать строку, которую человек узнает.
cidr_net() {  # АДРЕС/ПРЕФИКС
    _cn_a="${1%%/*}"; _cn_p="${1#*/}"
    case "$_cn_p" in ''|*[!0-9]*) printf '%s' "$1"; return 0 ;; esac
    [ "$_cn_p" -le 32 ] || { printf '%s' "$1"; return 0; }
    case "$_cn_a" in
        *.*.*.*) ;;
        *) printf '%s' "$1"; return 0 ;;
    esac
    _cn_o1="${_cn_a%%.*}"; _cn_r="${_cn_a#*.}"
    _cn_o2="${_cn_r%%.*}"; _cn_r="${_cn_r#*.}"
    _cn_o3="${_cn_r%%.*}"; _cn_o4="${_cn_r#*.}"
    case "$_cn_o1$_cn_o2$_cn_o3$_cn_o4" in ''|*[!0-9]*) printf '%s' "$1"; return 0 ;; esac
    _cn_ip=$(( (_cn_o1 << 24) | (_cn_o2 << 16) | (_cn_o3 << 8) | _cn_o4 ))
    if [ "$_cn_p" -eq 0 ]; then _cn_m=0; else _cn_m=$(( 0xFFFFFFFF << (32 - _cn_p) )); fi
    _cn_ip=$(( _cn_ip & _cn_m & 0xFFFFFFFF ))
    printf '%u.%u.%u.%u/%u' "$(( (_cn_ip >> 24) & 255 ))" "$(( (_cn_ip >> 16) & 255 ))" \
        "$(( (_cn_ip >> 8) & 255 ))" "$(( _cn_ip & 255 ))" "$_cn_p"
}

# Измерить, где выходит трафик выхода, и запомнить. Ничего не печатает: зовётся и из
# фонового процесса, где печатать некуда, и из синхронной ветки метода, где ответ собирает
# сам метод. Код возврата: 0 — измерили и записали.
#
# Запрос уходит ЧЕРЕЗ УСТРОЙСТВО ВЫХОДА (`curl --interface`), поэтому способ один на все виды
# туннелей: у vless устройство создаёт сам движок, у остальных оно и так есть.
# Чем этот выход был, когда мы мерили. Номер устройства в системе: при смене узла или
# перечитывании подписки движок пересоздаёт TUN, и номер меняется. Ровно это и означает «мы
# теперь выходим в другом месте» — даже когда выбран «первый рабочий» и спека не менялась.
geo_ident() {  # ВЫХОД
    _gi_dev="$("$STEER" status --spec "$SPEC" 2>/dev/null |
        sed -n "s/.*\"$1\":{[^}]*\"device\":\"\([^\"]*\)\".*/\1/p" | head -1)"
    [ -n "$_gi_dev" ] || { printf 'none'; return; }
    printf '%s:%s' "$_gi_dev" "$(cat "/sys/class/net/$_gi_dev/ifindex" 2>/dev/null || echo 0)"
}

geo_refresh() {  # ВЫХОД
    _gr_dev="$("$STEER" status --spec "$SPEC" 2>/dev/null |
        sed -n "s/.*\"$1\":{[^}]*\"device\":\"\([^\"]*\)\".*/\1/p" | head -1)"
    [ -n "$_gr_dev" ] || return 1
    command -v curl >/dev/null 2>&1 || return 1
    _gr_url="$(uci -q get splify2.main.geo_url)"
    [ -n "$_gr_url" ] || _gr_url="$GEO_URL_DEFAULT"
    # ОДИН запрос на всё: адрес, страна и время ответа. Времени здесь взяться неоткуда,
    # кроме как отсюда, — и незачем: соединение через устройство выхода уже установлено,
    # а отдельная проверка отклика (outbound_probe) поднимает его ВТОРОЙ раз и через
    # движок. Замерено на роутере: такая проверка занимает девятнадцать секунд на выход,
    # то есть на четырёх выходах экран больше минуты стоит с надписью «меряем…».
    #
    # `time_total` — это весь путь: установка соединения, TLS и ответ. Оно и есть та
    # задержка, которую человек чувствует, открывая страницу через этот выход; ICMP до
    # узла к ней ближе не становится, а через TUN он и не ходит.
    _gr_out="$(curl -4 -fsS --interface "$_gr_dev" --connect-timeout 4 --max-time 8 \
        -w '\nsplify_ms=%{time_total}\n' "$_gr_url" 2>/dev/null)"
    _gr_ip="$(printf '%s\n' "$_gr_out" | sed -n 's/^ip=\(.*\)$/\1/p' | head -1)"
    _gr_cc="$(printf '%s\n' "$_gr_out" | sed -n 's/^loc=\([A-Za-z][A-Za-z]\)$/\1/p' | head -1)"
    # Секунды с дробью -> миллисекунды целым: считает awk, потому что shell дробей не знает.
    _gr_ms="$(printf '%s\n' "$_gr_out" | sed -n 's/^splify_ms=\(.*\)$/\1/p' | head -1 |
        awk '{ printf "%d", $1 * 1000 }' 2>/dev/null)"
    case "${_gr_ms:-}" in ''|*[!0-9]*) _gr_ms=0 ;; esac
    [ -n "$_gr_ip" ] || return 1
    mkdir -p "$GEO_DIR" 2>/dev/null
    # Время ответа дописано ПЯТЫМ полем, а не вставлено в середину: строки, записанные
    # прежней версией, читаются теми же четырьмя переменными, и пятая просто остаётся пустой.
    printf '%s %s %s %s %s\n' "$(date +%s)" "${_gr_cc:--}" "$_gr_ip" "$(geo_ident "$1")" \
        "$_gr_ms" > "$GEO_DIR/geo-$1" 2>/dev/null
}

# Достать JSON из вывода движка, к которому подмешаны его же человеческие строки.
#
# Движок пишет предупреждения в stderr («соединился, пропущено мёртвых адресов: 2 из 15»), а
# нам нужен и он — когда JSON не пришёл вовсе, только эта строка и объясняет, что случилось.
# Поэтому потоки сливаются, а JSON отсюда ВЫНИМАЕТСЯ, а не проверяется на первый символ.
#
# Проверка первого символа тут и подвела: строка предупреждения оказалась перед JSON, вызов
# посчитал ответ негодным и вернул всю мешанину как ошибку — на экране это выглядело красной
# полосой с сырым JSON внутри вместо «ответ 53 мс».
json_tail() {  # СЫРОЙ_ВЫВОД -> JSON или пусто
    printf '%s\n' "$1" | sed -n '/^{/,$p'
}

# ---- отчёт для поддержки: помощники -------------------------------------------------
#
# ЗАЧЕМ ВООБЩЕ НУЖЕН ОТЧЁТ. У проекта есть приговоры проверок (`steer diag`), состояние
# выходов (`steer status`), версии пакетов, каталог стратегий обхода и выбранный резолвер —
# и не было НИ ОДНОГО места, где всё это собрано в один текст. В трекере из-за этого висят
# обращения вида «а как посмотреть, что у меня стоит»: человек, у которого не работает
# сайт, не может ответить на первый же вопрос помогающего, потому что ответ разложен по
# шести экранам. Образец жанра — `global_check` у podkop: один человекочитаемый текст,
# который вставляют в чат целиком.
#
# ТЕКСТ, А НЕ ОБЪЕКТ ПОЛЕЙ. Всё остальное у объекта отвечает разобранным JSON — его читает
# интерфейс. Здесь читатель другой: человек, который жмёт «скопировать» и вставляет
# результат в чужой чат. Раскладывать это по полям значило бы, что верстать отчёт заново
# обязан каждый, кто его показывает, — а формулировки «поднят» и «автозапуск снят» и есть
# половина смысла отчёта.
sr_line() {  # СТРОКА
    SR_TEXT="$SR_TEXT$1
"
}

# Слово вместо признака: отчёт читает человек, и «1» ему ничего не говорит.
sr_word() {  # ПРИЗНАК ДА НЕТ
    case "${1:-}" in 1|true) printf '%s' "$2" ;; *) printf '%s' "$3" ;; esac
}

case "$2" in

    status)
        # Движок печатает JSON сам. Если он не отвечает — честная ошибка, а не пустой
        # объект, который интерфейс покажет как «всё в порядке».
        out="$("$STEER" status --spec "$SPEC" 2>/dev/null)"
        case "$out" in '{'*) printf '%s\n' "$out" ;; *) fail "движок не ответил" ;; esac
        ;;

    diag)
        # Проверки состояния — движок печатает JSON сам. Отдаём дословно по той же причине,
        # что и status: свой разбор здесь означал бы вторую модель проверок в shell, которая
        # начнёт расходиться с движком при первой же новой проверке.
        #
        # Ненулевой код возврата — НЕ повод для ошибки: движок возвращает 1, когда нашёл
        # поломку, и это ровно тот ответ, который надо показать. Проверяем по виду вывода.
        out="$("$STEER" diag --spec "$SPEC" 2>/dev/null)"
        case "$out" in
            '{'*) printf '%s\n' "$out" ;;
            *) fail "движок не умеет diag — обновите steer" ;;
        esac
        ;;

    dev_stats)
        # Счёт устройств живёт в /usr/lib/splify2/fast.sh — там же, откуда его берёт круг
        # опроса. Одна реализация на два входа: копия здесь означала бы два места, где
        # считаются одни и те же числа, и они разошлись бы молча.
        #
        # Метод остался ради совместимости: страница спрашивает его отдельно только на
        # движке без метода `live` (старый пакет интерфейса), а вызывать его есть кому и
        # снаружи — контракт docs/rpcd-api.md объявлен и не отзывается.
        . "${FAST_SH:-/usr/lib/splify2/fast.sh}"
        fast_devices
        ;;

    net_info)
        # Сведения о сети считает /usr/lib/splify2/fast.sh — тот же довод, что у dev_stats:
        # одна реализация на два входа. Там же записано, почему внешнего адреса здесь нет.
        . "${FAST_SH:-/usr/lib/splify2/fast.sh}"
        printf '{%s}\n' "$(fast_net)"
        ;;

    devices)
        # Кандидаты в выход interface: только туннельные устройства.
        #
        # Отбор по /sys/class/net/*/type, а не по имени. Признак — ARPHRD_NONE (65534):
        # он у wireguard, amneziawg и tun, и его нет ни у мостов, ни у физических портов,
        # ни у wifi. 768 — ARPHRD_TUNNEL (ipip, gre), тоже туннель.
        #
        # Раньше отбор шёл по имени и отсекал eth*, но на современном OpenWrt порты
        # называются lan2, lan3, wan — и они попадали в список. Выход в физический порт
        # молча ничего не маршрутизирует: конфигурация выглядит настроенной, трафик
        # пропадает. Проверено на роутере — предлагались wan и три lan-порта.
        json_init
        json_add_array devices
        _dev_seen=" "
        # Файлы /sys читаются ВСТРОЕННЫМ read, а имя берётся подстановкой параметра.
        # Было четыре запуска процессов на устройство (basename и три cat, у одного из них
        # ещё sed с head в конвейере), устройств на типовой коробке десять — сорок с лишним
        # процессов на вызов. Замер на стенде 10.8.1.87: 287 мс, из которых сам ответ —
        # единицы миллисекунд. Тот же приём и по той же причине уже применён к счётчикам
        # устройств (см. fast.sh).
        for d in "$OUT_SYSNET"/*; do
            [ -d "$d" ] || continue
            n="${d##*/}"
            _t=''
            read -r _t < "$d/type" 2>/dev/null || continue
            case "$_t" in
                65534|768) ;;
                *) continue ;;
            esac
            # Физическое устройство туннелем не бывает: у него есть ссылка device.
            [ -e "$d/device" ] && continue
            _dev_seen="$_dev_seen$n "
            _op=''
            read -r _op < "$d/operstate" 2>/dev/null || _op=''
            # DEVTYPE стоит в uevent отдельной строкой; строк там единицы, поэтому перебор
            # встроенным read дешевле запуска sed.
            _kind=''
            while read -r _l; do
                case "$_l" in DEVTYPE=*) _kind="${_l#DEVTYPE=}"; break ;; esac
            done < "$d/uevent" 2>/dev/null
            json_add_object ""
            json_add_string name "$n"
            json_add_boolean up "$([ "$_op" = down ] && echo 0 || echo 1)"
            json_add_string kind "$_kind"
            json_close_object
        done
        # Устройства выходов, которые поднимает САМ ДВИЖОК (kind=vless, kind=xsteer).
        #
        # В /sys/class/net они появляются вместе со своим процессом, а не с настройкой,
        # поэтому выключенного сейчас туннеля в перечне не было вовсе — и законную форму
        # смешанного пула (устройство локации подписки рядом с wg0) с экрана было не собрать
        # (I-161). Перечень отвечает на «куда можно выпустить трафик», а это вопрос о
        # НАСТРОЙКЕ: локация, выключенная сегодня, завтра поднимется, и класть её в пул
        # человек вправе сейчас.
        #
        # Имена спрашиваются у движка (--devices), а не выводятся из имён выходов: устройство
        # выводится из имени выхода, НО может быть задано в спеке явно, и тогда «имя выхода» —
        # молча неверный список. Тот же довод, что у fw_devices_of, и та же функция.
        #
        # up здесь всегда 0: устройства нет, и это ровно то, что о нём известно.
        for n in $(fw_devices_of vless,xsteer); do
            case "$_dev_seen" in *" $n "*) continue ;; esac
            _dev_seen="$_dev_seen$n "
            json_add_object ""
            json_add_string name "$n"
            json_add_boolean up 0
            json_add_string kind ""
            json_close_object
        done
        json_close_array
        json_dump
        ;;

    client_nets)
        # Откуда приходят клиенты: устройства роутера, которые могут быть СЕТЬЮ КЛИЕНТОВ,
        # и подсети, которые из их адресов выводятся.
        #
        # ЗАЧЕМ. splify2#16. Роутер бывает выходной точкой не только для домашнего моста:
        # у автора обращения через него ходят ещё и хосты из Tailscale и ZeroTier, и правила
        # к ним хочется применять те же. В splify1 это был перечень интерфейсов через запятую
        # в /etc/config, здесь же выбирать было не из чего — перечня не существовало вовсе.
        # Соседний метод `devices` отвечает на противоположный вопрос (куда трафик выпустить)
        # и отбирает ровно туннели, поэтому переиспользовать его нельзя: домашнего моста в
        # его ответе нет и быть не должно.
        #
        # ЧТО ОТСЕИВАЕТСЯ И ПОЧЕМУ ИМЕНЕМ НЕ ОТСЕИВАЕТСЯ НИЧЕГО.
        #  * `lo` — единственное имя, зашитое здесь: петля клиентом не бывает ни на одном
        #    роутере, и объяснять её присутствие в списке пришлось бы каждому.
        #  * Порт внутри моста (есть ссылка `master`) — своей сетью не является: клиенты
        #    приходят через мост, и правило по `lan1` не увидело бы ни одного пакета.
        #  * wan НЕ отсеивается, а помечается. Отбор по имени тут особенно вреден: на одном
        #    роутере внешний интерфейс называется wan, на другом eth0.2, на третьем это
        #    вообще мост. Спрашиваем uci — он и есть ответ на «что здесь наружу». А выкинуть
        #    устройство совсем нельзя: человек ищет его глазами, не находит и решает, что
        #    перечень сломан. Помеченное он не выберет, и это разные вещи.
        #
        # ПОДСЕТЬ ЗДЕСЬ — ПОДСКАЗКА, А НЕ НАСТРОЙКА. Движок отвечает на «кто» правилом
        # `iifname` по именам устройств, и адреса в этом не участвуют вовсе; подсеть нужна
        # человеку, чтобы узнать, какое устройство какое. Именно поэтому клиентов и
        # описывают именем: у Tailscale адрес на роутере /32, то есть подсеть пиров из него
        # не выводится, а у клиентов за вторым роутером в LAN адреса чужой подсети при том
        # же интерфейсе.
        _cn_wan="$(uci -q get network.wan.device 2>/dev/null)"
        [ -n "$_cn_wan" ] || _cn_wan="$(uci -q get network.wan.ifname 2>/dev/null)"
        # Адреса ВСЕХ устройств одним запуском `ip`, а не по запуску на устройство.
        # Строки вида «br-lan 192.168.1.1/24»; второе поле после `inet` — адрес с префиксом,
        # хвост строки (brd, scope) отбрасывается. Было десять запусков на типовой коробке,
        # и каждый на 880 МГц стоит около двадцати миллисекунд (замер на стенде: 283 мс на
        # вызов при десяти мс на сам `ip`).
        _cn_addrs="$(ip -4 -o addr show 2>/dev/null |
                     awk '{ for (i = 1; i < NF; i++) if ($i == "inet") { print $2, $(i + 1); break } }')"
        json_init
        json_add_array nets
        for d in "$SYSNET"/*; do
            [ -d "$d" ] || continue
            n="${d##*/}"
            [ "$n" = lo ] && continue
            # Порт внутри моста: своя сеть у него не бывает, клиенты придут через мост.
            [ -e "$d/master" ] && continue
            _op=''
            read -r _op < "$d/operstate" 2>/dev/null || _op=''
            json_add_object ""
            json_add_string name "$n"
            json_add_boolean up "$([ "$_op" = down ] && echo 0 || echo 1)"
            json_add_boolean wan "$([ -n "$_cn_wan" ] && [ "$n" = "$_cn_wan" ] && echo 1 || echo 0)"
            json_add_array subnets
            # Устройство без адреса даёт пустой массив, а не пропуск: выбрать его законно,
            # адрес появится вместе с поднятием.
            _OIFS="$IFS"; IFS='
'
            for _row in $_cn_addrs; do
                IFS="$_OIFS"
                set -- $_row
                if [ "${1:-}" = "$n" ]; then
                    case "${2:-}" in
                        */*) json_add_string "" "$(cidr_net "$2")" ;;
                    esac
                fi
                IFS='
'
            done
            IFS="$_OIFS"
            json_close_array
            json_close_object
        done
        json_close_array
        json_dump
        ;;

    leases)
        # Аренды DHCP — чтобы «кого касается» выбирали из имён устройств, а не набирали MAC
        # руками. Опечатка в MAC не совпадёт ни с чем и не пожалуется: правило просто не будет
        # действовать, и объяснить это человеку будет нечем.
        json_init
        json_add_array leases
        while read -r _exp mac ip name _rest; do
            [ -n "$mac" ] || continue
            json_add_object
            json_add_string mac "$mac"
            json_add_string ip "$ip"
            # «*» в файле аренд значит «имени не сообщил». Показывать звёздочку человеку
            # незачем — пусть будет пусто, а интерфейс подставит адрес.
            [ "$name" = '*' ] && name=''
            json_add_string name "$name"
            json_close_object
        done < /tmp/dhcp.leases 2>/dev/null
        json_close_array
        json_dump
        ;;

    engine_state)
        # Состояние экземпляров движка и его последние слова.
        #
        # Понадобилось из-за того, что «выход настроен» и «туннель несёт трафик» — разные
        # вещи, а до сих пор интерфейс различал их только по наличию устройства. Устройство
        # у vless создаёт сам процесс туннеля, поэтому мёртвый туннель виден как пропавшее
        # устройство — но НЕ видно, почему он умер, и человеку оставалось лезть в logread.
        #
        # Движок теперь завершается с ненулевым кодом, когда туннель перестал нести трафик
        # (раньше в этом случае возвращался ноль, и procd с интерфейсом считали, что всё
        # прошло успешно). Значит procd знает про отказ, и это знание можно показать.
        #
        # Текст сообщений движка здесь НЕ разбирается, и это осознанно: их формулировки
        # меняются вместе с движком, а разбор на стороне интерфейса означал бы, что каждая
        # правка сообщения тихо ломает показ. Отдаём последние строки дословно — человек
        # прочитает их сам, а согласовывать нечего.
        # Собираем ДО json_init своего ответа: json_load затирает разбираемый документ,
        # и смешивать чужой разбор со своей сборкой в одном наборе нельзя.
        names=''
        state="$(ubus call service list '{"name":"steer","verbose":true}' 2>/dev/null)"
        if [ -n "$state" ] && json_load "$state" 2>/dev/null &&
           json_select steer 2>/dev/null && json_select instances 2>/dev/null; then
            json_get_keys inames
            for nm in $inames; do
                json_select "$nm" 2>/dev/null || continue
                json_get_var r running
                json_get_var p pid
                # Имя экземпляра — vless_<выход>, а выход проверен движком при apply:
                # пробелов и кавычек в нём быть не может, поэтому список через пробел.
                names="$names $nm:${r:-0}:${p:-0}"
                json_select ..
            done
        fi
        # Последние слова движка. Дословно и без разбора — см. пояснение выше.
        lines="$(logread -l 300 2>/dev/null | grep 'steer' | tail -12)"

        json_init
        json_add_object instances
        for e in $names; do
            nm="${e%%:*}"; rest="${e#*:}"
            json_add_object "$nm"
            json_add_boolean running "${rest%%:*}"
            json_add_int pid "${rest##*:}"
            json_close_object
        done
        json_close_object
        json_add_array log
        # Перебор построчно: в строках журнала есть пробелы, кавычки и что угодно ещё,
        # поэтому только IFS-разделение по переводу строки, а экранирование — на json_add_string.
        OIFS="$IFS"; IFS='
'
        for l in $lines; do json_add_string "" "$l"; done
        IFS="$OIFS"
        json_close_array
        json_dump
        ;;

    outbound_geo)
        # Где выходит трафик этого выхода: страна и адрес, как их видит внешняя сторона.
        #
        # ЗАЧЕМ МЕРИТЬ, А НЕ ЧИТАТЬ. Имя узла подписки («🇩🇪 Германия №2») пишет продавец, и
        # это подпись, а не факт: узел мог переехать, а у выходов поверх WireGuard и xsteer
        # имени нет вовсе. Поэтому спрашиваем у внешней стороны — и спрашиваем ЧЕРЕЗ САМ
        # ВЫХОД, привязав запрос к его устройству (`curl --interface`). Тогда ответ описывает
        # ровно ту точку, из которой роутер выходит в интернет, и способ один на все виды
        # выходов: у vless устройство создаёт сам движок, у остальных оно и так есть.
        #
        # ПОЧЕМУ ОТВЕТ ЗАПОМИНАЕТСЯ. Обращение наружу стоит секунд, а страница открывается
        # часто. Свежее измерение отдаётся из файла мгновенно, и только устаревшее (старше
        # GEO_TTL) заставляет сходить в сеть. Интерфейс к тому же рисует запомненное ещё до
        # ответа метода — вместе это и убирает паузу на открытии.
        read -r input
        json_load "$input" 2>/dev/null || fail "неразбираемый запрос"
        json_get_var output output
        json_get_var fresh fresh
        [ -n "$output" ] || fail "не указан выход"
        case "$output" in *[!a-zA-Z0-9_-]*) fail "недопустимое имя выхода" ;; esac

        _geo_f="$GEO_DIR/geo-$output"
        _geo_now="$(date +%s)"
        _geo_ip=''; _geo_cc=''; _geo_at=0; _geo_ms=''
        if [ -s "$_geo_f" ]; then
            read -r _geo_at _geo_cc _geo_ip _geo_id _geo_ms < "$_geo_f"
            case "${_geo_at:-}" in ''|*[!0-9]*) _geo_at=0 ;; esac
            # Прочерк в файле означает «страну не назвали»: поле в строке обязано быть,
            # иначе следующее (адрес) прочиталось бы на его место.
            [ "${_geo_cc:-}" = "-" ] && _geo_cc=''
            # Выход с тех пор пересоздали — значит и выходим мы теперь в другом месте.
            # Прежнее измерение не отдаём вовсе: «Эстония» рядом с только что выбранной
            # Польшей хуже пустоты, потому что выглядит как ответ.
            if [ -n "${_geo_id:-}" ] && [ "$_geo_id" != "$(geo_ident "$output")" ]; then
                _geo_at=0; _geo_cc=''; _geo_ip=''; _geo_ms=''
            fi
        fi
        _geo_age=$(( _geo_now - _geo_at ))

        # БЕЗ `fresh` МЕТОД НЕ ХОДИТ В СЕТЬ ВООБЩЕ — и это главное в нём.
        #
        # LuCI складывает вызовы страницы в ОДИН запрос к ubus и выполняет их подряд, поэтому
        # медленный вызов задерживает все остальные: пока этот метод ждал ответа из сети,
        # обзор восемь секунд писал «Загрузка…», хотя состояние движка было готово через
        # четверть секунды. Замерено на роутере: пакет вызовов занимал 5,6 с при 150-250 мс
        # на каждый вызов по отдельности.
        #
        # Поэтому обычный вызов отвечает тем, что запомнено (пусть даже пустотой), а
        # устаревшее измерение обновляется В ФОНЕ и приедет к следующему опросу. Поток
        # фонового процесса уводится в /dev/null нарочно: иначе он держал бы открытой
        # трубу, из которой rpcd читает ответ, и вызов не завершился бы до конца curl.
        if [ "$fresh" != "1" ] && [ "$fresh" != "true" ]; then
            if [ "$_geo_at" -le 0 ] || [ "$_geo_age" -ge "$GEO_TTL" ]; then
                geo_refresh "$output" >/dev/null 2>&1 &
            fi
            json_init
            json_add_string output "$output"
            [ -n "$_geo_ip" ] && json_add_string ip "$_geo_ip"
            [ -n "$_geo_cc" ] && json_add_string cc "$_geo_cc"
            # Время ответа того же запроса. Ноль означает «не мерили» — так читаются и
            # строки, записанные прежней версией, где пятого поля не было вовсе.
            [ "${_geo_ms:-0}" -gt 0 ] 2>/dev/null && json_add_int ms "$_geo_ms"
            [ "$_geo_at" -gt 0 ] && json_add_int at "$_geo_at"
            json_add_boolean cached 1
            json_dump
            exit 0
        fi

        json_init
        json_add_string output "$output"
        if geo_refresh "$output"; then
            read -r _geo_at _geo_cc _geo_ip _geo_id _geo_ms < "$GEO_DIR/geo-$output"
            [ "${_geo_cc:-}" = "-" ] && _geo_cc=''
            unset _geo_id
            json_add_string ip "$_geo_ip"
            [ -n "$_geo_cc" ] && json_add_string cc "$_geo_cc"
            [ "${_geo_ms:-0}" -gt 0 ] 2>/dev/null && json_add_int ms "$_geo_ms"
            json_add_int at "$_geo_at"
            json_add_boolean cached 0
        else
            # Измерить не вышло. Прежнее измерение всё равно отдаём: «где мы выходили в
            # прошлый раз» полезнее пустоты, а его возраст виден по полю at.
            [ -n "$_geo_ip" ] && json_add_string ip "$_geo_ip"
            [ -n "$_geo_cc" ] && json_add_string cc "$_geo_cc"
            [ "${_geo_ms:-0}" -gt 0 ] 2>/dev/null && json_add_int ms "$_geo_ms"
            [ "$_geo_at" -gt 0 ] && json_add_int at "$_geo_at"
            json_add_string why "через выход не ответили — выход не поднят, нет curl или молчит адрес проверки"
        fi
        json_dump
        ;;

    outbound_probe)
        # Отклик по ОДНОМУ выходу за вызов — по той же причине, что у vless_probe: проверка
        # упирается в таймаут, и «проверить все» не уложилось бы в срок жизни вызова ubus.
        #
        # Два разных способа, потому что это два разных вопроса. У vless отклик мерит сам
        # движок: ICMP через TUN не ходит вовсе, и ping показал бы «нет ответа» у исправного
        # туннеля. У обычного устройства меряем ping через него.
        read -r input
        json_load "$input" 2>/dev/null || fail "неразбираемый запрос"
        json_get_var output output
        [ -n "$output" ] || fail "не указан выход"
        kind=''
        for o in $("$STEER" outputs --kind vless --spec "$SPEC" 2>/dev/null); do
            [ "$o" = "$output" ] && kind=vless
        done
        json_init
        json_add_string output "$output"
        if [ "$kind" = vless ]; then
            out="$("$STEER" vless-probe "$output" --node -1 --timeout 6 --spec "$SPEC" 2>/dev/null)"
            ms="$(printf '%s' "$out" | sed -n 's/.*"ttfb_ms":[ ]*\([0-9]*\).*/\1/p')"
            case "$ms" in
                ''|*[!0-9]*) json_add_string state 'нет ответа'; json_add_int ms -1 ;;
                *) json_add_string state ok; json_add_int ms "$ms" ;;
            esac
            json_add_string how 'через туннель: ICMP по нему не ходит, меряет движок'
        else
            dev="$("$STEER" status --spec "$SPEC" 2>/dev/null |
                   sed -n "s/.*\"$output\":{[^}]*\"device\":\"\([^\"]*\)\".*/\1/p" | head -1)"
            if [ -z "$dev" ]; then
                json_add_string state 'нет устройства'; json_add_int ms -1
            else
                r="$(ping -c 1 -W 3 -I "$dev" 1.1.1.1 2>/dev/null | sed -n 's/.*time=\([0-9.]*\).*/\1/p' | head -1)"
                case "$r" in
                    '') json_add_string state 'нет ответа'; json_add_int ms -1 ;;
                    *)  json_add_string state ok; json_add_int ms "${r%%.*}" ;;
                esac
            fi
            json_add_string how 'ping через устройство выхода'
        fi
        json_dump
        ;;

    explain)
        read -r input
        json_load "$input" 2>/dev/null || fail "неразбираемый запрос"
        json_get_var address address
        [ -n "$address" ] || fail "не указан адрес"
        json_init
        json_add_string text "$("$STEER" explain "$address" --spec "$SPEC" 2>&1)"
        json_dump
        ;;

    xsteer_state)
        # Живое состояние туннелей xsteer: разгрузка, рукопожатие, восстановления, счётчики.
        #
        # ЗАЧЕМ ОТДЕЛЬНЫЙ МЕТОД, А НЕ ПОЛЕ live. Туннель xsteer, поднятый через netifd, движку не
        # принадлежит: в спеке он — обычный `kind: interface`, и `status` про него знает ровно то,
        # что знает про любое устройство (поднято ли, счётчики). Всё остальное — какой хаб, сколько
        # секунд назад было рукопожатие, встала ли разгрузка сегментации, сколько раз соединение
        # переподнималось и почему в последний раз — знает только сам процесс пира, и он пишет это в
        # свой файл состояния. Складывать это в `live` значило бы платить чтением файлов на каждый
        # круг опроса всем, у кого xsteer нет вовсе.
        #
        # Ответ ОТДАЁТСЯ ПЕЧАТЬЮ, а не собирается jshn: содержимое файла — уже готовый JSON от
        # движка, и разобрать его, чтобы тут же собрать заново, значило бы переписывать чужую схему
        # у себя. Так же поступает метод `status` — и по той же причине.
        #
        # Имена секций uci ограничены [A-Za-z0-9_], но проверяются всё равно: правило I-003 гласит,
        # что имя, попадающее в путь или в командную строку, проверяет тот, кто его подставляет, а
        # не тот, кто его записал.
        _now=$(date +%s)
        printf '{"ok":true,"tunnels":{'
        _first=1
        for _s in $(uci -q show network 2>/dev/null | sed -n \
                    "s/^network\.\([^.]*\)\.proto='xsteer'$/\1/p"); do
            backup_safe_word "$_s" || continue
            _dev=$(uci -q get "network.$_s.device_name")
            [ -n "$_dev" ] || _dev="xs-$_s"
            backup_safe_word "$_dev" || continue
            _f="$XS_STATE_DIR/xsteer-$_dev.json"
            [ "$_first" = 1 ] || printf ','
            _first=0
            printf '"%s":{"device":"%s"' "$_s" "$_dev"
            if [ -f "$_f" ]; then
                # ВОЗРАСТ ФАЙЛА, а не «свежий/несвежий»: порог решает интерфейс, потому что он
                # знает, как часто спрашивает. Процесс, которого убили, оставляет файл лежать
                # навсегда — и без возраста его последнее «up: true» выглядело бы живым.
                _mt=$(date -r "$_f" +%s 2>/dev/null || echo "$_now")
                printf ',"age":%s,"state":%s' "$((_now - _mt))" "$(cat "$_f" 2>/dev/null)"
            else
                # Файла нет — туннель не поднимался в этой загрузке. Это НЕ ошибка и не пустое
                # состояние: разница между «не поднимался» и «поднят и молчит» ровно та, за которой
                # человек сюда и пришёл.
                printf ',"state":null'
            fi
            printf '}'
        done
        printf '}}\n'
        ;;

    vless_nodes)
        read -r input
        json_load "$input" 2>/dev/null || fail "неразбираемый запрос"
        json_get_var output output
        json_get_var sub sub
        # Узлы можно спросить и у ПОДПИСКИ, без выхода: движок принимает путь к файлу вместо
        # имени выхода (steer vless-nodes /путь). Нужно редактору выхода: локации подписки
        # показываются до того, как на неё заведён хоть один выход, — иначе выход собирался бы
        # вслепую. Путь принимается только СВОЙ — из перечня подписок роутера: метод читает
        # файл с диска, и произвольный путь означал бы чтение произвольного файла.
        if [ -n "$sub" ]; then
            _vn_ok=0
            for _vn_n in $(sub_names); do
                sub_use "$_vn_n"
                [ "$SUB" = "$sub" ] && { _vn_ok=1; break; }
            done
            [ "$_vn_ok" = 1 ] || fail "нет такой подписки: $sub"
            [ -s "$sub" ] || fail "подписка ещё не скачана"
            output="$sub"
        fi
        [ -n "$output" ] || fail "не указан выход"
        # Движок печатает JSON сам — отдаём дословно. Разбирать его здесь значило бы
        # держать вторую модель узла в shell, а имена узлов приходят из подписки и
        # содержат что угодно, включая кавычки.
        raw="$("$STEER" vless-nodes "$output" --spec "$SPEC" 2>&1)"
        out="$(json_tail "$raw")"
        [ -n "$out" ] || fail "${raw:-движок не ответил}"
        printf '%s\n' "$out"
        ;;

    vless_probe)
        read -r input
        json_load "$input" 2>/dev/null || fail "неразбираемый запрос"
        json_get_var output output
        json_get_var node node
        [ -n "$output" ] || fail "не указан выход"
        # По одному узлу за вызов: проверка упирается в таймаут, и «проверить все» на
        # подписке из двадцати шести узлов заняло бы дольше, чем живёт вызов ubus.
        # Интерфейс спрашивает по одному и заполняет таблицу постепенно.
        [ -n "$node" ] || node=-1
        raw="$("$STEER" vless-probe "$output" --node "$node" --timeout 6 --spec "$SPEC" 2>&1)"
        out="$(json_tail "$raw")"
        [ -n "$out" ] || fail "${raw:-движок не ответил}"
        printf '%s\n' "$out"
        ;;

    support_report)
        # Один текст «скопировать в чат поддержки»: версии, приговоры проверок, выходы,
        # правила, обход DPI, DNS и подписка — тем же составом, каким об этом спрашивают в
        # обращениях. Зачем текстом, а не полями — в шапке помощника sr_line выше.
        #
        # ГЛАВНОЕ ТРЕБОВАНИЕ — НИ ОДНОГО СЕКРЕТА. Текст уезжает в общий чат, поэтому в нём
        # не должно быть ссылки подписки (в ней ключ доступа к панели), ссылок узлов,
        # приватных ключей туннелей, UUID узлов, имён узлов подписки и внешнего адреса
        # роутера. Имена узлов — не перестраховка: их пишет ПАНЕЛЬ, и там встречаются и
        # рекламные сообщения, и логин владельца.
        #
        # Отсюда способ сборки: отчёт читает ТОЛЬКО НАЗВАННЫЕ ПОЛЯ чужих ответов и никогда
        # не пересказывает документ целиком. Разница не косметическая. Выход в `steer status`
        # несёт поля спеки (контракт steer §2: OutputStatus — это Output плюс состояние), то
        # есть путь к файлу подписки и номера узлов; ответ `vless-nodes` несёт весь список
        # узлов с их именами и адресами. Дословный пересказ любого из двух — это готовая
        # утечка, а не «лишние подробности», и заметить её в тексте на сорок строк почти
        # невозможно. Поэтому берутся только `kind`/`up`/`device` у выхода и только числа
        # `usable`/`skipped`/`foreign` у подписки.
        #
        # ЧТО СЧИТАЕТСЯ ЗДЕСЬ — НИЧЕГО. Каждое число и каждое слово ниже приходит от того,
        # кто и так за него отвечает: версии и вариант сборки — от своего же метода `engine`
        # (см. ниже, почему подпроцессом), приговоры и состояние выходов — от движка,
        # обход DPI — от zapret.sh, резолвер — от doh.sh, подписки — от common.sh и движка.
        # Вторая реализация любого из них означала бы, что отчёт для поддержки описывает
        # роутер иначе, чем экраны, по которым его чинят, — а расходятся такие пары молча.
        SR_TEXT=""
        sr_line "=== splify2: отчёт для поддержки ==="
        # Время сборки: отчёт живёт в чате часами, и «когда это было снято» — первый вопрос
        # к нему. Без часового пояса: у роутера он бывает не выставлен вовсе.
        sr_line "собран: $(date '+%Y-%m-%d %H:%M')"

        # ---- версии и устройство --------------------------------------------------------
        #
        # ПОЧЕМУ МЕТОД `engine` ЗОВЁТСЯ ПОДПРОЦЕССОМ, А НЕ КОПИЕЙ ЕГО ПОМОЩНИКОВ. Версия
        # пакета, архитектура, вариант сборки и состояние службы считаются в группе движка
        # (m-engine.sh: pkg_version с памятью до смены базы пакетов, pkg_arch, engine_enabled,
        # engine_running) — четыре помощника, которых в этой группе нет и быть не должно:
        # файлы разнесены как раз затем, чтобы каждый вызов разбирал только свою группу.
        # Копия здесь означала бы пятое место, где решается «какая версия стоит», причём в
        # отчёте, по которому потом судят о роутере.
        #
        # Цена — один лишний разбор скрипта объекта (126 мс на mipsel 880 МГц). Она платится
        # РАЗ на нажатие кнопки, а не на каждом круге опроса, и это ровно тот случай, когда
        # честный ответ дороже миллисекунд. Вход подпроцессу закрыт (`</dev/null`): метод
        # `engine` стандартный ввод не читает, но оставлять ему наш — значит однажды съесть
        # чужой запрос.
        _sr_e="$(sh "$0" call engine </dev/null 2>/dev/null)"
        _sr_eok=0
        _sr_present=0; _sr_vless=0; _sr_ever=""; _sr_arch=""; _sr_en=0; _sr_run=0
        if [ -n "$_sr_e" ] && json_load "$_sr_e" 2>/dev/null; then
            json_get_var _sr_present present
            # Признак «ответ годен» — по полю `present`, а не по разбору JSON: объект ошибки
            # ({"ok":false,...}) разбирается прекрасно, и без этой проверки отказ метода
            # читался бы как «движка нет» — то есть самый громкий диагноз отчёта выдавался
            # бы по самому тихому поводу.
            case "$_sr_present" in 0|1) _sr_eok=1 ;; esac
            json_get_var _sr_vless vless
            json_get_var _sr_ever version
            json_get_var _sr_arch arch
            json_get_var _sr_en enabled
            json_get_var _sr_run running
        fi

        sr_line ""
        sr_line "-- устройство --"
        # Модель — из того же файла, откуда её берёт вся OpenWrt. Швом, потому что на машине
        # разработчика /tmp/sysinfo нет вовсе.
        _sr_model="$(sed -n '1{s/[[:space:]]*$//;p;}' "${SYSINFO_MODEL:-/tmp/sysinfo/model}" 2>/dev/null)"
        sr_line "модель: ${_sr_model:-не сообщил}"
        # Версия прошивки — из файла описания системы, тем же способом, каким оттуда читается
        # архитектура (pkg_arch в группе движка). DISTRIB_DESCRIPTION предпочтительнее номера:
        # в нём есть и ревизия сборки, а поддержке важна именно она.
        _sr_os=""
        [ -f "$OPENWRT_RELEASE" ] && _sr_os="$( . "$OPENWRT_RELEASE" 2>/dev/null
            printf '%s' "${DISTRIB_DESCRIPTION:-${DISTRIB_RELEASE:-}}" )"
        sr_line "прошивка: ${_sr_os:-не определилась}"
        sr_line "архитектура пакетов: ${_sr_arch:-не определилась}"
        sr_line "менеджер пакетов: $PM"

        sr_line ""
        sr_line "-- версии --"
        # Интерфейс — НОМЕРОМ СБОРКИ, а не версией пакета, и это осознанно. Номер сборки
        # читает загрузчик страницы на каждой загрузке (build-id.txt), у выпуска он равен
        # версии пакета, а у сборки из main вдобавок несёт ревизию и метку dirty — то есть
        # отвечает на вопрос поддержки точнее («какой ровно бандл у человека в браузере»).
        # Спрашивать вместо этого пакет значило бы либо копировать pkg_version, либо звать
        # метод splify2_versions, который перед ответом идёт за перечнем релизов в сеть — в
        # отчёте, который собирают как раз тогда, когда с сетью беда.
        _sr_ui="$(sed -n '1{s/[[:space:]]*$//;p;}' \
            "${BUILD_ID_FILE:-/www/luci-static/resources/splify2/build-id.txt}" 2>/dev/null)"
        sr_line "интерфейс splify2: ${_sr_ui:-не определилась} (номер сборки; у выпуска равен версии пакета)"
        if [ "$_sr_eok" != 1 ]; then
            # Свой же метод не ответил — и выдать это за «движка нет» нельзя: диагноз
            # «маршрутизации нет вовсе» уводит помогающего чинить не то. Отчёт обязан
            # называть незнание незнанием, ровно как это делают методы, проксирующие движок.
            sr_line "движок steer: узнать не удалось — метод engine не ответил"
        elif [ "$_sr_present" = 1 ]; then
            sr_line "движок steer: ${_sr_ever:-версия не определилась}, сборка $(sr_word "$_sr_vless" 'расширенная (VLESS есть)' 'базовая (VLESS нет)')"
            sr_line "служба движка: $(sr_word "$_sr_run" 'работает' 'не работает'), автозапуск $(sr_word "$_sr_en" 'включён' 'снят')"
        else
            # Отсутствие движка — самое важное, что может быть в отчёте: без него не работает
            # ничего, и половина обращений оказывается именно этим.
            sr_line "движок steer: НЕ УСТАНОВЛЕН — маршрутизации нет вовсе"
        fi

        # ---- приговоры проверок ---------------------------------------------------------
        #
        # Читаемым видом, а не JSON'ом: документ проверок и придуман как {id, verdict, what,
        # why}, где `what` и `why` — уже готовые русские фразы движка. Пересказывать их
        # своими словами здесь нельзя (формулировки принадлежат движку и меняются вместе с
        # ним), а показывать человеку JSON — значит требовать от него читать наш формат.
        sr_line ""
        sr_line "-- проверки движка (steer diag) --"
        _sr_d="$("$STEER" diag --spec "$SPEC" 2>/dev/null)"
        _sr_d="$(json_tail "$_sr_d")"
        if [ -n "$_sr_d" ] && json_load "$_sr_d" 2>/dev/null; then
            if json_select checks 2>/dev/null; then
                json_get_keys _sr_ks
                for _sr_k in $_sr_ks; do
                    json_select "$_sr_k" 2>/dev/null || continue
                    _sr_id=""; _sr_v=""; _sr_w=""; _sr_y=""
                    json_get_var _sr_id id
                    json_get_var _sr_v verdict
                    json_get_var _sr_w what
                    json_get_var _sr_y why
                    case "$_sr_v" in
                        fail) _sr_m="[ПРОВАЛ]" ;;
                        warn) _sr_m="[ВНИМАНИЕ]" ;;
                        note) _sr_m="[замечание]" ;;
                        *)    _sr_m="[в порядке]" ;;
                    esac
                    sr_line "$_sr_m ${_sr_id:-без имени}: ${_sr_w}${_sr_y:+ — $_sr_y}"
                    json_select ..
                done
                json_select ..
            fi
            _sr_fail=""; _sr_warn=""
            json_get_var _sr_fail fail
            json_get_var _sr_warn warn
            sr_line "итог: провалов ${_sr_fail:-0}, предупреждений ${_sr_warn:-0}"
        else
            sr_line "движок не ответил на diag — он старее проверок или не запускается"
        fi

        # ---- выходы и наборы правил в ядре ----------------------------------------------
        sr_line ""
        sr_line "-- выходы --"
        _sr_s="$("$STEER" status --spec "$SPEC" 2>/dev/null)"
        _sr_s="$(json_tail "$_sr_s")"
        if [ -n "$_sr_s" ] && json_load "$_sr_s" 2>/dev/null; then
            if json_select outputs 2>/dev/null; then
                json_get_keys _sr_outs
                for _sr_o in $_sr_outs; do
                    json_select "$_sr_o" 2>/dev/null || continue
                    _sr_kind=""; _sr_up=""; _sr_dev=""
                    json_get_var _sr_kind kind
                    json_get_var _sr_up up
                    json_get_var _sr_dev device
                    if [ "$_sr_kind" = direct ]; then
                        # У «напрямую» нет ни устройства, ни подъёма — и писать про них
                        # «нет» значило бы показать поломку там, где её быть не может.
                        sr_line "$_sr_o: direct (без туннеля)"
                    else
                        # Пустое `up` — это «движок не сказал», а не «не поднят»: так
                        # выглядит выход на движке постарше, и выдавать одно за другое
                        # нельзя — по этой строке человеку советуют, что чинить.
                        case "$_sr_up" in
                            1|true) _sr_ups="поднят" ;;
                            0|false) _sr_ups="НЕ ПОДНЯТ" ;;
                            *) _sr_ups="состояния движок не назвал" ;;
                        esac
                        sr_line "$_sr_o: ${_sr_kind:-вид не назван}, устройство ${_sr_dev:-не создано}, $_sr_ups"
                        # Перебор узлов подписки — не отказ, и в отчёте это надо различать:
                        # «НЕ ПОДНЯТ» на выходе, который прямо сейчас ищет живой узел,
                        # уводит помогающего чинить исправное (I-100).
                        if json_select probe 2>/dev/null; then
                            _sr_pst=""; _sr_ptot=""
                            json_get_var _sr_pst state
                            json_get_var _sr_ptot total
                            case "$_sr_pst" in
                                probing) sr_line "    (идёт перебор узлов подписки, пригодных ${_sr_ptot:-?})" ;;
                                failed) sr_line "    (ни один узел подписки не ответил, пригодных ${_sr_ptot:-0})" ;;
                                no_such_node) sr_line "    (выбран номер узла, которого в подписке нет; узлов ${_sr_ptot:-0})" ;;
                            esac
                            json_select ..
                        fi
                    fi
                    json_select ..
                done
                json_select ..
            fi
            # Наборы правил в ядре — ЧИСЛОМ. Их имена служебные (имя набора nft), а
            # читаемые имена правил берутся ниже из спеки: контракт объекта прямо
            # предупреждает, что `channels` в состоянии — это объединённые ГРУППЫ, а не
            # правила один к одному.
            _sr_sets=0; _sr_livesets=0
            if json_select channels 2>/dev/null; then
                json_get_keys _sr_cs
                for _sr_c in $_sr_cs; do
                    json_select "$_sr_c" 2>/dev/null || continue
                    _sr_live=""
                    json_get_var _sr_live live
                    _sr_sets=$((_sr_sets + 1))
                    case "$_sr_live" in 1|true) _sr_livesets=$((_sr_livesets + 1)) ;; esac
                    json_select ..
                done
                json_select ..
            fi
            sr_line "наборов правил в ядре: $_sr_sets (живых $_sr_livesets)"
        else
            sr_line "движок не ответил на status — состояния выходов нет"
        fi

        # ---- правила, как их завёл человек ----------------------------------------------
        #
        # Из СПЕКИ, а не из состояния: в состоянии правила уже сведены в наборы, и имя там
        # служебное. Имена правил в отчёт попадать могут — их пишет сам владелец роутера, и
        # без них строка «набор из трёх списков» человеку ни о чём не говорит. Это ровно та
        # граница, по которой имена узлов ПОДПИСКИ в отчёт не попадают: те пишет панель.
        sr_line ""
        sr_line "-- правила (из спеки) --"
        _sr_spec="$(cat "$SPEC" 2>/dev/null)"
        _sr_rules=0
        if [ -n "$_sr_spec" ] && json_load "$_sr_spec" 2>/dev/null && json_select channels 2>/dev/null; then
            json_get_keys _sr_rs
            for _sr_r in $_sr_rs; do
                json_select "$_sr_r" 2>/dev/null || continue
                _sr_rn=""; _sr_ro=""; _sr_ren=""
                json_get_var _sr_rn name
                json_get_var _sr_ro out
                json_get_var _sr_ren enabled
                # Вид списка — по набору ключей `match`, а не по своему разбору путей: тем
                # же ключом его отличает и движок, а путь к файлу в отчёте не нужен вовсе.
                _sr_mk=""
                if json_select match 2>/dev/null; then
                    json_get_keys _sr_mk
                    json_select ..
                fi
                case " $_sr_mk " in
                    *" domains_files "*)  _sr_mkind="доменные списки" ;;
                    *" prefixes_files "*) _sr_mkind="адресные списки" ;;
                    *" any "*)            _sr_mkind="весь трафик" ;;
                    *)                    _sr_mkind="вид списка не назван" ;;
                esac
                # Поля `enabled` нет — правило включено: спека, написанная до этого поля,
                # обязана значить то же самое.
                case "$_sr_ren" in
                    0|false) _sr_rst=" [ВЫКЛЮЧЕНО]" ;;
                    *) _sr_rst="" ;;
                esac
                sr_line "${_sr_rn:-без имени} -> ${_sr_ro:-выход не назван} ($_sr_mkind)$_sr_rst"
                _sr_rules=$((_sr_rules + 1))
                json_select ..
            done
            json_select ..
        fi
        [ "$_sr_rules" = 0 ] && sr_line "правил нет — трафик никуда не уводится"

        # ---- обход DPI ------------------------------------------------------------------
        sr_line ""
        sr_line "-- обход DPI (zapret) --"
        need_zapret
        if zp_installed; then
            sr_line "пакет: установлен, версия $(v="$(zp_version 2>/dev/null)"; printf '%s' "${v:-не определилась}")"
            sr_line "служба: $(zp_running && printf 'работает' || printf 'не работает'), автозапуск $(zp_enabled && printf 'включён' || printf 'снят')"
            _sr_za="$(zp_active_global 2>/dev/null)"
            if [ -n "$_sr_za" ]; then
                # Расхождение с каталогом — законное состояние (ночное обновление активную
                # стратегию не подменяет), и в отчёте оно объясняет самое непонятное: имя
                # стратегии то же, а ключи под ним уже другие.
                if zp_drifted_global "$_sr_za" 2>/dev/null; then
                    sr_line "активная стратегия: $_sr_za (в каталоге она уже ДРУГАЯ — применить заново)"
                else
                    sr_line "активная стратегия: $_sr_za"
                fi
            else
                # Пустой ответ — свежий роутер со стратегией из config.default: имени из
                # каталога там нет, и менеджер тоже ничего не показывает.
                sr_line "активная стратегия: не отмечена (стоит стратегия из поставки пакета)"
            fi
        else
            sr_line "пакет: не установлен"
        fi
        # Каталог считается и без пакета: он скачивается ночным обновлением, и «пакета нет,
        # а стратегии есть» — обычное состояние роутера, на котором обход ещё не ставили.
        sr_line "стратегий в каталоге: $(zp_count)"

        # ---- DNS ------------------------------------------------------------------------
        sr_line ""
        sr_line "-- DNS --"
        need_doh
        if doh_installed; then
            sr_line "DoH (https-dns-proxy): установлен, $(doh_running && printf 'работает' || printf 'не работает'), автозапуск $(doh_enabled && printf 'включён' || printf 'снят')"
            _sr_da="$(doh_active 2>/dev/null)"
            if [ -n "$_sr_da" ]; then
                sr_line "выбранный резолвер: $_sr_da"
            else
                # САМА ССЫЛКА В ОТЧЁТ НЕ ИДЁТ. Пустой ответ означает «в конфигурации ссылка,
                # которой нет в каталоге»: её вписали руками или взяли из версии менеджера
                # новее нашей. Показывать её человеку на вкладке правильно — там он её
                # хозяин; в чат она уезжать не обязана, а «чужая» тут говорит ровно
                # столько, сколько нужно помогающему.
                sr_line "выбранный резолвер: не из нашего каталога (ссылка вписана мимо интерфейса)"
            fi
        else
            sr_line "DoH (https-dns-proxy): не установлен"
        fi
        sr_line "DoH через туннель: $(doh_tunnel_on && printf 'да' || printf 'нет')"
        # Резолвер доменных правил и перенаправление порта 53 — постоянные величины, и
        # названы они здесь ровно тем же составом, каким их отдаёт метод doh_state: резолвер
        # держится всегда, поэтому перенаправление порта 53 наше, а force_dns у прокси
        # выключен. Без этой строки сброшенный force_dns выглядит как чужая порча настройки.
        sr_line "резолвер доменов движка (steer dnsd): держится всегда, перенаправление порта 53 наше"
        sr_line "force_dns у https-dns-proxy: $(doh_force_dns) — два перенаправления на порт 53 спорили бы молча"

        # ---- подписки -------------------------------------------------------------------
        #
        # НИ ССЫЛКИ, НИ НАЗВАНИЯ, НИ ИМЁН УЗЛОВ — только номер по порядку и числа. Название
        # подписки приходит из заголовка панели (движок разбирает его при скачивании), имена
        # узлов — оттуда же, и в обоих панели держат и рекламу, и логин владельца. Числа
        # пригодных, пропущенных и чужих узлов считает движок при чтении файла — то же
        # число, по которому интерфейс решает, не заглушка ли эта подписка.
        sr_line ""
        sr_line "-- подписки --"
        _sr_n=0
        for _sr_sub in $(sub_names); do
            sub_use "$_sr_sub"
            _sr_n=$((_sr_n + 1))
            if [ -s "$SUB" ]; then
                _sr_vn="$(json_tail "$("$STEER" vless-nodes "$SUB" --spec "$SPEC" 2>&1)")"
                if [ -n "$_sr_vn" ] && json_load "$_sr_vn" 2>/dev/null; then
                    _sr_us=""; _sr_sk=""; _sr_fo=""
                    json_get_var _sr_us usable
                    json_get_var _sr_sk skipped
                    json_get_var _sr_fo foreign
                    sr_line "подписка №$_sr_n: файл скачан, пригодных узлов: ${_sr_us:-0} (пропущено ${_sr_sk:-0}, чужих ${_sr_fo:-0})"
                else
                    sr_line "подписка №$_sr_n: файл скачан, но движок не смог перечислить узлы"
                fi
            else
                sr_line "подписка №$_sr_n: файл не скачан — узлов нет"
            fi
        done
        [ "$_sr_n" = 0 ] && sr_line "подписок нет"

        # Последняя строка — человеку, а не нам: он вставляет текст в общий чат и вправе
        # знать, чего в нём нет, не читая наш исходник. Слово «vless» здесь намеренно не
        # пишется целиком со схемой — стенд ищет в отчёте именно такую подстроку, и
        # объяснение не должно превращать проверку в ложную тревогу.
        sr_line ""
        sr_line "В отчёт намеренно не попали: ссылка подписки, ссылки и имена узлов, приватные"
        sr_line "ключи туннелей и внешний адрес роутера — этот текст можно вставлять в общий чат."

        json_init
        json_add_boolean ok 1
        json_add_string text "$SR_TEXT"
        json_dump
        ;;

    *) fail "неизвестный метод" ;;
esac
