# Скачивание, которое переживает блокировку издателя списков.
#
# ЗАЧЕМ. splify2#15: у части аудитории провайдер закрыл `raw.githubusercontent.com`, и роутер
# перестал получать всё, что берёт оттуда, — манифест каталога, сами списки, пакеты релиза.
# Снаружи это выглядит как «списки не устанавливаются», причём интерфейс исправен, туннель
# поднят и сайты через него открываются: не идёт ровно тот трафик, который роутер отправляет
# ОТ СЕБЯ. Обойти это чужим зеркалом (`gh-proxy` и родня) — так советуют в соседних проектах —
# значило бы отдать третьей стороне то, что роутер потом применит как правила маршрутизации,
# и держаться зеркала, которое закроют следующим. Поэтому обход тут свой: через туннель,
# который человек уже настроил.
#
# ПОЧЕМУ ПОВТОР ВООБЩЕ ВОЗМОЖЕН. Движок метит только `prerouting`, то есть трафик, идущий
# ЧЕРЕЗ роутер. Собственные запросы роутера в туннель не попадают никогда, как бы ни были
# написаны каналы, — и это правильно: движок не должен молча увести обновление прошивки или
# ntp. Зато маршрутное правило выхода (`ip rule ... lookup <таблица>`) к локальному трафику
# применимо, и достаточно на время скачивания добавить правило «к этим адресам — по таблице
# выхода». Замерено на роутере: собственный запрос уходил с адреса провайдера (46.42.17.15),
# с правилом — с адреса узла подписки (45.157.235.107), и манифест приезжал целиком.
#
# ПОЧЕМУ ПРАВИЛО, А НЕ МЕТКА В `output`. Метку тоже проверял, работает (`type route hook
# output`, 17 пакетов в счётчике). Но правило по адресу назначения не требует ни своей
# таблицы nftables рядом с таблицей движка, ни разбора чужой метки, и одинаково уводит и
# curl, и uclient-fetch — а без curl остаётся именно он: в зависимостях пакета curl нет.
#
# ЧТО ЭТО НЕ ДЕЛАЕТ. Правило живёт только на время скачивания и снимается сразу. Если
# процесс убили посередине, правило останется до следующего повтора (он чистит свой
# приоритет перед работой) — оставшееся правило означает лишь «к адресам издателя ходим
# через туннель» и ничему не мешает.
#
# `set -u` здесь НЕ ставится нарочно: файл подключается в том числе к rpcd-объекту, который
# его не включает и на необъявленных переменных живёт законно. Своё состояние поэтому
# объявлено ниже целиком, а чужое читается через `${x:-}`.

# Швы для стенда: на роутере это системные пути и системные команды.
FETCH_TIMEOUT=${FETCH_TIMEOUT:-60}
FETCH_CONNECT_TIMEOUT=${FETCH_CONNECT_TIMEOUT:-8}
FETCH_RULE_PREF=${FETCH_RULE_PREF:-30000}
FETCH_STEER=${FETCH_STEER:-/usr/sbin/steer}
FETCH_SPEC=${FETCH_SPEC:-/etc/steer/spec.json}
FETCH_API=${FETCH_API:-https://api.github.com/repos}
FETCH_GITLAB=${FETCH_GITLAB:-https://gitlab.com}
FETCH_CODELOAD=${FETCH_CODELOAD:-https://codeload.github.com}
FETCH_DIST_BRANCH=${FETCH_DIST_BRANCH:-dist}
FETCH_CACHE=${FETCH_CACHE:-/tmp/splify2-fetch}

# Почему скачивание пошло не напрямую — одной строкой для человека. Вызывающий печатает её
# предупреждением: молчание здесь означало бы, что списки то обновляются, то нет, и понять
# причину нечем.
FETCH_NOTE=""
# Признак «напрямую не отдают»: выставляется, только когда обход СРАБОТАЛ, — то есть когда
# доказано, что дело в адресе, а не в упавшей сети. Дальше в этом же прогоне прямой заход
# пропускается: обновление берёт до десятка файлов, и восемь секунд ожидания на каждом — это
# минута на пустом месте. Если обходы вдруг перестали работать, признак снимается и прямой
# заход делается снова: он мог отказать разово.
FETCH_DIRECT_DEAD=0

# ---- разбор URL --------------------------------------------------------------------
# Имя хоста из URL. Логин с паролём, порт и путь отбрасываются; адрес в квадратных
# скобках (IPv6) возвращается без них.
fetch_host() {  # URL
    _fh="${1#*://}"
    _fh="${_fh%%/*}"
    _fh="${_fh%%\?*}"
    _fh="${_fh##*@}"
    case "$_fh" in
        \[*) _fh="${_fh#\[}"; _fh="${_fh%%\]*}" ;;
        *) _fh="${_fh%%:*}" ;;
    esac
    printf '%s' "$_fh"
}

# IPv4-адреса имени. Только IPv4: таблица выхода содержит `default dev <устройство>` для
# IPv4, туннель IPv6 не несёт, и повтор с адресом AAAA ушёл бы мимо правила через провайдера
# — то есть туда, где уже отказали.
#
# Строка сервера в выводе nslookup отбрасывается по признаку «адрес идёт сразу за строкой
# Name:»: над блоком сервера стоит `Server:`, а по самому адресу их не различить — busybox
# в разных сборках печатает резолвер и с портом, и без.
fetch_addrs4() {  # ХОСТ
    case "$1" in
        *[!0-9.]*) ;;
        *) printf '%s\n' "$1"; return 0 ;;      # уже адрес, спрашивать не о чем
    esac
    nslookup "$1" 2>/dev/null | awk '
        /^Name:/ { named = 1; next }
        /^Address/ {
            if (!named) next
            named = 0
            for (i = 2; i <= NF; i++)
                if ($i ~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$/) { print $i; break }
            next
        }
        { named = 0 }' | sort -u
}

# ---- обход по хостам самого GitHub ---------------------------------------------------
# ПОЧЕМУ ЭТОТ ОБХОД ПЕРВЫЙ, А ТУННЕЛЬ ВТОРОЙ. Закрывают не GitHub, а `githubusercontent.com`
# — отдельный хост на сети Fastly. Проверено адресами: `raw.githubusercontent.com`,
# `objects.githubusercontent.com` и `release-assets.githubusercontent.com` — это одни и те же
# 185.199.108-111.133, а `github.com`, `api.github.com` и `codeload.github.com` живут на
# 140.82.121.x. То есть разом отваливаются и списки, и файлы релиза (прямая ссылка релиза
# перенаправляет как раз на `release-assets`), но `codeload` — нет: он отдаёт ветку архивом
# и никуда не перенаправляет.
#
# Путей внутри обхода три, и порядок между ними — от дешёвого к дорогому.
#
# Первый — зеркало на GitLab: репозитории зеркалятся туда тем же путём, а сырой файл GitLab
# отдаёт со своего же домена, без заголовка и без счётчика запросов. Второй —
# `api.github.com` (проверено: `contents` с заголовком `Accept: application/vnd.github.raw`
# отвечает сам, с адреса 140.82.121.5, и никуда не перенаправляет), но без ключа он считает
# 60 запросов в час на адрес, а за CGNAT их выбирают соседи, и файл больше мегабайта не
# отдаёт вовсе. Третий — архив ветки через `codeload`; он кэшируется на прогон, потому что
# обновление берёт несколько списков из одного репозитория и качать мегабайт на каждый
# незачем.
#
# Ни один из путей не требует ни туннеля, ни чужого зеркала, и оба работают на роутере, где
# ещё ничего не настроено.
#
# Ветка для файлов релиза — `dist`: релизный workflow выкладывает в неё те же пакеты.

# Разбор известного адреса GitHub в «ВЛАДЕЛЕЦ/РЕПО ВЕТКА ПУТЬ». Ветка со слэшем внутри
# (`feature/x`) не поддерживается: у наших адресов её не бывает, а разобрать её без обращения
# к API нельзя — по строке не видно, где кончается имя ветки и начинается путь.
fetch_gh_parts() {  # URL
    case "$1" in
        https://raw.githubusercontent.com/*)
            _gp="${1#https://raw.githubusercontent.com/}" ;;
        https://github.com/*/releases/download/*)
            _gp="${1#https://github.com/}"
            printf '%s %s %s' "${_gp%%/releases/download/*}" "$FETCH_DIST_BRANCH" "${1##*/}"
            return 0 ;;
        *) return 1 ;;
    esac
    _gp_o="${_gp%%/*}"; _gp="${_gp#*/}"
    _gp_r="${_gp%%/*}"; _gp="${_gp#*/}"
    case "$_gp" in refs/heads/*) _gp="${_gp#refs/heads/}" ;; esac
    _gp_b="${_gp%%/*}"; _gp_p="${_gp#*/}"
    [ -n "$_gp_o" ] && [ -n "$_gp_r" ] && [ -n "$_gp_b" ] || return 1
    [ -n "$_gp_p" ] && [ "$_gp_p" != "$_gp_b" ] || return 1
    printf '%s/%s %s %s' "$_gp_o" "$_gp_r" "$_gp_b" "$_gp_p"
}

# Один файл с зеркала. Репозитории зеркалятся на GitLab тем же путём (`gitlab.com/<владелец>/
# <репозиторий>`), и это самый дешёвый из обходов: GitLab отдаёт сырой файл с СВОЕГО домена,
# без отдельного хоста под содержимое, без заголовка и без счётчика запросов. То есть беда
# githubusercontent — «содержимое живёт на чужом хосте, который закрывают отдельно» — здесь
# не воспроизводится в принципе.
#
# Поэтому зеркало стоит первым среди обходов, а хосты GitHub — за ним: у contents API 60
# запросов в час на адрес, а архив ветки это мегабайт ради одного файла.
fetch_mirror_file() {  # РЕПОЗИТОРИЙ ПУТЬ ВЕТКА ФАЙЛ
    fetch_get "$FETCH_GITLAB/$1/-/raw/$3/$2" "$4" || { rm -f "$4"; return 1; }
    [ -s "$4" ] || { rm -f "$4"; return 1; }
}

# Один файл через api.github.com. Дешевле архива: берётся ровно нужный файл, а не
# репозиторий целиком — для steer это 300 КБ вместо пяти мегабайт, и на роутере с 64 МБ
# разница не косметическая (/tmp — это оперативная память).
#
# Ограничения, из-за которых этот путь не единственный: без ключа GitHub даёт 60 запросов
# в час НА АДРЕС, а за CGNAT их выбирают соседи (так это и пришло — splify2#5, ответ 403 на
# ровном месте), и файл больше мегабайта этот метод не отдаёт вовсе. Оба случая ловятся
# просто: ответа нет — идём архивом.
fetch_api_file() {  # РЕПОЗИТОРИЙ ПУТЬ ВЕТКА ФАЙЛ
    fetch_get "$FETCH_API/$1/contents/$2?ref=$3" "$4" "" \
        "Accept: application/vnd.github.raw" || { rm -f "$4"; return 1; }
    [ -s "$4" ] || { rm -f "$4"; return 1; }
}

# Архив ветки. Своё имя на процесс: чужой прогон мог оставить в кэше архив недельной
# давности, и обновление списков молча применило бы старое. Чужое подчищается по возрасту.
fetch_tarball() {  # РЕПОЗИТОРИЙ ВЕТКА
    mkdir -p "$FETCH_CACHE" 2>/dev/null || return 1
    find "$FETCH_CACHE" -type f -name '*.tgz' -mmin +60 -exec rm -f {} + 2>/dev/null
    _ft="$FETCH_CACHE/$$-$(printf '%s-%s' "$1" "$2" | tr '/' '_').tgz"
    if [ ! -s "$_ft" ]; then
        fetch_get "$FETCH_CODELOAD/$1/tar.gz/refs/heads/$2" "$_ft" || { rm -f "$_ft"; return 1; }
        [ -s "$_ft" ] || { rm -f "$_ft"; return 1; }
    fi
    printf '%s' "$_ft"
}

# Обход целиком: тот же файл с других адресов. Сначала зеркало на GitLab, потом хосты
# самого GitHub — поштучно через API и архивом ветки.
fetch_github() {  # URL ФАЙЛ
    _cl="$(fetch_gh_parts "$1")" || return 1
    [ -n "$_cl" ] || return 1
    _cl_repo="${_cl%% *}"; _cl_rest="${_cl#* }"
    _cl_branch="${_cl_rest%% *}"; _cl_path="${_cl_rest#* }"

    if fetch_mirror_file "$_cl_repo" "$_cl_path" "$_cl_branch" "$2"; then
        FETCH_NOTE="прямой адрес не отдал — взято с зеркала gitlab.com ($_cl_repo, ветка $_cl_branch)"
        return 0
    fi

    if fetch_api_file "$_cl_repo" "$_cl_path" "$_cl_branch" "$2"; then
        FETCH_NOTE="прямой адрес не отдал — взято через api.github.com ($_cl_repo, ветка $_cl_branch)"
        return 0
    fi

    _cl_tb="$(fetch_tarball "$_cl_repo" "$_cl_branch")" || return 1
    # Верхний каталог в архиве GitHub — «репозиторий-ветка», без владельца.
    tar -xzOf "$_cl_tb" "${_cl_repo#*/}-$_cl_branch/$_cl_path" > "$2" 2>/dev/null || {
        rm -f "$2"; return 1; }
    [ -s "$2" ] || { rm -f "$2"; return 1; }
    FETCH_NOTE="прямой адрес не отдал — взято архивом через codeload.github.com ($_cl_repo, ветка $_cl_branch)"
    return 0
}

# ---- выход, через который можно повторить -------------------------------------------
# Печатает «ИМЯ ТАБЛИЦА» первого поднятого выхода со своей таблицей маршрутизации.
# Через `steer outputs`, а не через jshn: этот файл подключает и splify2-update-lists,
# которому libubox не нужен ни для чего больше.
fetch_out() {
    _fo_st="$("$FETCH_STEER" status --spec "$FETCH_SPEC" 2>/dev/null)"
    [ -n "$_fo_st" ] || return 1
    for _fo_n in $("$FETCH_STEER" outputs --spec "$FETCH_SPEC" 2>/dev/null); do
        case "$_fo_n" in *[!a-zA-Z0-9_-]*) continue ;; esac
        _fo_up="$(printf '%s' "$_fo_st" | jsonfilter -e "@.outputs.$_fo_n.up" 2>/dev/null)"
        [ "$_fo_up" = "true" ] || [ "$_fo_up" = "1" ] || continue
        _fo_t="$(printf '%s' "$_fo_st" | jsonfilter -e "@.outputs.$_fo_n.table" 2>/dev/null)"
        case "${_fo_t:-}" in ''|*[!0-9]*) continue ;; esac
        printf '%s %s\n' "$_fo_n" "$_fo_t"
        return 0
    done
    return 1
}

# Адреса, к которым ходит САМ движок этого выхода. Увести их в туннель — это петля: пакет
# к узлу уйдёт в TUN, движок прочитает его оттуда и откроет к узлу ещё одно соединение, и
# так без конца. Случай не выдуманный: манифест или свой список законно живут на том же
# VPS, что и узел. Поэтому такой повтор не делается вовсе — лучше отказ с объяснением.
#
# Спрашивается только АКТИВНЫЙ узел: остальные движок не держит. Для выходов поверх
# WireGuard (kind=interface, обфускация, xsteer) адреса пиров печатает сам wg.
fetch_peers() {  # ВЫХОД
    _fp_j="$("$FETCH_STEER" vless-nodes "$1" --spec "$FETCH_SPEC" 2>/dev/null)"
    if [ -n "$_fp_j" ]; then
        _fp_i="$(printf '%s' "$_fp_j" | jsonfilter -e '@.node' 2>/dev/null)"
        case "${_fp_i:-}" in
            ''|*[!0-9]*) ;;
            *) _fp_h="$(printf '%s' "$_fp_j" |
                    jsonfilter -e "@.nodes[@.index=$_fp_i].host" 2>/dev/null | head -1)"
               [ -n "$_fp_h" ] && fetch_addrs4 "$_fp_h" ;;
        esac
    fi
    command -v wg >/dev/null 2>&1 || return 0
    wg show all endpoints 2>/dev/null | awk '{ for (i = 2; i <= NF; i++) {
        n = split($i, p, ":"); if (n == 2 && p[1] ~ /^[0-9.]+$/) print p[1] } }'
}

# ---- собственно скачивание ----------------------------------------------------------
# Один заход. ЧЕТВЁРТЫЙ аргумент — «только IPv4»: в повторе это обязательно, иначе curl
# возьмёт адрес AAAA и уйдёт мимо правила.
fetch_get() {  # URL ФАЙЛ ЧЕТВЁРКА ЗАГОЛОВОК
    _fg_4="${3:-}"
    _fg_h="${4:-}"
    if command -v curl >/dev/null 2>&1; then
        curl -fsSL ${_fg_4:+-4} ${_fg_h:+-H} ${_fg_h:+"$_fg_h"} \
             --connect-timeout "$FETCH_CONNECT_TIMEOUT" \
             --max-time "$FETCH_TIMEOUT" -o "$2" "$1"
    else
        uclient-fetch -q ${_fg_4:+-4} ${_fg_h:+--header="$_fg_h"} \
             -T "$FETCH_TIMEOUT" -O "$2" "$1"
    fi
}

fetch_rules_flush() {  # ТАБЛИЦА
    _fr_n=0
    while [ "$_fr_n" -lt 32 ] && ip rule del pref "$FETCH_RULE_PREF" 2>/dev/null; do
        _fr_n=$((_fr_n + 1))
    done
}

# Качать через туннель или нет — выбор человека, и других состояний у него нет.
#
# Было три (последняя ступень / первая / запрет), и владелец забраковал среднее дважды:
# «не должно быть состояния авто». Переключатель обязан значить то, что на нём написано, а
# не «мы сами решим, если не вышло». Поэтому значений два, и умолчание — НЕ качать через
# туннель: пока человек не сказал иначе, роутер ходит своим каналом и обходными адресами
# самого GitHub.
#
# `1` и `always` понимаются как «да», всё остальное (включая прежнее `auto`) — как «нет».
fetch_tunnel_on() {
    case "$(uci -q get splify2.main.fetch_via_tunnel 2>/dev/null)" in
        1|always|on|true|yes) return 0 ;;
        *) return 1 ;;
    esac
}

# Скачивание через туннель. Код 0 — файл на месте.
fetch_via_tunnel() {  # URL ФАЙЛ
    if ! fetch_tunnel_on; then
        FETCH_NOTE="скачивание через туннель выключено"
        return 1
    fi
    _vt_host="$(fetch_host "$1")"
    _vt_addrs="$(fetch_addrs4 "$_vt_host")"
    if [ -z "$_vt_addrs" ]; then
        FETCH_NOTE="$_vt_host не разрешается в адрес IPv4 — повторить через туннель нечем"
        return 1
    fi
    # Fake-IP из диапазона движка: сюда попадает адрес, выданный нашим же резолвером
    # доменному каналу. Обратного перевода для трафика САМОГО роутера нет (DNAT стоит в
    # prerouting, то есть для клиентов), и в туннель ушёл бы пакет в никуда.
    for _vt_a in $_vt_addrs; do
        case "$_vt_a" in
            198.18.*|198.19.*)
                FETCH_NOTE="$_vt_host разрешается в fake-IP $_vt_a — сначала уберите его домен из каналов"
                return 1 ;;
        esac
    done

    _vt_out="$(fetch_out)" || {
        FETCH_NOTE="$_vt_host напрямую не ответил, а поднятого выхода со своей таблицей нет"
        return 1
    }
    _vt_name="${_vt_out% *}"
    _vt_table="${_vt_out#* }"

    for _vt_p in $(fetch_peers "$_vt_name"); do
        for _vt_a in $_vt_addrs; do
            [ "$_vt_a" = "$_vt_p" ] || continue
            FETCH_NOTE="адрес издателя $_vt_a — это же адрес узла выхода $_vt_name: повтор через туннель ушёл бы в петлю"
            return 1
        done
    done

    fetch_rules_flush
    # `uidrange 0-0` — не украшение: правило по одному адресу назначения действует на ВЕСЬ
    # трафик к нему, включая трафик устройств сети через роутер. Пока скачивание идёт, чужой
    # компьютер, открывший тот же адрес, уехал бы в туннель вместе с нами — а это не наше
    # дело и не то, о чём человека спрашивали. У пересылаемого пакета сокета нет, значит нет
    # и владельца: условие по владельцу его не выбирает вовсе, а наш собственный запрос идёт
    # от root. Проверено на роутере: правило с таким условием ядро принимает.
    _vt_added=0
    for _vt_a in $_vt_addrs; do
        ip rule add to "$_vt_a" uidrange 0-0 lookup "$_vt_table" pref "$FETCH_RULE_PREF" 2>/dev/null &&
            _vt_added=$((_vt_added + 1))
    done
    # Условие по владельцу понимает только полный iproute2; busybox отвечает «invalid
    # argument 'uidrange'» (проверено на роутере). Без него правило увело бы в туннель и
    # трафик устройств сети, а этого делать нельзя — тогда лучше не идти туннелем вовсе.
    if [ "$_vt_added" = 0 ]; then
        fetch_rules_flush
        FETCH_NOTE="через туннель не выйдет: нужен полный iproute2 (пакет ip-full)"
        return 1
    fi
    fetch_get "$1" "$2" 4
    _vt_rc=$?
    fetch_rules_flush
    if [ "$_vt_rc" != 0 ] || [ ! -s "$2" ]; then
        rm -f "$2"
        FETCH_NOTE="$_vt_host не ответил ни напрямую, ни через выход $_vt_name"
        return 1
    fi
    FETCH_NOTE="скачано через выход $_vt_name"
    return 0
}

# Скачать. Три пути по очереди: прямой адрес, тот же файл через codeload.github.com,
# туннель роутера. Порядок именно такой: обход через codeload не требует ни поднятого
# выхода, ни правил маршрутизации, поэтому работает и на роутере, где ещё ничего не
# настроено, — а туннель остаётся для случая, когда закрыт весь GitHub.
download() {  # URL ФАЙЛ
    FETCH_NOTE=""
    _dl_tmp="$2.tmp"
    rm -f "$_dl_tmp"

    # Включён туннель — идём туда, и только туда: человек так распорядился. Выключен — не
    # трогаем его вовсе, остаются прямой адрес и обходные адреса самого GitHub.
    if fetch_tunnel_on && fetch_via_tunnel "$1" "$_dl_tmp"; then
        mv "$_dl_tmp" "$2"
        return 0
    fi

    if [ "$FETCH_DIRECT_DEAD" != 1 ]; then
        if fetch_get "$1" "$_dl_tmp" && [ -s "$_dl_tmp" ]; then
            mv "$_dl_tmp" "$2"
            return 0
        fi
        rm -f "$_dl_tmp"
    fi

    if fetch_github "$1" "$_dl_tmp"; then
        FETCH_DIRECT_DEAD=1
        mv "$_dl_tmp" "$2"
        return 0
    fi
    # Обход мимо. Если прямой заход в этот раз пропускался, сделать его сейчас:
    # признак «напрямую не отдают» мог остаться от другого хоста.
    if [ "$FETCH_DIRECT_DEAD" = 1 ]; then
        FETCH_DIRECT_DEAD=0
        if fetch_get "$1" "$_dl_tmp" && [ -s "$_dl_tmp" ]; then
            mv "$_dl_tmp" "$2"
            return 0
        fi
    fi
    rm -f "$_dl_tmp"
    # Сказать, что туннель мог бы спасти, но выключен: иначе в журнале остаётся «не
    # скачалось» без единой подсказки, куда смотреть.
    fetch_tunnel_on || FETCH_NOTE="${FETCH_NOTE:+$FETCH_NOTE; }скачивание через туннель выключено"
    return 1
}
