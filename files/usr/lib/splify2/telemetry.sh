# Сборка пакета телеметрии. Контракт — docs/TELEMETRY.md, он же читается панелью.
#
# ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Собирают пакет двое: метод `telemetry_preview` (человек смотрит,
# что уедет, ДО согласия) и команда отправки по расписанию. Две копии сборки означали бы, что
# экран «вот что уедет» показывает не то, что уезжает, — то есть обещание, которое нельзя
# проверить. Здесь одна функция, и стенд сверяет тело запроса с её выводом байт в байт.
#
# По ubus тот же пакет едет объектом, а не строкой, и приёмная сторона собирает его из
# разобранного заново: значения и порядок ключей те же, отступы её. Поэтому обещание звучит
# «тот же пакет», а не «те же байты», — второе проверяемо только на пути отправки.
#
# ГЛАВНОЕ ПРАВИЛО — ТО ЖЕ, ЧТО У ОТЧЁТА ДЛЯ ПОДДЕРЖКИ: читать ТОЛЬКО НАЗВАННЫЕ ПОЛЯ чужих
# ответов и никогда не пересказывать документ целиком. `steer status` несёт поля спеки (путь
# к файлу подписки, номера узлов, адрес сервера обфускации), `vless-nodes` — весь список
# узлов с именами и адресами. Дословный пересказ любого из двух это готовая утечка, а не
# «лишние подробности». Поэтому ниже нет ни одного `cat` чужого ответа: каждое поле берётся
# по имени и приводится к своему виду.
#
# И ВТОРОЕ ПРАВИЛО, КОТОРОГО У ОТЧЁТА НЕТ. Отчёт человек копирует глазами и вставляет туда,
# куда решил; телеметрия уезжает по расписанию без него. Поэтому три вещи, законные в отчёте,
# здесь запрещены: имена выходов, имена правил и названия подписок — их писал человек либо
# панель провайдера, и они говорят о нём, а не о работе продукта.
#
# `set -u` здесь не ставится: файл подключают и объект rpcd, и команда отправки, а объект
# живёт с необъявленными переменными законно.

TM_SCHEMA=1

STEER=${STEER:-/usr/sbin/steer}
SPEC=${SPEC:-/etc/steer/spec.json}
LISTS=${LISTS:-/etc/steer/lists}
GEO_DIR=${GEO_DIR:-/var/lib/splify2}
SYSINFO_MODEL=${SYSINFO_MODEL:-/tmp/sysinfo/model}
OPENWRT_RELEASE=${OPENWRT_RELEASE:-/etc/openwrt_release}
BUILD_ID_FILE=${BUILD_ID_FILE:-/www/luci-static/resources/splify2/build-id.txt}
# Признак загрузки: восемь знаков, свои у каждой загрузки. В /tmp нарочно — он и обязан
# теряться при перезагрузке, в этом весь его смысл.
TM_BOOT_FILE=${TM_BOOT_FILE:-/var/run/splify2-boot-id}
# Счётчики событий — тоже в /tmp: обработчик hotplug при флапающем WAN срабатывает десятки
# раз в минуту, и писать это во флеш значило бы убивать память роутера ровно в том случае,
# который мы и хотим измерить.
TM_EVENTS=${TM_EVENTS:-/var/run/splify2-events}
# Возраст страны выхода, после которого она в пакет не идёт. Сутки: страна меняется редко, а
# «Эстония» рядом с только что выбранной Польшей выглядит как ответ, хотя это память.
TM_GEO_MAX_AGE=${TM_GEO_MAX_AGE:-86400}

# ---- вывод JSON ----------------------------------------------------------------------
# Печатается потоком, без сборки документа в памяти: пакет читают дважды (предпросмотр и
# отправка), а собирать его в переменной оболочки значит один раз обжечься на строке в
# полтора килобайта с чужими байтами внутри.
tm_str() {  # СТРОКА -> строка JSON в кавычках
    printf '"'
    printf '%s' "${1:-}" | awk '
        BEGIN { RS = "^$" }
        {
            gsub(/\\/, "\\\\")
            gsub(/"/, "\\\"")
            gsub(/\n/, " ")
            gsub(/\r/, " ")
            gsub(/\t/, " ")
            printf "%s", $0
        }'
    printf '"'
}

# Число или ноль. Всё, что пришло не числом, — ноль: пакет читает чужая программа, и «null»
# вместо числа ей дороже, чем честный ноль.
tm_int() {  # ЗНАЧЕНИЕ
    case "${1:-}" in
        ''|*[!0-9-]*) printf '0' ;;
        *)            printf '%s' "$1" ;;
    esac
}

tm_bool() { [ "${1:-0}" = 1 ] && printf 'true' || printf 'false'; }

# ---- признак загрузки ------------------------------------------------------------------
tm_boot_id() {
    if [ -s "$TM_BOOT_FILE" ]; then
        sed -n '1{s/[^0-9a-f]//g;p;}' "$TM_BOOT_FILE" | cut -c1-8
        return 0
    fi
    mkdir -p "$(dirname "$TM_BOOT_FILE")" 2>/dev/null
    _tb="$(sed -n '1{s/[^0-9a-f]//g;p;}' /proc/sys/kernel/random/uuid 2>/dev/null | cut -c1-8)"
    [ -n "$_tb" ] || _tb="$(date +%s | cksum | tr -d ' -' | cut -c1-8)"
    printf '%s\n' "$_tb" > "$TM_BOOT_FILE" 2>/dev/null
    printf '%s' "$_tb"
}

# `uci_file` заводит /etc/config/splify2, если его ещё нет: без самого файла `uci set` молча
# ничего не пишет. Живёт она в common.sh объекта rpcd — а этот сборщик подключает ещё и
# команда отправки, у которой common.sh нет вовсе. Без запасного определения идентификатор не
# запоминался бы на роутере, где настройку ещё не заводили, и движок считал бы его заново
# КАЖДЫЙ ЧАС: 600 000 проходов PBKDF2 (3,24 с на AX3000T) вместо одного раза за жизнь
# роутера. Сбой при этом тихий — пакет уезжает верный, платится только время, — и потому его
# никто бы не заметил; на часовом такте эта плата стала суточной, и стенд её сторожит
# отдельной проверкой («отправка без движка уходит»).
UCI_SPLIFY2=${UCI_SPLIFY2:-/etc/config/splify2}
command -v uci_file >/dev/null 2>&1 || uci_file() {
    [ -f "$UCI_SPLIFY2" ] && return 0
    mkdir -p "$(dirname "$UCI_SPLIFY2")" 2>/dev/null
    touch "$UCI_SPLIFY2" 2>/dev/null
    [ -f "$UCI_SPLIFY2" ]
}

# ---- идентификатор ---------------------------------------------------------------------
#
# СЧИТАЕТ ДВИЖОК И СЧИТАЕТ МЕДЛЕННО (PBKDF2, 600 000 проходов) — поэтому ответ запоминается
# в настройке, а не спрашивается каждый раз. Счёт детерминирован: запомненное только
# избавляет от повторной платы и не становится вторым источником истины. После сброса к
# заводским настройкам роутер посчитает то же самое значение заново — ради этого свойства
# идентификатор и выводится из MAC, а не берётся случайным.
tm_id() {
    _ti="$(uci -q get splify2.main.telemetry_id 2>/dev/null)"
    case "${_ti:-}" in
        sp-[0-9a-f]*) printf '%s' "$_ti"; return 0 ;;
    esac
    [ -x "$STEER" ] || return 1
    _ti="$("$STEER" dev-id 2>/dev/null | sed -n 's/.*"tid":"\(sp-[0-9a-f]*\)".*/\1/p')"
    [ -n "$_ti" ] || return 1
    uci_file 2>/dev/null || true
    uci -q set "splify2.main.telemetry_id=$_ti" 2>/dev/null
    uci -q commit splify2 2>/dev/null
    printf '%s' "$_ti"
}

# ---- согласие --------------------------------------------------------------------------
#
# ПОЛЬЗУЯСЬ splify2, ЧЕЛОВЕК СОГЛАСИЛСЯ — это решение владельца продукта, и код обязан ему
# соответствовать буквально. Отказ здесь единственное явное действие, делается он в
# «Настройки → О ПО», и до тех пор отчёт о работе уезжает.
#
# ОПИСАНИЕ СОСТОЯНИЯ И РЕШЕНИЕ — РАЗНЫЕ ВОПРОСЫ, и разведены они нарочно. Три состояния
# остались, потому что интерфейсу есть разница между «работает по умолчанию» и «человек
# включил сам»: это разные надписи на одном и том же включённом переключателе. А решение
# «уедет ли пакет» одно на весь продукт и живёт в ОДНОЙ функции — tm_allowed. Повтори его
# вторым сравнением в команде отправки или в объекте rpcd, и однажды экран будет говорить
# одно, а расписание делать другое; поймать такое расхождение можно только жалобой человека.
tm_consent() {  # -> unset | off | on — что показать, а НЕ что делать
    case "$(uci -q get splify2.main.telemetry 2>/dev/null)" in
        1|on|yes|true) printf 'on' ;;
        '')            printf 'unset' ;;
        *)             printf 'off' ;;
    esac
}

# ЕДИНСТВЕННОЕ МЕСТО, ГДЕ РЕШАЕТСЯ, ОТПРАВЛЯТЬ ЛИ. Отправляем везде, кроме явного отказа;
# непонятное значение в ключе — тоже отказ, потому что записать его мог не наш код, а читать
# невнятное как «да» в вопросе про отправку данных наружу нельзя.
tm_allowed() {  # -> 0, если отправлять можно
    [ "$(tm_consent)" != off ]
}

# ---- счётчики событий ------------------------------------------------------------------
# Кумулятивные С ЗАГРУЗКИ, а не разностные, и это то, что позволяет не копить очередь при
# недоступной панели: пропущенная отправка не теряет ни одного события — следующая покажет
# число побольше, а `boot` и `uptime` объяснят перезагрузку.
tm_event() {  # ИМЯ -> число
    [ -s "$TM_EVENTS" ] || { printf '0'; return 0; }
    _te="$(sed -n "s/^${1:-}=\([0-9]*\)$/\1/p" "$TM_EVENTS" | tail -n1)"
    printf '%s' "${_te:-0}"
}

# ---- запись счётчиков: тальники ---------------------------------------------------------
#
# СЧЁТЧИК — НЕ ЧИСЛО В ФАЙЛЕ, А ДЛИНА ФАЙЛА-ТАЛЬНИКА. Довод целиком записан в обработчике
# hotplug (files/etc/hotplug.d/iface/96-splify2), там же, где он впервые понадобился: события
# приходят параллельно, «прочитал число, прибавил, записал» теряет их молча, а замок стоит
# дороже самой записи. Дозапись одного байта с O_APPEND ядро выполняет неделимо, поэтому
# двадцать одновременных писателей дают ровно двадцать байт без какой-либо договорённости.
#
# ЖИВЁТ ЭТО ЗДЕСЬ, А НЕ В ОБРАБОТЧИКЕ, потому что писателей стало двое: отвалы интерфейсов
# считает hotplug, падения — команда отправки. Две копии сборки видимого файла означали бы,
# что писатель, не знающий о счётчиках соседа, затирает их при каждой своей записи, — и
# заметить это можно было бы только по нулям в панели.
tm_event_bump() {  # ТАЛЬНИК (w, i, c/steer …) — дописать одно событие
    case "${1:-}" in */*) mkdir -p "$TM_EVENTS.$(dirname "$1")" 2>/dev/null ;; esac
    printf x >> "$TM_EVENTS.${1:-x}" 2>/dev/null
}

tm_event_sizes() {  # длины всех тальников одной строкой — признак «наше число устарело»
    for _tes in "$TM_EVENTS".w "$TM_EVENTS".i "$TM_EVENTS".c/*; do
        [ -f "$_tes" ] || continue
        printf '%s:%s ' "$_tes" "$(wc -c < "$_tes" 2>/dev/null)"
    done
}

tm_event_len() {  # ТАЛЬНИК -> число событий
    _tel="$(wc -c < "$TM_EVENTS.${1:-x}" 2>/dev/null)"
    printf '%s' "$(( ${_tel:-0} + 0 ))"
}

# ПЕРЕСБОРКА ВИДИМОГО ФАЙЛА. Тальники хранят истину, но читатель (tm_event) ждёт строк
# `имя=число`, поэтому файл собирается заново из длин и подменяется целиком через mv:
# читатель либо видит прежний файл, либо новый, но никогда — наполовину записанный.
#
# Сама подмена гонку допускает: писатель, посчитавший 19, может переписать файл уже после
# того, как посчитавший 20 его подменил. Лечится это сверкой длин ПОСЛЕ подмены — не выросли
# ли тальники, пока мы писали. Увидев рост, цикл считает заново, то есть каждый, кто записал
# устаревшее число, сам же его и исправляет; уходит только тот, чьё число не менялось ни до,
# ни после записи. Предел в 20 проходов — на случай файловой системы только для чтения.
tm_event_rebuild() {
    _ter_n=0
    while :; do
        _ter_n=$((_ter_n + 1))
        [ "$_ter_n" -gt 20 ] && return 1
        _ter_before="$(tm_event_sizes)"
        _ter_tmp="$TM_EVENTS.$$"
        {
            printf 'wan_down=%s\niface_down=%s\n' "$(tm_event_len w)" "$(tm_event_len i)"
            # Падения — теми же строками и в том же файле: у панели один читатель на все
            # счётчики, и заводить второй файл ради второго писателя незачем.
            for _ter_c in "$TM_EVENTS".c/*; do
                [ -f "$_ter_c" ] || continue
                printf 'crash_%s=%s\n' "${_ter_c##*/}" "$(tm_event_len "c/${_ter_c##*/}")"
            done
        } > "$_ter_tmp" 2>/dev/null || { rm -f "$_ter_tmp" 2>/dev/null; return 1; }
        mv -f "$_ter_tmp" "$TM_EVENTS" 2>/dev/null || { rm -f "$_ter_tmp" 2>/dev/null; return 1; }
        [ "$(tm_event_sizes)" = "$_ter_before" ] && return 0
    done
}

# ---- падения ----------------------------------------------------------------------------
#
# ЧТО ИМЕННО ЕДЕТ ПРИ ПАДЕНИИ — СТРУКТУРНЫЙ ФАКТ, А НЕ ТЕКСТ ЖУРНАЛА, и это не украшение
# контракта. Строка журнала — это пути, имена узлов и ссылки подписок с токенами в одном
# куске текста; весь стенд телеметрии стоит на «ни одного ://, ни одного IPv4, ни одного
# значения длиннее 64 байт», и ОДНА строка журнала обрушила бы эту гарантию целиком. Понадобится
# сам текст — это отдельный путь с отдельным явным согласием, а не новое поле здесь.
#
# Поэтому оба словесных поля берутся ИЗ ЗАКРЫТЫХ НАБОРОВ, а остальные — числа. Свободная
# строка в причине была бы готовым способом увезти в пакет что угодно: звать команду может
# кто угодно с правами root, включая чужой скрипт.
TM_CRASH_FILE=${TM_CRASH_FILE:-/var/run/splify2-crash}

tm_crash_what_ok() {  # ЧТО УПАЛО
    case "${1:-}" in steer|zapret|xsteer|wan) return 0 ;; esac
    return 1
}

tm_crash_reason_ok() {  # ПОЧЕМУ
    case "${1:-}" in
        steer_down|zapret_down|xsteer_down|wan_flap|boot|oom|apply_failed) return 0 ;;
    esac
    return 1
}

# Кто упал, если звавший не сказал. Отдельной таблицей, а не разбором имени причины: разбор
# «всё до подчёркивания» превратил бы закрытый набор в открытый на первой же новой причине.
tm_crash_what_for() {  # ПРИЧИНА -> ЧТО
    case "${1:-}" in
        steer_down|apply_failed|boot|oom) printf 'steer' ;;
        zapret_down)                      printf 'zapret' ;;
        xsteer_down)                      printf 'xsteer' ;;
        wan_flap)                         printf 'wan' ;;
    esac
}

# Код возврата и сигнал — числа не длиннее трёх знаков. Проверка та же и по той же причине,
# что у чужого ответа о городе: файл лежит в /tmp, куда пишет не только эта функция.
tm_crash_num() {  # ЗНАЧЕНИЕ -> число
    case "${1:-}" in
        ''|*[!0-9]*) printf '0' ;;
        *) [ "${#1}" -le 3 ] && printf '%s' "$1" || printf '0' ;;
    esac
}

# ЗАПИСЬ ФАКТА ПАДЕНИЯ. Делается ВСЕГДА, даже когда сама отправка погашена ограничителем
# потопа: счётчик обязан остаться верным, иначе панель увидела бы одно падение там, где их
# было сорок, и «сыпется» стало бы неотличимо от «дёрнулось однажды».
tm_crash_record() {  # ЧТО ПРИЧИНА КОД СИГНАЛ
    tm_crash_what_ok "${1:-}" || return 1
    tm_crash_reason_ok "${2:-}" || return 1
    tm_event_bump "c/$1"
    tm_event_rebuild
    _tcr_tmp="$TM_CRASH_FILE.$$"
    mkdir -p "$(dirname "$TM_CRASH_FILE")" 2>/dev/null
    printf 'what=%s\nreason=%s\ncode=%s\nsignal=%s\nat=%s\n' \
        "$1" "$2" "$(tm_crash_num "${3:-0}")" "$(tm_crash_num "${4:-0}")" "$(date +%s)" \
        > "$_tcr_tmp" 2>/dev/null || { rm -f "$_tcr_tmp" 2>/dev/null; return 1; }
    mv -f "$_tcr_tmp" "$TM_CRASH_FILE" 2>/dev/null || { rm -f "$_tcr_tmp" 2>/dev/null; return 1; }
    return 0
}

# ---- страны выходов --------------------------------------------------------------------
# ТОЛЬКО ИЗ КЭША, и это решение про цену: свежее измерение — это запрос через КАЖДЫЙ выход
# по восемь секунд, то есть скрытая плата за телеметрию на роутере, который человек в этот
# момент не трогает. Кэш наполняет вкладка, когда человек её открывает.
#
# Из строки кэша берётся ВТОРОЕ поле и только оно. В третьем лежит внешний адрес выхода —
# ровно то, чего в пакете быть не должно, и лежит оно в том же файле, в соседнем поле.
tm_geo_cc() {  # ВЫХОД -> код страны или пусто
    _tg="$GEO_DIR/geo-${1:-}"
    [ -s "$_tg" ] || return 1
    read -r _tg_at _tg_cc _tg_rest < "$_tg" 2>/dev/null || return 1
    case "${_tg_at:-}" in ''|*[!0-9]*) return 1 ;; esac
    _tg_age=$(( $(date +%s) - _tg_at ))
    [ "$_tg_age" -le "$TM_GEO_MAX_AGE" ] || return 1
    case "${_tg_cc:-}" in
        [A-Za-z][A-Za-z]) printf '%s' "$_tg_cc" | tr 'a-z' 'A-Z' ;;
        *) return 1 ;;
    esac
}

# ---- город и провайдер -------------------------------------------------------------------
#
# ВТОРОЙ И ПОСЛЕДНИЙ ВНЕШНИЙ ВЫЗОВ РОУТЕРА, и разрешает его РОУТЕР, а не панель. Панель видит
# адрес, с которого пришёл пакет, и могла бы разрешить его сама — но тогда адрес пришлось бы
# у неё держать хотя бы на время разбора, а обещано, что он не уезжает вовсе. Обещание,
# которое выполняется «где-то на той стороне», проверить нельзя; это — можно, стендом.
#
# АДРЕС НЕ ПОПАДАЕТ ДАЖЕ В КЭШ. Сервис возвращает его первым же полем (`"ip":"…"`), и
# сохранить ответ целиком значило бы положить на диск ровно то, чего мы не отправляем. В файл
# идут ТРИ ПРОВЕРЕННЫХ ЗНАЧЕНИЯ и больше ничего — ответ не хранится нигде ни секунды дольше
# разбора.
#
# СПРАШИВАЕТСЯ ТОЛЬКО ПРИ СОГЛАСИИ И ТОЛЬКО КОМАНДОЙ ОТПРАВКИ. Сборщик наружу не ходит — он
# читает кэш. Иначе предпросмотр, экран «посмотреть, что уедет» ДО согласия, сам обращался бы
# к третьей стороне: ответом на вопрос «уедет ли что-нибудь» было бы действие.
#
# ОТВЕТ — ЧУЖОЙ ВВОД, и разбирается он как чужой ввод: не больше двух килобайт, три поля по
# имени, каждое приведено к своему виду, и не подошедшего поля в пакете нет ВОВСЕ. Пустая
# строка или ноль здесь были бы хуже отсутствия: они неотличимы от измеренного значения.
TM_NET_FILE=${TM_NET_FILE:-$GEO_DIR/net}
# Неделя. Город и номер сети меняются с переездом и сменой провайдера, то есть раз в годы;
# кэш при этом лежит в /tmp и теряется на каждой перезагрузке, так что верхняя граница здесь
# сторожит не свежесть, а забытый файл.
TM_NET_MAX_AGE=${TM_NET_MAX_AGE:-604800}
TM_NET_URL_DEF=${TM_NET_URL_DEF:-https://ipinfo.io/json}
TM_NET_BYTES=${TM_NET_BYTES:-2048}
TM_CURL=${TM_CURL:-curl}

# Проверка значений вынесена отдельно, потому что делается ДВАЖДЫ: на записи в кэш и на
# чтении из него. Второй раз не лишний — файл лежит в /tmp, куда пишет не только эта
# функция, и пакет собирается из того, что в нём НАЙДЕНО, а не из того, что мы туда клали.
tm_net_ok() {  # ПОЛЕ ЗНАЧЕНИЕ -> 0, если значение годится
    case "${1:-}" in
        at)   case "${2:-}" in ''|*[!0-9]*) ;; *) return 0 ;; esac ;;
        cc)   case "${2:-}" in [A-Za-z][A-Za-z]) return 0 ;; esac ;;
        asn)  case "${2:-}" in ''|*[!0-9]*) ;; *) [ "${#2}" -le 10 ] && return 0 ;; esac ;;
        # Только латиница, пробел и дефис, не длиннее 32 байт. Всё, что сложнее, — либо не
        # название города, либо чужая строка, которой в пакете быть незачем.
        city) case "${2:-}" in
                  ''|*[!A-Za-z\ -]*) ;;
                  *) [ "${#2}" -le 32 ] && return 0 ;;
              esac ;;
    esac
    return 1
}

# СВЕЖ ЛИ КЭШ — ОТДЕЛЬНЫЙ ВОПРОС, И ЗАДАЁТ ЕГО ТОТ, КТО СОБРАЛСЯ НАРУЖУ.
#
# Пока пакет уезжал раз в сутки, запрос города на каждой отправке был мелочью. На часовом
# такте это сто шестьдесят восемь обращений к третьей стороне в неделю вместо одного, и
# третья сторона видит наш роутер каждый час — то есть цена не только в трафике.
#
# Проверка стоит СНАРУЖИ tm_net_refresh нарочно: сама функция обязана освежать по требованию
# (её зовёт и ручной путь, и стенд), а решать «пора ли» — дело того, кто платит. Иначе
# «освежить» и «освежить, если протухло» назывались бы одним именем.
tm_net_fresh() {  # -> 0, если кэш ещё годен и наружу идти незачем
    [ -s "$TM_NET_FILE" ] || return 1
    _tnf_at="$(sed -n 's/^at=\([0-9]*\)$/\1/p' "$TM_NET_FILE" | tail -n1)"
    case "${_tnf_at:-}" in ''|*[!0-9]*) return 1 ;; esac
    [ $(( $(date +%s) - _tnf_at )) -le "$TM_NET_MAX_AGE" ]
}

tm_net_refresh() {
    _tnr_url="$(uci -q get splify2.main.geo_city_url 2>/dev/null)"
    [ -n "${_tnr_url:-}" ] || _tnr_url="$TM_NET_URL_DEF"
    command -v "$TM_CURL" >/dev/null 2>&1 || return 1
    # Обрезка на два килобайта стоит ЗДЕСЬ, на входе, а не на разборе: разбор идёт sed-ом по
    # строке, и мегабайт чужого ответа — это мегабайт в памяти роутера со 64 МБ.
    _tnr_raw="$("$TM_CURL" -4 -sS --connect-timeout 8 --max-time 15 "$_tnr_url" 2>/dev/null |
        head -c "$TM_NET_BYTES")"
    [ -n "$_tnr_raw" ] || return 1
    _tnr_cc="$(printf '%s' "$_tnr_raw" |
        sed -n 's/.*"country"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -1)"
    _tnr_city="$(printf '%s' "$_tnr_raw" |
        sed -n 's/.*"city"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -1)"
    # Номер сети — ВЕДУЩИЙ `AS…` из `org`, а не строка целиком: за номером там идёт название
    # провайдера, которое пишет он сам, и в нём встречается что угодно вплоть до адреса.
    _tnr_asn="$(printf '%s' "$_tnr_raw" |
        sed -n 's/.*"org"[[:space:]]*:[[:space:]]*"[Aa][Ss]\([0-9]\{1,10\}\).*/\1/p' | head -1)"
    tm_net_ok cc   "$_tnr_cc"   || _tnr_cc=''
    tm_net_ok city "$_tnr_city" || _tnr_city=''
    tm_net_ok asn  "$_tnr_asn"  || _tnr_asn=''
    [ -n "$_tnr_cc$_tnr_city$_tnr_asn" ] || return 1
    mkdir -p "$(dirname "$TM_NET_FILE")" 2>/dev/null
    # Через временный файл: кэш читает сборщик, и половина записи выглядела бы у него
    # неотличимо от целой — с городом без страны или с обрезанным номером сети.
    _tnr_tmp="$TM_NET_FILE.$$"
    {
        printf 'at=%s\n' "$(date +%s)"
        [ -n "$_tnr_cc" ]   && printf 'cc=%s\n' "$_tnr_cc"
        [ -n "$_tnr_asn" ]  && printf 'asn=%s\n' "$_tnr_asn"
        [ -n "$_tnr_city" ] && printf 'city=%s\n' "$_tnr_city"
        :
    } > "$_tnr_tmp" 2>/dev/null || { rm -f "$_tnr_tmp"; return 1; }
    mv "$_tnr_tmp" "$TM_NET_FILE" 2>/dev/null || { rm -f "$_tnr_tmp"; return 1; }
    return 0
}

tm_net_get() {  # ПОЛЕ -> значение или пусто
    [ -s "$TM_NET_FILE" ] || return 1
    _tng_at="$(sed -n 's/^at=\([0-9]*\)$/\1/p' "$TM_NET_FILE" | tail -n1)"
    case "${_tng_at:-}" in ''|*[!0-9]*) return 1 ;; esac
    [ $(( $(date +%s) - _tng_at )) -le "$TM_NET_MAX_AGE" ] || return 1
    _tng_v="$(sed -n "s/^${1:-}=\(.*\)$/\1/p" "$TM_NET_FILE" | tail -n1)"
    tm_net_ok "${1:-}" "${_tng_v:-}" || return 1
    printf '%s' "$_tng_v"
}

# ---- домен панели подписки -------------------------------------------------------------
#
# Отправляется РЕГИСТРИРУЕМЫЙ домен — две последние метки, — а не хост целиком. У части
# панелей токен живёт в поддомене (`https://<токен>.sub.example.org/`), и «отрезали всё после
# хоста» там не спасает: секретом оказывается сам хост.
#
# Схема (`https://`) не отправляется вовсе. Пользы в ней ноль — панели работают по HTTPS, — а
# её отсутствие делает запрет «в пакете нет ни одного ://» сплошным и потому проверяемым.
#
# Признак `deep` говорит панели, что меток было больше двух: тогда группировка приблизительна
# (у суффиксов вида `co.uk` две последние метки — это не домен), и она об этом знает.
tm_sub_host() {  # ССЫЛКА -> «домен deep» либо пусто
    _th="${1:-}"
    case "$_th" in *://*) _th="${_th#*://}" ;; esac
    _th="${_th%%/*}"          # путь
    _th="${_th%%\?*}"         # запрос
    _th="${_th##*@}"          # логин с паролём
    _th="${_th%%:*}"          # порт
    case "$_th" in ''|*[!A-Za-z0-9.-]*) return 1 ;; esac
    _th_n="$(printf '%s' "$_th" | awk -F. '{ print NF }')"
    [ "${_th_n:-0}" -ge 2 ] || return 1
    _th_last="$(printf '%s' "$_th" | awk -F. '{ print $(NF-1) "." $NF }')"
    # Признак «меток было больше двух». Он честнее любого нашего списка суффиксов: у
    # `co.uk` две последние метки — это не домен, а хвост, и без полного перечня публичных
    # суффиксов (мегабайт данных ради одного поля) отличить один случай от другого нечем.
    # Панель по этому признаку знает, что группировка здесь приблизительная.
    _th_deep=0
    [ "$_th_n" -gt 2 ] && _th_deep=1
    printf '%s %s' "$_th_last" "$_th_deep"
}

# Пути списков из спеки, по одному на строку.
#
# СПЕКА ЧИТАЕТСЯ КАК ОДНА СТРОКА, а не построчно: её пишет и человек, и восстановление из
# архива, и она бывает и в одну строку, и с переносами. Построчный разбор молча терял бы
# половину списков на второй форме — то есть пакет говорил бы «этими списками не
# пользуются», а ими пользуются.
tm_list_files() {
    tr -d '\n' < "$SPEC" 2>/dev/null |
        sed 's/"\(prefixes_files\|domains_files\)":\[/\n@@[/g' |
        sed -n 's/^@@\[\([^]]*\)\].*/\1/p' |
        tr ',' '\n' | tr -d '" ' | grep . | sort -u
}

# ---- сам пакет -------------------------------------------------------------------------
#
# Печатается ОДНОЙ строкой JSON. Ни одного поля с неизвестным значением: если величины нет,
# нет и поля — панель обязана это пережить (правило совместимости в docs/TELEMETRY.md).
# «Ноль вместо неизвестного» здесь хуже отсутствия: ноль неотличим от измеренного нуля.
RPCD_OBJ=${RPCD_OBJ:-/usr/libexec/rpcd/splify2}
ZAPRET_SH=${ZAPRET_SH:-/usr/lib/splify2/zapret.sh}
DOH_SH=${DOH_SH:-/usr/lib/splify2/doh.sh}

# Значение поля из ответа объекта rpcd. Разбор по ИМЕНИ ПОЛЯ, а не по порядку: ответ читается
# как данные, а не как текст известной формы.
#
# ПРОБЕЛ ПОСЛЕ ДВОЕТОЧИЯ ОБЯЗАТЕЛЕН В ШАБЛОНЕ, и это не придирчивость. Ответ печатает jshn
# (`json_dump`), а он ставит пробел: `{ "present": true, "arch": "aarch64_cortex-a53" }`.
# Движок в своих ответах печатает плотно (`"up":true`), и шаблон, написанный по движку, на
# ответе собственного объекта не совпадал ни разу. Молчаливо: `tm_field` отдавала пустоту,
# числовой разбор признаков — пустоту тоже (`[0-9-]*` совпадает и с нулём знаков), а дальше
# «пусто» читалось и как «поля нет», и как «ноль». В пакете это выглядело так, будто движка на роутере
# нет вовсе: `steer_kind: absent`, `steer_up: false`, ни `dev.arch`, ни `ver.steer` — на
# роутере, где движок стоит, работает и отвечает. Найдено проверкой на живом роутере;
# песочница стенда подставляла несуществующий объект и этот разбор не трогала совсем.
#
# Числового разбора здесь НЕТ НАРОЧНО: в ответе объекта нет ни одного числового поля, и
# помощник, которого никто не зовёт, ни на чём не проверяется — а `[0-9-]*` в нём совпадал бы
# и с нулём знаков, то есть отдавал бы пустоту вместо отказа. Понадобится число — писать
# заново и вместе со стендом.
tm_field() {  # JSON ИМЯ
    printf '%s' "${1:-}" |
        sed -n "s/.*\"${2:-}\"[[:space:]]*:[[:space:]]*\"\([^\"]*\)\".*/\1/p" | head -1
}
# Булево поле ответа. Отдельно от числового, потому что jshn печатает ИМЕННО `true`/`false`,
# а не 1/0: `json_add_boolean` — это тип, а не сокращение для единицы. Пока признаки движка
# читались числовым разбором, каждый из них приходил пустым.
tm_field_bool() {  # JSON ИМЯ -> 1 | 0
    case "$(printf '%s' "${1:-}" |
            sed -n "s/.*\"${2:-}\"[[:space:]]*:[[:space:]]*\([a-z01]*\).*/\1/p" | head -1)" in
        true|1) printf '1' ;;
        *)      printf '0' ;;
    esac
}

tm_build() {
    _tm_id="$(tm_id)" || return 1
    printf '{"v":%s,"id":' "$TM_SCHEMA"
    tm_str "$_tm_id"
    printf ',"at":%s,"boot":' "$(date +%s)"
    tm_str "$(tm_boot_id)"
    printf ',"uptime":%s' "$(tm_int "$(cut -d. -f1 /proc/uptime 2>/dev/null)")"

    # ---- устройство и версии ----
    #
    # ЧЕРЕЗ СВОЙ ЖЕ МЕТОД `engine`, подпроцессом, а не копией его помощников. Версия пакета,
    # архитектура, вариант сборки и состояние службы считаются в группе движка четырьмя
    # помощниками; копия здесь означала бы пятое место, где решается «какая версия стоит», —
    # причём в пакете, по которому потом судят о роутере. Тот же довод, что у отчёта для
    # поддержки, и та же цена: один лишний разбор скрипта объекта, раз в час.
    _tm_e=""
    [ -x "$RPCD_OBJ" ] && _tm_e="$(sh "$RPCD_OBJ" call engine </dev/null 2>/dev/null)"
    printf ',"dev":{'
    printf '"model":'; tm_str "$(sed -n '1{s/[[:space:]]*$//;p;}' "$SYSINFO_MODEL" 2>/dev/null)"
    _tm_os=""
    [ -f "$OPENWRT_RELEASE" ] && _tm_os="$( . "$OPENWRT_RELEASE" 2>/dev/null
        printf '%s' "${DISTRIB_DESCRIPTION:-${DISTRIB_RELEASE:-}}" )"
    printf ',"os":'; tm_str "$_tm_os"
    _tm_arch="$(tm_field "$_tm_e" arch)"
    [ -n "$_tm_arch" ] && { printf ',"arch":'; tm_str "$_tm_arch"; }
    printf '}'

    printf ',"ver":{'
    printf '"ui":'; tm_str "$(sed -n '1{s/[[:space:]]*$//;p;}' "$BUILD_ID_FILE" 2>/dev/null)"
    _tm_sv="$(tm_field "$_tm_e" version)"
    [ -n "$_tm_sv" ] && { printf ',"steer":'; tm_str "$_tm_sv"; }
    # Вид сборки движка. Без него вся статистика перекошена: базовая сборка не умеет VLESS, и
    # «у них не работает подписка» на ней — не поломка, а не та сборка.
    _tm_present="$(tm_field_bool "$_tm_e" present)"
    _tm_vless="$(tm_field_bool "$_tm_e" vless)"
    if [ "${_tm_present:-0}" = 1 ]; then
        [ "${_tm_vless:-0}" = 1 ] && _tm_kind=extended || _tm_kind=base
    else
        _tm_kind=absent
    fi
    printf ',"steer_kind":'; tm_str "$_tm_kind"
    printf ',"steer_up":%s' "$(tm_bool "$(tm_field_bool "$_tm_e" running)")"
    printf '}'

    # ---- город и провайдер ----
    # Из КЭША, как и страны выходов: наружу ходит только команда отправки и только с согласия.
    _tm_gcc="$(tm_net_get cc 2>/dev/null || true)"
    _tm_gasn="$(tm_net_get asn 2>/dev/null || true)"
    _tm_gcity="$(tm_net_get city 2>/dev/null || true)"
    if [ -n "$_tm_gcc$_tm_gasn$_tm_gcity" ]; then
        printf ',"geo":{'
        _tm_first=1
        [ -n "$_tm_gcc" ] && { printf '"cc":'; tm_str "$_tm_gcc"; _tm_first=0; }
        [ -n "$_tm_gasn" ] && { [ "$_tm_first" = 1 ] || printf ','
                                printf '"asn":%s' "$_tm_gasn"; _tm_first=0; }
        [ -n "$_tm_gcity" ] && { [ "$_tm_first" = 1 ] || printf ','
                                 printf '"city":'; tm_str "$_tm_gcity"; _tm_first=0; }
        # КОГДА измерено. Без этого поля панель не отличит «переехал» от «кэш недельной
        # давности», а значения здесь живут дольше всего остального в пакете.
        _tm_gat="$(tm_net_get at 2>/dev/null || true)"
        [ -n "$_tm_gat" ] && { [ "$_tm_first" = 1 ] || printf ','
                               printf '"at":%s' "$(tm_int "$_tm_gat")"; }
        printf '}'
    fi

    # ---- выходы ----
    #
    # ПО НОМЕРУ, А НЕ ПО ИМЕНИ. Имя выхода писал человек, и «vpn-для-тёщи» это сведения о нём.
    # Номер — порядок в спеке, тот же, каким выходы перечисляет отчёт для поддержки.
    #
    # Из ответа движка берутся ТРИ поля: вид, поднятость и состояние пробы. Рядом в том же
    # объекте лежат `device`, `mark`, `table`, `nodes[]`, `opts_file` и `obfs.server` — адрес
    # и порт сервера обфускации; пересказ объекта целиком был бы утечкой, а не подробностью.
    _tm_st=""
    [ -x "$STEER" ] && _tm_st="$("$STEER" status --spec "$SPEC" 2>/dev/null)"
    printf ',"out":['
    _tm_i=0
    _tm_first=1
    for _tm_name in $(printf '%s' "$_tm_st" |
            sed -n 's/.*"outputs":{\(.*\)/\1/p' |
            grep -o '"[A-Za-z0-9_.:@-]*":{"kind"' | sed 's/":{"kind"//; s/^"//'); do
        _tm_i=$((_tm_i + 1))
        _tm_obj="$(printf '%s' "$_tm_st" | grep -o "\"$_tm_name\":{[^{}]*\(}[^{}]*\)\?" | head -1)"
        _tm_kindv="$(tm_field "$_tm_obj" kind)"
        case "$_tm_kindv" in direct|interface|vless|zapret|obfs|xsteer|tgws) ;; *) _tm_kindv=other ;; esac
        [ "$_tm_first" = 1 ] || printf ','
        _tm_first=0
        printf '{"i":%s,"kind":' "$_tm_i"
        tm_str "$_tm_kindv"
        case "$(printf '%s' "$_tm_obj" | grep -o '"up":[a-z]*' | head -1)" in
            '"up":true')  printf ',"up":true' ;;
            '"up":false') printf ',"up":false' ;;
        esac
        _tm_cc="$(tm_geo_cc "$_tm_name" 2>/dev/null)" && { printf ',"cc":'; tm_str "$_tm_cc"; }
        printf '}'
    done
    printf ']'

    # ---- списки ----
    #
    # ЧЕМ пользуются, а не сколько в них записей: число записей владелец не просил, и это
    # верно — оно ничего не говорит о продукте, зато самый дорогой вопрос из всех.
    #
    # Хозяин списка узнаётся ПО ПУТИ, тем же правилом, каким он записан на диске: свой
    # подкаталог у второго издателя, `custom` у человека. Имена своих списков не уезжают —
    # только их число: их набирал человек.
    printf ',"lists":{"cat":['
    _tm_first=1
    for _tm_f in $(tm_list_files); do
        case "$_tm_f" in
            "$LISTS"/itdog/*|"$LISTS"/custom/*|'') continue ;;
            "$LISTS"/*) ;;
            *) continue ;;
        esac
        _tm_n="${_tm_f#"$LISTS"/}"; _tm_n="${_tm_n%.lst}"; _tm_n="${_tm_n#domains/}"
        case "$_tm_n" in ''|*[!A-Za-z0-9_-]*) continue ;; esac
        [ "$_tm_first" = 1 ] || printf ','
        _tm_first=0
        tm_str "$_tm_n"
    done
    printf '],"itdog":['
    _tm_first=1
    for _tm_f in $(tm_list_files); do
        case "$_tm_f" in "$LISTS"/itdog/*) ;; *) continue ;; esac
        _tm_n="${_tm_f##*/}"; _tm_n="${_tm_n%.lst}"
        case "$_tm_n" in ''|*[!A-Za-z0-9_-]*) continue ;; esac
        [ "$_tm_first" = 1 ] || printf ','
        _tm_first=0
        tm_str "$_tm_n"
    done
    _tm_custom="$(tm_list_files | grep -c "^$LISTS/custom/")"
    printf '],"custom":%s}' "$(tm_int "$_tm_custom")"

    # ---- DoH ----
    # Провайдер — ТОЛЬКО id из нашего каталога: вписанную руками ссылку `doh_active` не
    # отдаёт вовсе, и это решено не здесь, а там, где ей и место.
    if [ -r "$DOH_SH" ]; then
        ( . "$DOH_SH" 2>/dev/null
          printf ',"doh":{"installed":%s,"running":%s,"enabled":%s,"provider":' \
              "$(tm_bool "$(doh_installed && echo 1 || echo 0)")" \
              "$(tm_bool "$(doh_running && echo 1 || echo 0)")" \
              "$(tm_bool "$(doh_enabled && echo 1 || echo 0)")"
          tm_str "$(doh_active 2>/dev/null)"
          printf '}' )
    fi

    # ---- обход DPI ----
    if [ -r "$ZAPRET_SH" ]; then
        ( . "$ZAPRET_SH" 2>/dev/null
          printf ',"zapret":{"installed":%s,"running":%s,"enabled":%s' \
              "$(tm_bool "$(zp_installed && echo 1 || echo 0)")" \
              "$(tm_bool "$(zp_running && echo 1 || echo 0)")" \
              "$(tm_bool "$(zp_enabled && echo 1 || echo 0)")"
          _tm_v="$(zp_version 2>/dev/null)"
          [ -n "$_tm_v" ] && { printf ',"version":'; tm_str "$_tm_v"; }
          # Имя стратегии уезжает, только если оно ЕСТЬ В КАТАЛОГЕ. Иначе это чужая или
          # правленная руками строка, и вместо неё едет слово `custom`: имя, которого нет у
          # автора, ничего не говорит о продукте, зато может быть чем угодно.
          _tm_a="$(zp_active_global 2>/dev/null)"
          if [ -n "$_tm_a" ]; then
              if zp_has "$_tm_a" 2>/dev/null; then
                  printf ',"strategy":'; tm_str "$_tm_a"
              else
                  printf ',"strategy":"custom"'
              fi
              # ИМЯ обязательно: zp_drifted_global первой же строкой выходит без него, и
              # без имени поле уезжало «не разошлась» ВСЕГДА (тот же класс, что I-156).
              printf ',"drifted":%s' \
                  "$(tm_bool "$(zp_drifted_global "$_tm_a" 2>/dev/null && echo 1 || echo 0)")"
          fi
          _tm_yv="$(zp_yv_get 2>/dev/null)"; [ -n "$_tm_yv" ] && printf ',"yv":%s' "$(tm_int "$_tm_yv")"
          _tm_dv="$(zp_dv_get 2>/dev/null)"; [ -n "$_tm_dv" ] && printf ',"dv":%s' "$(tm_int "$_tm_dv")"
          _tm_gv="$(zp_game_gv 2>/dev/null)"; [ -n "$_tm_gv" ] && printf ',"gv":%s' "$(tm_int "$_tm_gv")"
          printf ',"strategies":%s}' "$(tm_int "$(zp_count 2>/dev/null)")" )
    fi

    # ---- подписки ----
    #
    # НОМЕРОМ И ДОМЕНОМ. Названия не уезжают: их пишет либо человек, либо панель провайдера,
    # а в её строках встречаются и рекламные сообщения, и логин владельца — этот же отказ уже
    # принят для отчёта поддержки, и два разных ответа на один вопрос разошлись бы молча.
    printf ',"subs":['
    _tm_i=0
    _tm_first=1
    for _tm_key in $(uci -q show splify2 2>/dev/null |
                     sed -n 's/^splify2\.\(main\|sub_[A-Za-z0-9_]*\)\.sub_url=.*/\1.sub_url/p;
                             s/^splify2\.\(sub_[A-Za-z0-9_]*\)\.url=.*/\1.url/p'); do
        _tm_url="$(uci -q get "splify2.${_tm_key%.*}.${_tm_key##*.}" 2>/dev/null)"
        [ -n "$_tm_url" ] || continue
        _tm_i=$((_tm_i + 1))
        _tm_hd="$(tm_sub_host "$_tm_url")" || continue
        [ "$_tm_first" = 1 ] || printf ','
        _tm_first=0
        printf '{"i":%s,"host":' "$_tm_i"
        tm_str "${_tm_hd% *}"
        printf ',"deep":%s}' "$(tm_bool "${_tm_hd#* }")"
    done
    printf ']'

    # ---- приговоры проверок ----
    #
    # ТОЛЬКО `id` И `verdict`, ни одного символа `what`/`why`: там подставлены имена выходов
    # («выход vpn-для-тёщи: …»). Это не ошибки, а готовые диагнозы, и «у 30% роутеров
    # dns_redirect: fail» — указание, что чинить в продукте.
    _tm_d=""
    [ -x "$STEER" ] && _tm_d="$("$STEER" diag --spec "$SPEC" 2>/dev/null)"
    printf ',"diag":{'
    _tm_dfirst=1
    for _tm_v in fail warn note; do
        [ "$_tm_dfirst" = 1 ] || printf ','
        _tm_dfirst=0
        printf '"%s":[' "$_tm_v"
        _tm_first=1
        for _tm_c in $(printf '%s' "$_tm_d" | grep -o "{\"id\":\"[a-z_]*\",\"verdict\":\"$_tm_v\"" |
                       sed 's/{"id":"//; s/",".*//'); do
            [ "$_tm_first" = 1 ] || printf ','
            _tm_first=0
            tm_str "$_tm_c"
        done
        printf ']'
    done
    printf '}'

    # ---- последнее падение ----
    #
    # ЕДЕТ В КАЖДОМ ПАКЕТЕ, а не только во внеплановом: внеплановая отправка может не уйти
    # (панель недоступна, ограничитель потопа), и тогда факт падения расскажет ближайший
    # плановый пакет. Терять его незачем — он и есть то, ради чего отправка стала частой.
    #
    # ЧИТАЕТСЯ КАК ЧУЖОЙ ВВОД, и это не паранойя: файл лежит в /var/run, куда пишет root, а
    # не только мы. Оба словесных поля сверяются с закрытым набором, остальные — числа; не
    # прошедшего проверку поля в пакете нет ВОВСЕ, а не пустой строкой.
    if [ -s "$TM_CRASH_FILE" ]; then
        _tm_cw="$(sed -n 's/^what=\(.*\)$/\1/p' "$TM_CRASH_FILE" | tail -n1)"
        _tm_cr="$(sed -n 's/^reason=\(.*\)$/\1/p' "$TM_CRASH_FILE" | tail -n1)"
        if tm_crash_what_ok "${_tm_cw:-}" && tm_crash_reason_ok "${_tm_cr:-}"; then
            printf ',"crash":{"what":"%s","reason":"%s","code":%s,"signal":%s,"at":%s,"count":%s}' \
                "$_tm_cw" "$_tm_cr" \
                "$(tm_crash_num "$(sed -n 's/^code=\(.*\)$/\1/p' "$TM_CRASH_FILE" | tail -n1)")" \
                "$(tm_crash_num "$(sed -n 's/^signal=\(.*\)$/\1/p' "$TM_CRASH_FILE" | tail -n1)")" \
                "$(tm_int "$(sed -n 's/^at=\(.*\)$/\1/p' "$TM_CRASH_FILE" | tail -n1)")" \
                "$(tm_int "$(tm_event "crash_$_tm_cw")")"
        fi
    fi

    # ---- события ----
    printf ',"ev":{"wan_down":%s,"iface_down":%s,"since":%s}' \
        "$(tm_int "$(tm_event wan_down)")" \
        "$(tm_int "$(tm_event iface_down)")" \
        "$(tm_int "$(cut -d. -f1 /proc/uptime 2>/dev/null)")"
    printf '}\n'
}
