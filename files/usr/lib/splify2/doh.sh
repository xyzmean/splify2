# DNS over HTTPS: каталог резолверов, настройка https-dns-proxy и его состояние.
#
# ЗАЧЕМ ВООБЩЕ. Провайдер видит имена сайтов раньше, чем что-либо ещё: DNS идёт открытым
# текстом, и по нему и блокируют, и подменяют ответы. Обход по SNI и обход по адресу от этого
# не спасают — до них дело не доходит, потому что адрес уже подменён. Поэтому DoH здесь не
# «ещё одна настройка», а первая ступень: без неё половина стратегий обхода лечит симптом.
#
# ЧТО ЗДЕСЬ, А ЧЕГО НЕТ. Здесь каталог резолверов и запись /etc/config/https-dns-proxy. Правил
# nftables здесь НЕТ: «DoH через туннель» — это метка в цепочке output, и живёт она рядом с
# такой же меткой фикса Zapret Manager, в объекте rpcd, где уже есть и опрос движка, и разбор
# его состояния. Две реализации одного приёма разошлись бы.
#
# `set -u` не ставится: файл подключает объект rpcd, который на необъявленных переменных
# живёт законно.

DOH_CONF=${DOH_CONF:-/etc/config/https-dns-proxy}
DOH_INIT=${DOH_INIT:-/etc/init.d/https-dns-proxy}
DOH_LIST=${DOH_LIST:-/usr/share/splify2/doh-providers.conf}
# Свои резолверы человека — тем же форматом, что каталог, но в /etc: каталог приезжает с
# пакетом и переписывается обновлением, а своё должно пережить и обновление, и прошивку
# (keep.d). id у своих начинается с `my_` — так их отличают и список, и удаление.
DOH_CUSTOM=${DOH_CUSTOM:-/etc/splify2/doh-custom.conf}
DOH_STEER=${DOH_STEER:-/usr/sbin/steer}
DOH_SPEC=${DOH_SPEC:-/etc/steer/spec.json}
# С какого порта раздавать резолверам listen_port. 5053 — то же, что у менеджера и у
# умолчаний пакета: на этот порт ссылается dnsmasq, и менять его без нужды значило бы
# разойтись с чужой настройкой, которая уже могла быть сделана.
DOH_PORT0=${DOH_PORT0:-5053}

doh_installed() { [ -x "$DOH_INIT" ]; }
# Работает ли и включён ли автозапуск — на роутере по процессу и по ссылке в /etc/rc.d, а не
# через init-скрипт: тот стоит оболочки с rc.common на каждый вопрос, а вкладка задаёт их два
# при каждом открытии. Подменённый стендом init-скрипт спрашивается как раньше.
doh_running()   {
    doh_installed || return 1
    if [ "$DOH_INIT" = /etc/init.d/https-dns-proxy ]; then pidof https-dns-proxy >/dev/null 2>&1
    else "$DOH_INIT" running >/dev/null 2>&1
    fi
}
# Включён ли автозапуск. Отдельно от «работает»: выключенная служба после перезагрузки не
# вернётся, и человеку это надо видеть до перезагрузки, а не после.
doh_enabled()   {
    doh_installed || return 1
    if [ "$DOH_INIT" = /etc/init.d/https-dns-proxy ] && [ -d /etc/rc.d ]; then
        set -- /etc/rc.d/S[0-9][0-9]https-dns-proxy
        [ -e "$1" ]
    else "$DOH_INIT" enabled >/dev/null 2>&1
    fi
}

# ---- каталог ------------------------------------------------------------------------
# Строки каталога без комментариев и пустых — сначала общий каталог, за ним свои резолверы.
# Одним перечнем нарочно: всё, что ниже (выбор, активный, запись конфигурации), знает один
# источник строк и не различает, откуда резолвер, — различает только список на странице.
doh_providers() {
    [ -s "$DOH_LIST" ] || [ -s "$DOH_CUSTOM" ] || return 1
    { [ -s "$DOH_LIST" ] && cat "$DOH_LIST"; [ -s "$DOH_CUSTOM" ] && cat "$DOH_CUSTOM"; } |
        grep -v '^[[:space:]]*#' | grep '|'
}

# ---- свои резолверы -----------------------------------------------------------------
# Владелец: «в идеале переключатель dnsmasq/наш DoH + возможность добавлять свои». Свой
# резолвер — строка того же формата, что у каталога; название необязательно (тогда — хост
# из ссылки). Ссылка обязана быть https: DoH по http — не DoH, и https-dns-proxy её отвергнет
# уже после того, как мы переписали конфигурацию.
doh_custom_id() {  # ССЫЛКА → my_<хост_с_подчёркиваниями>
    printf 'my_%s' "$(printf '%s' "$1" | sed -e 's#^https://##' -e 's#/.*$##' -e 's/[^A-Za-z0-9]/_/g' | cut -c1-40)"
}
doh_custom_add() {  # ССЫЛКА [НАЗВАНИЕ] [BOOTSTRAP]; печатает id
    case "${1:-}" in
        https://?*) ;;
        *) return 1 ;;
    esac
    case "$1${2:-}${3:-}" in *'|'*|*"'"*) return 1 ;; esac
    _dc_id="$(doh_custom_id "$1")"
    _dc_title="${2:-${1#https://}}"; _dc_title="${_dc_title%%/*}"
    mkdir -p "$(dirname "$DOH_CUSTOM")" 2>/dev/null || return 1
    # Повтор по ссылке — замена строки, а не вторая: два пункта с одной ссылкой были бы
    # неразличимы и в списке, и для doh_active.
    { [ -s "$DOH_CUSTOM" ] && awk -F'|' -v id="$_dc_id" '$1 != id' "$DOH_CUSTOM"
      printf '%s|%s|%s|%s\n' "$_dc_id" "$_dc_title" "$1" "${3:-}"
    } > "$DOH_CUSTOM.tmp" && mv "$DOH_CUSTOM.tmp" "$DOH_CUSTOM" || return 1
    printf '%s' "$_dc_id"
}
doh_custom_del() {  # ID
    case "${1:-}" in my_?*) ;; *) return 1 ;; esac
    [ -s "$DOH_CUSTOM" ] || return 1
    awk -F'|' -v id="$1" '$1 != id' "$DOH_CUSTOM" > "$DOH_CUSTOM.tmp" && mv "$DOH_CUSTOM.tmp" "$DOH_CUSTOM"
}

# Пункты списка: id и название, по одному на пункт. Несколько строк с одним id — это один
# пункт с несколькими резолверами (см. шапку файла каталога).
doh_items() {
    doh_providers | awk -F'|' '!seen[$1]++ { print $1 "|" $2 }'
}

doh_has() { doh_providers | cut -d'|' -f1 | grep -qxF "${1:-}"; }

# ---- какой резолвер стоит сейчас -----------------------------------------------------
# По ссылкам в конфигурации, а не по своей записи «что мы выбрали». Своя запись разошлась бы
# с настоящей настройкой ровно в тот момент, когда её поменяли не нами — руками, менеджером
# или страницей luci-app-https-dns-proxy. Тот же довод, что с активной стратегией обхода.
#
# Сравниваются НАБОРЫ ссылок: у пункта «по умолчанию» их две, и совпадение по одной означало
# бы, что «Cloudflare» и «по умолчанию» неразличимы.
doh_active() {
    [ -s "$DOH_CONF" ] || return 1
    _da_cur="$(sed -n "s/^[[:space:]]*option resolver_url '\([^']*\)'.*/\1/p" "$DOH_CONF" |
               sort | tr '\n' ' ')"
    [ -n "$_da_cur" ] || return 1
    for _da_id in $(doh_providers | cut -d'|' -f1 | awk '!seen[$0]++'); do
        _da_want="$(doh_providers | awk -F'|' -v id="$_da_id" '$1 == id { print $3 }' |
                    sort | tr '\n' ' ')"
        [ "$_da_cur" = "$_da_want" ] && { printf '%s' "$_da_id"; return 0; }
    done
    # Ссылка есть, а в каталоге её нет — законное состояние: человек вписал свою руками или
    # взял из версии менеджера новее нашей. Пустой ответ здесь означает «чужой», и интерфейс
    # обязан показать ссылку как есть, а не «не настроено».
    return 1
}

# Ссылки как есть — чтобы показать чужой резолвер, которого нет в каталоге.
doh_urls() {
    [ -s "$DOH_CONF" ] || return 1
    sed -n "s/^[[:space:]]*option resolver_url '\([^']*\)'.*/\1/p" "$DOH_CONF"
}

# ---- копия чужой настройки -----------------------------------------------------------
# ЗАЧЕМ. Файл /etc/config/https-dns-proxy — не наш. Пакет приезжает нашей зависимостью, но
# конфигурацию его правят и руками, и Zapret Manager, и страница luci-app-https-dns-proxy, и
# человек вполне мог вписать туда свой резолвер, которого нет ни в одном каталоге. Мы этот
# файл переписываем целиком (см. doh_write), то есть первая же наша запись стирает чужую
# работу. Прежде цена была названа в интерфейсе — и только; вернуть настройку было нечем.
#
# ОТКУДА ПРИЁМ. Так делает podkop (itdoginfo/podkop, backup_dnsmasq_config_option /
# dnsmasq_configure / dnsmasq_restore) с чужим ему /etc/config/dhcp: копия кладётся в ТОТ ЖЕ
# конфиг под своим префиксом, а не в отдельный файл. Довод сильный: отдельный файл живёт своей
# жизнью — его унесёт чистка /var, он останется от прошлой установки, он разойдётся с конфигом
# после правки руками. Копия внутри самого файла не может отстать от того, что копирует: её
# видно в `uci show https-dns-proxy`, она уезжает вместе с файлом и с ним же удаляется.
#
# ЧТО ИМЕННО ХРАНИМ. У podkop меняются три ключа, поэтому у него три префиксных ключа. У нас
# переписывается ВЕСЬ файл, значит и копия — весь файл, строка в строку: `list splify2_orig`.
# Текстом, а не разобранным uci, нарочно — так переживают и комментарии человека, и порядок
# секций, то есть ровно то, что теряет любой пересбор через uci. Пустые строки не берутся:
# в uci-файле это только оформление, а хранить пустое значение в list незачем.
#
# ЧТО ОХРАНЯЕТ СОСТОЯНИЕ. splify2_state — то же, что shutdown_correctly у podkop, и сторожит
# он обе стороны:
#   * копия снимается, только если состояния ЕЩЁ НЕТ. Иначе вторая запись положила бы в копию
#     нашу же настройку, и оригинал исчез бы навсегда — а выглядело бы это как исправная
#     копия. Именно поэтому падение между копией и восстановлением безопасно: копия уже снята,
#     и следующий проход её не тронет;
#   * восстановление срабатывает, только если состояние ЕСТЬ. Файл без состояния мы не писали
#     (или уже вернули), и «откатить» его значило бы снести чужую настройку под видом отката.
#
# У podkop флаг лежит в его собственном конфиге, то есть в другом файле, чем копия, — двумя
# отдельными записями, которые могут разойтись. У нас состояние и копия пишутся ОДНОЙ заменой
# файла, поэтому разойтись не могут: есть состояние — есть копия.
#
# СОСТОЯНИЙ ДВА: saved — файл был, строки в копии; none — файла до нас не было вовсе, и это
# тоже состояние, потому что «вернуть как было» здесь означает удалить наш файл, а не оставить
# его. Пустой ответ — третий случай: мы этого файла не касались.
#
# Секция своего типа: init-скрипт https-dns-proxy разбирает только секции 'main' и
# 'https-dns-proxy', а всё прочее ему не видно. Ключи с префиксом splify2_ — чтобы человек в
# `uci show` сразу видел, чьё это, и по этому же признаку копию узнаёт splify2-purge.
DOH_BAK_SECT=${DOH_BAK_SECT:-splify2_backup}
DOH_BAK_NAME=${DOH_BAK_NAME:-splify2}

# ---- чьё это хозяйство --------------------------------------------------------------
# УПРАВЛЯЕМ МЫ ИЛИ ЧЕЛОВЕК. Признак завёлся после обратки, и вот почему он нужен.
#
# Пакет https-dns-proxy приезжает нашей зависимостью, но он НЕ наш: его настройку правят и
# руками, и Zapret Manager, и страница luci-app-https-dns-proxy, а человек вправе держать свой
# DoH и без нас — «пользователь и сам должен иметь возможность управлять своим DoH без нашего
# пакета» (решение владельца). Пока признака не было, мы вели себя как единственный хозяин:
# выбрал человек «Системный DNS» — мы выключали службу вместе с автозапуском, а `doh_force_sync`
# из apply и из установки продолжал переписывать ему force_dns и перезапускать прокси. Со
# стороны это и выглядело как перехват: «выбрал системный днс, поставил https-dns-proxy рядом —
# splify2 всё равно им распоряжается».
#
# ГДЕ ХРАНИТСЯ. В нашей настройке (`splify2.main.doh_managed`), а не в чужом файле: чужой файл
# мы как раз и обязаны перестать трогать, когда признак снят.
#
# ЗАПИСИ НЕТ — роутер жил до этого различения. Тогда управляемым считается ровно то, во что мы
# уже писали, а признак этого — наша секция копии внутри самого файла. Так обновление пакета не
# меняет поведение ни на одном роутере: где мы вели DoH, там и продолжаем.
DOH_UCI=${DOH_UCI:-uci}

doh_managed() {
    _dm="$("$DOH_UCI" -q get splify2.main.doh_managed 2>/dev/null)"
    case "${_dm:-}" in
        1) return 0 ;;
        0) return 1 ;;
    esac
    [ -n "$(doh_backup_state)" ]
}

doh_manage_set() {  # 1|0
    "$DOH_UCI" -q get splify2.main >/dev/null 2>&1 || {
        "$DOH_UCI" -q set splify2.main=splify2 || return 1
    }
    "$DOH_UCI" -q set "splify2.main.doh_managed=$1" || return 1
    "$DOH_UCI" -q commit splify2
}

# Состояние копии: saved, none или пусто (копии нет).
doh_backup_state() {
    [ -s "$DOH_CONF" ] || return 0
    sed -n "s/^[[:space:]]*option splify2_state '\([^']*\)'.*/\1/p" "$DOH_CONF" | head -1
}

# Исходные строки как есть. Апостроф в значении uci экранируется как '\'' — здесь он
# разворачивается обратно.
doh_backup_lines() {
    [ -s "$DOH_CONF" ] || return 0
    sed -n "s/^[[:space:]]*list splify2_orig '\(.*\)'$/\1/p" "$DOH_CONF" |
        sed "s/'\\\\''/'/g"
}

# Секция копии для новой редакции файла: уже снятая переносится как есть, ещё не снятая
# снимается с текущего содержимого. Значения переносятся НЕ разворачивая апострофы — лишний
# круг «развернуть и снова экранировать» тут ничего не даёт, кроме места, где ошибиться.
doh_backup_dump() {
    printf "\nconfig %s '%s'\n" "$DOH_BAK_SECT" "$DOH_BAK_NAME"
    _dbd_st="$(doh_backup_state)"
    if [ -n "$_dbd_st" ]; then
        printf "\toption splify2_state '%s'\n" "$_dbd_st"
        sed -n "s/^[[:space:]]*list splify2_orig '\(.*\)'$/\1/p" "$DOH_CONF" |
        while IFS= read -r _dbd_l; do
            printf "\tlist splify2_orig '%s'\n" "$_dbd_l"
        done
        return 0
    fi
    if [ -s "$DOH_CONF" ]; then
        printf "\toption splify2_state 'saved'\n"
        # Последняя строка без перевода строки тоже строка: `|| [ -n "$_dbd_l" ]`.
        sed "s/'/'\\\\''/g" "$DOH_CONF" | grep -v '^[[:space:]]*$' |
        while IFS= read -r _dbd_l || [ -n "$_dbd_l" ]; do
            printf "\tlist splify2_orig '%s'\n" "$_dbd_l"
        done
    else
        printf "\toption splify2_state 'none'\n"
    fi
    return 0
}

# Снять копию, ничего больше не меняя.
#
# Нужна отдельно от doh_write потому, что ПЕРВАЯ наша запись в этот файл — не обязательно
# doh_write. force_dns правится из apply и из скрипта установки пакета (doh_force_sync), то
# есть задолго до того, как человек вообще откроет вкладку и выберет резолвер. Копия, снятая
# только в doh_write, к тому моменту уже опоздала бы на один ключ.
doh_backup_save() {
    [ -n "$(doh_backup_state)" ] && return 0
    _dbs_tmp="$DOH_CONF.splify2.tmp"
    { [ -s "$DOH_CONF" ] && cat "$DOH_CONF"; doh_backup_dump; } > "$_dbs_tmp" ||
        { rm -f "$_dbs_tmp"; return 1; }
    mv "$_dbs_tmp" "$DOH_CONF"
}

# Вернуть чужую настройку и убрать за собой.
#
# Службу здесь НЕ перезапускаем: зовут это из splify2-purge, а его зовут и на роутере, с
# которого пакеты уже сняты, — перезапускать было бы нечем, а решение «что делать с прокси
# дальше» покажет сам purge своей строкой.
doh_restore() {
    _dr_st="$(doh_backup_state)"
    [ -n "$_dr_st" ] || return 0
    if [ "$_dr_st" = none ]; then rm -f "$DOH_CONF"; return 0; fi
    _dr_tmp="$DOH_CONF.splify2.tmp"
    doh_backup_lines > "$_dr_tmp" || { rm -f "$_dr_tmp"; return 1; }
    mv "$_dr_tmp" "$DOH_CONF"
}

# ---- запись настройки ----------------------------------------------------------------
# Нужен ли роутеру наш резолвер доменных каналов. Спрашивается у движка, а не выводится из
# спеки: то же правило, что у init-скрипта (см. needs-dnsd там).
doh_needs_dnsd() {
    [ -x "$DOH_STEER" ] && "$DOH_STEER" needs-dnsd --spec "$DOH_SPEC" >/dev/null 2>&1
}

# ГЛАВНАЯ ТОНКОСТЬ ВСЕГО ФАЙЛА — force_dns.
#
# Этот ключ заставляет https-dns-proxy завернуть весь DNS локальной сети (порты 53 и 853) на
# роутер. Zapret Manager ставит его в 1 всегда, и для роутера без движка это верно.
#
# У нас же на том же порту 53 стоит СВОЁ перенаправление — на резолвер движка (steer dnsd,
# порт 5300), и именно он превращает доменные правила в маршрутизацию. Два перенаправления на
# один порт в одной точке (nat prerouting, приоритет dstnat) выигрывает то, которое
# зарегистрировалось раньше, а это зависит от порядка запуска служб. Проиграв, наш резолвер
# перестаёт видеть запросы — и доменные правила молча перестают действовать: сайты
# открываются, но идут мимо туннеля, и понять это можно только по счётчику канала, который
# стоит на нуле.
#
# Поэтому: движку нужен резолвер — force_dns выключаем. Ничего при этом не теряется, DNS всё
# равно заворачивается на роутер, только нашим правилом. Не нужен — ставим 1, как менеджер.
# С запуска 65 — КОНСТАНТА, и это решение владельца: резолвер держим всегда, значит наше
# перенаправление порта 53 стоит всегда, значит force_dns у прокси всегда выключен.
#
# Прежняя редакция выводила ключ из `steer needs-dnsd`, то есть из наличия доменных каналов.
# Переменная годилась, пока доменность жила в спеке: менялась она только через метод apply,
# а тот сразу же и синхронизировал ключ. С гибридными списками (домен и подсеть в одном
# файле) доменность стала зависеть от СОДЕРЖИМОГО списка — то есть могла бы перевернуться
# ночным обновлением, которое зовёт `steer apply` напрямую, минуя метод. Тогда правило
# появлялось бы, а ключ оставался прежним: два перенаправления в одной точке nat prerouting,
# и проигравший молчит.
#
# КОПИЯ ЧУЖОЙ НАСТРОЙКИ ЭТОМУ НЕ МЕШАЕТ, и порядок здесь важен. В копии лежит исходное
# значение force_dns — как правило 1, потому что так его пишут и пакет, и менеджер. Возвращать
# его из копии на каждом проходе означало бы воевать с самим себой: doh_force_sync ставит 0,
# откат — 1, и порт 53 отбирался бы у нашего резолвера через проход. Поэтому копия отдаётся
# ЦЕЛИКОМ и только при полном отказе от нашей настройки (splify2-purge), а не по ключу.
#
# doh_force_sync при этом НЕ становится лишним, наоборот. Он теперь сторожит константу, а не
# гоняется за переменной, — и сторожит от ТРЕТЬЕЙ стороны: Zapret Manager ставит force_dns в
# 1 всегда, и без сверки его правка тихо забирала бы у нас порт 53.
doh_force_dns() { printf '0'; }

# Что стоит в ЧУЖОМ файле сейчас. Пусто — ключа нет вовсе, а у прокси умолчание единица (см.
# его init: `config_get_bool force_dns 'config' 'force_dns' '1'`), поэтому пустое здесь читается
# так же, как «1».
#
# Нужно с тех пор, как мы перестали править этот ключ у чужого хозяйства (doh_managed): молчать
# про расхождение нельзя — доменные правила от него перестают действовать, — а исправлять его
# молча и есть тот перехват, от которого ушли. Значит: показать и предложить.
doh_force_now() {
    [ -s "$DOH_CONF" ] || return 1
    sed -n "s/^[[:space:]]*option force_dns '\([^']*\)'.*/\1/p" "$DOH_CONF" | head -1
}

# Спорит ли чужая настройка с нашим резолвером. Спорит, когда прокси заворачивает DNS сети сам
# (force_dns не ноль) — тогда на порт 53 в одной точке nat prerouting претендуют двое, и
# проигравший молчит.
doh_force_conflict() {
    doh_installed || return 1
    doh_running || return 1
    case "$(doh_force_now 2>/dev/null)" in 0) return 1 ;; esac
    return 0
}

# Исправить ключ ПО ПРОСЬБЕ человека — то же, что делал doh_force_sync, но однократно и по
# нажатию. Копия чужой настройки снимается, как и везде: правка в чужом файле без возврата
# недопустима.
doh_force_fix() {
    doh_installed || return 1
    [ -s "$DOH_CONF" ] || return 1
    doh_backup_save || return 1
    "$DOH_UCI" -q set "https-dns-proxy.@main[0].force_dns=$(doh_force_dns)" || return 1
    "$DOH_UCI" -q commit https-dns-proxy || return 1
    "$DOH_INIT" restart >/dev/null 2>&1
    return 0
}

# Записать конфигурацию под выбранный пункт каталога.
#
# ФАЙЛ ПЕРЕПИСЫВАЕТСЯ ЦЕЛИКОМ, как это делает менеджер (`rm -f "$fileDoH"; printf ... >`), и
# это осознанно: набор секций у резолверов разный (у «по умолчанию» их две, у остальных одна),
# а править многострочный uci вслепую в shell — способ однажды оставить половину прежней
# настройки. Цена — потеря чужих правок в этом файле, и она больше не только названа в
# интерфейсе: чужая редакция уезжает в копию внутри этого же файла (см. раздел выше), откуда
# её возвращает doh_restore. Секция копии выдаётся при КАЖДОЙ записи, иначе следующая же
# запись стёрла бы её вместе с остальным файлом.
doh_write() {  # ID
    doh_has "${1:-}" || return 1
    _dw_tmp="$DOH_CONF.splify2.tmp"
    {
        # Шапка — дословно та же, что у менеджера, кроме force_dns (см. выше). Каждый ключ
        # тут неспроста: canary_* отключают у Firefox и iOS их собственный DoH (иначе они
        # ходят мимо роутера), dnsmasq_config_update '*' переставляет dnsmasq на наш прокси,
        # notrack_dns снимает лишний учёт conntrack, heartbeat_* — проверка живости.
        printf "config main 'config'\n"
        printf "\toption canary_domains_icloud '1'\n"
        printf "\toption canary_domains_mozilla '1'\n"
        printf "\toption dnsmasq_config_update '*'\n"
        printf "\toption force_dns '%s'\n" "$(doh_force_dns)"
        printf "\toption notrack_dns '1'\n"
        printf "\tlist force_dns_port '53'\n"
        printf "\tlist force_dns_port '853'\n"
        printf "\tlist force_dns_src_interface 'lan'\n"
        printf "\toption procd_trigger_wan6 '0'\n"
        printf "\toption heartbeat_domain 'heartbeat.mossdef.org'\n"
        printf "\toption heartbeat_sleep_timeout '10'\n"
        printf "\toption heartbeat_wait_timeout '10'\n"
        # Пользователь nobody — не косметика: под ним же ходят исходящие запросы прокси, и
        # именно по нему их узнаёт правило «DoH через туннель» (объект rpcd, doh_rules_sync).
        printf "\toption user 'nobody'\n"
        printf "\toption group 'nogroup'\n"
        printf "\toption listen_addr '127.0.0.1'\n"
        printf "\toption force_ip_family 'auto'\n"
        _dw_port="$DOH_PORT0"
        doh_providers | awk -F'|' -v id="$1" '$1 == id { print $3 "|" $4 }' |
        while IFS='|' read -r _dw_url _dw_boot; do
            [ -n "$_dw_url" ] || continue
            printf "\nconfig https-dns-proxy\n"
            printf "\toption resolver_url '%s'\n" "$_dw_url"
            [ -n "$_dw_boot" ] && printf "\toption bootstrap_dns '%s'\n" "$_dw_boot"
            printf "\toption listen_port '%s'\n" "$_dw_port"
            _dw_port=$((_dw_port + 1))
        done
        doh_backup_dump
    } > "$_dw_tmp" || { rm -f "$_dw_tmp"; return 1; }
    # Проверка «ссылка записалась» — по НАЧАЛУ строки: в копии тоже лежат ссылки (это и есть
    # чужой резолвер), и без привязки к началу строки она подтвердила бы запись, которой нет.
    grep -q "^[[:space:]]*option resolver_url '" "$_dw_tmp" ||
        { rm -f "$_dw_tmp"; return 1; }
    mv "$_dw_tmp" "$DOH_CONF" || return 1
    # С этой минуты настройку ведём мы — и только с этой. Признак ставится ПОСЛЕ удачной
    # записи: объявить себя хозяином файла, которого не написал, значило бы запретить
    # force_dns-сверку там, где она как раз нужна.
    doh_manage_set 1
    return 0
}

# Привести force_dns в согласие с тем, нужен ли движку свой резолвер.
#
# ЗАЧЕМ ОТДЕЛЬНО ОТ doh_write. Пакет https-dns-proxy — зависимость splify2, то есть он
# приезжает всем и включается со своей стандартной настройкой, где force_dns = 1. Пока
# доменных правил нет, это верно и безобидно. Но правило по доменам человек заводит ПОЗЖЕ —
# и с этой минуты на порт 53 претендуют двое: наш резолвер и прокси. Проигравший (а кто
# проиграет, решает порядок запуска служб) молча остаётся без запросов, и доменные правила
# перестают действовать: сайты открываются, счётчик канала стоит на нуле.
#
# Поэтому вызывается это из `apply` — ровно в тот момент, когда доменные каналы появляются
# или исчезают, — и из скрипта установки пакета. Ничего не делает, когда значение уже верное:
# перезапуск прокси на каждом «Применить» стоил бы человеку паузы в DNS на ровном месте.
#
# Через uci, а не переписыванием файла: у человека в этом файле может стоять свой резолвер,
# вписанный руками, и терять его ради одного ключа незачем. Секция берётся по ТИПУ (@main[0]),
# а не по имени: имя задаёт пакет, и держаться за него — держаться за чужое умолчание.
doh_force_sync() {
    doh_installed || return 0
    [ -s "$DOH_CONF" ] || return 0
    # ТОЛЬКО ПОКА DoH ВЕДЁМ МЫ. Ключ живёт в чужом файле, и править его у человека, который
    # выбрал «Системный DNS» или настроил прокси сам, — это и есть перехват управления, на
    # который пришла обратка. Расхождение при этом не замалчивается: `doh_state` отдаёт и
    # `needs_dnsd`, и настоящий force_dns, а вкладка предлагает исправить его одной кнопкой.
    # Разница между «сделали молча» и «предложили» здесь вся: чужой настройкой распоряжается
    # её хозяин.
    doh_managed || return 0
    # Копия — ДО правки ключа, а не после: этот вызов и есть наша первая запись в чужой файл
    # на роутере, где вкладку DoH ещё не открывали. Отказ снять копию останавливает всё: без
    # копии правка ключа необратима, а ради одного force_dns это слишком.
    doh_backup_save || return 1
    _dfs_want="$(doh_force_dns)"
    _dfs_now="$("$DOH_UCI" -q get https-dns-proxy.@main[0].force_dns 2>/dev/null)"
    [ "$_dfs_now" = "$_dfs_want" ] && return 0
    "$DOH_UCI" -q set "https-dns-proxy.@main[0].force_dns=$_dfs_want" || return 1
    "$DOH_UCI" -q commit https-dns-proxy || return 1
    "$DOH_INIT" restart >/dev/null 2>&1
    return 0
}

# Применить: перезапустить прокси и dnsmasq.
#
# dnsmasq перезапускается ОБЯЗАТЕЛЬНО и вторым: список серверов ему переписывает сам
# https-dns-proxy (dnsmasq_config_update '*'), но подхватывает он его только при перезапуске.
# Без этой строки настройка выглядит применённой, а запросы идут прежним путём.
doh_apply() {
    doh_installed || return 1
    # ЗАПОМИНАЕМ ЧУЖОЕ СОСТОЯНИЕ АВТОЗАПУСКА — до того, как включим своё, и только один раз.
    # Тот же приём и тот же довод, что у копии чужой настройки: вернуть человеку надо ровно
    # то, что у него было, а не то, что мы считаем правильным. Вторая запись затёрла бы
    # оригинал нашим же значением, и «как было» стало бы недостижимо.
    if [ -z "$("$DOH_UCI" -q get splify2.main.doh_prev_enabled 2>/dev/null)" ]; then
        "$DOH_UCI" -q get splify2.main >/dev/null 2>&1 || "$DOH_UCI" -q set splify2.main=splify2
        "$DOH_UCI" -q set "splify2.main.doh_prev_enabled=$(doh_enabled && echo 1 || echo 0)"
        "$DOH_UCI" -q commit splify2
    fi
    "$DOH_INIT" enable >/dev/null 2>&1
    "$DOH_INIT" restart >/dev/null 2>&1
    /etc/init.d/dnsmasq restart >/dev/null 2>&1
    return 0
}

# Выключить DoH — и ВЕРНУТЬ ЧЕЛОВЕКУ УПРАВЛЕНИЕ. Это и есть «Системный DNS» на вкладке.
#
# ЧТО ЗДЕСЬ ИЗМЕНИЛОСЬ И ПОЧЕМУ. Прежде выключение делало три вещи: `disable`, `stop` и всё.
# Настройка при этом оставалась НАШЕЙ — переписанной целиком, с нашей копией внутри, — а
# `doh_force_sync` из apply продолжал править в ней force_dns. То есть человек, выбравший
# системный DNS, получал выключенную службу, чужую настройку в своём файле и наши правки в
# ней же. Поставив https-dns-proxy рядом и нажав «Start» на его странице, он видел, что
# распоряжаемся им по-прежнему мы. Обратка называла это прямо: «сплифу перехватывает
# управление им будто энивей».
#
# Теперь выключение — это отказ от управления:
#
#   1. настройка возвращается человеку (doh_restore): его файл, каким он был до нас, а если
#      файла до нас не было вовсе — его и не остаётся;
#   2. служба останавливается — иначе «системный DNS» не наступит: dnsmasq продолжал бы
#      ходить в прокси;
#   3. АВТОЗАПУСК ВОЗВРАЩАЕТСЯ К ТОМУ, КАКИМ БЫЛ ДО НАС, а не снимается. Прежний безусловный
#      `disable` и был той дверью, которую мы закрывали за собой: снятая ссылка в /etc/rc.d —
#      это состояние, которого человек на странице https-dns-proxy не видит и с нами не
#      связывает, а «Start» там после перезагрузки ничего не значит. Решать, поднимется ли
#      чужая служба на следующей загрузке, мы не вправе; вернуть ей то, что было, — обязаны.
#      Записи нет (мы её не включали) — не трогаем вовсе;
#   4. признак управления снимается, и вместе с ним — сверка force_dns.
#
# dnsmasq перезапускается последним: список серверов ему переписывал прокси, и без
# перезапуска он продолжает ходить на порт, где никого нет.
doh_off() {
    doh_manage_set 0
    doh_installed || return 0
    doh_restore
    _dof_prev="$("$DOH_UCI" -q get splify2.main.doh_prev_enabled 2>/dev/null)"
    case "${_dof_prev:-}" in
        0) "$DOH_INIT" disable >/dev/null 2>&1 ;;
        1) "$DOH_INIT" enable  >/dev/null 2>&1 ;;
    esac
    [ -n "${_dof_prev:-}" ] && {
        "$DOH_UCI" -q delete splify2.main.doh_prev_enabled 2>/dev/null
        "$DOH_UCI" -q commit splify2
    }
    "$DOH_INIT" stop >/dev/null 2>&1
    /etc/init.d/dnsmasq restart >/dev/null 2>&1
    return 0
}

# Запустить чужую службу по просьбе человека: то же, что «Start» на странице
# https-dns-proxy, но из нашей вкладки.
#
# ЗАЧЕМ ЭТО НАМ. Затем, что кнопка на той странице у людей не срабатывает, а вкладка DoH —
# то место, где про DoH и спрашивают. Хозяином настройки мы при этом не становимся: файл не
# трогаем вовсе, признак управления не ставим.
doh_start() {
    doh_installed || return 1
    "$DOH_INIT" start >/dev/null 2>&1
    /etc/init.d/dnsmasq restart >/dev/null 2>&1
    doh_running
}

# Остановить — то же самое с другой стороны. Автозапуск не трогается по тому же доводу.
doh_stop() {
    doh_installed || return 1
    "$DOH_INIT" stop >/dev/null 2>&1
    /etc/init.d/dnsmasq restart >/dev/null 2>&1
    doh_running && return 1
    return 0
}

# ---- системный DNS: свои резолверы АДРЕСОМ ---------------------------------------------
#
# ЗАЧЕМ. «В этом разделе не хватает опции вносить не формат https://…/dns-query, а просто ip
# (если я хочу внести днс провайдера своего интернета)» — обратка, и она про целый режим, а не
# про поле ввода. Резолвер бывает двух родов, и они живут в разных местах роутера:
#
#   DoH — ссылка, её обслуживает https-dns-proxy, а dnsmasq ходит к нему на 127.0.0.1:5053;
#   обычный — АДРЕС, и ходит к нему сам dnsmasq. Никакого прокси здесь нет вовсе.
#
# Поэтому «Системный DNS» перестал быть «ничего не настраиваем»: это второй режим со своей
# настройкой — списком адресов. Пусто — как отдаёт провайдер (то есть правда «ничего»).
#
# ЧТО ИМЕННО ПИШЕТСЯ. `list server` первого экземпляра dnsmasq плюс `noresolv`. Второй ключ
# обязателен: без него dnsmasq продолжает читать /tmp/resolv.conf.d/resolv.conf.auto, то есть
# резолверы провайдера, — и вписанный адрес становится не заменой, а дополнением к тому, от
# чего человек как раз уходит.
#
# ЧУЖИЕ ЗАПИСИ НЕ ТРОГАЮТСЯ, и это главная тонкость. В том же списке живут:
#   * `127.0.0.1#5053` — их пишет туда сам https-dns-proxy (dnsmasq_config_update);
#   * `/mask.icloud.com/`, `/use-application-dns.net/` — доменные заглушки canary, тоже его;
#   * всё, что человек вписал руками для отдельных доменов.
# Наши — только простые адреса. Поэтому чтение и запись фильтруют список по форме записи, а
# не переписывают его целиком: переписав целиком, мы унесли бы работу прокси и человека.
#
# КОПИЯ — тем же приёмом, что у чужой настройки прокси (см. раздел выше и podkop): исходные
# адреса и исходный noresolv ложатся в ТОТ ЖЕ раздел под своим префиксом, и по признаку
# состояния их возвращает doh_sys_restore. Отдельный файл разошёлся бы с настройкой.
DOH_DHCP_SECT=${DOH_DHCP_SECT:-dhcp.@dnsmasq[0]}

# Простой адрес резолвера: 1.2.3.4 или 1.2.3.4#5353. Всё остальное (доменные заглушки,
# петля прокси, IPv6 в скобках) — не наше.
doh_sys_is_addr() {  # ЗАПИСЬ
    case "${1:-}" in
        127.0.0.1|127.0.0.1#*) return 1 ;;   # это прокси DoH, а не резолвер человека
        /*) return 1 ;;
        '') return 1 ;;
    esac
    printf '%s' "$1" | grep -qE '^([0-9]{1,3}\.){3}[0-9]{1,3}(#[0-9]{1,5})?$'
}

# Адреса, которыми сейчас пользуется dnsmasq, по одному на строку.
doh_sys_get() {
    "$DOH_UCI" -q get "$DOH_DHCP_SECT.server" 2>/dev/null | tr ' ' '\n' |
    while IFS= read -r _dsg_v; do
        doh_sys_is_addr "$_dsg_v" && printf '%s\n' "$_dsg_v"
    done
    return 0
}

# Копия исходного списка — снимается один раз, как и у прокси.
doh_sys_backup_save() {
    [ -n "$("$DOH_UCI" -q get "$DOH_DHCP_SECT.splify2_dns_state" 2>/dev/null)" ] && return 0
    for _dsb_v in $("$DOH_UCI" -q get "$DOH_DHCP_SECT.server" 2>/dev/null); do
        doh_sys_is_addr "$_dsb_v" &&
            "$DOH_UCI" -q add_list "$DOH_DHCP_SECT.splify2_orig_server=$_dsb_v"
    done
    "$DOH_UCI" -q set \
        "$DOH_DHCP_SECT.splify2_orig_noresolv=$("$DOH_UCI" -q get "$DOH_DHCP_SECT.noresolv" 2>/dev/null || echo -)"
    "$DOH_UCI" -q set "$DOH_DHCP_SECT.splify2_dns_state=saved"
}

# Вернуть как было и убрать за собой. Зовётся и из пустого списка («как отдаёт провайдер»),
# и из splify2-purge.
doh_sys_restore() {
    [ -n "$("$DOH_UCI" -q get "$DOH_DHCP_SECT.splify2_dns_state" 2>/dev/null)" ] || return 0
    for _dsr_v in $("$DOH_UCI" -q get "$DOH_DHCP_SECT.server" 2>/dev/null); do
        doh_sys_is_addr "$_dsr_v" && "$DOH_UCI" -q del_list "$DOH_DHCP_SECT.server=$_dsr_v"
    done
    for _dsr_v in $("$DOH_UCI" -q get "$DOH_DHCP_SECT.splify2_orig_server" 2>/dev/null); do
        "$DOH_UCI" -q add_list "$DOH_DHCP_SECT.server=$_dsr_v"
    done
    _dsr_nr="$("$DOH_UCI" -q get "$DOH_DHCP_SECT.splify2_orig_noresolv" 2>/dev/null)"
    case "${_dsr_nr:--}" in
        -) "$DOH_UCI" -q delete "$DOH_DHCP_SECT.noresolv" ;;
        *) "$DOH_UCI" -q set "$DOH_DHCP_SECT.noresolv=$_dsr_nr" ;;
    esac
    "$DOH_UCI" -q delete "$DOH_DHCP_SECT.splify2_orig_server"
    "$DOH_UCI" -q delete "$DOH_DHCP_SECT.splify2_orig_noresolv"
    "$DOH_UCI" -q delete "$DOH_DHCP_SECT.splify2_dns_state"
    "$DOH_UCI" -q commit dhcp
}

# Поставить свои адреса. Пусто — вернуть как было.
doh_sys_set() {  # «АДРЕС АДРЕС …»
    for _dss_v in ${1:-}; do
        doh_sys_is_addr "$_dss_v" || return 1
    done
    if [ -z "${1:-}" ]; then
        doh_sys_restore
        /etc/init.d/dnsmasq restart >/dev/null 2>&1
        return 0
    fi
    doh_sys_backup_save || return 1
    for _dss_v in $("$DOH_UCI" -q get "$DOH_DHCP_SECT.server" 2>/dev/null); do
        doh_sys_is_addr "$_dss_v" && "$DOH_UCI" -q del_list "$DOH_DHCP_SECT.server=$_dss_v"
    done
    for _dss_v in $1; do
        "$DOH_UCI" -q add_list "$DOH_DHCP_SECT.server=$_dss_v" || return 1
    done
    # Резолверы провайдера больше не подмешиваются: вписанный адрес — замена, а не добавка.
    "$DOH_UCI" -q set "$DOH_DHCP_SECT.noresolv=1"
    "$DOH_UCI" -q commit dhcp || return 1
    /etc/init.d/dnsmasq restart >/dev/null 2>&1
    return 0
}
