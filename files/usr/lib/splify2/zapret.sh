# ---- установлен ли обход ------------------------------------------------------------
zp_installed() { [ -x "$ZP_NFQWS" ]; }

# Версия пакета. Двумя менеджерами: apk на 24.10+ и opkg на 23.05 и старше. Тишина здесь
# законна — пакета может не быть.
zp_version() {
    # С памятью до смены базы пакетов — тот же довод и тот же приём, что у pkg_version в
    # объекте rpcd: перебор базы стоит триста миллисекунд, а спрашивают его на каждом
    # открытии вкладки.
    _zv_c="/tmp/splify2-pkgver-zapret"
    _zv_db=/lib/apk/db/installed
    command -v apk >/dev/null 2>&1 || _zv_db=/usr/lib/opkg/status
    if [ -f "$_zv_db" ] && [ -f "$_zv_c" ] && [ "$_zv_c" -nt "$_zv_db" ]; then
        cat "$_zv_c"
        return 0
    fi
    _zv_v="$(if command -v apk >/dev/null 2>&1; then
        apk list -I 2>/dev/null | sed -n 's/^zapret-\([0-9][^ ]*\)-r[0-9]* .*/\1/p' | head -1
    else
        opkg list-installed zapret 2>/dev/null | awk '{sub(/-r[0-9]+$/,"",$3); print $3}'
    fi)"
    [ -f "$_zv_db" ] && printf '%s' "$_zv_v" > "$_zv_c" 2>/dev/null
    printf '%s' "$_zv_v"
}

# Работает ли обход СЕЙЧАС. По процессам, а не по init-скрипту: `enabled` и «запущен» —
# разные вопросы, а человека на вкладке интересует второй.
zp_running() { [ -n "$(pgrep -f "$ZP_NFQWS" 2>/dev/null)" ]; }

# ---- каталог ------------------------------------------------------------------------
# Имена стратегий по одному в строке, в порядке файла.
zp_names() { [ -s "$ZP_CATALOG" ] || return 1; sed -n 's/^#//p' "$ZP_CATALOG"; }

# Сколько стратегий в каталоге — ЧИСЛОМ и всегда с кодом 0.
#
# Отдельной функцией, потому что `grep -c` на пустом вводе печатает 0 И ВОЗВРАЩАЕТ 1. То есть
# привычное `$(... | grep -c . || echo 0)` печатает ноль ВТОРОЙ раз, и подстановка отдаёт
# «0\n0». В объекте rpcd это уходило в json_add_int и ломало весь ответ: страница получала не
# JSON и показывала «нет данных» на исправном роутере. Поймано стендом rpcdmatch.
zp_count() { zp_names 2>/dev/null | grep -c . 2>/dev/null || true; }

# Блок одной стратегии ЦЕЛИКОМ, вместе со строкой `#Имя`.
#
# Заголовок входит в блок нарочно, и это ровно то место, где живёт совместимость с Zapret
# Manager: он записывает выбранную стратегию в NFQWS_OPT вместе с этой строкой и по ней же
# потом узнаёт активную (`grep -o '#v[0-9]*'`, `grep -o '#Yv[0-9]*'`). Отрезать заголовок
# значило бы записать стратегию, которую менеджер рядом покажет как «не выбрана».
zp_block() {  # ИМЯ
    [ -n "${1:-}" ] || return 1
    awk -v want="#$1" '
        $0 == want { on = 1; print; next }
        on && /^#/ { exit }
        on && NF   { print }
    ' "$ZP_CATALOG"
}

# Есть ли такая стратегия в каталоге. Отдельно от zp_block, потому что «нет блока» и «блок
# пустой» — разные беды, и вызывающему надо их различать.
zp_has() { [ -s "$ZP_CATALOG" ] && sed -n 's/^#//p' "$ZP_CATALOG" | grep -qxF "${1:-}"; }

# ---- активная стратегия -------------------------------------------------------------
# Как её отмечает Zapret Manager, так читаем и мы: первая строка-комментарий внутри
# `option NFQWS_OPT '...'`. Своего второго признака (файла, ключа uci) здесь заводить
# НЕЛЬЗЯ — он разошёлся бы с тем, что стоит в конфигурации, ровно в тот момент, когда
# стратегию поменяли не нами, а менеджером.
#
# ПУСТОЙ ОТВЕТ — ЗАКОННОЕ СОСТОЯНИЕ, а не сбой, и его надо уметь показать. Так выглядит
# свежий роутер: пакет zapret приезжает со своей стратегией в config.default, а отметки
# `#Имя` там нет — есть только `--comment=Strategy__v6_by_StressOzz`, то есть подпись
# автора внутри ключей, а не имя из каталога. Менеджер в этом случае тоже не показывает
# ничего (его grep ищет ровно `#v[0-9]*`), и придумывать здесь разбор чужой подписи значило
# бы называть стратегию именем, которого в каталоге может не быть вовсе.
zp_active_global() {
    [ -s "$ZP_CONF" ] || return 1
    awk "
        /option NFQWS_OPT '/ { on = 1; next }
        on && /^'\$/        { exit }
        on && /^#/          { sub(/^#/, \"\"); print; exit }
    " "$ZP_CONF"
}

# То же для выхода kind=zapret: там активная стратегия — заголовок его файла ключей.
zp_active_out() {  # ВЫХОД
    [ -n "${1:-}" ] && [ -s "$ZP_OPTS_DIR/$1.opts" ] || return 1
    sed -n '1{s/^#//p;}' "$ZP_OPTS_DIR/$1.opts"
}

# ---- применение ---------------------------------------------------------------------
# Стратегия выходу kind=zapret. Просто файл: движок читает его построчно, строки с `#`
# пропускает, поэтому заголовок туда едет и служит той же отметкой активной.
#
# Через временный файл и mv: обработчик читает файл при подъёме, и оборванная запись
# означала бы поднятый nfqws с половиной ключей — то есть стратегию, которой никто не
# выбирал.
zp_apply_out() {  # ВЫХОД ИМЯ
    zp_has "${2:-}" || return 1
    case "${1:-}" in ''|*[!A-Za-z0-9_.-]*) return 1 ;; esac
    mkdir -p "$ZP_OPTS_DIR" 2>/dev/null || return 1
    zp_block "$2" > "$ZP_OPTS_DIR/$1.opts.tmp" || return 1
    [ -s "$ZP_OPTS_DIR/$1.opts.tmp" ] || { rm -f "$ZP_OPTS_DIR/$1.opts.tmp"; return 1; }
    # Проверка ключей ДО того, как файл встанет на место: у nfqws для этого есть --dry-run,
    # и он отвечает кодом возврата. Без проверки негодная стратегия означала бы экземпляр,
    # который procd поднимает и роняет по кругу, а трафик канала при on_fail=drop стоит.
    if zp_installed && ! zp_dry_run "$ZP_OPTS_DIR/$1.opts.tmp"; then
        rm -f "$ZP_OPTS_DIR/$1.opts.tmp"
        return 1
    fi
    mv "$ZP_OPTS_DIR/$1.opts.tmp" "$ZP_OPTS_DIR/$1.opts"
}

# Принимает ли nfqws эти ключи. Файл читается построчно, как это делает init-скрипт движка:
# ключ @файл у nfqws существует, но с ним нельзя передать --qnum, поэтому и там и здесь
# аргументы собираются из строк.
zp_dry_run() {  # ФАЙЛ_КЛЮЧЕЙ
    # Путь запоминается ДО `set --`: тот стирает позиционные параметры, а перенаправление
    # `< "$1"` вычисляется уже после него — то есть файл читался бы из пустого имени.
    _zd_f="${1:-}"
    [ -s "$_zd_f" ] || return 1
    set --
    # `|| [ -n "$_zl" ]` — не косметика: `read` на последней строке файла БЕЗ завершающего
    # перевода строки возвращает ненулевой код, УЖЕ заполнив переменную, и тело цикла не
    # исполняется. Обёртка обработчика этот же файл читает целиком (правка на стороне steer),
    # поэтому без этой половины проверка видела бы на один ключ меньше, чем движок запустит:
    # негодный последний ключ прошёл бы dry-run и уронил уже живой экземпляр.
    while IFS= read -r _zl || [ -n "$_zl" ]; do
        case "$_zl" in ''|\#*) continue ;; esac
        set -- "$@" "$_zl"
    done < "$_zd_f"
    [ "$#" -gt 0 ] || return 1
    "$ZP_NFQWS" --dry-run --qnum=0 "$@" >/dev/null 2>&1
}

# Стратегия всему роутеру — в /etc/config/zapret, ровно как это делает Zapret Manager:
# всё от строки `option NFQWS_OPT '` до конца файла отрезается и дописывается заново.
#
# ПОЧЕМУ «ДО КОНЦА ФАЙЛА», А НЕ ДО ЗАКРЫВАЮЩЕЙ КАВЫЧКИ. Так делает менеджер, и это не его
# небрежность: NFQWS_OPT в этом файле последний по построению (его же и дописывают), а
# многострочное значение uci в ash разобрать надёжно нечем. Мы повторяем его приём буква в
# букву, потому что цель — чтобы после нас менеджер видел свою конфигурацию, а не нашу.
#
# Порты дописываются, если их там нет: стратегии Flowseal ловят игровые порты и порты
# Discord, а в NFQWS_PORTS_* пакета их нет. Без этого стратегия применяется и не действует
# на половине того, для чего написана.
zp_apply_global() {  # ИМЯ
    zp_has "${1:-}" || return 1
    [ -s "$ZP_CONF" ] || return 1
    _zg_tmp="$ZP_CONF.splify2.tmp"
    sed "/option NFQWS_OPT '/,\$d" "$ZP_CONF" > "$_zg_tmp" || { rm -f "$_zg_tmp"; return 1; }
    {
        printf "\toption NFQWS_OPT '\n"
        zp_block "$1"
        printf "'\n"
    } >> "$_zg_tmp"
    grep -q "option NFQWS_OPT '" "$_zg_tmp" || { rm -f "$_zg_tmp"; return 1; }
    mv "$_zg_tmp" "$ZP_CONF" || return 1
    zp_ports_add NFQWS_PORTS_TCP "2053,2083,2087,2096,8443"
    zp_ports_add NFQWS_PORTS_UDP "19294-19344,50000-50100"
}

# Дописать порты в список, если их там ещё нет. Тот же приём, что add_ports_if_missing у
# менеджера: значение uci здесь — одна строка с запятыми, и дописывание в неё дешевле, чем
# разбор и сборка.
zp_ports_add() {  # КЛЮЧ ПОРТЫ
    grep -q "option $1 .*$2" "$ZP_CONF" 2>/dev/null && return 0
    sed -i "/^[[:space:]]*option $1 '/s/'\$/,$2'/" "$ZP_CONF"
}

# Перезапустить обход. Отдельной функцией, потому что зовут её из трёх мест, а «применил и
# не перезапустил» выглядит как «стратегия не подействовала».
zp_restart() {
    [ -x "$ZP_INIT" ] || return 1
    "$ZP_INIT" restart >/dev/null 2>&1
}

