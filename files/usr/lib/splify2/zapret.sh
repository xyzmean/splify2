# Стратегии Flowseal: архив ветки, из него general*.bat в корне.
#
# general (ALT5).bat пропускается — его пропускает и менеджер. Причина видна в самом файле:
# там нет ни одного профиля из тех шести, что мы забираем, то есть блок вышел бы пустым.
zp_add_flowseal() {  # РАБОЧИЙ_КАТАЛОГ ФАЙЛ_КАТАЛОГА
    # Аргументы запоминаются СРАЗУ: ниже стоит `set --`, который собирает имена членов
    # архива в позиционные параметры и тем самым затирает $1 и $2. Пока этого не было,
    # find получал в качестве каталога имя файла из архива, а каталог стратегий
    # дописывался не туда.
    _zf_dir="$1"
    _zf_cat="$2"
    _zf_tgz="$_zf_dir/flowseal.tgz"
    download "$ZP_CODELOAD/$ZP_FLOWSEAL_REPO/tar.gz/refs/heads/$ZP_FLOWSEAL_BRANCH" \
             "$_zf_tgz" || return 1
    [ -s "$_zf_tgz" ] || return 1

    # Имена членов архива берутся ИЗ АРХИВА, а не перечисляются здесь: у Flowseal список
    # стратегий меняется, и зашитый перечень означал бы каталог, который тихо отстаёт.
    # Верхний каталог в архиве GitHub называется «репозиторий-ветка», поэтому первый
    # сегмент пути любой.
    _zf_list="$(tar -tzf "$_zf_tgz" 2>/dev/null |
                grep -E '^[^/]+/general[^/]*\.bat$' | grep -vF 'general (ALT5).bat')"
    [ -n "$_zf_list" ] || return 1

    # ОДИН проход по архиву на все файлы, а не по проходу на файл: распаковка gzip на 1,6 МБ
    # стоит на роутере ощутимо, а стратегий два десятка. Имена содержат пробелы и скобки,
    # поэтому собираются в позиционные параметры, а не в строку.
    set --
    _zf_ifs="$IFS"
    IFS='
'
    for _zf_m in $_zf_list; do
        IFS="$_zf_ifs"
        set -- "$@" "$_zf_m"
        IFS='
'
    done
    IFS="$_zf_ifs"
    # Файлы-подделки — тем же проходом: они лежат в bin/ того же архива, и качать их
    # отдельно (как делает менеджер) значило бы восемь запросов туда, куда уже сходили.
    #
    # IFS восстановлен ДО этого цикла нарочно: ZP_FAKE_FILES объявлен в несколько строк, и
    # с IFS по переводу строки он делился бы на строки, а не на имена — в архиве искались бы
    # члены с именем «stun2.bin quic_initial_tencent_com.bin …», то есть ни один. Ошибка при
    # этом молчит: tar о ненайденном члене сообщает в stderr, который здесь отброшен, а
    # подделок нет — и стратегия применяется, ничего не делая.
    _zf_top="${_zf_list%%/*}"
    for _zf_f in $ZP_FAKE_FILES; do
        set -- "$@" "$_zf_top/bin/$_zf_f"
    done
    # Отсутствующий член архива для tar — не беда, а сообщение в stderr: часть подделок
    # могла исчезнуть у автора. Поэтому код возврата здесь не проверяется, а проверяется
    # результат — файлы на диске.
    tar -xzf "$_zf_tgz" -C "$_zf_dir" "$@" 2>/dev/null

    # Через конвейер и `read -r`, а не подстановкой в `for`: имена стратегий содержат
    # пробелы и скобки («general (FAKE TLS AUTO ALT2).bat»), и деление по словам разнесло бы
    # одно имя на три. Подоболочка конвейера здесь безвредна — состояние оболочки внутри не
    # меняется, только дописывается файл.
    #
    # Порядок задан явно (LC_ALL=C sort), хотя менеджеру он безразличен: у него список
    # печатается в порядке `find`, то есть в порядке файловой системы. Человеку список
    # показывается в интерфейсе, и «тот же роутер, другой порядок после обновления» читается
    # как «стратегии поменялись».
    find "$_zf_dir" -type f -name 'general*.bat' | LC_ALL=C sort | while IFS= read -r _zf_m; do
        zp_flowseal_block "$_zf_m" "$(basename "$_zf_m" .bat)" >> "$_zf_cat"
    done

    # Подделки раскладываются только если обход установлен: иначе каталога нет, и создавать
    # его самим значило бы оставить мусор на роутере без zapret.
    if [ -d "$ZP_FAKE_DIR" ]; then
        for _zf_f in $ZP_FAKE_FILES; do
            _zf_src="$(find "$_zf_dir" -name "$_zf_f" -type f 2>/dev/null | head -1)"
            [ -n "$_zf_src" ] && [ ! -s "$ZP_FAKE_DIR/$_zf_f" ] &&
                cp "$_zf_src" "$ZP_FAKE_DIR/$_zf_f" 2>/dev/null
        done
    fi
    return 0
}

# Один .bat в блок каталога.
#
# Из файла берутся ТОЛЬКО строки шести профилей — те же, что берёт менеджер. Остальное в
# .bat — это Windows: смена кодовой страницы, вызовы service.bat, запуск winws.exe. Шесть
# образцов ниже переписаны из download_strategies дословно, включая порядок.
zp_flowseal_block() {  # ФАЙЛ ИМЯ
    _zb_m="$(grep -E \
        '^--filter-udp=19294-19344,50000-50100|^--filter-tcp=%GameFilterTCP%|^--filter-udp=%GameFilterUDP%|^--filter-tcp=2053,2083,2087,2096,8443|^--filter-tcp=443 --hostlist="%LISTS%list-google\.txt"|^--filter-tcp=80,443 --hostlist="%LISTS%list-general\.txt"' \
        "$1" 2>/dev/null)"
    [ -n "$_zb_m" ] || return 1
    printf '#%s\n' "$2"
    # Каждый ключ на свою строку: в .bat профиль записан одной длинной строкой, а nfqws мы
    # кормим построчно (см. init-скрипт движка). Пустые строки и хвостовые пробелы уходят
    # здесь же — заодно с этим уходит \r, которым кончаются строки в .bat.
    printf '%s\n' "$_zb_m" | sed 's/--/\n--/g' | sed '/^$/d' | sed 's/[[:space:]]*$//'
    printf '\n'
}

# Замены путей и вычерки — ровно те же и в том же порядке, что в download_strategies.
#
# Применяются ко ВСЕМУ каталогу разом, а не к каждому блоку, и это тоже как у менеджера:
# результат тот же, а проходов sed в двадцать раз меньше.
#
# Что здесь происходит по смыслу: у Flowseal пути записаны переменными Windows (%BIN%,
# %LISTS%), а списки — свои, которых на роутере нет. Поэтому подделки переставляются на
# каталог пакета zapret, часть фильтров вычёркивается совсем (их роль на роутере играют
# списки самого zapret), а игровые порты подставляются числами.
#
# ВЫЧЕРКИ ИМЕННО СТРОКАМИ. После разбивки по ключам каждый ключ стоит на своей строке,
# поэтому `/образец/d` убирает ровно один ключ. До разбивки такой вычерк снёс бы весь
# профиль — двадцать ключей вместо одного.
zp_polish() {  # ФАЙЛ_КАТАЛОГА
    _zp_f="/opt/zapret/files/fake"
    sed -i \
        -e "s|\"%BIN%tls_clienthello_www_google_com.bin\"|$_zp_f/tls_clienthello_www_google_com.bin|g" \
        -e '/--hostlist="%LISTS%list-general.txt"/d' \
        -e '/--ipset="%LISTS%ipset-all.txt"/d' \
        -e '/--hostlist="%LISTS%list-general-user.txt"/d' \
        -e '/--ipset-exclude="%LISTS%ipset-exclude.txt"/d' \
        -e '/--ipset-exclude="%LISTS%ipset-exclude-user.txt"/d' \
        -e '/--hostlist-exclude="%LISTS%list-exclude-user.txt"/d' \
        -e 's|"%LISTS%list-exclude.txt"|/opt/zapret/ipset/zapret-hosts-user-exclude.txt|g' \
        -e 's/--new[[:space:]]\^/--new/g' \
        -e 's|"%LISTS%list-google.txt"|/opt/zapret/ipset/zapret-hosts-google.txt|g' \
        "$1"
    sed -i \
        -e "s|\"%BIN%tls_clienthello_sochi_park.bin\"|$_zp_f/tls_clienthello_sochi_park.bin|g" \
        -e "s|\"%BIN%stun.bin\"|$_zp_f/stun.bin|g" \
        -e "s|\"%BIN%tls_clienthello_4pda_to.bin\"|$_zp_f/4pda.bin|g" \
        -e "s|\"%BIN%quic_initial_www_google_com.bin\"|$_zp_f/quic_initial_www_google_com.bin|g" \
        -e "s|\"%BIN%stun2.bin\"|$_zp_f/stun2.bin|g" \
        -e "s|\"%BIN%quic_initial_tencent_com.bin\"|$_zp_f/quic_initial_tencent_com.bin|g" \
        -e "s|\"%BIN%quic_initial_steamcommunity_com.bin\"|$_zp_f/quic_initial_steamcommunity_com.bin|g" \
        -e "s|\"%BIN%quic_initial_4pda_to.bin\"|$_zp_f/quic_initial_4pda_to.bin|g" \
        -e "s|\"%BIN%ACTIVE_DISCORD_UDP.bin\"|$_zp_f/quic_initial_steamcommunity_com.bin|g" \
        -e "s|\"%BIN%ACTIVE_GAME_UDP.bin\"|$_zp_f/quic_initial_4pda_to.bin|g" \
        -e "s|\"%BIN%tls_clienthello_max_ru.bin\"|$_zp_f/tls_clienthello_www_onetrust_com.bin|g" \
        -e "s|\"%BIN%quic_initial_5ka_ru.bin\"|$_zp_f/quic_initial_5ka_ru.bin|g" \
        -e "s|\"%BIN%quic_initial_rutube_ru.bin\"|$_zp_f/quic_initial_rutube_ru.bin|g" \
        -e "s|%GameFilterTCP%|$ZP_PORTS_TCP|g" \
        -e "s|%GameFilterUDP%|$ZP_PORTS_UDP|g" \
        -e "s|\\^!|$_zp_f/tls_clienthello_www_google_com.bin|g" \
        -e 's/[[:space:]]\+$//' \
        -e '/^[[:space:]]*$/d' \
        "$1"
}

# Стратегии `v` — из самого Zapret-Manager.sh.
#
# Каждая там лежит одной строкой: `strategy_v7() { printf '%s\n' "#v7" "--ключ" ... ; }`.
# Разбор поэтому прямой: взять всё в двойных кавычках по порядку. Экранированных кавычек в
# этих строках нет по построению — ключи nfqws их не содержат, — поэтому деление по кавычке
# однозначно.
#
# ПОЧЕМУ РАЗБОР, А НЕ КОПИЯ. Скопированные сюда стратегии разошлись бы с оригиналом при
# первой правке у автора, и увидеть это было бы нечем: список выглядит полным. Требование
# владельца — брать оттуда же, откуда берёт менеджер, и для этих стратегий «оттуда же» и
# значит «из его скрипта».
zp_add_v() {  # РАБОЧИЙ_КАТАЛОГ ФАЙЛ_КАТАЛОГА
    _zv_sh="$1/zm.sh"
    download "$ZP_RAW/$ZP_ZM_REPO/$ZP_ZM_BRANCH/Zapret-Manager.sh" "$_zv_sh" || return 1
    [ -s "$_zv_sh" ] || return 1
    awk '
        /^strategy_v[0-9]+\(\)[ \t]*\{[ \t]*printf/ {
            n = split($0, q, "\"")
            # Чётные поля деления по кавычке — это содержимое кавычек. Первое из них
            # обязано быть заголовком «#vN»: строка без него не стратегия, а что-то,
            # что мы не поняли, и молча выдать её за стратегию нельзя.
            if (n < 3 || substr(q[2], 1, 2) != "#v") next
            for (i = 2; i < n; i += 2) print q[i]
            print ""
        }
    ' "$_zv_sh" >> "$2"
}

# Стратегии `Yv` — файл files/StrYoutube того же репозитория. Он уже в нашем формате, поэтому
# едет как есть: только \r убирается и хвостовые пробелы.
zp_add_yv() {  # РАБОЧИЙ_КАТАЛОГ ФАЙЛ_КАТАЛОГА
    _zy_f="$1/StrYoutube"
    download "$ZP_RAW/$ZP_ZM_REPO/$ZP_ZM_BRANCH/files/StrYoutube" "$_zy_f" || return 1
    [ -s "$_zy_f" ] || return 1
    grep -q '^#Yv' "$_zy_f" || return 1
    sed -e 's/[[:space:]]*$//' -e '/^$/d' "$_zy_f" |
        awk '/^#/ && NR > 1 { print "" } { print }' >> "$2"
    printf '\n' >> "$2"
}

# Какие семейства стратегий есть в каталоге. Печатает слова через пробел: flowseal, v, yv.
#
# Нужно, чтобы обновление умело отличить «каталог стал другим» от «каталог обеднел».
zp_families() {  # ФАЙЛ
    [ -s "${1:-}" ] || return 0
    grep -q '^#general' "$1" && printf 'flowseal '
    grep -q '^#v[0-9]' "$1" && printf 'v '
    grep -q '^#Yv' "$1" && printf 'yv '
    return 0
}

# Собрать каталог целиком в указанный файл.
#
# Источники СКЛАДЫВАЮТСЯ, а не заменяют друг друга, и провал одного не отменяет остальных:
# репозиторий Flowseal может быть недоступен, а менеджер доступен, и половина каталога
# лучше, чем ПУСТОЙ список — на роутере, где каталога ещё нет вовсе. Пусто вышло целиком —
# это отказ.
#
# Но «лучше, чем пустой» верно только для ПЕРВОЙ сборки. Решает это не здесь, а zp_sync:
# здесь просто собирается то, что дали, а замену на диске он разрешает или запрещает сам.
zp_build() {  # ФАЙЛ
    zp_need_download || return 1
    _zb_dir="$(mktemp -d /tmp/splify2-zapret.XXXXXX 2>/dev/null)" || return 1
    : > "$1"
    zp_add_flowseal "$_zb_dir" "$1"
    zp_add_v "$_zb_dir" "$1"
    zp_add_yv "$_zb_dir" "$1"
    rm -rf "$_zb_dir"
    zp_polish "$1"
    [ -s "$1" ] && grep -q '^#' "$1"
}

# Обновить каталог на диске.
#
# ДВА ПРАВИЛА, И ОБА ПОСТАВЛЕНЫ ВЛАДЕЛЬЦЕМ.
#
# Первое: каталог обновляется раз в сутки, и делает это ночное обновление списков — одно
# задание крона на всё, со случайной минутой (см. splify2-update-lists).
#
# Второе: АКТИВНУЮ СТРАТЕГИЮ ОБНОВЛЯТЬ НЕ НАДО. Здесь это выражено тем, что функция трогает
# ТОЛЬКО каталог: ни /etc/config/zapret, ни файлы ключей выходов, ни сам обход она не
# касается. То есть правка стратегии у автора не меняет того, что работает на роутере, и не
# перезапускает обход в три часа ночи. Человек увидит во вкладке, что выбранная стратегия в
# каталоге изменилась, и решит сам.
#
# Файл переписывается только при изменении содержимого: каталог лежит во флеш-разделе, а
# «то же самое» переписывать — это износ ради ничего. Отметка времени ставится всегда:
# «проверяли, всё то же» и «не проверяли неделю» — разные вещи.
zp_sync() {
    mkdir -p "$ZP_DIR" 2>/dev/null || return 1
    _zs_new="$ZP_CATALOG.new"
    zp_build "$_zs_new" || { rm -f "$_zs_new"; return 1; }

    # ОБЕДНЕВШИЙ КАТАЛОГ НА ДИСК НЕ ПУСКАЕМ, и это не осторожность ради осторожности.
    #
    # Источников три, и они независимы: стратегии Flowseal из своего репозитория, `v` и `Yv`
    # из скрипта менеджера. Недоступен один — сборка отдаёт то, что дали, потому что на
    # роутере без каталога половина списка лучше пустого. Но при ОБНОВЛЕНИИ это уже не так:
    # ночная попытка, у которой не отдал raw.githubusercontent.com (а он у этой аудитории не
    # отдаёт регулярно — ровно это и видно в отчёте на живом роутере), заменила бы каталог из
    # пятидесяти восьми стратегий каталогом из двадцати одной. Выбранная человеком стратегия
    # при этом просто исчезла бы из списка, и он бы не понял, куда.
    #
    # Правило поэтому такое: семейство, которое в каталоге БЫЛО, обязано в нём остаться.
    # Появление нового семейства не мешает, исчезновение — запрещает замену. Сравниваются
    # именно семейства, а не число стратегий: у автора их количество законно меняется в обе
    # стороны, а вот пропажа целого семейства — это всегда недокачка.
    _zs_had="$(zp_families "$ZP_CATALOG")"
    _zs_got="$(zp_families "$_zs_new")"
    for _zs_f in $_zs_had; do
        case " $_zs_got " in
            *" $_zs_f "*) ;;
            *)  rm -f "$_zs_new"
                # Отметку времени НЕ ставим: «проверяли, всё то же» здесь неправда, попытка
                # не удалась, и следующий прогон обязан попробовать снова.
                ZP_NOTE="каталог не обновлён: не отдалось семейство $_zs_f, прежний список цел"
                return 1 ;;
        esac
    done

    if [ -s "$ZP_CATALOG" ] && cmp -s "$_zs_new" "$ZP_CATALOG"; then
        rm -f "$_zs_new"
    else
        mv "$_zs_new" "$ZP_CATALOG" || { rm -f "$_zs_new"; return 1; }
    fi
    date +%s > "$ZP_STAMP" 2>/dev/null
    return 0
}

# Разошлась ли активная стратегия с той, что теперь в каталоге. Отвечает на вопрос, который
# иначе человеку задать нечем: «то, что у меня работает, ещё то же самое?»
zp_drifted() {  # ИМЯ ФАЙЛ_ПРИМЕНЁННОГО
    [ -n "${1:-}" ] && [ -s "${2:-}" ] || return 1
    zp_has "$1" || return 1
    ! zp_block "$1" | cmp -s - "$2"
}
