# Каталог стратегий обхода DPI, применение стратегии и совместимость с Zapret Manager.
#
# ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Этим занимаются трое: объект rpcd (спрашивает каталог и применяет
# выбранное), ночное обновление (splify2-update-lists) и фоновая проверка стратегий
# (splify2-zapret-test). Копия в каждом означала бы три места, которые обязаны согласиться о
# формате каталога и о том, где лежит активная стратегия, — и разошлись бы они молча: каталог
# выглядит на месте, а выбранное в нём не находится.
#
# ОТКУДА БЕРУТСЯ СТРАТЕГИИ. Оттуда же, откуда их берёт сам Zapret Manager, и это требование
# владельца, а не удобство: человек, который пользуется и тем и этим, должен видеть один и тот
# же список.
#
#   Flowseal  — репозиторий Flowseal/zapret-discord-youtube, файлы general*.bat в корне.
#               Это стратегии для Windows (winws), и превращение их в ключи nfqws — ровно тот
#               же набор замен, что делает download_strategies в Zapret-Manager.sh. Замены
#               перенесены пошагово и в том же порядке; расхождение проверяет стенд
#               tests/zapretmatch.sh на приложенном образце.
#   v         — из самого Zapret-Manager.sh: там они лежат функциями strategy_v<N>, каждая
#               одной строкой `printf '%s\n' "#vN" "--ключ" ...`. Разбираются оттуда же, а не
#               переписываются сюда: переписанные разошлись бы с оригиналом при первой правке
#               у автора, и понять это было бы нечем.
#   Yv        — файл files/StrYoutube того же репозитория. Он УЖЕ в нужном формате.
#
# ПОЧЕМУ АРХИВОМ, А НЕ zip, КАК У МЕНЕДЖЕРА. Менеджер качает zip ветки Flowseal (1,6 МБ) и
# ставит для него пакет unzip, если его нет. Архив tar.gz той же ветки того же размера, но
# tar есть в busybox всегда, — то есть ровно та же работа без новой зависимости на роутере.
# Источник от этого не меняется: тот же репозиторий, та же ветка.
#
# ФОРМАТ КАТАЛОГА — тот же, что у менеджера, и это тоже про совместимость: строка `#Имя`,
# затем ключи nfqws по одному в строке. ПУСТЫХ СТРОК НЕТ: последним шагом обработки менеджер
# вычёркивает их все (`sed -i '/^[[:space:]]*$/d'`), то есть блоки разделены только строками
# `#Имя`. Мы повторяем это буква в букву, потому что такой блок должен копироваться в
# NFQWS_OPT и обратно без правки. Заодно оттуда же видно, что следующий шаг менеджера —
# вычерк пустой строки после `--new` — у него уже ничего не делает: пустых строк к тому
# моменту не осталось. Здесь его поэтому нет.
#
# `set -u` здесь НЕ ставится: файл подключает объект rpcd, который на необъявленных
# переменных живёт законно. Своё состояние объявлено целиком ниже, чужое читается через ${x:-}.

